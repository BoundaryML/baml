"""
Example of code that would be generated by the BAML code generator.
This demonstrates how user-defined types work with the type map system.
"""
from dataclasses import dataclass
from enum import Enum
from typing import List, Dict, Any
from baml_py_cffi.serde.type_map import TypeMap
from baml_py_cffi.serde import cffi_pb2
from baml_py_cffi.serde.encode import encode_value
from baml_py_cffi.serde.decode import decode_value


# Example user-defined class (no encode/decode methods visible to users)
@dataclass
class User:
    """A user-defined class that will be used in BAML functions."""
    name: str
    age: int
    email: str
    tags: List[str]


# Example enum
class Status(Enum):
    """A user-defined enum that will be used in BAML functions."""
    ACTIVE = "active"
    INACTIVE = "inactive"
    PENDING = "pending"


# CodeGen generates specific encoders (hidden from users)
def encode_User(user: User, type_map: TypeMap) -> cffi_pb2.CFFIValueHolder:
    """CodeGen-specific encoder for User class."""
    holder = cffi_pb2.CFFIValueHolder()
    
    # Set up the class value
    holder.class_value.CopyFrom(cffi_pb2.CFFIValueClass())
    
    # Set the class name
    holder.class_value.name.CopyFrom(cffi_pb2.CFFITypeName())
    holder.class_value.name.namespace = cffi_pb2.CFFITypeNamespace.TYPES
    holder.class_value.name.name = "User"
    
    # Encode fields
    fields = {
        "name": user.name,
        "age": user.age,
        "email": user.email,
        "tags": user.tags
    }
    
    for field_name, field_value in fields.items():
        entry = cffi_pb2.CFFIMapEntry()
        entry.key = field_name
        # Recursively encode the field value (might be primitive or complex)
        entry.value.CopyFrom(encode_value(field_value, type_map=type_map))
        holder.class_value.fields.append(entry)
    
    return holder


def decode_User(holder: cffi_pb2.CFFIValueHolder, type_map: TypeMap) -> User:
    """CodeGen-specific decoder for User class."""
    if not holder.HasField('class_value'):
        raise ValueError("Expected class_value in holder for User type")
    
    # Extract fields from the class value
    fields = {}
    for field in holder.class_value.fields:
        fields[field.key] = decode_value(field.value, type_map=type_map)
    
    # Construct the User object
    return User(
        name=fields.get("name", ""),
        age=fields.get("age", 0),
        email=fields.get("email", ""),
        tags=fields.get("tags", [])
    )


def encode_Status(status: Status, type_map: TypeMap) -> cffi_pb2.CFFIValueHolder:
    """CodeGen-specific encoder for Status enum."""
    holder = cffi_pb2.CFFIValueHolder()
    
    # Set up the enum value
    holder.enum_value.CopyFrom(cffi_pb2.CFFIValueEnum())
    
    # Set the enum name
    holder.enum_value.name.CopyFrom(cffi_pb2.CFFITypeName())
    holder.enum_value.name.namespace = cffi_pb2.CFFITypeNamespace.TYPES
    holder.enum_value.name.name = "Status"
    
    # Set the enum value
    holder.enum_value.value = status.value
    holder.enum_value.is_dynamic = False
    
    return holder


def decode_Status(holder: cffi_pb2.CFFIValueHolder, type_map: TypeMap) -> Status:
    """CodeGen-specific decoder for Status enum."""
    if not holder.HasField('enum_value'):
        raise ValueError("Expected enum_value in holder for Status type")
    
    # Map the string value back to the enum
    value_map = {
        "active": Status.ACTIVE,
        "inactive": Status.INACTIVE,
        "pending": Status.PENDING
    }
    
    value = holder.enum_value.value
    if value not in value_map:
        raise ValueError(f"Unknown Status value: {value}")
    
    return value_map[value]


# Example of a more complex class with nested types
@dataclass
class UserProfile:
    """A more complex class with nested user-defined types."""
    user: User
    status: Status
    metadata: Dict[str, Any]


def encode_UserProfile(profile: UserProfile, type_map: TypeMap) -> cffi_pb2.CFFIValueHolder:
    """CodeGen-specific encoder for UserProfile class."""
    holder = cffi_pb2.CFFIValueHolder()
    
    # Set up the class value
    holder.class_value.CopyFrom(cffi_pb2.CFFIValueClass())
    
    # Set the class name
    holder.class_value.name.CopyFrom(cffi_pb2.CFFITypeName())
    holder.class_value.name.namespace = cffi_pb2.CFFITypeNamespace.TYPES
    holder.class_value.name.name = "UserProfile"
    
    # Encode fields - using type map for nested types
    fields = [
        ("user", encode_value(profile.user, type_name="User", type_map=type_map)),
        ("status", encode_value(profile.status, type_name="Status", type_map=type_map)),
        ("metadata", encode_value(profile.metadata, type_map=type_map))
    ]
    
    for field_name, field_holder in fields:
        entry = cffi_pb2.CFFIMapEntry()
        entry.key = field_name
        entry.value.CopyFrom(field_holder)
        holder.class_value.fields.append(entry)
    
    return holder


def decode_UserProfile(holder: cffi_pb2.CFFIValueHolder, type_map: TypeMap) -> UserProfile:
    """CodeGen-specific decoder for UserProfile class."""
    if not holder.HasField('class_value'):
        raise ValueError("Expected class_value in holder for UserProfile type")
    
    # Extract fields from the class value
    fields = {}
    for field in holder.class_value.fields:
        if field.key == "user":
            fields[field.key] = decode_value(field.value, type_name="User", type_map=type_map)
        elif field.key == "status":
            fields[field.key] = decode_value(field.value, type_name="Status", type_map=type_map)
        else:
            fields[field.key] = decode_value(field.value, type_map=type_map)
    
    # Construct the UserProfile object
    return UserProfile(
        user=fields.get("user"),
        status=fields.get("status"),
        metadata=fields.get("metadata", {})
    )


# CodeGen creates type map for this module
def create_type_map() -> TypeMap:
    """Create type map with all user-defined types."""
    type_map: TypeMap = {}
    
    # Register User
    type_map["User"] = (
        User,
        lambda u: encode_User(u, type_map),
        lambda h: decode_User(h, type_map)
    )
    
    # Register Status
    type_map["Status"] = (
        Status,
        lambda s: encode_Status(s, type_map),
        lambda h: decode_Status(h, type_map)
    )
    
    # Register UserProfile
    type_map["UserProfile"] = (
        UserProfile,
        lambda p: encode_UserProfile(p, type_map),
        lambda h: decode_UserProfile(h, type_map)
    )
    
    return type_map