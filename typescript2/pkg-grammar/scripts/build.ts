#!/usr/bin/env tsx
// Generate the canonical TextMate grammar JSON from the typed sources in src/.
// The emitted JSON files are the artifacts every consumer reads
// (app-promptfiddle, pkg-editor) and the source for the app-vscode-ext mirror
// (see scripts/sync.mjs). Run via `pnpm --filter @b/pkg-grammar build`.
//
// Also emits dist/index.js + dist/index.d.ts with the grammar inlined as a JS
// object literal. Consumers of the published package import that instead of
// the raw JSON: JSON imports need `with { type: "json" }` under
// moduleResolution nodenext, and some bundlers (Metro/React Native) don't
// parse that attribute, so the JS module keeps JSON out of the consumer
// boundary entirely.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { emitJSON, type Grammar } from "tmlanguage-generator";
import { baml } from "../src/baml.ts";

const here = dirname(fileURLToPath(import.meta.url));
const pkgRoot = resolve(here, "..");

const GRAMMARS: { grammar: Grammar; out: string }[] = [
  { grammar: baml, out: "baml.tmLanguage.json" },
];

for (const { grammar, out } of GRAMMARS) {
  const json = await emitJSON(grammar, { errorSourceFilePath: out });
  writeFileSync(resolve(pkgRoot, out), json);
  console.log(`generated ${out}`);

  if (out !== "baml.tmLanguage.json") {
    continue;
  }

  // Round-trip through JSON.parse/stringify so the inlined literal is exactly
  // the parsed value of the raw JSON artifact (the drift test relies on this).
  const literal = JSON.stringify(JSON.parse(json), null, 2);
  const distDir = resolve(pkgRoot, "dist");
  mkdirSync(distDir, { recursive: true });

  writeFileSync(
    resolve(distDir, "index.js"),
    `// Generated by scripts/build.ts from src/baml.ts. Do not edit.
// The grammar is inlined as a JS object literal so consumers never import
// JSON (avoids \`with { type: "json" }\` import-attribute incompatibilities
// across Vite, Metro, and nodenext).
const grammar = ${literal};

export const bamlLanguage = grammar;
export default bamlLanguage;
`,
  );

  writeFileSync(
    resolve(distDir, "index.d.ts"),
    `// Generated by scripts/build.ts from src/baml.ts. Do not edit.
import type { LanguageRegistration } from "@shikijs/types";

/**
 * The BAML TextMate grammar (\`scopeName: "source.baml"\`) as a Shiki
 * \`LanguageRegistration\`, also usable anywhere a raw TextMate grammar
 * object is accepted (vscode-textmate, monaco-textmate, ...).
 */
export declare const bamlLanguage: LanguageRegistration;
export default bamlLanguage;
`,
  );

  console.log("generated dist/index.js, dist/index.d.ts");
}
