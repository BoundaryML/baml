import { execFile } from 'node:child_process';
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import {
  buildLineIndex,
  loadProject,
  utf16OffsetToUtf8,
} from '@boundaryml/baml-tooling';
import { describe, expect, it } from 'vitest';

const nativeBridge = process.env.BAML_TOOLING_BRIDGE_PATH;
const execFileAsync = promisify(execFile);
const require = createRequire(import.meta.url);

describe.runIf(nativeBridge)('native compiler bridge', () => {
  it('owns projection, navigation, rename, overlays, and last-good output', async () => {
    const root = await mkdtemp(join(tmpdir(), 'baml-native-'));
    const source = join(root, 'baml_src/main.baml');
    await mkdir(join(root, 'baml_src'));
    await writeFile(join(root, 'baml.toml'), '');
    const valid =
      '/// Astral docs 😀\r\nclass Person {\r\n  name string\r\n}\r\nfunction Greet(p: Person) -> string {\r\n  "hi"\r\n}\r\n';
    await writeFile(source, valid);

    const project = await loadProject({ backend: 'native', cwd: root });
    expect(project.capabilities().features).toContain('rename.v1');
    expect(project.check().diagnostics).toEqual([]);
    const declaration = project.resolveDts(source, source);
    expect(declaration.code).toContain('export interface Person');
    expect(declaration.map.segments.length).toBeGreaterThan(4);
    const personOffset = utf16OffsetToUtf8(
      buildLineIndex(valid),
      valid.indexOf('Person'),
    );
    const canonicalSource = declaration.map.sources[0];
    expect(project.definitionAt(source, personOffset)[0]?.path).toBe(
      canonicalSource,
    );
    expect(project.referencesAt(source, personOffset).length).toBeGreaterThan(
      1,
    );
    expect(project.completionsAt().map((item) => item.label)).toContain(
      'Person',
    );
    const person = declaration.map.segments.find(
      (segment) => segment.symbolId === 'T:user.Person',
    );
    if (!person) throw new Error('missing compiler segment for Person');
    expect(project.hoverAt('', 0, person.symbolId).markdown).toContain(
      'Astral docs',
    );
    expect(project.prepareRename(person.symbolId).startUtf8).toBe(personOffset);
    expect(
      project.rename(person.symbolId, 'Human').edits.length,
    ).toBeGreaterThan(1);
    expect(() => project.rename(person.symbolId, 'Greet')).toThrow(/collide/);

    project.updateFile(source, 'class Person {');
    expect(
      project.check().diagnostics.some((item) => item.severity === 'error'),
    ).toBe(true);
    const stale = project.resolveDts(source, source);
    expect(stale.stale).toBe(true);
    expect(stale.code).toBe(declaration.code);
    project.updateFile(source, valid.replaceAll('Person', 'Human'));
    expect(project.check().diagnostics).toEqual([]);
    expect(project.resolveDts(source, source).code).toContain('Human');
    project.dispose();
  });

  it('generates fingerprinted sidecars accepted by plain tsc', async () => {
    const root = await mkdtemp(join(tmpdir(), 'baml-sidecar-'));
    const source = join(root, 'main.baml');
    await writeFile(join(root, 'baml.toml'), '');
    await writeFile(
      source,
      'class Person { name string }\nfunction Greet(p: Person) -> string { "hi" }\n',
    );
    await writeFile(
      join(root, 'index.ts'),
      "import { b, Person } from './main.baml'; const p: Person = { name: 'Ada' }; b.Greet(p);\n",
    );
    await writeFile(
      join(root, 'tsconfig.json'),
      JSON.stringify({
        compilerOptions: {
          allowArbitraryExtensions: true,
          module: 'esnext',
          moduleResolution: 'bundler',
          noEmit: true,
          strict: true,
        },
        include: ['index.ts'],
      }),
    );
    const generator = new URL(
      '../../pkg-baml-tooling/dist/bin/baml-ts-gen.js',
      import.meta.url,
    ).pathname;
    await execFileAsync(process.execPath, [generator], {
      cwd: root,
      env: { ...process.env, BAML_TOOLING_BRIDGE_PATH: nativeBridge },
    });
    expect(await readFile(`${source}.d.ts`, 'utf8')).toMatch(
      /^\/\/ Generated by BAML tooling\.v1[\s\S]*\/\/ baml-fingerprint: [a-f0-9]+/,
    );
    await execFileAsync(
      process.execPath,
      [
        require.resolve('typescript/bin/tsc'),
        '-p',
        join(root, 'tsconfig.json'),
      ],
      { cwd: root },
    );
  });
});
