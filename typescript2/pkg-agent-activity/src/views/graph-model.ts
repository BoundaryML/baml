// The graph behind the Graph view: declarations as nodes, references as
// edges, clustered by file.
//
// It shows the part of the project the session is about: every declaration
// the agent changed, plus the declarations those reference or are referenced
// by (one hop), so a changed type appears with the functions that use it.
// References are found by name: a declaration's text mentioning another
// declaration's name. That over-approximates (a comment counts) but needs no
// compiler, and works for every language the outline understands. Generated
// files are left out: they reference everything and say nothing about intent.

import type { ActivityModel } from '../engine/model';
import type {
  OutlineSymbol,
  SymbolChangeKind,
  SymbolKind,
} from '../engine/outline';

export type NodeState = SymbolChangeKind | 'context';

export interface GraphNode {
  id: string;
  path: string;
  key: string;
  name: string;
  label: string;
  kind: SymbolKind;
  state: NodeState;
  /** Index of the last edit that touched it; -1 for context nodes. */
  lastEdit: number;
}

export interface GraphEdge {
  id: string;
  from: string;
  to: string;
}

export interface GraphData {
  nodes: GraphNode[];
  edges: GraphEdge[];
  files: string[];
}

const GRAPH_KINDS = new Set<SymbolKind>([
  'class',
  'struct',
  'enum',
  'interface',
  'trait',
  'type',
  'function',
  'method',
  'const',
  'client',
  'template',
  'test',
]);

const MAX_NODES = 60;
/** Unchanged neighbors shown per changed declaration. */
const NEIGHBORS_PER_NODE = 3;

/** Generated code (a client, bindings) references everything and says nothing about intent. */
export function isGenerated(text: string | null): boolean {
  if (!text) return false;
  const head = text.slice(0, 400);
  return /(@generated|do not edit|auto-?generated|generated by)/i.test(head);
}

/** Names too common to count as a reference to a declaration. */
const STOP_NAMES = new Set([
  'new',
  'default',
  'from',
  'into',
  'main',
  'test',
  'get',
  'set',
  'run',
  'build',
  'value',
  'name',
  'type',
]);

export function nodeId(path: string, key: string): string {
  return `${path}#${key}`;
}

export function buildGraph(model: ActivityModel, played: number): GraphData {
  const files = model.touchedFiles(played).map((f) => f.path);
  const generated = new Set(
    files.filter((p) => isGenerated(model.contentAt(p, played))),
  );
  const all: { path: string; sym: OutlineSymbol; text: string }[] = [];
  for (const path of files) {
    const content = model.contentAt(path, played);
    if (content === null || generated.has(path)) continue;
    const lines = content.split('\n');
    for (const sym of model.outlineAt(path, played)) {
      if (!GRAPH_KINDS.has(sym.kind)) continue;
      all.push({
        path,
        sym,
        text: lines.slice(sym.start, sym.end + 1).join('\n'),
      });
    }
  }

  // Changed declarations, most recently touched first.
  const ledger = model
    .ledger(played)
    .filter((e) => GRAPH_KINDS.has(e.change.kind));
  const changed = new Map<
    string,
    { state: NodeState; lastEdit: number; removed?: OutlineSymbol }
  >();
  for (const e of ledger) {
    if (e.change.change === 'body' && e.touches === 0) continue;
    if (generated.has(e.path)) continue;
    changed.set(nodeId(e.path, e.change.key), {
      lastEdit: e.lastEdit,
      removed: e.change.change === 'removed' ? e.change.before : undefined,
      state: e.change.change,
    });
  }

  // Name index for reference matching.
  const byName = new Map<string, typeof all>();
  for (const d of all) {
    if (d.sym.name.length < 3 || STOP_NAMES.has(d.sym.name)) continue;
    const list = byName.get(d.sym.name) ?? [];
    list.push(d);
    byName.set(d.sym.name, list);
  }
  const edges = new Map<string, GraphEdge>();
  const neighbors = new Map<string, Set<string>>();
  const link = (a: string, b: string) => {
    if (!neighbors.has(a)) neighbors.set(a, new Set());
    neighbors.get(a)!.add(b);
  };
  for (const d of all) {
    const from = nodeId(d.path, d.sym.key);
    const tokens = new Set(d.text.match(/[A-Za-z_]\w+/g) ?? []);
    for (const token of tokens) {
      if (token === d.sym.name) continue;
      for (const target of byName.get(token) ?? []) {
        const to = nodeId(target.path, target.sym.key);
        if (to === from) continue;
        edges.set(`${from}->${to}`, { from, id: `${from}->${to}`, to });
        link(from, to);
        link(to, from);
      }
    }
  }

  // Changed nodes first, then their neighbors, up to the cap.
  const chosen = new Set<string>();
  const changedIds = [...changed.entries()]
    .sort((a, b) => b[1].lastEdit - a[1].lastEdit)
    .map(([id]) => id);
  for (const id of changedIds) if (chosen.size < MAX_NODES) chosen.add(id);
  for (const id of changedIds) {
    let added = 0;
    for (const n of neighbors.get(id) ?? []) {
      if (chosen.size >= MAX_NODES || added >= NEIGHBORS_PER_NODE) break;
      if (!chosen.has(n)) {
        chosen.add(n);
        added++;
      }
    }
  }

  const nodes: GraphNode[] = [];
  const byId = new Map(all.map((d) => [nodeId(d.path, d.sym.key), d]));
  for (const id of chosen) {
    const d = byId.get(id);
    const c = changed.get(id);
    const sym = d?.sym ?? c?.removed;
    if (!sym) continue;
    const path = d?.path ?? id.slice(0, id.indexOf('#'));
    nodes.push({
      id,
      key: sym.key,
      kind: sym.kind,
      label: sym.container ? `${sym.container}.${sym.name}` : sym.name,
      lastEdit: c?.lastEdit ?? -1,
      name: sym.name,
      path,
      state: c?.state ?? 'context',
    });
  }
  const ids = new Set(nodes.map((n) => n.id));
  return {
    edges: [...edges.values()].filter((e) => ids.has(e.from) && ids.has(e.to)),
    files: [...new Set(nodes.map((n) => n.path))],
    nodes,
  };
}
