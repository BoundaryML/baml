#!/usr/bin/env node
// Regenerates `problems-index.ts` from every `problems/*.json`.
// Run from this directory:  node gen-index.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const problemsDir = join(here, 'problems');

const files = readdirSync(problemsDir)
  .filter((f) => f.endsWith('.json'))
  .sort();

const problems = files.map((f) => {
  const p = JSON.parse(readFileSync(join(problemsDir, f), 'utf8'));
  const expectedSlug = f.replace(/\.json$/, '');
  if (p.slug !== expectedSlug) {
    throw new Error(
      `slug mismatch in ${f}: slug="${p.slug}" file="${expectedSlug}"`,
    );
  }
  return p;
});

problems.sort((a, b) => a.id - b.id);

const imports = files
  .map((f) => {
    const slug = f.replace(/\.json$/, '');
    const ident = slug.replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) =>
      c ? c.toUpperCase() : '',
    );
    return { file: f, ident, slug };
  })
  .sort((a, b) => a.ident.localeCompare(b.ident));

const header = `// AUTO-GENERATED by gen-index.mjs - do not edit by hand.\n// Run \`node gen-index.mjs\` after adding or editing a problem JSON.\nimport type { Problem } from './types';\n\n`;

const importLines = imports
  .map((i) => `import ${i.ident} from './problems/${i.file}';`)
  .join('\n');

const arrayLines = imports
  .map((i) => `  ${i.ident} as unknown as Problem,`)
  .join('\n');

const body = `\n\nexport const PROBLEMS: Problem[] = [\n${arrayLines}\n].sort((a, b) => a.id - b.id);\n\nexport const PROBLEMS_BY_SLUG: Record<string, Problem> = Object.fromEntries(\n  PROBLEMS.map((p) => [p.slug, p]),\n);\n\nexport function getProblem(slug: string): Problem | undefined {\n  return PROBLEMS_BY_SLUG[slug];\n}\n`;

writeFileSync(join(here, 'problems-index.ts'), header + importLines + body);
console.log(`wrote problems-index.ts with ${problems.length} problems`);
