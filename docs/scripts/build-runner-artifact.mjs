import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  copyFile,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  writeFile,
} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { brotliCompressSync, constants, gzipSync } from 'node:zlib';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const repositoryRoot = path.resolve(packageRoot, '..');
const crate = path.join(repositoryRoot, 'baml_language/crates/bridge_wasm');
const publicRoot = path.join(packageRoot, 'public/baml-runtime');
const artifactsRoot = path.join(publicRoot, 'artifacts');
const scratch = await mkdtemp(path.join(os.tmpdir(), 'baml-docs-wasm-'));

function capture(command, args, options = {}) {
  const result = spawnSync(command, args, { encoding: 'utf8', ...options });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed:\n${result.stderr ?? ''}`);
  }
  return result.stdout.trim();
}

function digest(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

try {
  const environment = { ...process.env, CARGO_PROFILE_RELEASE_OPT_LEVEL: 'z' };
  delete environment.RUSTC_WRAPPER;
  const built = spawnSync(
    'wasm-pack',
    [
      'build',
      crate,
      '--target',
      'web',
      '--release',
      '--out-dir',
      scratch,
      '--out-name',
      'bridge_wasm',
    ],
    { env: environment, stdio: 'inherit' },
  );
  if (built.error) throw built.error;
  if (built.status !== 0) process.exit(built.status ?? 1);

  const wasmPath = path.join(scratch, 'bridge_wasm_bg.wasm');
  const modulePath = path.join(scratch, 'bridge_wasm.js');
  const wasmBytes = await readFile(wasmPath);
  const moduleBytes = await readFile(modulePath);
  const sha256 = digest(wasmBytes);
  const artifactName = sha256.slice(0, 16);
  const artifactRoot = path.join(artifactsRoot, artifactName);

  const runtime = await import(`${pathToFileURL(modulePath).href}?artifact=${sha256}`);
  await runtime.default({ module_or_path: wasmBytes });

  const bamlBinary =
    process.env.BAML_BIN ??
    path.join(repositoryRoot, 'baml_language/target/debug/baml-cli');
  const sourceCommit = capture('git', ['rev-parse', 'HEAD'], { cwd: repositoryRoot });
  const toolchain = capture(bamlBinary, ['--version']);
  const gzipBytes = gzipSync(wasmBytes, { level: 9 }).length;
  const brotliBytes = brotliCompressSync(wasmBytes, {
    params: { [constants.BROTLI_PARAM_QUALITY]: 11 },
  }).length;

  // This directory is exclusively generated by this script. Keeping only the
  // content-addressed artifact referenced by the manifest avoids serving stale
  // runtimes while retaining immutable caching for the active one.
  await rm(artifactsRoot, { recursive: true, force: true });
  await mkdir(artifactRoot, { recursive: true });
  await copyFile(modulePath, path.join(artifactRoot, 'bridge_wasm.js'));
  await copyFile(wasmPath, path.join(artifactRoot, 'bridge_wasm_bg.wasm'));

  const manifest = {
    schemaVersion: 1,
    runtimeVersion: runtime.version(),
    runtimeCommit: runtime.commitHash(),
    runtimeBuildTimeUnix: runtime.getBuildTime(),
    sourceCommit,
    toolchain,
    sha256,
    moduleSha256: digest(moduleBytes),
    rawBytes: wasmBytes.length,
    gzipBytes,
    brotliBytes,
    module: `/baml-runtime/artifacts/${artifactName}/bridge_wasm.js`,
    wasm: `/baml-runtime/artifacts/${artifactName}/bridge_wasm_bg.wasm`,
  };
  await writeFile(
    path.join(publicRoot, 'manifest.json'),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );

  console.log(
    `wrote runtime ${manifest.runtimeVersion} (${wasmBytes.length} raw, ${gzipBytes} gzip, ${brotliBytes} brotli)`,
  );
} finally {
  await rm(scratch, { recursive: true, force: true });
}
