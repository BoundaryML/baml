//! Go SDK test target build-side setup.
//!
//! The Go target stages the runtime `function_calls` fixture and the
//! compile-first `type_shapes` fixture. Unsupported symbols are omitted by the
//! emitter, while compile-time assertions in the customizable Go source pin
//! the exact signatures of every primitive surface supported by this stage.

use std::{env, fs, path::PathBuf};

use baml_codegen_types::NamingConvention;

use crate::{
    BuildDiagnostics, copy_customizable, emit_cargo_line, fixtures_root_from_manifest,
    load_fixture, watch_dir,
};

const FIXTURES: &[&str] = &["function_calls", "type_shapes"];

pub fn run_all() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let fixtures_root = fixtures_root_from_manifest(&manifest_dir);
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let diagnostics = BuildDiagnostics::new(&out_dir);

    for fixture in FIXTURES {
        let loaded = load_fixture(&fixtures_root, fixture);
        let fixture_root = manifest_dir.join(fixture);
        let generated = fixture_root.join("generated");
        let sdk = generated.join("baml_sdk");
        if generated.exists() {
            fs::remove_dir_all(&generated).unwrap();
        }
        fs::create_dir_all(&sdk).unwrap();

        let output = sdkgen_go::to_source_code_with_bytecode(
            &loaded.pool,
            &loaded.baml_bytecode,
            NamingConvention::Language,
            "baml.local/sdk/baml_sdk",
        );
        for (relative, contents) in output {
            let path = sdk.join(relative);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).unwrap();
            }
            fs::write(path, contents).unwrap();
        }

        let customizable = fixture_root.join("customizable");
        if customizable.exists() {
            copy_customizable(&customizable, &generated);
        }

        fs::write(
            generated.join("go.mod"),
            "module baml.local/sdk\n\ngo 1.23\n\nrequire github.com/boundaryml/baml/sdks/go/baml_go v0.0.0\n\nreplace github.com/boundaryml/baml/sdks/go/baml_go => ../../../../../sdks/go/baml_go\n",
        )
        .unwrap();

        watch_dir(&loaded.baml_src);
        watch_dir(&customizable);
    }

    let mut tests = String::from(
        "// Generated by sdk_test_harness_setup::go::run_all — do not edit.\n::sdk_test_harness_runner::build_diagnostics!();\n::sdk_test_harness_runner::setup_guard!(\"SDK_TEST_GO_SETUP\");\n",
    );
    for fixture in FIXTURES {
        tests.push_str(&format!(
            "\nmod {fixture} {{\n    #[test]\n    fn go_test() {{\n        ::sdk_test_harness_runner::run_go_test({fixture:?});\n    }}\n}}\n"
        ));
    }
    fs::write(out_dir.join("go_tests.rs"), tests).unwrap();
    diagnostics.finalize();

    emit_cargo_line(format_args!("cargo:rerun-if-changed=build.rs"));
}
