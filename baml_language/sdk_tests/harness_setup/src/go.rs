//! Go SDK test target build-side setup.
//!
//! The Go target stages the runtime `function_calls` fixture, the compile-first
//! `type_shapes` fixture, an `unsupported_only` package proving deferred
//! symbols leave valid Go behind, and a synthetic `package_edges` fixture for
//! cross-package import collisions. Compile-time assertions pin the exact
//! signatures and class shapes supported by this stage.

use std::{collections::HashMap, env, fs, path::PathBuf};

use baml_base::Name as BaseName;
use baml_codegen_types::{
    Class, ClassProperty, Name, NamingConvention, Origin, Symbol, SymbolPool, Ty,
};

use crate::{
    BuildDiagnostics, copy_customizable, emit_cargo_line, fixtures_root_from_manifest,
    load_fixture, watch_dir,
};

const SOURCE_FIXTURES: &[&str] = &["function_calls", "type_shapes", "unsupported_only"];
const FIXTURES: &[&str] = &[
    "function_calls",
    "type_shapes",
    "unsupported_only",
    "package_edges",
];

pub fn run_all() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let fixtures_root = fixtures_root_from_manifest(&manifest_dir);
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let diagnostics = BuildDiagnostics::new(&out_dir);

    for fixture in SOURCE_FIXTURES {
        let loaded = load_fixture(&fixtures_root, fixture);
        let output = sdkgen_go::to_source_code_with_bytecode(
            &loaded.pool,
            &loaded.baml_bytecode,
            NamingConvention::Language,
            "baml.local/sdk/baml_sdk",
        );
        stage_output(&manifest_dir, fixture, output);

        watch_dir(&loaded.baml_src);
        watch_dir(&manifest_dir.join(fixture).join("customizable"));
    }
    stage_package_edges(&manifest_dir);

    let mut tests = String::from(
        "// Generated by sdk_test_harness_setup::go::run_all — do not edit.\n::sdk_test_harness_runner::build_diagnostics!();\n::sdk_test_harness_runner::setup_guard!(\"SDK_TEST_GO_SETUP\");\n",
    );
    for fixture in FIXTURES {
        tests.push_str(&format!(
            "\nmod {fixture} {{\n    #[test]\n    fn go_test() {{\n        ::sdk_test_harness_runner::run_go_test({fixture:?});\n    }}\n}}\n"
        ));
    }
    fs::write(out_dir.join("go_tests.rs"), tests).unwrap();
    diagnostics.finalize();

    emit_cargo_line(format_args!("cargo:rerun-if-changed=build.rs"));
}

fn stage_output(manifest_dir: &std::path::Path, fixture: &str, output: HashMap<PathBuf, String>) {
    let fixture_root = manifest_dir.join(fixture);
    let generated = fixture_root.join("generated");
    let sdk = generated.join("baml_sdk");
    if generated.exists() {
        fs::remove_dir_all(&generated).unwrap();
    }
    fs::create_dir_all(&sdk).unwrap();
    for (relative, contents) in output {
        let path = sdk.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        fs::write(path, contents).unwrap();
    }

    let customizable = fixture_root.join("customizable");
    if customizable.exists() {
        copy_customizable(&customizable, &generated);
    }
    fs::write(
        generated.join("go.mod"),
        "module baml.local/sdk\n\ngo 1.23\n\nrequire github.com/boundaryml/baml/sdks/go/baml_go v0.0.0\n\nreplace github.com/boundaryml/baml/sdks/go/baml_go => ../../../../../sdks/go/baml_go\n",
    )
    .unwrap();
}

fn stage_package_edges(manifest_dir: &std::path::Path) {
    let context = Name::new(BaseName::new("context"), vec![], BaseName::new("Thing"));
    let dashed = Name::new(BaseName::new("foo-bar"), vec![], BaseName::new("Thing"));
    let snake = Name::new(BaseName::new("foo_bar"), vec![], BaseName::new("Thing"));
    let holder = Name::new(BaseName::new("user"), vec![], BaseName::new("Holder"));
    let pool = SymbolPool::from([
        synthetic_class(context.clone(), vec![("value", Ty::String)]),
        synthetic_class(dashed.clone(), vec![("value", Ty::Int)]),
        synthetic_class(snake.clone(), vec![("value", Ty::Bool)]),
        synthetic_class(
            holder,
            vec![
                ("context_thing", Ty::Class(context, vec![])),
                ("dashed_thing", Ty::Class(dashed, vec![])),
                ("snake_thing", Ty::Class(snake, vec![])),
            ],
        ),
    ]);
    let output = sdkgen_go::to_source_code_with_bytecode(
        &pool,
        &[],
        NamingConvention::Language,
        "baml.local/sdk/baml_sdk",
    );
    stage_output(manifest_dir, "package_edges", output);
    watch_dir(&manifest_dir.join("package_edges").join("customizable"));
}

fn synthetic_class(name: Name, properties: Vec<(&str, Ty)>) -> (Name, Symbol) {
    let class = Class {
        name: name.clone(),
        generic_params: vec![],
        docstring: None,
        properties: properties
            .into_iter()
            .map(|(name, ty)| ClassProperty {
                name: BaseName::new(name),
                docstring: None,
                ty,
            })
            .collect(),
        static_methods: vec![],
        instance_methods: vec![],
        origin: Origin {
            source_file_path: "synthetic.baml".to_string(),
            span_start: 0,
        },
    };
    (name, Symbol::Class(class))
}
