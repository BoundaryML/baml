//! Browser TypeScript sdk-test target — build-script side.

use std::{
    env, fs,
    path::{Path, PathBuf},
};

use sdkgen_typescript_web::NamingConvention;

use crate::{
    BuildDiagnostics, copy_customizable, discover_fixtures, emit_cargo_line,
    fixtures_root_from_manifest, load_fixture, watch_dir,
};

const PACKAGE_JSON_TEMPLATE: &str = include_str!("templates/package_web.json");
const TSCONFIG_JSON: &str = include_str!("templates/tsconfig_web.json");
const VITEST_CONFIG: &str = include_str!("templates/vitest_web.config.ts");
const CACHE_SUBDIR: &str = "pnpm-store";
const CACHE_ENV_VAR: &str = "npm_config_store_dir";
const SETUP_ENV_VAR: &str = "SDK_TEST_TYPESCRIPT_WEB_SETUP";

pub fn run_all() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let fixtures_root = fixtures_root_from_manifest(&manifest_dir);
    let node_tests_root = manifest_dir.parent().unwrap().join("typescript_node");
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let mut diagnostics = BuildDiagnostics::new(&out_dir);
    let fixtures = discover_fixtures(&fixtures_root);
    assert!(
        !fixtures.is_empty(),
        "no fixtures discovered under {}",
        fixtures_root.display()
    );

    let mut fixture_tests = Vec::new();
    for fixture in &fixtures {
        let custom = node_tests_root.join(fixture).join("customizable");
        codegen_fixture(
            &fixtures_root,
            fixture,
            &manifest_dir,
            &custom,
            &mut diagnostics,
        );
        fixture_tests.push((fixture.clone(), has_vitest_tests(&custom)));
        watch_dir(&custom);
    }
    write_fixtures_tests_rs(&out_dir, &fixture_tests);
    diagnostics.finalize();
    emit_cargo_line(format_args!("cargo:rerun-if-changed=build.rs"));
    watch_dir(&fixtures_root);
}

fn codegen_fixture(
    fixtures_root: &Path,
    fixture: &str,
    manifest_dir: &Path,
    custom: &Path,
    diagnostics: &mut BuildDiagnostics,
) {
    let loaded = load_fixture(fixtures_root, fixture);
    let generated = manifest_dir.join(fixture).join("generated");
    if generated.exists() {
        for entry in fs::read_dir(&generated).unwrap().flatten() {
            let path = entry.path();
            if path.file_name().and_then(|name| name.to_str()) == Some("node_modules") {
                continue;
            }
            let result = if path.is_dir() {
                fs::remove_dir_all(&path)
            } else {
                fs::remove_file(&path)
            };
            if let Err(error) = result {
                diagnostics.record("generated_cleanup", fixture, error);
            }
        }
    }
    let baml_sdk = generated.join("baml_sdk");
    fs::create_dir_all(&baml_sdk).unwrap();
    let output = sdkgen_typescript_web::to_source_code_with_bytecode(
        &loaded.pool,
        &loaded.baml_bytecode,
        NamingConvention::PreserveCase,
    );
    for (relative, content) in output {
        let path = baml_sdk.join(relative);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).unwrap();
        }
        if let Err(error) = fs::write(&path, content) {
            diagnostics.record("codegen_write", fixture, error);
        }
    }
    if custom.exists() {
        copy_customizable(custom, &generated);
    }
    rewrite_test_bridge_imports(&generated);
    let package_name = format!("sdk-tests-web-typescript-{}", fixture.replace('_', "-"));
    fs::write(
        generated.join("package.json"),
        PACKAGE_JSON_TEMPLATE.replace("__PACKAGE_NAME__", &package_name),
    )
    .unwrap();
    fs::write(generated.join("tsconfig.json"), TSCONFIG_JSON).unwrap();
    fs::write(generated.join("vitest.config.ts"), VITEST_CONFIG).unwrap();
}

fn rewrite_test_bridge_imports(dir: &Path) {
    for entry in fs::read_dir(dir).unwrap().flatten() {
        let path = entry.path();
        if path.is_dir() {
            if path.file_name().and_then(|name| name.to_str()) != Some("baml_sdk") {
                rewrite_test_bridge_imports(&path);
            }
        } else if path.extension().and_then(|ext| ext.to_str()) == Some("ts") {
            let source = fs::read_to_string(&path).unwrap();
            let web_source =
                source.replace("@boundaryml/baml-bridge", "@boundaryml/baml-bridge-web");
            if source != web_source {
                fs::write(path, web_source).unwrap();
            }
        }
    }
}

fn write_fixtures_tests_rs(out_dir: &Path, fixtures: &[(String, bool)]) {
    let mut source = String::from(
        "// Generated by sdk_test_harness_setup::typescript_web::run_all — do not edit.\n",
    );
    source.push_str("::sdk_test_harness_runner::build_diagnostics!();\n");
    source.push_str(&format!(
        "::sdk_test_harness_runner::setup_guard!({SETUP_ENV_VAR:?});\n"
    ));
    for (fixture, has_tests) in fixtures {
        source.push_str(&format!(r#"
mod {fixture} {{
    fn cmd(command: &str) {{
        ::sdk_test_harness_runner::run_test_cmd("{fixture}", command, "{CACHE_SUBDIR}", "{CACHE_ENV_VAR}");
    }}

    #[test]
    fn esm_output() {{ ::sdk_test_harness_runner::assert_typescript_web_generated_esm("{fixture}"); }}

    #[test]
    fn tsc() {{ cmd("node node_modules/typescript/bin/tsc --noEmit"); }}
"#));
        if *has_tests {
            source.push_str("    #[test]\n    fn vitest() { cmd(\"pnpm exec vitest run --config vitest.config.ts\"); }\n");
        }
        source.push_str("}\n");
    }
    fs::write(out_dir.join("typescript_web_tests.rs"), source).unwrap();
}

fn has_vitest_tests(dir: &Path) -> bool {
    fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .any(|entry| {
            let path = entry.path();
            (path.is_dir() && has_vitest_tests(&path))
                || path
                    .file_name()
                    .and_then(|name| name.to_str())
                    .is_some_and(|name| name.ends_with(".test.ts"))
        })
}
