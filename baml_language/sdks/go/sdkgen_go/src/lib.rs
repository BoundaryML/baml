struct WireCodecs {
    class_names: Vec<Name>,
    class_indexes: BTreeMap<Name, usize>,
    enum_names: Vec<Name>,
    enum_indexes: BTreeMap<Name, usize>,
    union_keys: Vec<(BaseName, GoUnionKey)>,
    union_indexes: BTreeMap<(BaseName, GoUnionKey), usize>,
    dynamic_union_keys: BTreeSet<(BaseName, GoUnionKey)>,
    callback_keys: Vec<(BaseName, GoFunctionKey)>,
    callback_indexes: BTreeMap<(BaseName, GoFunctionKey), usize>,
}

impl WireCodecs {
    fn is_empty(&self) -> bool {
        self.class_names.is_empty()
            && self.enum_names.is_empty()
            && self.union_keys.is_empty()
            && self.callback_keys.is_empty()
    }

    fn for_functions(
        functions: &[GeneratedFunction<'_>],
        declared_classes: &[GeneratedClass<'_>],
        declared_unions: &[GoUnionKey],
        pool: &SymbolPool,
        projection: &GoTypeProjection<'_>,
        current_package: &BaseName,
    ) -> Self {
        let mut collected = CollectedCodecTypes::default();
        for routed in functions {
            if let Some(receiver) = &routed.receiver {
                collect_projected_codec_types(
                    &GoTy::Class(
                        receiver.owner_name.clone(),
                        receiver
                            .class
                            .generic_params
                            .iter()
                            .cloned()
                            .map(GoTy::TypeVar)
                            .collect::<Vec<_>>()
                            .into_boxed_slice(),
                    ),
                    current_package,
                    pool,
                    projection,
                    &mut collected,
                );
            }
            for ty in routed
                .function
                .arguments
                .iter()
                .map(|argument| &argument.ty)
                .chain(std::iter::once(&routed.function.return_type))
            {
                collect_projected_codec_types(
                    &projection.project(ty),
                    current_package,
                    pool,
                    projection,
                    &mut collected,
                );
            }
        }
        for key in declared_unions {
            collect_projected_codec_types(
                &GoTy::TypedUnion(key.clone()),
                current_package,
                pool,
                projection,
                &mut collected,
            );
        }
        for class in declared_classes {
            if class.class.generic_params.is_empty() {
                continue;
            }
            for field in &class.fields {
                collect_projected_codec_types(
                    &projection.project(&field.property.ty),
                    current_package,
                    pool,
                    projection,
                    &mut collected,
                );
            }
        }
        let class_names = collected.classes.into_iter().collect::<Vec<_>>();
        let class_indexes = class_names
            .iter()
            .cloned()
            .enumerate()
            .map(|(index, name)| (name, index))
            .collect();
        let enum_names = collected.enums.into_iter().collect::<Vec<_>>();
        let enum_indexes = enum_names
            .iter()
            .cloned()
            .enumerate()
            .map(|(index, name)| (name, index))
            .collect();
        let union_keys = collected.unions.into_iter().collect::<Vec<_>>();
        let union_indexes = union_keys
            .iter()
            .cloned()
            .enumerate()
            .map(|(index, key)| (key, index))
            .collect();
        let callback_keys = collected.callbacks.into_iter().collect::<Vec<_>>();
        let callback_indexes = callback_keys
            .iter()
            .cloned()
            .enumerate()
            .map(|(index, key)| (key, index))
            .collect();
        Self {
            class_names,
            class_indexes,
            enum_names,
            enum_indexes,
            union_keys,
            union_indexes,
            dynamic_union_keys: collected.dynamic_unions,
            callback_keys,
            callback_indexes,
        }
    }

    fn ident(&self, name: &Name, direction: ClassCodecDirection) -> ClassCodecIdent {
        ClassCodecIdent::new(
            direction,
            *self
                .class_indexes
                .get(name)
                .expect("class codec was not registered"),
        )
    }

    fn enum_ident(&self, name: &Name, direction: EnumCodecDirection) -> EnumCodecIdent {
        EnumCodecIdent::new(
            direction,
            *self
                .enum_indexes
                .get(name)
                .expect("enum codec was not registered"),
        )
    }

    fn union_ident(
        &self,
        package: &BaseName,
        key: &GoUnionKey,
        direction: UnionCodecDirection,
    ) -> UnionCodecIdent {
        UnionCodecIdent::new(
            direction,
            *self
                .union_indexes
                .get(&(package.clone(), key.clone()))
                .expect("union codec was not registered"),
        )
    }

    fn callback_ident(&self, package: &BaseName, key: &GoFunctionKey) -> CallbackCodecIdent {
        CallbackCodecIdent::new(
            *self
                .callback_indexes
                .get(&(package.clone(), key.clone()))
                .expect("callback codec was not registered"),
        )
    }
}

#[derive(Default)]
struct CollectedCodecTypes {
    classes: BTreeSet<Name>,
    enums: BTreeSet<Name>,
    unions: BTreeSet<(BaseName, GoUnionKey)>,
    dynamic_unions: BTreeSet<(BaseName, GoUnionKey)>,
    callbacks: BTreeSet<(BaseName, GoFunctionKey)>,
    visited_classes: HashSet<Name>,
}

fn collect_projected_codec_types(
    ty: &GoTy,
    owner_package: &BaseName,
    pool: &SymbolPool,
    projection: &GoTypeProjection<'_>,
    collected: &mut CollectedCodecTypes,
) {
    match ty {
        GoTy::Class(name, arguments) => {
            let Symbol::Class(class) = &pool[name] else {
                unreachable!()
            };
            if class.generic_params.is_empty()
                && collected.classes.insert(name.clone())
                && collected.visited_classes.insert(name.clone())
            {
                for field in &class.properties {
                    collect_projected_codec_types(
                        &projection.project(&field.ty),
                        name.package(),
                        pool,
                        projection,
                        collected,
                    );
                }
            }
            for argument in arguments {
                collect_projected_codec_types(argument, owner_package, pool, projection, collected);
            }
        }
        GoTy::Enum(name) | GoTy::EnumVariant(name, _) => {
            collected.enums.insert(name.clone());
        }
        GoTy::List(inner) | GoTy::Optional(inner) => {
            collect_projected_codec_types(inner, owner_package, pool, projection, collected);
        }
        GoTy::Map { key, value } => {
            collect_projected_codec_types(key, owner_package, pool, projection, collected);
            collect_projected_codec_types(value, owner_package, pool, projection, collected);
        }
        GoTy::TypedUnion(key) => {
            if collected
                .unions
                .insert((owner_package.clone(), key.clone()))
            {
                for member in key.members() {
                    collect_projected_codec_types(
                        member,
                        owner_package,
                        pool,
                        projection,
                        collected,
                    );
                }
            }
        }
        GoTy::DynamicUnion { key, .. } if projected_contains_type_var(ty) => {
            for member in key.members() {
                collect_projected_codec_types(member, owner_package, pool, projection, collected);
            }
        }
        GoTy::DynamicUnion { key, .. } => {
            collected
                .dynamic_unions
                .insert((owner_package.clone(), key.clone()));
            if collected
                .unions
                .insert((owner_package.clone(), key.clone()))
            {
                for member in key.members() {
                    collect_projected_codec_types(
                        member,
                        owner_package,
                        pool,
                        projection,
                        collected,
                    );
                }
            }
        }
        GoTy::Function(key) => {
            collected
                .callbacks
                .insert((owner_package.clone(), key.clone()));
            for param in key.params() {
                collect_projected_codec_types(
                    param.ty(),
                    owner_package,
                    pool,
                    projection,
                    collected,
                );
            }
            if let Some(ret) = key.ret() {
                collect_projected_codec_types(ret, owner_package, pool, projection, collected);
            }
        }
        _ => {}
    }
}

fn generated_classes<'a>(
    pool: &'a SymbolPool,
    names: &GoNames,
    package: &GoPackage,
    renderable: &BTreeSet<Name>,
) -> Vec<GeneratedClass<'a>> {
    let mut classes = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Class(class)
                if name.package() == package.baml_name() && renderable.contains(name) =>
            {
                Some((name, class))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    classes.sort_by_key(|(name, _)| *name);
    classes
        .into_iter()
        .map(|(name, class)| {
            let fqn = BamlFqn::symbol(name);
            GeneratedClass {
                name,
                class,
                go_name: names
                    .project(&fqn, GoNameKind::Class, GoVisibility::Exported)
                    .clone(),
                fields: class
                    .properties
                    .iter()
                    .map(|property| GeneratedField {
                        property,
                        go_name: names
                            .project(
                                &fqn.member(&property.name),
                                GoNameKind::Field,
                                GoVisibility::Exported,
                            )
                            .clone(),
                    })
                    .collect(),
            }
        })
        .collect()
}

fn generated_enums<'a>(
    pool: &'a SymbolPool,
    names: &GoNames,
    package: &GoPackage,
) -> Vec<GeneratedEnum<'a>> {
    let mut enums = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Enum(enum_) if name.package() == package.baml_name() => Some((name, enum_)),
            _ => None,
        })
        .collect::<Vec<_>>();
    enums.sort_by_key(|(name, _)| *name);
    enums
        .into_iter()
        .map(|(name, enum_)| {
            let fqn = BamlFqn::symbol(name);
            GeneratedEnum {
                name,
                enum_,
                go_name: names
                    .project(&fqn, GoNameKind::Enum, GoVisibility::Exported)
                    .clone(),
                variants: enum_
                    .variants
                    .iter()
                    .map(|variant| GeneratedEnumVariant {
                        go_name: names
                            .project(
                                &fqn.member(&variant.name),
                                GoNameKind::EnumVariant,
                                GoVisibility::Exported,
                            )
                            .clone(),
                    })
                    .collect(),
            }
        })
        .collect()
}

