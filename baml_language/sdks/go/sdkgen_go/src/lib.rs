        let void_name = Name::new(BaseName::new("user"), vec![], BaseName::new("no_op"));
        let void_function = Function {
            name: BaseName::new("no_op"),
            generic_params: vec![],
            docstring: None,
            arguments: vec![],
            return_type: Ty::Unit,
            throws: None,
            watchers: vec![],
            origin: origin(),
        };
        let bigint_name = Name::new(
            BaseName::new("user"),
            vec![],
            BaseName::new("round_trip_bigint"),
        );
        let bigint_function = Function {
            name: BaseName::new("round_trip_bigint"),
            generic_params: vec![],
            docstring: None,
            arguments: vec![FunctionArgument {
                name: BaseName::new("value"),
                docstring: None,
                ty: Ty::Bigint,
                default: None,
            }],
            return_type: Ty::Bigint,
            throws: None,
            watchers: vec![],
            origin: origin(),
        };
        let pool = SymbolPool::from([
            (void_name, Symbol::Function(void_function)),
            (bigint_name, Symbol::Function(bigint_function)),
        ]);

        let files = to_source_code_with_bytecode(
            &pool,
            &[],
            NamingConvention::Language,
            "example.com/project/baml_sdk",
        );
        let functions = &files[&PathBuf::from("functions.go")];
        assert!(functions.contains("\n\t\"math/big\"\n"));
