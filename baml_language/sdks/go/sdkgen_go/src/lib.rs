//! Greenfield Go SDK emitter.
//!
//! The first vertical slice deliberately covers primitive, non-generic free
//! functions. It establishes the generated package boundary, bytecode
//! bootstrap, context-aware call shape, and wire names without inheriting the
//! retired Go bridge's API.

use std::{collections::HashMap, fmt::Write as _, path::PathBuf};

use baml_base::Literal;
use baml_codegen_types::{Function, NamingConvention, Symbol, SymbolPool, Ty};

const BANNER: &str = "// Code generated by BAML. DO NOT EDIT.\n\n";

/// Generate files relative to a project's `baml_sdk/` directory.
pub fn to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
    sdk_import_path: &str,
) -> HashMap<PathBuf, String> {
    assert!(
        matches!(naming_convention, NamingConvention::Language),
        "sdkgen_go requires naming_convention = language"
    );

    let mut functions = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Function(function)
                if name.pkg.as_str() == "user" && supported_function(function) =>
            {
                Some((name, function))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    functions.sort_by_key(|(name, _)| name.to_string());

    HashMap::from([
        (
            PathBuf::from("functions.go"),
            render_functions(&functions, sdk_import_path),
        ),
        (
            PathBuf::from("internal/bootstrap/bootstrap.go"),
            render_bootstrap(baml_bytecode),
        ),
    ])
}

fn supported_function(function: &Function) -> bool {
    function.generic_params.is_empty()
        && function
            .arguments
            .iter()
            .all(|arg| arg.default.is_none() && primitive_kind(&arg.ty).is_some())
        && (primitive_kind(&function.return_type).is_some()
            || matches!(function.return_type, Ty::Unit))
}

#[derive(Clone, Copy)]
enum PrimitiveKind {
    String,
    Int,
    Bigint,
    Float,
    Bool,
    Null,
    Uint8Array,
}

fn primitive_kind(ty: &Ty) -> Option<PrimitiveKind> {
    match ty {
        Ty::String => Some(PrimitiveKind::String),
        Ty::Int => Some(PrimitiveKind::Int),
        Ty::Bigint => Some(PrimitiveKind::Bigint),
        Ty::Float => Some(PrimitiveKind::Float),
        Ty::Bool => Some(PrimitiveKind::Bool),
        Ty::Null => Some(PrimitiveKind::Null),
        Ty::Uint8Array => Some(PrimitiveKind::Uint8Array),
        Ty::Literal(literal) => match literal {
            Literal::String(_) => Some(PrimitiveKind::String),
            Literal::Int(_) => Some(PrimitiveKind::Int),
            Literal::Bigint(_) => Some(PrimitiveKind::Bigint),
            Literal::Float(_) => Some(PrimitiveKind::Float),
            Literal::Bool(_) => Some(PrimitiveKind::Bool),
        },
        _ => None,
    }
}

fn render_functions(
    functions: &[(&baml_codegen_types::Name, &Function)],
    sdk_import_path: &str,
) -> String {
    let mut out = String::from(BANNER);
    out.push_str("package baml_sdk\n\n");
    out.push_str("import (\n\t\"context\"\n");
    if functions.iter().any(|(_, function)| {
        primitive_kind(&function.return_type)
            .is_some_and(|kind| matches!(kind, PrimitiveKind::Bigint))
            || function.arguments.iter().any(|argument| {
                primitive_kind(&argument.ty)
                    .is_some_and(|kind| matches!(kind, PrimitiveKind::Bigint))
            })
    }) {
        out.push_str("\t\"math/big\"\n");
    }
    out.push('\n');
    let _ = writeln!(
        out,
        "\t{:?}",
        format!("{sdk_import_path}/internal/bootstrap")
    );
    out.push_str("\t\"github.com/boundaryml/baml/sdks/go/baml_go\"\n)\n");

    for (name, function) in functions {
        let go_name = go_callable_name(name);
        let args = function
            .arguments
            .iter()
            .map(|arg| format!("{} {}", safe_go_local(arg.name.as_str()), go_type(&arg.ty)))
            .collect::<Vec<_>>();
        let mut params = vec!["ctx context.Context".to_string()];
        params.extend(args);

        if matches!(function.return_type, Ty::Unit) {
            let _ = writeln!(out, "\nfunc {go_name}({}) error {{", params.join(", "));
        } else {
            let _ = writeln!(
                out,
                "\nfunc {go_name}({}) ({}, error) {{",
                params.join(", "),
                go_type(&function.return_type)
            );
        }
        out.push_str("\tif err := bootstrap.Ensure(); err != nil {\n");
        if matches!(function.return_type, Ty::Unit) {
            out.push_str("\t\treturn err\n\t}\n");
            out.push_str("\t_, err := baml_go.Call(ctx, ");
        } else {
            let _ = writeln!(out, "\t\tvar zero {}", go_type(&function.return_type));
            out.push_str("\t\treturn zero, err\n\t}\n");
            out.push_str("\tresult, err := baml_go.Call(ctx, ");
        }
        let _ = write!(out, "{:?}, map[string]baml_go.Input{{", name.to_string());
        if !function.arguments.is_empty() {
            out.push('\n');
            for arg in &function.arguments {
                let local = safe_go_local(arg.name.as_str());
                let _ = writeln!(
                    out,
                    "\t\t{:?}: baml_go.{}({local}),",
                    arg.name.as_str(),
                    input_constructor(&arg.ty)
                );
            }
            out.push('\t');
        }
        out.push_str("})\n");
        if matches!(function.return_type, Ty::Unit) {
            out.push_str("\treturn err\n");
        } else {
            out.push_str("\tif err != nil {\n");
            let _ = writeln!(out, "\t\tvar zero {}", go_type(&function.return_type));
            out.push_str("\t\treturn zero, err\n\t}\n");
            let _ = writeln!(
                out,
                "\treturn result.{}()",
                output_method(&function.return_type)
            );
        }
        out.push_str("}\n");
    }

    out
}

fn render_bootstrap(bytecode: &[u8]) -> String {
    let mut out = String::from(BANNER);
    out.push_str("package bootstrap\n\n");
    out.push_str("import (\n\t\"sync\"\n\n");
    out.push_str("\t\"github.com/boundaryml/baml/sdks/go/baml_go\"\n)\n\n");
    out.push_str("var (\n\tonce          sync.Once\n\tinitializeErr error\n)\n\n");
    out.push_str("var bytecode = []byte{\n");
    for chunk in bytecode.chunks(20) {
        let line = chunk
            .iter()
            .map(u8::to_string)
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "\t{line},");
    }
    out.push_str("}\n\n");
    out.push_str("func Ensure() error {\n");
    out.push_str("\tonce.Do(func() { initializeErr = baml_go.Initialize(bytecode) })\n");
    out.push_str("\treturn initializeErr\n}\n");
    out
}

fn go_callable_name(name: &baml_codegen_types::Name) -> String {
    name.namespace_path
        .iter()
        .map(|segment| go_exported(segment.as_str()))
        .chain(std::iter::once(go_exported(name.name.as_str())))
        .collect()
}

fn go_exported(value: &str) -> String {
    value
        .split(|ch: char| !ch.is_ascii_alphanumeric())
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn safe_go_local(value: &str) -> String {
    match value {
        "break" | "default" | "func" | "interface" | "select" | "case" | "defer" | "go" | "map"
        | "struct" | "chan" | "else" | "goto" | "package" | "switch" | "const" | "fallthrough"
        | "if" | "range" | "type" | "continue" | "for" | "import" | "return" | "var" => {
            format!("{value}_")
        }
        _ => value.to_string(),
    }
}

fn go_type(ty: &Ty) -> &'static str {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => "string",
        PrimitiveKind::Int => "int64",
        PrimitiveKind::Bigint => "*big.Int",
        PrimitiveKind::Float => "float64",
        PrimitiveKind::Bool => "bool",
        PrimitiveKind::Null => "baml_go.Null",
        PrimitiveKind::Uint8Array => "[]byte",
    }
}

fn input_constructor(ty: &Ty) -> &'static str {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => "String",
        PrimitiveKind::Int => "Int64",
        PrimitiveKind::Bigint => "BigInt",
        PrimitiveKind::Float => "Float64",
        PrimitiveKind::Bool => "Bool",
        PrimitiveKind::Null => "NullInput",
        PrimitiveKind::Uint8Array => "Uint8Array",
    }
}

fn output_method(ty: &Ty) -> &'static str {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => "String",
        PrimitiveKind::Int => "Int64",
        PrimitiveKind::Bigint => "BigInt",
        PrimitiveKind::Float => "Float64",
        PrimitiveKind::Bool => "Bool",
        PrimitiveKind::Null => "Null",
        PrimitiveKind::Uint8Array => "Uint8Array",
    }
}

#[cfg(test)]
mod tests {
    use baml_base::Name as BaseName;
    use baml_codegen_types::{FunctionArgument, Name, Origin};

    use super::*;

    fn origin() -> Origin {
        Origin {
            source_file_path: "main.baml".to_string(),
            span_start: 0,
        }
    }

    #[test]
    fn emits_context_scalar_call_and_bootstrap() {
        let name = Name::new(BaseName::new("user"), vec![], BaseName::new("echo_text"));
        let function = Function {
            name: BaseName::new("echo_text"),
            generic_params: vec![],
            docstring: None,
            arguments: vec![FunctionArgument {
                name: BaseName::new("value"),
                docstring: None,
                ty: Ty::String,
                default: None,
            }],
            return_type: Ty::String,
            throws: None,
            watchers: vec![],
            origin: origin(),
        };
        let pool = SymbolPool::from([(name, Symbol::Function(function))]);

        let files = to_source_code_with_bytecode(
            &pool,
            &[1, 2, 3],
            NamingConvention::Language,
            "example.com/project/baml_sdk",
        );
        let functions = &files[&PathBuf::from("functions.go")];
        assert!(
            functions.contains("func EchoText(ctx context.Context, value string) (string, error)")
        );
        assert!(functions.contains("\"user.echo_text\""));
        assert!(functions.contains("baml_go.String(value)"));
        assert!(
            files[&PathBuf::from("internal/bootstrap/bootstrap.go")]
                .contains("var bytecode = []byte{\n\t1, 2, 3,")
        );
    }

    #[test]
    fn flattens_namespace_into_exported_name() {
        let name = Name::new(
            BaseName::new("user"),
            vec![BaseName::new("billing"), BaseName::new("v2")],
            BaseName::new("lookup_invoice"),
        );
        assert_eq!(go_callable_name(&name), "BillingV2LookupInvoice");
    }

    #[test]
    fn maps_every_in_scope_primitive_and_literal_to_go() {
        let cases = [
            (Ty::Int, "int64"),
            (Ty::Bigint, "*big.Int"),
            (Ty::Float, "float64"),
            (Ty::String, "string"),
            (Ty::Bool, "bool"),
            (Ty::Null, "baml_go.Null"),
            (Ty::Uint8Array, "[]byte"),
            (Ty::Literal(Literal::Int(42)), "int64"),
            (Ty::Literal(Literal::Bigint(42.into())), "*big.Int"),
            (Ty::Literal(Literal::Float("3.14".to_string())), "float64"),
            (Ty::Literal(Literal::String("draft".to_string())), "string"),
            (Ty::Literal(Literal::Bool(true)), "bool"),
        ];

        for (ty, expected) in cases {
            assert_eq!(go_type(&ty), expected, "BAML type {ty}");
        }

        assert!(
            primitive_kind(&Ty::Media(baml_base::MediaKind::Image)).is_none(),
            "media is deliberately deferred to the resource-type stage"
        );
    }

    #[test]
    fn emits_void_as_error_only_and_imports_math_big_for_bigint() {
        let void_name = Name::new(BaseName::new("user"), vec![], BaseName::new("no_op"));
        let void_function = Function {
            name: BaseName::new("no_op"),
            generic_params: vec![],
            docstring: None,
            arguments: vec![],
            return_type: Ty::Unit,
            throws: None,
            watchers: vec![],
            origin: origin(),
        };
        let bigint_name = Name::new(
            BaseName::new("user"),
            vec![],
            BaseName::new("round_trip_bigint"),
        );
        let bigint_function = Function {
            name: BaseName::new("round_trip_bigint"),
            generic_params: vec![],
            docstring: None,
            arguments: vec![FunctionArgument {
                name: BaseName::new("value"),
                docstring: None,
                ty: Ty::Bigint,
                default: None,
            }],
            return_type: Ty::Bigint,
            throws: None,
            watchers: vec![],
            origin: origin(),
        };
        let pool = SymbolPool::from([
            (void_name, Symbol::Function(void_function)),
            (bigint_name, Symbol::Function(bigint_function)),
        ]);

        let files = to_source_code_with_bytecode(
            &pool,
            &[],
            NamingConvention::Language,
            "example.com/project/baml_sdk",
        );
        let functions = &files[&PathBuf::from("functions.go")];
        assert!(functions.contains("\n\t\"math/big\"\n"));
        assert!(functions.contains("func NoOp(ctx context.Context) error"));
        assert!(functions.contains(
            "func RoundTripBigint(ctx context.Context, value *big.Int) (*big.Int, error)"
        ));
    }
}
