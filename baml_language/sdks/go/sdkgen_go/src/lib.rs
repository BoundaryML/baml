fn try_to_source_code_with_bytecode_metadata_and_options(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    embedded_baml_toml: Option<&str>,
    options: &GoGenOptions<'_>,
) -> Result<HashMap<PathBuf, String>, GoGenerationError> {
    formatting::gofmt_generated_files(render_source_code_with_bytecode_and_options(
        pool,
        baml_bytecode,
        embedded_baml_toml,
        options,
    ))
}

fn render_source_code_with_bytecode_and_options(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    embedded_baml_toml: Option<&str>,
    options: &GoGenOptions<'_>,
) -> HashMap<PathBuf, String> {
    assert!(
        matches!(options.naming_convention, NamingConvention::Language),
        "sdkgen_go requires naming_convention = language"
    );

    let interface_tokens = public_interface_tokens(pool);
    let packages = GoPackages::for_pool_with_interfaces(pool, &interface_tokens);
    let projection = GoTypeProjection::new(pool, options.max_typed_union_arity);
    let names = GoNames::for_pool(pool, &packages, &projection, &interface_tokens);
    let root_import_path = packages
        .get(&BaseName::new("user"))
        .import_path(options.sdk_import_path);
    let renderable_classes = renderable_class_names(pool, &projection);
    let renderable_aliases = renderable_alias_names(pool, &renderable_classes, &projection);
    let wireable_classes = wireable_class_names(pool, &renderable_classes, &projection);
    let cyclic_edges = cyclic_class_edges(pool, &renderable_classes);
    let mut files = HashMap::from([(
        PathBuf::from("internal/bootstrap/bootstrap.go"),
        render_bootstrap(baml_bytecode, embedded_baml_toml),
    )]);
    files.insert(
        PathBuf::from("reflect/reflect.go"),
        render_reflect_facade(options.sdk_import_path),
    );

    for package in packages.iter() {
        let functions = generated_functions(pool, &names, package, &wireable_classes, &projection);
        let classes = generated_classes(pool, &names, package, &renderable_classes);
        let enums = generated_enums(pool, &names, package);
        let aliases = generated_aliases(pool, &names, package, &renderable_aliases);
        let typed_unions = projection
            .typed_unions_in(package.baml_name())
            .filter(|key| {
                key.members()
                    .iter()
                    .all(|member| supported_go_type(member, &renderable_classes))
            })
            .cloned()
            .collect::<Vec<_>>();
        let codecs = WireCodecs::for_functions(
            &functions,
            &classes,
            &typed_unions,
            pool,
            &projection,
            package.baml_name(),
        );
        if !functions.is_empty() || !codecs.is_empty() || package.baml_name().as_str() == "user" {
            files.insert(
                package.file("functions.go"),
                render_functions(
                    &functions,
                    &codecs,
                    &FunctionRenderContext {
                        current_baml_package: package.baml_name(),
                        current_package: package.go_name(),
                        pool,
                        names: &names,
                        packages: &packages,
                        sdk_import_path: &root_import_path,
                        projection: &projection,
                    },
                ),
            );
        }
        if !aliases.is_empty()
            || !classes.is_empty()
            || !enums.is_empty()
            || !typed_unions.is_empty()
        {
            files.insert(
                package.file("types.go"),
                render_types(
                    &aliases,
                    &enums,
                    &classes,
                    &typed_unions,
                    &TypeRenderContext {
                        current_baml_package: package.baml_name(),
                        current_package: package.go_name(),
                        pool,
                        names: &names,
                        packages: &packages,
                        cyclic_edges: &cyclic_edges,
                        sdk_import_path: options.sdk_import_path,
                        projection: &projection,
                        codecs: &codecs,
                    },
                ),
            );
        }
        let package_interface_tokens = interface_tokens
            .iter()
            .filter(|name| name.package() == package.baml_name())
            .cloned()
            .collect::<Vec<_>>();
        if !package_interface_tokens.is_empty() {
            files.insert(
                package.file("interface_tokens.go"),
                render_interface_tokens(&package_interface_tokens, &names, package.go_name()),
            );
        }
    }
    files
}

fn render_interface_tokens(
    tokens: &[Name],
    names: &GoNames,
    current_package: &GoPackageName,
) -> String {
    let mut out = format!("{BANNER}package {}\n\n", current_package.as_str());
    out.push_str("import baml_go \"github.com/boundaryml/baml-go\"\n");
    for token in tokens {
        let projected = names.project(
            &BamlFqn::symbol(token),
            GoNameKind::InterfaceToken,
            GoVisibility::Exported,
        );
        let _ = writeln!(
            out,
            "\n// {} is the erased runtime token for BAML interface `{}`.\nvar {} = baml_go.InterfaceBAMLType({:?})",
            projected.identifier(current_package),
            token.render_dotted(false),
            projected.identifier(current_package),
            token.render_dotted(false),
        );
    }
    out
}

fn render_reflect_facade(sdk_import_path: &str) -> String {
    let source = r#"// Code generated by BAML. DO NOT EDIT.

package reflect

import (
	"context"

	baml_go "github.com/boundaryml/baml-go"
	"__SDK_IMPORT__/internal/bootstrap"
)

// Type is the opaque host representation of a first-class BAML type.
type Type = baml_go.BAMLType
type Metadata = baml_go.BAMLTypeMetadata
type MetadataOption = baml_go.MetadataOption
type Diagnostic = baml_go.Diagnostic
type CompilationError = baml_go.CompilationError
type EvaluationError = baml_go.EvaluationError
type SessionBusy = baml_go.SessionBusy

func WithAlias(value string) MetadataOption { return baml_go.WithAlias(value) }
func WithDescription(value string) MetadataOption { return baml_go.WithDescription(value) }
func WithDocstring(value string) MetadataOption { return baml_go.WithDocstring(value) }
func WithOther(value map[string]string) MetadataOption { return baml_go.WithOther(value) }

// Field is one ordered runtime-class field.
type Field struct {
	Name string
	Metadata Metadata
}

func NewField(name string, ty Type, options ...MetadataOption) Field {
	return Field{Name: name, Metadata: ty.Meta(options...)}
}

// NewMetadataField accepts a row previously produced by Type.Meta.
func NewMetadataField(name string, metadata Metadata) Field {
	return Field{Name: name, Metadata: metadata}
}

// EnumValue is one ordered runtime-enum row.
type EnumValue struct {
	Name string
	Metadata Metadata
}

func NewEnumValue(name string, options ...MetadataOption) EnumValue {
	metadata := baml_go.PrimitiveBAMLType(baml_go.StringType).Meta(options...)
	return EnumValue{Name: name, Metadata: metadata}
}

// TypeOf converts a supported Go token to an opaque portable definition.
func TypeOf[T any]() Type { return baml_go.DefinitionOf[T]() }

func metadataInput(metadata Metadata) baml_go.Input {
	return baml_go.Class("reflect.Meta", map[string]baml_go.Input{
		"alias": baml_go.OptionalEncoder(baml_go.String)(metadata.Alias),
		"description": baml_go.OptionalEncoder(baml_go.String)(metadata.Description),
		"docstring": baml_go.OptionalEncoder(baml_go.String)(metadata.Docstring),
		"other": baml_go.Map(metadata.Other, baml_go.String),
	})
}

func withMetadataInput(metadata Metadata) baml_go.Input {
	return baml_go.ClassWithTypeArgs(
		"reflect.WithMeta",
		[]baml_go.BAMLType{baml_go.MetaTypeBAMLType()},
		map[string]baml_go.Input{
			"ty": baml_go.Type(metadata.Type),
			"alias": baml_go.OptionalEncoder(baml_go.String)(metadata.Alias),
			"description": baml_go.OptionalEncoder(baml_go.String)(metadata.Description),
			"docstring": baml_go.OptionalEncoder(baml_go.String)(metadata.Docstring),
			"other": baml_go.Map(metadata.Other, baml_go.String),
		},
	)
}

func hasMetadata(metadata Metadata) bool {
	return metadata.Alias != nil || metadata.Description != nil || metadata.Docstring != nil || len(metadata.Other) != 0
}

// Class validates and constructs a closed runtime class. Slice order is BAML
// definition order; duplicate rows are intentionally preserved for diagnostics.
func Class(ctx context.Context, name string, fields []Field) (Type, error) {
	if err := bootstrap.Ensure(); err != nil { return Type{}, err }
	rows := make([]baml_go.NamedInput, len(fields))
	for index, field := range fields {
		value := baml_go.Type(field.Metadata.Type)
		if hasMetadata(field.Metadata) { value = withMetadataInput(field.Metadata) }
		rows[index] = baml_go.NamedInput{Name: field.Name, Value: value}
	}
	result, err := baml_go.Call(ctx, "reflect.class.new", map[string]baml_go.Input{
		"name": baml_go.String(name),
		"fields": baml_go.OrderedMap(rows),
	})
	if err != nil { return Type{}, err }
	return result.Type()
}

// Enum validates and constructs a closed runtime enum in slice order.
func Enum(ctx context.Context, name string, values []EnumValue) (Type, error) {
	if err := bootstrap.Ensure(); err != nil { return Type{}, err }
	rows := make([]baml_go.Input, len(values))
	for index, value := range values {
		rows[index] = baml_go.Class("reflect.enum.Value", map[string]baml_go.Input{
			"name": baml_go.String(value.Name),
			"meta": metadataInput(value.Metadata),
		})
	}
	result, err := baml_go.Call(ctx, "reflect.enum.new", map[string]baml_go.Input{
		"name": baml_go.String(name),
		"values": baml_go.List(rows, func(value baml_go.Input) baml_go.Input { return value }),
	})
	if err != nil { return Type{}, err }
	return result.Type()
}

// Package is an isolated runtime-compiled package. The context used for the
// compile is retained for its subsequent flat finder methods.
type Package struct {
	ctx context.Context
	inner baml_go.OpaqueHandle
}

func CompilePackage(ctx context.Context, files map[string]string) (*Package, error) {
	if err := bootstrap.Ensure(); err != nil { return nil, err }
	result, err := baml_go.Call(ctx, "reflect.Package.compile", map[string]baml_go.Input{
		"files": baml_go.Map(files, baml_go.String),
	})
	if err != nil { return nil, err }
	classValue, err := result.Class("reflect.Package")
	if err != nil { return nil, err }
	innerValue, err := classValue.Field("_inner")
	if err != nil { return nil, err }
	inner, err := innerValue.OpaqueHandle()
	if err != nil { return nil, err }
	return &Package{ctx: ctx, inner: inner}, nil
}

func (pkg *Package) input() baml_go.Input {
	return baml_go.Class("reflect.Package", map[string]baml_go.Input{
		"_inner": baml_go.OpaqueHandleInput(pkg.inner),
	})
}

func (pkg *Package) GetClass(name string) (*Type, error) {
	if pkg == nil { return nil, nil }
	result, err := baml_go.Call(pkg.ctx, "reflect.Package.get_class", map[string]baml_go.Input{
		"self": pkg.input(),
		"name": baml_go.String(name),
	})
	if err != nil { return nil, err }
	isNull, err := result.IsNull()
	if err != nil { return nil, err }
	if isNull { return nil, nil }
	ty, err := result.Type()
	if err != nil { return nil, err }
	return &ty, nil
}
"#;
    source.replace("__SDK_IMPORT__", sdk_import_path)
}

