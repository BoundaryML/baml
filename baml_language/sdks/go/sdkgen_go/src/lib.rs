fn generated_functions<'a>(
    pool: &'a SymbolPool,
    names: &GoNames,
    package: &GoPackage,
    wireable_classes: &BTreeSet<Name>,
    projection: &GoTypeProjection<'_>,
) -> Vec<GeneratedFunction<'a>> {
    let mut functions = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Function(function)
                if name.package() == package.baml_name()
                    && supported_function(function, pool, wireable_classes, projection) =>
            {
                Some((name, function))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    functions.sort_by_key(|(name, _)| *name);
    let mut generated = functions
        .into_iter()
        .map(|(name, function)| {
            let fqn = BamlFqn::symbol(name);
            GeneratedFunction {
                function,
                fqn: fqn.clone(),
                owner_name: None,
                owner_type_parameters: vec![],
                receiver: None,
                method_syntax: false,
                method_helper: false,
                go_name: names
                    .project(&fqn, GoNameKind::Function, GoVisibility::Exported)
                    .clone(),
                option_type: (function
                    .arguments
                    .iter()
                    .any(|argument| argument.default.is_some())
                    || !function.generic_params.is_empty())
                .then(|| {
                    names
                        .project(&fqn, GoNameKind::FunctionOptionType, GoVisibility::Exported)
                        .clone()
                }),
                arguments: function
                    .arguments
                    .iter()
                    .map(|argument| GeneratedArgument {
                        argument,
                        go_name: names
                            .project(
                                &fqn.member(&argument.name),
                                GoNameKind::Parameter,
                                GoVisibility::Exported,
                            )
                            .clone(),
                        option_setter: argument.default.as_ref().map(|_| {
                            names
                                .project(
                                    &fqn.member(&argument.name),
                                    GoNameKind::FunctionOptionSetter,
                                    GoVisibility::Exported,
                                )
                                .clone()
                        }),
                    })
                    .collect(),
            }
        })
        .collect::<Vec<_>>();

    let mut classes = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Class(class)
                if name.package() == package.baml_name()
                    // Stdlib classes use native/handle codecs rather than the
                    // ordinary field codecs used by user-authored classes.
                    && name.package().as_str() == RESERVED_USER_PACKAGE =>
            {
                Some((name, class))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    classes.sort_by_key(|(name, _)| *name);
    for (owner_name, class) in classes {
        let mut methods = class
            .instance_methods
            .iter()
            .filter(|method| {
                wireable_classes.contains(owner_name)
                    && supported_function(method, pool, wireable_classes, projection)
                    && !method.arguments.iter().any(|argument| {
                        argument.default.is_some()
                            && projected_contains_type_var(&projection.project(&argument.ty))
                    })
            })
            .collect::<Vec<_>>();
        methods.sort_by(|left, right| {
            left.name
                .cmp(&right.name)
                .then_with(|| left.origin.span_start.cmp(&right.origin.span_start))
        });
        let class_fqn = BamlFqn::symbol(owner_name);
        for method in methods {
            let method_fqn = class_fqn.member(&method.name);
            generated.push(GeneratedFunction {
                function: method,
                fqn: method_fqn.clone(),
                owner_name: Some(owner_name),
                owner_type_parameters: class.generic_params.iter().collect(),
                receiver: Some(GeneratedReceiver {
                    owner_name,
                    class,
                    go_name: names
                        .project(&class_fqn, GoNameKind::Class, GoVisibility::Exported)
                        .clone(),
                }),
                method_syntax: method.generic_params.is_empty(),
                method_helper: !method.generic_params.is_empty(),
                go_name: names
                    .project(
                        &method_fqn,
                        if method.generic_params.is_empty() {
                            GoNameKind::Method
                        } else {
                            GoNameKind::MethodHelper
                        },
                        GoVisibility::Exported,
                    )
                    .clone(),
                option_type: (method
                    .arguments
                    .iter()
                    .any(|argument| argument.default.is_some())
                    || !class.generic_params.is_empty()
                    || !method.generic_params.is_empty())
                .then(|| {
                    names
                        .project(
                            &method_fqn,
                            GoNameKind::MethodOptionType,
                            GoVisibility::Exported,
                        )
                        .clone()
                }),
                arguments: method
                    .arguments
                    .iter()
                    .map(|argument| GeneratedArgument {
                        argument,
                        go_name: names
                            .project(
                                &method_fqn.member(&argument.name),
                                GoNameKind::Parameter,
                                GoVisibility::Exported,
                            )
                            .clone(),
                        option_setter: argument.default.as_ref().map(|_| {
                            names
                                .project(
                                    &method_fqn.member(&argument.name),
                                    GoNameKind::MethodOptionSetter,
                                    GoVisibility::Exported,
                                )
                                .clone()
                        }),
                    })
                    .collect(),
            });
        }

        let mut static_methods = class
            .static_methods
            .iter()
            .filter(|method| {
                supported_function(method, pool, wireable_classes, projection)
                    && !method.arguments.iter().any(|argument| {
                        argument.default.is_some()
                            && projected_contains_type_var(&projection.project(&argument.ty))
                    })
            })
            .collect::<Vec<_>>();
        static_methods.sort_by(|left, right| {
            left.name
                .cmp(&right.name)
                .then_with(|| left.origin.span_start.cmp(&right.origin.span_start))
        });
        for method in static_methods {
            let method_fqn = class_fqn.member(&method.name);
            let owner_type_parameters = class
                .generic_params
                .iter()
                .filter(|parameter| method_references_type_var(method, parameter, projection))
                .collect();
            generated.push(GeneratedFunction {
                function: method,
                fqn: method_fqn.clone(),
                owner_name: Some(owner_name),
                owner_type_parameters,
                receiver: None,
                method_syntax: false,
                method_helper: true,
                go_name: names
                    .project(
                        &method_fqn,
                        GoNameKind::MethodHelper,
                        GoVisibility::Exported,
                    )
                    .clone(),
                option_type: (method
                    .arguments
                    .iter()
                    .any(|argument| argument.default.is_some())
                    || !class.generic_params.is_empty()
                    || !method.generic_params.is_empty())
                .then(|| {
                    names
                        .project(
                            &method_fqn,
                            GoNameKind::MethodOptionType,
                            GoVisibility::Exported,
                        )
                        .clone()
                }),
                arguments: method
                    .arguments
                    .iter()
                    .map(|argument| GeneratedArgument {
                        argument,
                        go_name: names
                            .project(
                                &method_fqn.member(&argument.name),
                                GoNameKind::Parameter,
                                GoVisibility::Exported,
                            )
                            .clone(),
                        option_setter: argument.default.as_ref().map(|_| {
                            names
                                .project(
                                    &method_fqn.member(&argument.name),
                                    GoNameKind::MethodOptionSetter,
                                    GoVisibility::Exported,
                                )
                                .clone()
                        }),
                    })
                    .collect(),
            });
        }
    }
    generated
}

