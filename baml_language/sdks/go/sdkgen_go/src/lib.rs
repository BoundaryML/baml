//! Greenfield Go SDK emitter.
//!
//! The current vertical slice covers primitive free functions, class-typed
//! functions whose class graphs contain primitives and required acyclic class
//! references, and non-generic class declarations composed from primitives,
//! class references, and nullable variants of those types. A BAML package
//! becomes one Go package. BAML namespaces stay within that Go package and
//! qualify exported identifiers, preserving legal cyclic references between
//! namespaces.

use std::{
    collections::{BTreeMap, BTreeSet, HashMap, HashSet},
    fmt::Write as _,
    path::PathBuf,
};

use baml_base::{Literal, Name as BaseName};
use baml_codegen_types::{
    Class, ClassProperty, Function, FunctionArgument, Name, NamingConvention, Symbol, SymbolPool,
    Ty,
};

mod names;
mod packages;
mod rendering;

use names::{BamlFqn, GoName, GoNameKind, GoNames, GoPackageName, GoVisibility};
use packages::{GoPackage, GoPackages};
use rendering::{GeneratorIdent, GoImports};

const BANNER: &str = "// Code generated by BAML. DO NOT EDIT.\n\n";

/// Generate files relative to a project's `baml_sdk/` directory.
pub fn to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
    sdk_import_path: &str,
) -> HashMap<PathBuf, String> {
    assert!(
        matches!(naming_convention, NamingConvention::Language),
        "sdkgen_go requires naming_convention = language"
    );

    let packages = GoPackages::for_pool(pool);
    let names = GoNames::for_pool(pool, &packages);
    let root_import_path = packages
        .get(&BaseName::new("user"))
        .import_path(sdk_import_path);
    let renderable_classes = renderable_class_names(pool);
    let wireable_classes = wireable_class_names(pool);
    let cyclic_edges = cyclic_class_edges(pool, &renderable_classes);
    let mut files = HashMap::from([(
        PathBuf::from("internal/bootstrap/bootstrap.go"),
        render_bootstrap(baml_bytecode),
    )]);

    for package in packages.iter() {
        let functions = generated_functions(pool, &names, package, &wireable_classes);
        let classes = generated_classes(pool, &names, package, &renderable_classes);
        if !functions.is_empty() || package.baml_name().as_str() == "user" {
            files.insert(
                package.file("functions.go"),
                render_functions(
                    &functions,
                    package.go_name(),
                    pool,
                    &names,
                    &packages,
                    &root_import_path,
                ),
            );
        }
        if !classes.is_empty() {
            files.insert(
                package.file("types.go"),
                render_classes(
                    &classes,
                    package.go_name(),
                    &names,
                    &packages,
                    &cyclic_edges,
                    sdk_import_path,
                ),
            );
        }
    }
    files
}

fn generated_functions<'a>(
    pool: &'a SymbolPool,
    names: &GoNames,
    package: &GoPackage,
    wireable_classes: &BTreeSet<Name>,
) -> Vec<GeneratedFunction<'a>> {
    let mut functions = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Function(function)
                if name.pkg == *package.baml_name()
                    && supported_function(function, wireable_classes) =>
            {
                Some((name, function))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    functions.sort_by(|(left, _), (right, _)| left.cmp(right));
    functions
        .into_iter()
        .map(|(name, function)| {
            let fqn = BamlFqn::symbol(name);
            GeneratedFunction {
                function,
                go_name: names
                    .project(&fqn, GoNameKind::Function, GoVisibility::Exported)
                    .clone(),
                arguments: function
                    .arguments
                    .iter()
                    .map(|argument| GeneratedArgument {
                        argument,
                        go_name: names
                            .project(
                                &fqn.member(&argument.name),
                                GoNameKind::Parameter,
                                GoVisibility::Exported,
                            )
                            .clone(),
                    })
                    .collect(),
            }
        })
        .collect()
}

struct GeneratedFunction<'a> {
    function: &'a Function,
    go_name: GoName,
    arguments: Vec<GeneratedArgument<'a>>,
}

struct GeneratedArgument<'a> {
    argument: &'a FunctionArgument,
    go_name: GoName,
}

struct GeneratedClass<'a> {
    name: &'a Name,
    class: &'a Class,
    go_name: GoName,
    fields: Vec<GeneratedField<'a>>,
}

struct GeneratedField<'a> {
    property: &'a ClassProperty,
    go_name: GoName,
}

fn generated_classes<'a>(
    pool: &'a SymbolPool,
    names: &GoNames,
    package: &GoPackage,
    renderable: &BTreeSet<Name>,
) -> Vec<GeneratedClass<'a>> {
    let mut classes = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Class(class)
                if name.pkg == *package.baml_name() && renderable.contains(name) =>
            {
                Some((name, class))
            }
            _ => None,
        })
        .collect::<Vec<_>>();
    classes.sort_by(|(left, _), (right, _)| left.cmp(right));
    classes
        .into_iter()
        .map(|(name, class)| {
            let fqn = BamlFqn::symbol(name);
            GeneratedClass {
                name,
                class,
                go_name: names
                    .project(&fqn, GoNameKind::Class, GoVisibility::Exported)
                    .clone(),
                fields: class
                    .properties
                    .iter()
                    .map(|property| GeneratedField {
                        property,
                        go_name: names
                            .project(
                                &fqn.member(&property.name),
                                GoNameKind::Field,
                                GoVisibility::Exported,
                            )
                            .clone(),
                    })
                    .collect(),
            }
        })
        .collect()
}

fn renderable_class_names(pool: &SymbolPool) -> BTreeSet<Name> {
    let mut candidates = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Class(class) if class.generic_params.is_empty() => Some(name.clone()),
            _ => None,
        })
        .collect::<BTreeSet<_>>();

    loop {
        let next = candidates
            .iter()
            .filter(|name| {
                let Symbol::Class(class) = &pool[*name] else {
                    unreachable!()
                };
                class
                    .properties
                    .iter()
                    .all(|property| supported_class_type(&property.ty, &candidates))
            })
            .cloned()
            .collect::<BTreeSet<_>>();
        if next == candidates {
            return candidates;
        }
        candidates = next;
    }
}

fn supported_class_type(ty: &Ty, classes: &BTreeSet<Name>) -> bool {
    if primitive_kind(ty).is_some() {
        return true;
    }
    match ty {
        Ty::Class(name, arguments) => arguments.is_empty() && classes.contains(name),
        Ty::Union(items) => {
            nullable_inner(items).is_some_and(|inner| supported_class_type(inner, classes))
        }
        _ => false,
    }
}

/// Classes crossing the runtime boundary are intentionally narrower than the
/// classes whose declarations can be rendered. Starting from primitive-only
/// classes and growing a fixed point admits required acyclic nesting while
/// naturally excluding nullable fields and recursive class graphs.
fn wireable_class_names(pool: &SymbolPool) -> BTreeSet<Name> {
    let candidates = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::Class(class) if class.generic_params.is_empty() => Some(name.clone()),
            _ => None,
        })
        .collect::<BTreeSet<_>>();
    let mut wireable = BTreeSet::new();
    loop {
        let previous_len = wireable.len();
        for name in &candidates {
            let Symbol::Class(class) = &pool[name] else {
                unreachable!()
            };
            if class.properties.iter().all(|property| {
                primitive_kind(&property.ty).is_some()
                    || matches!(
                        &property.ty,
                        Ty::Class(target, arguments)
                            if arguments.is_empty() && wireable.contains(target)
                    )
            }) {
                wireable.insert(name.clone());
            }
        }
        if wireable.len() == previous_len {
            return wireable;
        }
    }
}

fn nullable_inner(items: &[Ty]) -> Option<&Ty> {
    if items.len() != 2 || items.iter().filter(|item| matches!(item, Ty::Null)).count() != 1 {
        return None;
    }
    items.iter().find(|item| !matches!(item, Ty::Null))
}

fn cyclic_class_edges(pool: &SymbolPool, classes: &BTreeSet<Name>) -> BTreeSet<(Name, Name)> {
    let graph = classes
        .iter()
        .map(|name| {
            let Symbol::Class(class) = &pool[name] else {
                unreachable!()
            };
            let targets = class
                .properties
                .iter()
                .filter_map(|property| match &property.ty {
                    Ty::Class(target, arguments)
                        if arguments.is_empty() && classes.contains(target) =>
                    {
                        Some(target.clone())
                    }
                    _ => None,
                })
                .collect::<BTreeSet<_>>();
            (name.clone(), targets)
        })
        .collect::<BTreeMap<_, _>>();

    graph
        .iter()
        .flat_map(|(source, targets)| {
            targets
                .iter()
                .filter(|target| reaches_class(target, source, &graph, &mut HashSet::new()))
                .map(|target| (source.clone(), target.clone()))
        })
        .collect()
}

fn reaches_class(
    current: &Name,
    target: &Name,
    graph: &BTreeMap<Name, BTreeSet<Name>>,
    visited: &mut HashSet<Name>,
) -> bool {
    if current == target {
        return true;
    }
    if !visited.insert(current.clone()) {
        return false;
    }
    graph.get(current).is_some_and(|next| {
        next.iter()
            .any(|name| reaches_class(name, target, graph, visited))
    })
}

fn supported_function(function: &Function, wireable_classes: &BTreeSet<Name>) -> bool {
    function.generic_params.is_empty()
        && function
            .arguments
            .iter()
            .all(|arg| arg.default.is_none() && supported_wire_type(&arg.ty, wireable_classes))
        && (supported_wire_type(&function.return_type, wireable_classes)
            || matches!(function.return_type, Ty::Unit))
}

fn supported_wire_type(ty: &Ty, wireable_classes: &BTreeSet<Name>) -> bool {
    primitive_kind(ty).is_some()
        || matches!(ty, Ty::Class(name, arguments) if arguments.is_empty() && wireable_classes.contains(name))
}

#[derive(Clone, Copy)]
enum PrimitiveKind {
    String,
    Int,
    Bigint,
    Float,
    Bool,
    Null,
    Uint8Array,
}

fn primitive_kind(ty: &Ty) -> Option<PrimitiveKind> {
    match ty {
        Ty::String => Some(PrimitiveKind::String),
        Ty::Int => Some(PrimitiveKind::Int),
        Ty::Bigint => Some(PrimitiveKind::Bigint),
        Ty::Float => Some(PrimitiveKind::Float),
        Ty::Bool => Some(PrimitiveKind::Bool),
        Ty::Null => Some(PrimitiveKind::Null),
        Ty::Uint8Array => Some(PrimitiveKind::Uint8Array),
        Ty::Literal(literal) => match literal {
            Literal::String(_) => Some(PrimitiveKind::String),
            Literal::Int(_) => Some(PrimitiveKind::Int),
            Literal::Bigint(_) => Some(PrimitiveKind::Bigint),
            Literal::Float(_) => Some(PrimitiveKind::Float),
            Literal::Bool(_) => Some(PrimitiveKind::Bool),
        },
        _ => None,
    }
}

fn render_functions(
    functions: &[GeneratedFunction<'_>],
    current_package: &GoPackageName,
    pool: &SymbolPool,
    names: &GoNames,
    packages: &GoPackages,
    sdk_import_path: &str,
) -> String {
    let context_package = GeneratorIdent::ContextPackage;
    let bootstrap_package = GeneratorIdent::BootstrapPackage;
    let runtime_package = GeneratorIdent::RuntimePackage;
    let context_parameter = GeneratorIdent::ContextParameter;
    let error_local = GeneratorIdent::ErrorLocal;
    let result_local = GeneratorIdent::ResultLocal;
    let zero_local = GeneratorIdent::ZeroLocal;
    let string_type = GeneratorIdent::StringType;
    let error_type = GeneratorIdent::ErrorType;
    let mut out = String::from(BANNER);
    let _ = writeln!(out, "package {}\n", current_package.as_str());
    if functions.is_empty() {
        return out;
    }
    let mut imports = GoImports::default();
    imports.add_generator(context_package, "context");
    if functions.iter().any(|routed| {
        let function = routed.function;
        primitive_kind(&function.return_type)
            .is_some_and(|kind| matches!(kind, PrimitiveKind::Bigint))
            || function.arguments.iter().any(|argument| {
                primitive_kind(&argument.ty)
                    .is_some_and(|kind| matches!(kind, PrimitiveKind::Bigint))
            })
    }) {
        imports.add_generator(GeneratorIdent::BigPackage, "math/big");
    }
    imports.add_generator(
        bootstrap_package,
        &format!("{sdk_import_path}/internal/bootstrap"),
    );
    imports.add_generator(
        runtime_package,
        "github.com/boundaryml/baml/sdks/go/baml_go",
    );
    let mut visited_class_imports = HashSet::new();
    for routed in functions {
        for ty in routed
            .function
            .arguments
            .iter()
            .map(|argument| &argument.ty)
            .chain(std::iter::once(&routed.function.return_type))
        {
            add_wire_type_imports(
                ty,
                current_package,
                pool,
                packages,
                sdk_import_path,
                &mut imports,
                &mut visited_class_imports,
            );
        }
    }
    out.push_str(&imports.render());

    for routed in functions {
        let function = routed.function;
        let go_name = routed.go_name.identifier(current_package);
        let args = routed
            .arguments
            .iter()
            .map(|argument| {
                format!(
                    "{} {}",
                    argument.go_name.identifier(current_package),
                    function_go_type(&argument.argument.ty, current_package, names)
                )
            })
            .collect::<Vec<_>>();
        let mut params = vec![format!("{context_parameter} {context_package}.Context")];
        params.extend(args);

        if matches!(function.return_type, Ty::Unit) {
            let _ = writeln!(
                out,
                "\nfunc {go_name}({}) {error_type} {{",
                params.join(", ")
            );
        } else {
            let _ = writeln!(
                out,
                "\nfunc {go_name}({}) ({}, {error_type}) {{",
                params.join(", "),
                function_go_type(&function.return_type, current_package, names)
            );
        }
        let _ = writeln!(
            out,
            "\tif {error_local} := {bootstrap_package}.Ensure(); {error_local} != nil {{"
        );
        if matches!(function.return_type, Ty::Unit) {
            let _ = writeln!(out, "\t\treturn {error_local}\n\t}}");
            let _ = write!(
                out,
                "\t_, {error_local} := {runtime_package}.Call({context_parameter}, "
            );
        } else {
            let _ = writeln!(
                out,
                "\t\tvar {zero_local} {}",
                function_go_type(&function.return_type, current_package, names)
            );
            let _ = writeln!(out, "\t\treturn {zero_local}, {error_local}\n\t}}");
            let _ = write!(
                out,
                "\t{result_local}, {error_local} := {runtime_package}.Call({context_parameter}, "
            );
        }
        let _ = write!(
            out,
            "{:?}, map[{string_type}]{runtime_package}.Input{{",
            routed.go_name.wire().to_string()
        );
        if !routed.arguments.is_empty() {
            out.push('\n');
            for argument in &routed.arguments {
                let argument_identifier = argument.go_name.identifier(current_package).to_string();
                let _ = writeln!(
                    out,
                    "\t\t{:?}: {},",
                    argument.go_name.wire().to_string(),
                    input_expression(
                        &argument.argument.ty,
                        &argument_identifier,
                        "\t\t",
                        pool,
                        names,
                        packages,
                    )
                );
            }
            out.push('\t');
        }
        out.push_str("})\n");
        if matches!(function.return_type, Ty::Unit) {
            let _ = writeln!(out, "\treturn {error_local}");
        } else {
            let _ = writeln!(out, "\tif {error_local} != nil {{");
            let _ = writeln!(
                out,
                "\t\tvar {zero_local} {}",
                function_go_type(&function.return_type, current_package, names)
            );
            let _ = writeln!(out, "\t\treturn {zero_local}, {error_local}\n\t}}");
            if primitive_kind(&function.return_type).is_some() {
                let _ = writeln!(
                    out,
                    "\treturn {result_local}.{}()",
                    output_method(&function.return_type)
                );
            } else {
                render_class_output(
                    &mut out,
                    &function.return_type,
                    current_package,
                    pool,
                    names,
                    packages,
                );
            }
        }
        out.push_str("}\n");
    }

    out
}

fn add_wire_type_imports(
    ty: &Ty,
    current_package: &GoPackageName,
    pool: &SymbolPool,
    packages: &GoPackages,
    sdk_import_path: &str,
    imports: &mut GoImports,
    visited: &mut HashSet<Name>,
) {
    if primitive_kind(ty).is_some() || matches!(ty, Ty::Unit) {
        return;
    }
    let Ty::Class(name, arguments) = ty else {
        unreachable!("function was filtered to supported wire types")
    };
    debug_assert!(arguments.is_empty());
    if !visited.insert(name.clone()) {
        return;
    }
    let target_package = packages.get(&name.pkg);
    if target_package.go_name() != current_package {
        imports.add_package(
            target_package.go_name(),
            &target_package.import_path(sdk_import_path),
        );
    }
    let Symbol::Class(class) = &pool[name] else {
        unreachable!("class type did not resolve to a class symbol")
    };
    for property in &class.properties {
        add_wire_type_imports(
            &property.ty,
            current_package,
            pool,
            packages,
            sdk_import_path,
            imports,
            visited,
        );
    }
}

fn function_go_type(ty: &Ty, current_package: &GoPackageName, names: &GoNames) -> String {
    if primitive_kind(ty).is_some() {
        return go_type(ty);
    }
    let Ty::Class(name, arguments) = ty else {
        unreachable!("function was filtered to supported wire types")
    };
    debug_assert!(arguments.is_empty());
    names
        .project(
            &BamlFqn::symbol(name),
            GoNameKind::Class,
            GoVisibility::Exported,
        )
        .identifier(current_package)
        .to_string()
}

fn input_expression(
    ty: &Ty,
    value: &str,
    indent: &str,
    pool: &SymbolPool,
    names: &GoNames,
    packages: &GoPackages,
) -> String {
    let runtime_package = GeneratorIdent::RuntimePackage;
    let string_type = GeneratorIdent::StringType;
    if primitive_kind(ty).is_some() {
        return format!("{runtime_package}.{}({value})", input_constructor(ty));
    }

    let Ty::Class(name, arguments) = ty else {
        unreachable!("function was filtered to supported wire types")
    };
    debug_assert!(arguments.is_empty());
    let Symbol::Class(class) = &pool[name] else {
        unreachable!("class type did not resolve to a class symbol")
    };
    let class_fqn = BamlFqn::symbol(name);
    let class_name = names.project(&class_fqn, GoNameKind::Class, GoVisibility::Exported);
    let owner_package = packages.get(&name.pkg).go_name();
    let mut out = format!(
        "{runtime_package}.Class({:?}, map[{string_type}]{runtime_package}.Input{{",
        class_name.wire().to_string()
    );
    if !class.properties.is_empty() {
        out.push('\n');
        for property in &class.properties {
            let field = names.project(
                &class_fqn.member(&property.name),
                GoNameKind::Field,
                GoVisibility::Exported,
            );
            let field_value = format!("{value}.{}", field.identifier(owner_package));
            let field_input = input_expression(
                &property.ty,
                &field_value,
                &format!("{indent}\t"),
                pool,
                names,
                packages,
            );
            let _ = writeln!(
                out,
                "{indent}\t{:?}: {field_input},",
                field.wire().to_string(),
            );
        }
        out.push_str(indent);
    }
    out.push_str("})");
    out
}

fn render_class_output(
    out: &mut String,
    ty: &Ty,
    current_package: &GoPackageName,
    pool: &SymbolPool,
    names: &GoNames,
    packages: &GoPackages,
) {
    let result_local = GeneratorIdent::ResultLocal;
    let Ty::Class(name, arguments) = ty else {
        unreachable!("function was filtered to supported class output")
    };
    debug_assert!(arguments.is_empty());
    let class_name = names.project(
        &BamlFqn::symbol(name),
        GoNameKind::Class,
        GoVisibility::Exported,
    );
    let source = format!("{result_local}.Class({:?})", class_name.wire().to_string());
    let expression =
        class_output_expression(ty, &source, "\t", current_package, pool, names, packages);
    let _ = writeln!(out, "\treturn {expression}");
}

/// Render a decoder expression whose source returns `(baml_go.ClassValue,
/// error)`. Nested class fields recursively use the same shape, so each level
/// owns its fixed locals and user field names only ever appear as selectors.
fn class_output_expression(
    ty: &Ty,
    source: &str,
    indent: &str,
    current_package: &GoPackageName,
    pool: &SymbolPool,
    names: &GoNames,
    packages: &GoPackages,
) -> String {
    let runtime_package = GeneratorIdent::RuntimePackage;
    let error_type = GeneratorIdent::ErrorType;
    let error_local = GeneratorIdent::ErrorLocal;
    let zero_local = GeneratorIdent::ZeroLocal;
    let class_value_local = GeneratorIdent::ClassValueLocal;
    let decoded_local = GeneratorIdent::DecodedLocal;
    let Ty::Class(name, arguments) = ty else {
        unreachable!("function was filtered to supported class output")
    };
    debug_assert!(arguments.is_empty());
    let Symbol::Class(class) = &pool[name] else {
        unreachable!("class type did not resolve to a class symbol")
    };
    let class_fqn = BamlFqn::symbol(name);
    let go_type = function_go_type(ty, current_package, names);
    let owner_package = packages.get(&name.pkg).go_name();
    let mut out = format!(
        "func({class_value_local} {runtime_package}.ClassValue, {error_local} {error_type}) ({go_type}, {error_type}) {{\n"
    );
    let _ = writeln!(out, "{indent}\tif {error_local} != nil {{");
    let _ = writeln!(out, "{indent}\t\tvar {zero_local} {go_type}");
    let _ = writeln!(
        out,
        "{indent}\t\treturn {zero_local}, {error_local}\n{indent}\t}}"
    );
    let _ = writeln!(out, "{indent}\tvar {decoded_local} {go_type}");

    for property in &class.properties {
        let field = names.project(
            &class_fqn.member(&property.name),
            GoNameKind::Field,
            GoVisibility::Exported,
        );
        let field_identifier = field.identifier(owner_package);
        if primitive_kind(&property.ty).is_some() {
            let _ = writeln!(
                out,
                "{indent}\t{decoded_local}.{field_identifier}, {error_local} = {class_value_local}.{}({:?})",
                output_method(&property.ty),
                field.wire().to_string(),
            );
        } else {
            let Ty::Class(target, arguments) = &property.ty else {
                unreachable!("wireable class field was not primitive or class")
            };
            debug_assert!(arguments.is_empty());
            let target_name = names.project(
                &BamlFqn::symbol(target),
                GoNameKind::Class,
                GoVisibility::Exported,
            );
            let nested_source = format!(
                "{class_value_local}.Class({:?}, {:?})",
                field.wire().to_string(),
                target_name.wire().to_string(),
            );
            let nested = class_output_expression(
                &property.ty,
                &nested_source,
                &format!("{indent}\t"),
                current_package,
                pool,
                names,
                packages,
            );
            let _ = writeln!(
                out,
                "{indent}\t{decoded_local}.{field_identifier}, {error_local} = {nested}"
            );
        }
        let _ = writeln!(out, "{indent}\tif {error_local} != nil {{");
        let _ = writeln!(out, "{indent}\t\tvar {zero_local} {go_type}");
        let _ = writeln!(
            out,
            "{indent}\t\treturn {zero_local}, {error_local}\n{indent}\t}}"
        );
    }

    let _ = write!(
        out,
        "{indent}\treturn {decoded_local}, nil\n{indent}}}({source})"
    );
    out
}

fn render_classes(
    classes: &[GeneratedClass<'_>],
    current_package: &GoPackageName,
    names: &GoNames,
    packages: &GoPackages,
    cyclic_edges: &BTreeSet<(Name, Name)>,
    sdk_import_path: &str,
) -> String {
    let mut type_renderer = ClassTypeRenderer {
        current_package,
        names,
        packages,
        cyclic_edges,
        sdk_import_path,
        imports: GoImports::default(),
    };
    let mut body = String::new();
    for generated in classes {
        debug_assert_eq!(generated.name, &generated.class.name);
        let class_name = generated.go_name.identifier(current_package);
        let _ = writeln!(body, "type {class_name} struct {{");
        for field in &generated.fields {
            let field_name = field.go_name.identifier(current_package);
            let field_type = type_renderer
                .render(&field.property.ty, generated.name, false)
                .expect("class was filtered to supported field types");
            let wire_name = field.go_name.wire().to_string();
            let _ = writeln!(body, "\t{field_name} {field_type} `json:{wire_name:?}`");
        }
        body.push_str("}\n\n");
    }

    let mut out = String::from(BANNER);
    let _ = writeln!(out, "package {}\n", current_package.as_str());
    out.push_str(&type_renderer.imports.render());
    out.push_str(&body);
    out
}

struct ClassTypeRenderer<'a> {
    current_package: &'a GoPackageName,
    names: &'a GoNames,
    packages: &'a GoPackages,
    cyclic_edges: &'a BTreeSet<(Name, Name)>,
    sdk_import_path: &'a str,
    imports: GoImports,
}

impl ClassTypeRenderer<'_> {
    fn render(&mut self, ty: &Ty, owner: &Name, optional: bool) -> Option<String> {
        if let Some(kind) = primitive_kind(ty) {
            match kind {
                PrimitiveKind::Bigint => {
                    self.imports
                        .add_generator(GeneratorIdent::BigPackage, "math/big");
                }
                PrimitiveKind::Null => {
                    self.imports.add_generator(
                        GeneratorIdent::RuntimePackage,
                        "github.com/boundaryml/baml/sdks/go/baml_go",
                    );
                }
                _ => {}
            }
            let rendered = go_type(ty);
            return Some(if optional {
                format!("*{rendered}")
            } else {
                rendered
            });
        }

        match ty {
            Ty::Class(target, arguments) if arguments.is_empty() => {
                let target_package = self.packages.get(&target.pkg);
                if target_package.go_name() != self.current_package {
                    self.imports.add_package(
                        target_package.go_name(),
                        &target_package.import_path(self.sdk_import_path),
                    );
                }
                let target_name = self
                    .names
                    .project(
                        &BamlFqn::symbol(target),
                        GoNameKind::Class,
                        GoVisibility::Exported,
                    )
                    .identifier(self.current_package)
                    .to_string();
                let indirect =
                    optional || self.cyclic_edges.contains(&(owner.clone(), target.clone()));
                Some(if indirect {
                    format!("*{target_name}")
                } else {
                    target_name
                })
            }
            Ty::Union(items) => self.render(nullable_inner(items)?, owner, true),
            _ => None,
        }
    }
}

fn render_bootstrap(bytecode: &[u8]) -> String {
    let mut out = String::from(BANNER);
    out.push_str("package bootstrap\n\n");
    out.push_str("import (\n\t\"sync\"\n\n");
    out.push_str("\t\"github.com/boundaryml/baml/sdks/go/baml_go\"\n)\n\n");
    out.push_str("var (\n\tonce          sync.Once\n\tinitializeErr error\n)\n\n");
    out.push_str("var bytecode = []byte{\n");
    for chunk in bytecode.chunks(20) {
        let line = chunk
            .iter()
            .map(u8::to_string)
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "\t{line},");
    }
    out.push_str("}\n\n");
    out.push_str("func Ensure() error {\n");
    out.push_str("\tonce.Do(func() { initializeErr = baml_go.Initialize(bytecode) })\n");
    out.push_str("\treturn initializeErr\n}\n");
    out
}

fn go_type(ty: &Ty) -> String {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => GeneratorIdent::StringType.to_string(),
        PrimitiveKind::Int => GeneratorIdent::Int64Type.to_string(),
        PrimitiveKind::Bigint => format!("*{}.Int", GeneratorIdent::BigPackage),
        PrimitiveKind::Float => GeneratorIdent::Float64Type.to_string(),
        PrimitiveKind::Bool => GeneratorIdent::BoolType.to_string(),
        PrimitiveKind::Null => format!("{}.Null", GeneratorIdent::RuntimePackage),
        PrimitiveKind::Uint8Array => format!("[]{}", GeneratorIdent::ByteType),
    }
}

fn input_constructor(ty: &Ty) -> &'static str {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => "String",
        PrimitiveKind::Int => "Int64",
        PrimitiveKind::Bigint => "BigInt",
        PrimitiveKind::Float => "Float64",
        PrimitiveKind::Bool => "Bool",
        PrimitiveKind::Null => "NullInput",
        PrimitiveKind::Uint8Array => "Uint8Array",
    }
}

fn output_method(ty: &Ty) -> &'static str {
    match primitive_kind(ty).expect("function was filtered to primitive types") {
        PrimitiveKind::String => "String",
        PrimitiveKind::Int => "Int64",
        PrimitiveKind::Bigint => "BigInt",
        PrimitiveKind::Float => "Float64",
        PrimitiveKind::Bool => "Bool",
        PrimitiveKind::Null => "Null",
        PrimitiveKind::Uint8Array => "Uint8Array",
    }
}

