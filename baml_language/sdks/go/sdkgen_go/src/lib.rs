fn collect_interface_tys(ty: &Ty, out: &mut BTreeSet<Name>) {
    match ty {
        Ty::Interface(name, generics, associated, _) => {
            out.insert(name.clone());
            for nested in generics.iter().chain(associated.iter().map(|(_, ty)| ty)) {
                collect_interface_tys(nested, out);
            }
        }
        Ty::Class(_, arguments, _) => {
            for argument in arguments {
                collect_interface_tys(argument, out);
            }
        }
        Ty::List(inner, _) => collect_interface_tys(inner, out),
        Ty::Map { key, value, .. } => {
            collect_interface_tys(key, out);
            collect_interface_tys(value, out);
        }
        Ty::Union(items, _) => {
            for item in items {
                collect_interface_tys(item, out);
            }
        }
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => {
            for parameter in params {
                collect_interface_tys(&parameter.ty, out);
            }
            collect_interface_tys(ret, out);
            collect_interface_tys(throws, out);
        }
        Ty::Future(value, error, _) => {
            collect_interface_tys(value, out);
            collect_interface_tys(error, out);
        }
        _ => {}
    }
}

fn public_interface_tokens(pool: &SymbolPool) -> BTreeSet<Name> {
    fn collect_function(function: &Function, out: &mut BTreeSet<Name>) {
        for argument in &function.arguments {
            collect_interface_tys(&argument.ty, out);
        }
        collect_interface_tys(&function.return_type, out);
        if let Some(throws) = &function.throws {
            collect_interface_tys(throws, out);
        }
        for (_, watcher) in &function.watchers {
            collect_interface_tys(watcher, out);
        }
    }

    let mut out = BTreeSet::new();
    for symbol in pool.values() {
        match symbol {
            Symbol::Function(function) => collect_function(function, &mut out),
            Symbol::Class(class) => {
                for property in &class.properties {
                    collect_interface_tys(&property.ty, &mut out);
                }
                for method in class.static_methods.iter().chain(&class.instance_methods) {
                    collect_function(method, &mut out);
                }
            }
            Symbol::TypeAlias(alias) => collect_interface_tys(&alias.resolves_to, &mut out),
            Symbol::Enum(_) => {}
        }
    }
    out
}

#[derive(Clone, Debug)]
pub struct GoGenOptions<'a> {
    pub naming_convention: NamingConvention,
    pub sdk_import_path: &'a str,
    pub max_typed_union_arity: usize,
}

/// Generate files relative to a project's `baml_sdk/` directory.
pub fn to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
    sdk_import_path: &str,
) -> HashMap<PathBuf, String> {
    try_to_source_code_with_bytecode(pool, baml_bytecode, naming_convention, sdk_import_path)
        .unwrap_or_else(|error| panic!("Go SDK generation failed: {error}"))
}

pub fn try_to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
    sdk_import_path: &str,
) -> Result<HashMap<PathBuf, String>, GoGenerationError> {
    try_to_source_code_with_bytecode_and_options(
        pool,
        baml_bytecode,
        &GoGenOptions {
            naming_convention,
            sdk_import_path,
            max_typed_union_arity: DEFAULT_MAX_TYPED_UNION_ARITY,
        },
    )
}

