#[derive(Debug)]
pub enum CSharpGenerationError {
    Unsupported(String),
    MissingCallable(String),
    InvalidEnum(String),
    FileRoute(FileRouteError),
    Preparation(PreparationError),
}

impl fmt::Display for CSharpGenerationError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Unsupported(message) | Self::InvalidEnum(message) => formatter.write_str(message),
            Self::MissingCallable(identity) => {
                write!(
                    formatter,
                    "missing typed callable identity for `{identity}`"
                )
            }
            Self::FileRoute(error) => write!(formatter, "C# file routing failed: {error}"),
            Self::Preparation(error) => write!(formatter, "C# generation failed: {error}"),
        }
    }
}

impl std::error::Error for CSharpGenerationError {}

impl From<FileRouteError> for CSharpGenerationError {
    fn from(error: FileRouteError) -> Self {
        Self::FileRoute(error)
    }
}

impl From<PreparationError> for CSharpGenerationError {
    fn from(error: PreparationError) -> Self {
        Self::Preparation(error)
    }
}

