fn project_resource_method_result(owner: &Name, class: &Class, method: &Function, ty: &Ty) -> Ty {
    let Ty::Interface(interface, _, _, attr) = ty else {
        return ty.clone();
    };
    if interface.to_string() != "baml.iter.Iterator" {
        return ty.clone();
    }

    match (owner.to_string().as_str(), method.name.as_str()) {
        ("baml.csv.CsvReader", "iter") => Ty::Class(owner.clone(), Vec::new(), attr.clone()),
        ("baml.csv.CsvReader", "rows") => Ty::Class(
            Name::new(
                owner.package().clone(),
                owner.namespace().clone(),
                BaseName::new("CsvRows"),
            ),
            method
                .generic_params
                .first()
                .map(|parameter| Ty::TypeVar(ParamTy::new(0, parameter.clone()), TyAttr::EMPTY))
                .into_iter()
                .collect(),
            attr.clone(),
        ),
        ("baml.csv.CsvRows", "iter") => Ty::Class(
            owner.clone(),
            class
                .generic_params
                .iter()
                .enumerate()
                .map(|(index, parameter)| {
                    Ty::TypeVar(
                        ParamTy::new(
                            u32::try_from(index).expect("generic parameter index fits in u32"),
                            parameter.clone(),
                        ),
                        TyAttr::EMPTY,
                    )
                })
                .collect(),
            attr.clone(),
        ),
        _ => ty.clone(),
    }
}

fn is_canonical_generic_binding(ty: &Ty) -> bool {
    match ty {
        Ty::Bool { .. }
        | Ty::Int { .. }
        | Ty::Bigint { .. }
        | Ty::Float { .. }
        | Ty::String { .. }
        | Ty::Uint8Array { .. }
        | Ty::Media(MediaKind::Image | MediaKind::Audio | MediaKind::Video | MediaKind::Pdf, _)
        | Ty::BuiltinUnknown { .. }
        | Ty::Enum(..) => true,
        Ty::Class(name, arguments, _) => {
            (is_resource_projection(name) && !arguments.iter().any(contains_type_var))
                || (builtin_projection(name) != Some(BuiltinProjection::OpaqueHandle)
                    && arguments.is_empty())
        }
        _ => false,
    }
}

fn codec_type(ty: &Ty) -> Ty {
    match ty {
        Ty::Bool { .. } => Ty::Bool {
            attr: TyAttr::EMPTY,
        },
        Ty::Int { .. } => Ty::Int {
            attr: TyAttr::EMPTY,
        },
        Ty::Bigint { .. } => Ty::Bigint {
            attr: TyAttr::EMPTY,
        },
        Ty::Float { .. } => Ty::Float {
            attr: TyAttr::EMPTY,
        },
        Ty::String { .. } => Ty::String {
            attr: TyAttr::EMPTY,
        },
        Ty::Uint8Array { .. } => Ty::Uint8Array {
            attr: TyAttr::EMPTY,
        },
        Ty::Null { .. } => Ty::Null {
            attr: TyAttr::EMPTY,
        },
        Ty::BuiltinUnknown { .. } => Ty::BuiltinUnknown {
            attr: TyAttr::EMPTY,
        },
        Ty::Media(kind, _) => Ty::Media(*kind, TyAttr::EMPTY),
        Ty::Literal(literal, freshness, _) => {
            Ty::Literal(literal.clone(), *freshness, TyAttr::EMPTY)
        }
        Ty::Class(name, arguments, _) => Ty::Class(
            name.clone(),
            arguments.iter().map(codec_type).collect(),
            TyAttr::EMPTY,
        ),
        Ty::Enum(name, _) => Ty::Enum(name.clone(), TyAttr::EMPTY),
        Ty::EnumVariant(name, variant, _) => {
            Ty::EnumVariant(name.clone(), variant.clone(), TyAttr::EMPTY)
        }
        Ty::List(item, _) => Ty::List(Box::new(codec_type(item)), TyAttr::EMPTY),
        Ty::Map { key, value, .. } => Ty::Map {
            key: Box::new(codec_type(key)),
            value: Box::new(codec_type(value)),
            attr: TyAttr::EMPTY,
        },
        Ty::Union(members, _) => normalize_ty(&Ty::Union(
            members.iter().map(codec_type).collect(),
            TyAttr::EMPTY,
        )),
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => Ty::Function {
            params: params
                .iter()
                .map(|parameter| CallableParam {
                    name: parameter.name.clone(),
                    ty: codec_type(&parameter.ty),
                    mode: parameter.mode,
                })
                .collect(),
            ret: Box::new(codec_type(ret)),
            throws: Box::new(codec_type(throws)),
            attr: TyAttr::EMPTY,
        },
        Ty::TypeAlias(name, _) => Ty::TypeAlias(name.clone(), TyAttr::EMPTY),
        Ty::TypeVar(name, _) => Ty::TypeVar(name.clone(), TyAttr::EMPTY),
        Ty::Void { .. } => Ty::Void {
            attr: TyAttr::EMPTY,
        },
        Ty::Never { .. } => Ty::Never {
            attr: TyAttr::EMPTY,
        },
        _ => ty.clone(),
    }
}

fn collect_argument_type_closure(
    ty: &Ty,
    model: &CodegenModel,
    types: &mut BTreeSet<Ty>,
) -> Result<(), CSharpGenerationError> {
    if let Ty::Function {
        params,
        ret,
        throws,
        ..
    } = ty
        && contains_type_var(ty)
    {
        require_supported_argument_type(ty, model, "reachable callable argument")?;
        for parameter in params {
            collect_type_closure(&parameter.ty, model, types)?;
        }
        if !matches!(ret.as_ref(), Ty::Void { .. }) {
            collect_type_closure(ret, model, types)?;
        }
        if !matches!(throws.as_ref(), Ty::Never { .. } | Ty::Void { .. })
            && !is_host_callable_error(throws)
        {
            collect_type_closure(throws, model, types)?;
        }
        return Ok(());
    }

    collect_type_closure(ty, model, types)
}

fn collect_type_closure(
    ty: &Ty,
    model: &CodegenModel,
    types: &mut BTreeSet<Ty>,
) -> Result<(), CSharpGenerationError> {
    require_supported_type(ty, model, "reachable type graph")?;
    if contains_type_var(ty) {
        return Ok(());
    }
    if !types.insert(codec_type(ty)) {
        return Ok(());
    }
    match ty {
        Ty::Class(name, arguments, _) if is_resource_projection(name) => {
            let Some(Symbol::Class(class)) = model.symbols.get(name) else {
                return Err(unsupported(
                    "reachable type graph",
                    &format!("resource class `{name}`"),
                ));
            };
            for property in class
                .properties
                .iter()
                .filter(|property| !property.name.as_str().starts_with('_'))
            {
                collect_type_closure(
                    &instantiated_class_property_codec_type(
                        &class.name,
                        &class.generic_params,
                        arguments,
                        &property.ty,
                    ),
                    model,
                    types,
                )?;
            }
        }
        Ty::Class(name, _, _) if is_runtime_class_projection(name) => {}
        Ty::Class(name, arguments, _) => {
            let Some(Symbol::Class(class)) = model.symbols.get(name) else {
                return Err(unsupported(
                    "reachable type graph",
                    &format!("class `{name}`"),
                ));
            };
            for property in &class.properties {
                collect_type_closure(
                    &instantiated_class_property_codec_type(
                        &class.name,
                        &class.generic_params,
                        arguments,
                        &property.ty,
                    ),
                    model,
                    types,
                )?;
            }
        }
        Ty::List(item, _) => collect_type_closure(item, model, types)?,
        Ty::Map { key, value, .. } => {
            collect_type_closure(key, model, types)?;
            collect_type_closure(value, model, types)?;
        }
        Ty::Union(members, _) => {
            for member in members {
                if !matches!(member, Ty::Null { .. }) {
                    collect_type_closure(member, model, types)?;
                }
            }
        }
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => {
            for parameter in params {
                collect_type_closure(&parameter.ty, model, types)?;
            }
            if !matches!(ret.as_ref(), Ty::Void { .. }) {
                collect_type_closure(ret, model, types)?;
            }
            if !matches!(throws.as_ref(), Ty::Never { .. } | Ty::Void { .. })
                && !is_host_callable_error(throws)
            {
                collect_type_closure(throws, model, types)?;
            }
        }
        Ty::EnumVariant(name, _, _) => {
            types.insert(Ty::Enum(name.clone(), TyAttr::EMPTY));
        }
        Ty::TypeAlias(name, _) => {
            let Some(Symbol::TypeAlias(alias)) = model.symbols.get(name) else {
                return Err(unsupported(
                    "reachable type graph",
                    &format!("alias `{name}`"),
                ));
            };
            collect_type_closure(&alias.resolves_to, model, types)?;
        }
        _ => {}
    }
    Ok(())
}

fn render_functions(
    render: &RenderContext<'_>,
    functions: &[&FunctionSpec<'_>],
    program_namespace_requests: &[CSharpNameRequest],
    program_type_request: &CSharpNameRequest,
    deferred_instance_request: &CSharpNameRequest,
) -> String {
    let mut source = String::from(GENERATED_HEADER);
    let namespace = rendered_namespace(render.names, &functions[0].namespace_requests);
    if !namespace.is_empty() {
        source.push_str(&format!("\nnamespace {namespace};\n"));
    }
    let holder = allocated(render.names, &functions[0].holder_request).source();
    source.push_str(&format!("\npublic static partial class {holder}\n{{\n"));
    let program = qualified_name(
        render.names,
        program_namespace_requests,
        program_type_request,
    );
    let instance = allocated(
        render.names,
        &helper_request(&generated_program_fqn(), "Instance"),
    )
    .source();
    let deferred_instance = allocated(render.names, deferred_instance_request).source();
    for function in functions {
        let result = render.type_source_for(&function.result, &function.generic_params);
        let method = allocated(render.names, &function.method_request).source();
        let async_method = allocated(render.names, &function.async_request).source();
        let cancellation = allocated(render.names, &function.cancellation_request).source();
        let function_field = allocated(render.names, &function.field_request).source();
        let bound_function = allocated(render.names, &function.locals.function_request).source();
        let arguments = allocated(render.names, &function.locals.arguments_request).source();
        let type_parameters = if function.generic_params.is_empty() {
            String::new()
        } else {
            format!(
                "<{}>",
                function
                    .generic_params
                    .iter()
                    .map(|parameter| allocated(render.names, &parameter.request).source())
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let mut ordered_arguments = function.arguments.iter().collect::<Vec<_>>();
        ordered_arguments.sort_by_key(|argument| argument.optional);
        let mut parameters = ordered_arguments
            .iter()
            .map(|argument| {
                let ty = if is_public_resource_stdlib_function(function.name)
                    && string_literal_union_members(&argument.ty).is_some()
                {
                    "string".to_string()
                } else {
                    render.type_source_for(&argument.ty, &function.generic_params)
                };
                let name = allocated(render.names, &argument.parameter_request).source();
                if argument.optional {
                    format!("global::Baml.BamlOptional<{ty}> {name} = default")
                } else {
                    format!("{ty} {name}")
                }
            })
            .collect::<Vec<_>>();
        parameters.push(format!(
            "global::System.Threading.CancellationToken {cancellation} = default"
        ));
        let parameters = parameters.join(",\n        ");
        let builder = if function.generic_params.is_empty() {
            render_argument_builder(render, function, &program)
        } else {
            render_generic_argument_builder(render, function, &program)
        };
        if is_stream_callable_variant(function.variant) {
            let partial = function
                .stream_partial
                .as_ref()
                .expect("stream functions carry their partial result type");
            let partial_source = render.type_source_for(partial, &function.generic_params);
            let partial_type = if function.generic_params.is_empty() {
                format!("{program}.{}", render.type_field(partial))
            } else {
                render_generic_type_token(render, function, partial, &program)
            };
            let callable = if function.generic_params.is_empty() {
                format!("{program}.{function_field}")
            } else {
                bound_function.to_string()
            };
            source.push_str(&format!(
                "    public static global::Baml.BamlStream<{partial_source}, {result}> {method}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return global::Baml.Generated.V1.BamlGeneratedContract.CreateStream(\n            {program}.{deferred_instance},\n            {callable},\n            {partial_type},\n            {arguments}.Build(),\n            {partial_option},\n            {cancellation});\n    }}\n\n",
                partial_option = csharp_string(&render.wire_option_name(partial)),
            ));
            continue;
        }
        source.push_str(&format!(
            "    public static {result} {method}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return {program}.{instance}.Call(\n            {callable},\n            {arguments}.Build(),\n            {cancellation});\n    }}\n\n",
            callable = if function.generic_params.is_empty() {
                format!("{program}.{function_field}")
            } else {
                bound_function.to_string()
            },
        ));
        source.push_str(&format!(
            "    public static global::System.Threading.Tasks.Task<{result}> {async_method}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return {program}.{instance}.CallAsync(\n            {callable},\n            {arguments}.Build(),\n            {cancellation});\n    }}\n\n",
            callable = if function.generic_params.is_empty() {
                format!("{program}.{function_field}")
            } else {
                bound_function.to_string()
            },
        ));
    }
    source.push_str("}\n");
    source
}

fn render_generic_argument_builder(
    render: &RenderContext<'_>,
    function: &FunctionSpec<'_>,
    program: &str,
) -> String {
    let result = render.type_source_for(&function.result, &function.generic_params);
    let function_field = allocated(render.names, &function.field_request).source();
    let bound_function = allocated(render.names, &function.locals.function_request).source();
    let arguments = allocated(render.names, &function.locals.arguments_request).source();
    let mut body = String::new();
    for (index, parameter) in function.generic_params.iter().enumerate() {
        let source = allocated(render.names, &parameter.request).source();
        let local = allocated(render.names, &function.locals.type_requests[index]).source();
        let binding = allocated(render.names, &function.locals.binding_requests[index]).source();
        body.push_str(&format!(
            "        global::Baml.Generated.V1.BamlGeneratedType<{source}> {local} =\n            {program}.Registry.ResolveType<{source}>({wire});\n",
            wire = csharp_string(parameter.name.as_str()),
        ));
        body.push_str(&format!(
            "        global::Baml.Generated.V1.BamlGeneratedTypeBinding {binding} =\n            {program}.Registry.BindType({program}.{field}, {local});\n",
            field = allocated(render.names, &parameter.field_request).source(),
        ));
    }
    let result_type = render_generic_type_token(render, function, &function.result, program);
    let bindings = function
        .generic_params
        .iter()
        .enumerate()
        .map(|(index, _)| {
            allocated(render.names, &function.locals.binding_requests[index])
                .source()
                .to_string()
        })
        .collect::<Vec<_>>()
        .join(", ");
    body.push_str(&format!(
        "        global::Baml.Generated.V1.BamlGeneratedBoundFunction<{result}> {bound_function} =\n            {program}.Registry.BindFunction(\n                {program}.{function_field},\n                {result_type}{comma}{bindings});\n        global::Baml.Generated.V1.BamlGeneratedGenericArgumentsBuilder<{result}> {arguments} =\n            {program}.Registry.CreateArgumentsBuilder({bound_function});\n",
        comma = if bindings.is_empty() { "" } else { ",\n                " },
    ));
    for argument in &function.arguments {
        let field = allocated(render.names, &argument.field_request).source();
        let parameter = allocated(render.names, &argument.parameter_request).source();
        let argument_type = render_generic_type_token(render, function, &argument.ty, program);
        let input_value = if argument.optional {
            format!("{parameter}.Value")
        } else {
            parameter.to_string()
        };
        let value = render_public_stdlib_argument_value(
            render,
            &argument.ty,
            &function.generic_params,
            &input_value,
            parameter,
            is_public_resource_stdlib_function(function.name),
        );
        if matches!(&argument.ty, Ty::Function { .. }) && contains_type_var(&argument.ty) {
            let argument_token = format!("{program}.{field}");
            if argument.optional {
                let addition = render_generic_host_callable_add(
                    render,
                    &argument.ty,
                    &function.generic_params,
                    &value,
                    arguments,
                    &argument_token,
                    &function.locals,
                    "            ",
                    |ty| render_generic_type_token(render, function, ty, program),
                );
                body.push_str(&format!(
                    "        if ({parameter}.IsSet)\n        {{\n{addition}        }}\n        else\n        {{\n            {arguments}.Omit({program}.{field});\n        }}\n"
                ));
            } else {
                body.push_str(&render_generic_host_callable_add(
                    render,
                    &argument.ty,
                    &function.generic_params,
                    &value,
                    arguments,
                    &argument_token,
                    &function.locals,
                    "        ",
                    |ty| render_generic_type_token(render, function, ty, program),
                ));
            }
            continue;
        }
        if argument.optional {
            body.push_str(&format!(
                "        if ({parameter}.IsSet)\n        {{\n            {arguments}.Add({program}.{field}, {argument_type}, {value});\n        }}\n        else\n        {{\n            {arguments}.Omit({program}.{field});\n        }}\n"
            ));
        } else {
            body.push_str(&format!(
                "        {arguments}.Add({program}.{field}, {argument_type}, {value});\n"
            ));
        }
    }
    body
}

fn render_generic_type_token(
    render: &RenderContext<'_>,
    function: &FunctionSpec<'_>,
    ty: &Ty,
    program: &str,
) -> String {
    match ty {
        Ty::TypeVar(name, _) => {
            let parameter = function
                .generic_params
                .iter()
                .find(|parameter| parameter.name == name.name())
                .unwrap_or_else(|| panic!("unbound generated type variable {name}"));
            let index = function
                .generic_params
                .iter()
                .position(|candidate| candidate.name == parameter.name)
                .expect("bound generic function parameter has a local");
            allocated(render.names, &function.locals.type_requests[index])
                .source()
                .to_string()
        }
        _ if contains_type_var(ty) => format!(
            "{program}.Registry.ResolveType<{}>({})",
            render.type_source_for(ty, &function.generic_params),
            csharp_string(&ty.to_string()),
        ),
        _ => format!("{program}.{}", render.type_field(ty)),
    }
}

#[allow(clippy::too_many_arguments)]
fn render_generic_host_callable_add(
    render: &RenderContext<'_>,
    ty: &Ty,
    generic_parameters: &[GenericParamSpec<'_>],
    callback_value: &str,
    arguments: &str,
    argument: &str,
    locals: &CallableLocalRequests,
    indent: &str,
    mut type_token: impl FnMut(&Ty) -> String,
) -> String {
    let Ty::Function { params, ret, .. } = ty else {
        panic!("generic host-callable rendering requires a function type")
    };
    let context = allocated(render.names, &locals.host_context_request).source();
    let encoded_delegate = allocated(render.names, &locals.host_encoded_delegate_request).source();
    let invoked_delegate = allocated(render.names, &locals.host_invoked_delegate_request).source();
    let invocation_arguments =
        allocated(render.names, &locals.host_invocation_arguments_request).source();
    let invocation_cancellation =
        allocated(render.names, &locals.host_invocation_cancellation_request).source();
    let delegate_type = render.type_source_for(ty, generic_parameters);
    let descriptors = params
        .iter()
        .map(|parameter| {
            let token = type_token(&parameter.ty);
            match parameter.mode {
                CodegenFunctionParamMode::Required => {
                    format!("{context}.Required({token})")
                }
                CodegenFunctionParamMode::Optional => format!(
                    "{context}.Optional({}, {token})",
                    csharp_string(
                        parameter
                            .name
                            .as_ref()
                            .expect("supported optional callback parameters have wire names")
                            .as_str()
                    ),
                ),
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    let result = if matches!(ret.as_ref(), Ty::Void { .. }) {
        format!("{context}.VoidResult()")
    } else {
        format!("{context}.Result({})", type_token(ret))
    };
    let mut invocation = params
        .iter()
        .enumerate()
        .map(|(index, parameter)| {
            let source = render.type_source_for(&parameter.ty, generic_parameters);
            let source = if parameter.mode == CodegenFunctionParamMode::Optional {
                format!("global::Baml.BamlOptional<{source}>")
            } else {
                source
            };
            format!("({source}){invocation_arguments}[{index}]!")
        })
        .collect::<Vec<_>>();
    invocation.push(invocation_cancellation.to_string());

    format!(
        "{indent}{arguments}.AddHostCallable(\n{indent}    {argument},\n{indent}    {callback_value},\n{indent}    ({context}, {encoded_delegate}) =>\n{indent}        {context}.HostCallable(\n{indent}            {encoded_delegate},\n{indent}            new global::Baml.Generated.V1.BamlGeneratedHostParameter[] {{ {descriptors} }},\n{indent}            {result},\n{indent}            static ({invoked_delegate}, {invocation_arguments}, {invocation_cancellation}) =>\n{indent}                global::Baml.Generated.V1.BamlGeneratedHostCallableRuntime.Await(\n{indent}                    (({delegate_type}){invoked_delegate})({invocation}))));\n",
        invocation = invocation.join(", "),
    )
}

fn render_argument_builder(
    render: &RenderContext<'_>,
    function: &FunctionSpec<'_>,
    program: &str,
) -> String {
    let function_field = allocated(render.names, &function.field_request).source();
    let arguments = allocated(render.names, &function.locals.arguments_request).source();
    let mut body = format!(
        "        global::Baml.Generated.V1.BamlGeneratedArgumentsBuilder<{}> {arguments} =\n            {program}.Registry.CreateArgumentsBuilder({program}.{function_field});\n",
        render.type_source(&function.result)
    );
    for argument in &function.arguments {
        let field = allocated(render.names, &argument.field_request).source();
        let parameter = allocated(render.names, &argument.parameter_request).source();
        let input_value = if argument.optional {
            format!("{parameter}.Value")
        } else {
            parameter.to_string()
        };
        let value = render_public_stdlib_argument_value(
            render,
            &argument.ty,
            &function.generic_params,
            &input_value,
            parameter,
            is_public_resource_stdlib_function(function.name),
        );
        if argument.optional {
            body.push_str(&format!(
                "        if ({parameter}.IsSet)\n        {{\n            {arguments}.Add({program}.{field}, {value});\n        }}\n        else\n        {{\n            {arguments}.Omit({program}.{field});\n        }}\n"
            ));
        } else {
            body.push_str(&format!(
                "        {arguments}.Add({program}.{field}, {value});\n"
            ));
        }
    }
    body
}

fn render_class(render: &RenderContext<'_>, class: &ClassSpec<'_>) -> String {
    let mut source = String::from(GENERATED_HEADER);
    let namespace = rendered_namespace(render.names, &class.namespace_requests);
    if !namespace.is_empty() {
        source.push_str(&format!("\nnamespace {namespace};\n"));
    }
    let name = allocated(render.names, &class.type_request).source();
    let generic_params = if class.generic_params.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            class
                .generic_params
                .iter()
                .map(|parameter| allocated(render.names, &parameter.request).source())
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let resource = is_resource_projection(class.name);
    let implements_disposable = if resource {
        " : global::System.IDisposable"
    } else {
        ""
    };
    source.push_str(&format!(
        "\npublic sealed partial class {name}{generic_params}{implements_disposable}\n{{\n"
    ));
    if resource {
        let resource_source = format!("{name}{generic_params}");
        let public_properties = class
            .properties
            .iter()
            .filter(|property| !property.property.name.as_str().starts_with('_'))
            .collect::<Vec<_>>();
        source.push_str(
            "    private readonly global::Baml.Generated.V1.BamlGeneratedResource resource;\n\n",
        );
        let mut constructor_parameters =
            vec!["global::Baml.Generated.V1.BamlGeneratedResource resource".to_string()];
        constructor_parameters.extend(public_properties.iter().enumerate().map(
            |(index, property)| {
                format!(
                    "{} property{index}",
                    property_type_source(render, class, &property.property.ty)
                )
            },
        ));
        source.push_str(&format!(
            "    internal {name}(\n        {})\n    {{\n        this.resource = resource ?? throw new global::System.ArgumentNullException(nameof(resource));\n",
            constructor_parameters.join(",\n        "),
        ));
        for (index, property) in public_properties.iter().enumerate() {
            source.push_str(&format!(
                "        {} = property{index};\n",
                allocated(render.names, &property.request).source(),
            ));
        }
        source.push_str(
            "    }\n\n    internal global::Baml.Generated.V1.BamlGeneratedResource Resource => resource;\n\n",
        );
        for property in &public_properties {
            source.push_str(&format!(
                "    public {} {} {{ get; }}\n\n",
                property_type_source(render, class, &property.property.ty),
                allocated(render.names, &property.request).source(),
            ));
        }
        let clone_properties = public_properties
            .iter()
            .map(|property| allocated(render.names, &property.request).source())
            .collect::<Vec<_>>();
        source.push_str(&format!(
            "    public bool IsClosed => resource.IsClosed;\n\n    public {resource_source} Clone() => new(\n        resource.Clone(){comma}{properties});\n\n    public void Dispose() => resource.Dispose();\n\n",
            comma = if clone_properties.is_empty() { "" } else { ",\n        " },
            properties = clone_properties.join(",\n        "),
        ));
    } else {
        for property in &class.properties {
            let required = if !class.name.is_stream()
                || property.property.ty.attr().sap_pending_never == TyAttrValue::Set
            {
                "required "
            } else {
                ""
            };
            source.push_str(&format!(
                "    public {required}{} {} {{ get; init; }}\n\n",
                property_type_source(render, class, &property.property.ty),
                allocated(render.names, &property.request).source(),
            ));
        }
    }
    let program_namespace_requests = generated_program_namespace_requests();
    let program_fqn = generated_program_fqn();
    let program_type_request = generated_request(
        program_fqn,
        "BamlProgram",
        CSharpNameKind::HelperType,
        CSharpScope::Namespace {
            package: BaseName::new("user"),
            path: vec![BaseName::new("Baml"), BaseName::new("Generated")],
        },
    );
    let program = qualified_name(
        render.names,
        &program_namespace_requests,
        &program_type_request,
    );
    for method in &class.methods {
        source.push_str(&render_method(render, class, method, &program));
    }
    source.push_str("}\n");
    source
}

fn property_type_source(render: &RenderContext<'_>, class: &ClassSpec<'_>, ty: &Ty) -> String {
    render.type_source_for(&property_codec_type(class, ty), &class.generic_params)
}

fn property_codec_type(class: &ClassSpec<'_>, ty: &Ty) -> Ty {
    property_codec_type_for_name(class.name, ty)
}

fn property_codec_type_for_name(class_name: &Name, ty: &Ty) -> Ty {
    let projected = codec_type(ty);
    if !class_name.is_stream()
        || ty.attr().sap_pending_never == TyAttrValue::Set
        || type_allows_null(&projected)
    {
        return projected;
    }

    normalize_ty(&Ty::Union(
        vec![
            projected,
            Ty::Null {
                attr: TyAttr::EMPTY,
            },
        ],
        TyAttr::EMPTY,
    ))
}

fn instantiated_class_property_codec_type(
    class_name: &Name,
    parameters: &[BaseName],
    arguments: &[Ty],
    ty: &Ty,
) -> Ty {
    debug_assert_eq!(
        parameters.len(),
        arguments.len(),
        "supported closed generic classes have one argument per parameter"
    );
    substitute_type_variables(
        &property_codec_type_for_name(class_name, ty),
        parameters,
        arguments,
    )
}

fn closed_stream_nullable_type_var(class: &ClassSpec<'_>, arguments: &[Ty], ty: &Ty) -> Option<Ty> {
    if arguments.is_empty()
        || !class.name.is_stream()
        || ty.attr().sap_pending_never == TyAttrValue::Set
    {
        return None;
    }

    let projected = codec_type(ty);
    let inner = match &projected {
        Ty::TypeVar(..) => &projected,
        Ty::Union(members, _)
            if members
                .iter()
                .filter(|member| !matches!(member, Ty::Null { .. }))
                .count()
                == 1
                && members
                    .iter()
                    .any(|member| matches!(member, Ty::Null { .. })) =>
        {
            members
                .iter()
                .find(|member| !matches!(member, Ty::Null { .. }))
                .filter(|member| matches!(member, Ty::TypeVar(..)))?
        }
        _ => return None,
    };
    Some(substitute_type_variables(
        inner,
        &class.class.generic_params,
        arguments,
    ))
}

fn substitute_type_variables(ty: &Ty, parameters: &[BaseName], arguments: &[Ty]) -> Ty {
    match ty {
        Ty::TypeVar(name, _) => parameters
            .iter()
            .position(|parameter| parameter == name.name())
            .and_then(|index| arguments.get(index))
            .cloned()
            .unwrap_or_else(|| ty.clone()),
        Ty::Class(name, nested, attr) => Ty::Class(
            name.clone(),
            nested
                .iter()
                .map(|item| substitute_type_variables(item, parameters, arguments))
                .collect(),
            attr.clone(),
        ),
        Ty::List(item, attr) => Ty::List(
            Box::new(substitute_type_variables(item, parameters, arguments)),
            attr.clone(),
        ),
        Ty::Map { key, value, attr } => Ty::Map {
            key: Box::new(substitute_type_variables(key, parameters, arguments)),
            value: Box::new(substitute_type_variables(value, parameters, arguments)),
            attr: attr.clone(),
        },
        Ty::Union(members, attr) => normalize_ty(&Ty::Union(
            members
                .iter()
                .map(|member| substitute_type_variables(member, parameters, arguments))
                .collect(),
            attr.clone(),
        )),
        Ty::Function {
            params,
            ret,
            throws,
            attr,
        } => Ty::Function {
            params: params
                .iter()
                .map(|parameter| CallableParam {
                    name: parameter.name.clone(),
                    ty: substitute_type_variables(&parameter.ty, parameters, arguments),
                    mode: parameter.mode,
                })
                .collect(),
            ret: Box::new(substitute_type_variables(ret, parameters, arguments)),
            throws: Box::new(substitute_type_variables(throws, parameters, arguments)),
            attr: attr.clone(),
        },
        _ => ty.clone(),
    }
}

fn type_allows_null(ty: &Ty) -> bool {
    matches!(ty, Ty::Null { .. })
        || matches!(
            ty,
            Ty::Union(members, _)
                if members.iter().any(|member| matches!(member, Ty::Null { .. }))
        )
}

fn render_method(
    render: &RenderContext<'_>,
    class: &ClassSpec<'_>,
    method: &MethodSpec<'_>,
    program: &str,
) -> String {
    let result = render.type_source_for(&method.result, &method.type_params);
    let method_name = allocated(render.names, &method.method_request).source();
    let async_name = allocated(render.names, &method.async_request).source();
    let cancellation = allocated(render.names, &method.cancellation_request).source();
    let bound_function = allocated(render.names, &method.locals.function_request).source();
    let arguments = allocated(render.names, &method.locals.arguments_request).source();
    let instance = allocated(
        render.names,
        &helper_request(&generated_program_fqn(), "Instance"),
    )
    .source();
    let own_type_parameters = method
        .type_params
        .iter()
        .rev()
        .take(method.method_type_param_count)
        .rev()
        .map(|parameter| allocated(render.names, &parameter.request).source())
        .collect::<Vec<_>>();
    let type_parameters = if own_type_parameters.is_empty() {
        String::new()
    } else {
        format!("<{}>", own_type_parameters.join(", "))
    };
    let modifier = if method.is_static { "static " } else { "" };
    let mut ordered_arguments = method.arguments.iter().collect::<Vec<_>>();
    ordered_arguments.sort_by_key(|argument| argument.optional);
    let mut parameters = ordered_arguments
        .iter()
        .map(|argument| {
            let ty = if is_resource_projection(class.name)
                && string_literal_union_members(&argument.ty).is_some()
            {
                "string".to_string()
            } else {
                render.type_source_for(&argument.ty, &method.type_params)
            };
            let name = allocated(render.names, &argument.parameter_request).source();
            if argument.optional {
                format!("global::Baml.BamlOptional<{ty}> {name} = default")
            } else {
                format!("{ty} {name}")
            }
        })
        .collect::<Vec<_>>();
    parameters.push(format!(
        "global::System.Threading.CancellationToken {cancellation} = default"
    ));
    let parameters = parameters.join(",\n        ");
    if is_resource_iterator_identity_method(class, method) {
        return format!(
            "    public {result} {method_name}{type_parameters}(\n        {parameters})\n    {{\n        {cancellation}.ThrowIfCancellationRequested();\n        return this;\n    }}\n\n    public global::System.Threading.Tasks.Task<{result}> {async_name}{type_parameters}(\n        {parameters})\n    {{\n        return {cancellation}.IsCancellationRequested\n            ? global::System.Threading.Tasks.Task.FromCanceled<{result}>({cancellation})\n            : global::System.Threading.Tasks.Task.FromResult<{result}>(this);\n    }}\n\n"
        );
    }
    let builder = render_method_argument_builder(render, class, method, program);
    if is_stream_callable_variant(method.variant) {
        let partial = method
            .stream_partial
            .as_ref()
            .expect("stream methods carry their partial result type");
        let partial_source = render.type_source_for(partial, &method.type_params);
        let partial_type = render_method_type_token(render, method, partial, program);
        let deferred_instance = allocated(
            render.names,
            &helper_request(&generated_program_fqn(), "DeferredProgram"),
        )
        .source();
        return format!(
            "    public {modifier}global::Baml.BamlStream<{partial_source}, {result}> {method_name}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return global::Baml.Generated.V1.BamlGeneratedContract.CreateStream(\n            {program}.{deferred_instance},\n            {bound_function},\n            {partial_type},\n            {arguments}.Build(),\n            {partial_option},\n            {cancellation});\n    }}\n\n",
            partial_option = csharp_string(&render.wire_option_name(partial)),
        );
    }
    format!(
        "    public {modifier}{result} {method_name}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return {program}.{instance}.Call(\n            {bound_function},\n            {arguments}.Build(),\n            {cancellation});\n    }}\n\n    public {modifier}global::System.Threading.Tasks.Task<{result}> {async_name}{type_parameters}(\n        {parameters})\n    {{\n{builder}        return {program}.{instance}.CallAsync(\n            {bound_function},\n            {arguments}.Build(),\n            {cancellation});\n    }}\n\n"
    )
}

fn is_resource_iterator_identity_method(class: &ClassSpec<'_>, method: &MethodSpec<'_>) -> bool {
    !method.is_static
        && method.method.name.as_str() == "iter"
        && method.arguments.is_empty()
        && matches!(
            class.name.to_string().as_str(),
            "baml.csv.CsvReader" | "baml.csv.CsvRows"
        )
}

fn render_method_argument_builder(
    render: &RenderContext<'_>,
    class: &ClassSpec<'_>,
    method: &MethodSpec<'_>,
    program: &str,
) -> String {
    let result = render.type_source_for(&method.result, &method.type_params);
    let function_field = allocated(render.names, &method.function_field_request).source();
    let bound_function = allocated(render.names, &method.locals.function_request).source();
    let arguments = allocated(render.names, &method.locals.arguments_request).source();
    let mut body = String::new();
    for (index, parameter) in method.type_params.iter().enumerate() {
        let source = allocated(render.names, &parameter.request).source();
        let local = allocated(render.names, &method.locals.type_requests[index]).source();
        let binding = allocated(render.names, &method.locals.binding_requests[index]).source();
        body.push_str(&format!(
            "        global::Baml.Generated.V1.BamlGeneratedType<{source}> {local} =\n            {program}.Registry.ResolveType<{source}>({position});\n        global::Baml.Generated.V1.BamlGeneratedTypeBinding {binding} =\n            {program}.Registry.BindType({program}.{parameter_field}, {local});\n",
            position = csharp_string(&format!(
                "{}.{}.{}",
                class.name, method.method.name, parameter.name
            )),
            parameter_field = allocated(render.names, &parameter.field_request).source(),
        ));
    }
    let result_type = render_method_type_token(render, method, &method.result, program);
    let bindings = method
        .locals
        .binding_requests
        .iter()
        .map(|request| allocated(render.names, request).source())
        .collect::<Vec<_>>()
        .join(", ");
    body.push_str(&format!(
        "        global::Baml.Generated.V1.BamlGeneratedBoundFunction<{result}> {bound_function} =\n            {program}.Registry.BindFunction(\n                {program}.{function_field},\n                {result_type}{comma}{bindings});\n        global::Baml.Generated.V1.BamlGeneratedGenericArgumentsBuilder<{result}> {arguments} =\n            {program}.Registry.CreateArgumentsBuilder({bound_function});\n",
        comma = if bindings.is_empty() {
            ""
        } else {
            ",\n                "
        },
    ));
    if let Some(receiver) = &method.receiver_field_request {
        let receiver_type = class_receiver_type(class);
        let receiver_token = render_method_type_token(render, method, &receiver_type, program);
        body.push_str(&format!(
            "        {arguments}.Add({program}.{receiver}, {receiver_token}, this);\n",
            receiver = allocated(render.names, receiver).source(),
        ));
    }
    for argument in &method.arguments {
        let field = allocated(render.names, &argument.field_request).source();
        let parameter = allocated(render.names, &argument.parameter_request).source();
        let argument_type = render_method_type_token(render, method, &argument.ty, program);
        let input_value = if argument.optional {
            format!("{parameter}.Value")
        } else {
            parameter.to_string()
        };
        let value = render_public_stdlib_argument_value(
            render,
            &argument.ty,
            &method.type_params,
            &input_value,
            parameter,
            is_resource_projection(class.name),
        );
        if matches!(&argument.ty, Ty::Function { .. }) && contains_type_var(&argument.ty) {
            let argument_token = format!("{program}.{field}");
            if argument.optional {
                let addition = render_generic_host_callable_add(
                    render,
                    &argument.ty,
                    &method.type_params,
                    &value,
                    arguments,
                    &argument_token,
                    &method.locals,
                    "            ",
                    |ty| render_method_type_token(render, method, ty, program),
                );
                body.push_str(&format!(
                    "        if ({parameter}.IsSet)\n        {{\n{addition}        }}\n        else\n        {{\n            {arguments}.Omit({program}.{field});\n        }}\n"
                ));
            } else {
                body.push_str(&render_generic_host_callable_add(
                    render,
                    &argument.ty,
                    &method.type_params,
                    &value,
                    arguments,
                    &argument_token,
                    &method.locals,
                    "        ",
                    |ty| render_method_type_token(render, method, ty, program),
                ));
            }
            continue;
        }
        if argument.optional {
            body.push_str(&format!(
                "        if ({parameter}.IsSet)\n        {{\n            {arguments}.Add({program}.{field}, {argument_type}, {value});\n        }}\n        else\n        {{\n            {arguments}.Omit({program}.{field});\n        }}\n"
            ));
        } else {
            body.push_str(&format!(
                "        {arguments}.Add({program}.{field}, {argument_type}, {value});\n"
            ));
        }
    }
    body
}

fn string_literal_union_members(ty: &Ty) -> Option<Vec<&str>> {
    let Ty::Union(members, _) = ty else {
        return None;
    };
    if members.len() < 2 {
        return None;
    }
    members
        .iter()
        .map(|member| match member {
            Ty::Literal(Literal::String(value), ..) => Some(value.as_str()),
            _ => None,
        })
        .collect()
}

fn render_public_stdlib_argument_value(
    render: &RenderContext<'_>,
    ty: &Ty,
    parameters: &[GenericParamSpec<'_>],
    value: &str,
    parameter: &str,
    public_stdlib_surface: bool,
) -> String {
    let Some(members) = public_stdlib_surface
        .then(|| string_literal_union_members(ty))
        .flatten()
    else {
        return value.to_string();
    };
    let union = render.type_source_for(ty, parameters);
    let mut source = format!("{value} switch\n            {{\n");
    for (index, member) in members.iter().enumerate() {
        source.push_str(&format!(
            "                {} => {union}.FromT{index}({value}),\n",
            csharp_string(member),
        ));
    }
    source.push_str(&format!(
        "                _ => throw new global::System.ArgumentOutOfRangeException(\n                    nameof({parameter}),\n                    {value},\n                    {}),\n            }}",
        csharp_string(&format!("Expected one of: {}.", members.join(", "))),
    ));
    source
}

fn render_method_type_token(
    render: &RenderContext<'_>,
    method: &MethodSpec<'_>,
    ty: &Ty,
    program: &str,
) -> String {
    match ty {
        Ty::TypeVar(name, _) => {
            let index = method
                .type_params
                .iter()
                .rposition(|parameter| parameter.name == name.name())
                .unwrap_or_else(|| panic!("unbound generated method type variable {name}"));
            allocated(render.names, &method.locals.type_requests[index])
                .source()
                .to_string()
        }
        _ if contains_type_var(ty) => format!(
            "{program}.Registry.ResolveType<{}>({})",
            render.type_source_for(ty, &method.type_params),
            csharp_string(&format!("{}.{}", method.method.name, ty)),
        ),
        _ => format!("{program}.{}", render.type_field(ty)),
    }
}

fn render_enum(render: &RenderContext<'_>, enumeration: &EnumSpec<'_>) -> String {
    let mut source = String::from(GENERATED_HEADER);
    let namespace = rendered_namespace(render.names, &enumeration.namespace_requests);
    if !namespace.is_empty() {
        source.push_str(&format!("\nnamespace {namespace};\n"));
    }
    let name = allocated(render.names, &enumeration.type_request).source();
    source.push_str(&format!("\npublic enum {name} : long\n{{\n"));
    for variant in &enumeration.variants {
        source.push_str(&format!(
            "    {} = {},\n",
            allocated(render.names, &variant.request).source(),
            variant.discriminant,
        ));
    }
    source.push_str("}\n");
    source
}

#[allow(clippy::too_many_arguments)]
fn render_program(
    render: &RenderContext<'_>,
    functions: &[FunctionSpec<'_>],
    namespace_requests: &[CSharpNameRequest],
    program_type_request: &CSharpNameRequest,
    registry_request: &CSharpNameRequest,
    instance_request: &CSharpNameRequest,
    deferred_instance_request: &CSharpNameRequest,
    embedded_baml_toml: Option<&str>,
) -> String {
    let namespace = rendered_namespace(render.names, namespace_requests);
    let program_type = allocated(render.names, program_type_request).source();
    let registry = allocated(render.names, registry_request).source();
    let instance = allocated(render.names, instance_request).source();
    let deferred_instance = allocated(render.names, deferred_instance_request).source();
    let mut source = format!(
        "{GENERATED_HEADER}\nnamespace {namespace};\n\ninternal static class {program_type}\n{{\n    private const string Fingerprint = \"{PROGRAM_FINGERPRINT_PLACEHOLDER}\";\n\n    private static readonly byte[] Bytecode =\n    [\n{PROGRAM_BYTES_PLACEHOLDER}    ];\n\n    private static readonly global::System.Lazy<global::Baml.Generated.V1.BamlGeneratedProgram> Program =\n        new(Register, global::System.Threading.LazyThreadSafetyMode.ExecutionAndPublication);\n\n    internal static readonly global::Baml.Generated.V1.BamlGeneratedRegistry {registry};\n"
    );
    for ty in render.type_specs {
        source.push_str(&format!(
            "    internal static readonly global::Baml.Generated.V1.BamlGeneratedType<{}> {};\n",
            render.type_source(&ty.ty),
            allocated(render.names, &ty.field_request).source(),
        ));
    }
    for function in functions {
        if function.generic_params.is_empty() {
            source.push_str(&format!(
                "    internal static readonly global::Baml.Generated.V1.BamlGeneratedFunction<{}> {};\n",
                render.type_source(&function.result),
                allocated(render.names, &function.field_request).source(),
            ));
        } else {
            source.push_str(&format!(
                "    internal static readonly global::Baml.Generated.V1.BamlGeneratedGenericFunction {};\n",
                allocated(render.names, &function.field_request).source(),
            ));
            for parameter in &function.generic_params {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedTypeParameter {};\n",
                    allocated(render.names, &parameter.field_request).source(),
                ));
            }
        }
        for argument in &function.arguments {
            if function.generic_params.is_empty() {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedArgument<{}, {}> {};\n",
                    render.type_source(&function.result),
                    render.type_source(&argument.ty),
                    allocated(render.names, &argument.field_request).source(),
                ));
            } else {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedGenericArgument {};\n",
                    allocated(render.names, &argument.field_request).source(),
                ));
            }
        }
    }
    for class in render.classes {
        for method in &class.methods {
            source.push_str(&format!(
                "    internal static readonly global::Baml.Generated.V1.BamlGeneratedGenericFunction {};\n",
                allocated(render.names, &method.function_field_request).source(),
            ));
            for parameter in &method.type_params {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedTypeParameter {};\n",
                    allocated(render.names, &parameter.field_request).source(),
                ));
            }
            if let Some(receiver) = &method.receiver_field_request {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedGenericArgument {};\n",
                    allocated(render.names, receiver).source(),
                ));
            }
            for argument in &method.arguments {
                source.push_str(&format!(
                    "    internal static readonly global::Baml.Generated.V1.BamlGeneratedGenericArgument {};\n",
                    allocated(render.names, &argument.field_request).source(),
                ));
            }
        }
    }
    source.push_str(&format!(
        "\n    internal static global::System.Lazy<global::Baml.Generated.V1.BamlGeneratedProgram> {deferred_instance} => Program;\n\n    internal static global::Baml.Generated.V1.BamlGeneratedProgram {instance} => Program.Value;\n\n    static {program_type}()\n    {{\n        global::Baml.Generated.V1.BamlGeneratedRegistryBuilder builder =\n            global::Baml.Generated.V1.BamlGeneratedContract.CreateRegistryBuilder(\n                global::Baml.Generated.V1.BamlGeneratedContract.Version);\n"
    ));
    for ty in render.type_specs {
        source.push_str(&format!(
            "        {field} = builder.DeclareType<{source_ty}>({identity}, {metadata});\n        builder.RegisterCodec({field}, new {codec}());\n",
            field = allocated(render.names, &ty.field_request).source(),
            source_ty = render.type_source(&ty.ty),
            identity = csharp_string(&ty.ty.to_string()),
            metadata = byte_array_source(&render.wire_metadata(&ty.ty)),
            codec = allocated(render.names, &ty.codec_request).source(),
        ));
        if is_canonical_generic_binding(&ty.ty) {
            source.push_str(&format!(
                "        builder.RegisterGenericBinding({});\n",
                allocated(render.names, &ty.field_request).source(),
            ));
        }
    }
    for function in functions {
        let variant = if is_stream_callable_variant(function.variant) {
            "stream"
        } else {
            "call"
        };
        if function.generic_params.is_empty() {
            source.push_str(&format!(
                "        {function_field} = builder.DeclareFunction(\n            {identity},\n            {variant},\n            {result_field});\n",
                function_field = allocated(render.names, &function.field_request).source(),
                identity = csharp_string(&function.wire_identity),
                variant = csharp_string(variant),
                result_field = render.type_field(&function.result),
            ));
        } else {
            source.push_str(&format!(
                "        {function_field} = builder.DeclareGenericFunction(\n            {identity},\n            {variant});\n",
                function_field = allocated(render.names, &function.field_request).source(),
                identity = csharp_string(&function.wire_identity),
                variant = csharp_string(variant),
            ));
            for parameter in &function.generic_params {
                source.push_str(&format!(
                    "        {parameter_field} = builder.DeclareTypeParameter(\n            {function_field},\n            {wire});\n",
                    parameter_field = allocated(render.names, &parameter.field_request).source(),
                    function_field = allocated(render.names, &function.field_request).source(),
                    wire = csharp_string(parameter.name.as_str()),
                ));
            }
        }
        for argument in &function.arguments {
            if function.generic_params.is_empty() {
                source.push_str(&format!(
                    "        {argument_field} = builder.DeclareArgument(\n            {function_field},\n            {wire},\n            {type_field},\n            optional: {optional});\n",
                    argument_field = allocated(render.names, &argument.field_request).source(),
                    function_field = allocated(render.names, &function.field_request).source(),
                    wire = csharp_string(argument.argument.name.as_str()),
                    type_field = render.type_field(&argument.ty),
                    optional = argument.optional,
                ));
            } else {
                source.push_str(&format!(
                    "        {argument_field} = builder.DeclareGenericArgument(\n            {function_field},\n            {wire},\n            optional: {optional});\n",
                    argument_field = allocated(render.names, &argument.field_request).source(),
                    function_field = allocated(render.names, &function.field_request).source(),
                    wire = csharp_string(argument.argument.name.as_str()),
                    optional = argument.optional,
                ));
            }
        }
    }
    for class in render.classes {
        for method in &class.methods {
            let function_field = allocated(render.names, &method.function_field_request).source();
            let variant = if is_stream_callable_variant(method.variant) {
                "stream"
            } else {
                "call"
            };
            source.push_str(&format!(
                "        {function_field} = builder.DeclareGenericFunction(\n            {identity},\n            {variant});\n",
                identity = csharp_string(&method.wire_identity),
                variant = csharp_string(variant),
            ));
            for parameter in &method.type_params {
                source.push_str(&format!(
                    "        {parameter_field} = builder.DeclareTypeParameter(\n            {function_field},\n            {wire});\n",
                    parameter_field = allocated(render.names, &parameter.field_request).source(),
                    wire = csharp_string(parameter.name.as_str()),
                ));
            }
            if let Some(receiver) = &method.receiver_field_request {
                source.push_str(&format!(
                    "        {receiver_field} = builder.DeclareGenericArgument(\n            {function_field},\n            \"self\",\n            isSelf: true);\n",
                    receiver_field = allocated(render.names, receiver).source(),
                ));
            }
            for argument in &method.arguments {
                source.push_str(&format!(
                    "        {argument_field} = builder.DeclareGenericArgument(\n            {function_field},\n            {wire},\n            optional: {optional});\n",
                    argument_field = allocated(render.names, &argument.field_request).source(),
                    wire = csharp_string(argument.argument.name.as_str()),
                    optional = argument.optional,
                ));
            }
        }
    }
    for class in render
        .classes
        .iter()
        .filter(|class| !class.generic_params.is_empty())
    {
        let open_type = format!(
            "{}<{}>",
            render.nominal_source(class.name, true),
            ",".repeat(class.generic_params.len() - 1),
        );
        let factory = allocated(render.names, &class.generic_factory_request).source();
        source.push_str(&format!(
            "        builder.RegisterGenericTypeFactory(\n            typeof({open_type}),\n            typeof({program_type}).GetMethod(\n                nameof({factory}),\n                global::System.Reflection.BindingFlags.Static\n                    | global::System.Reflection.BindingFlags.NonPublic)!);\n"
        ));
    }
    source.push_str(&format!(
        "        {registry} = builder.Build();\n    }}\n\n    private static global::Baml.Generated.V1.BamlGeneratedProgram Register() =>\n        global::Baml.Generated.V1.BamlGeneratedContract.RegisterProgram(\n            global::Baml.Generated.V1.BamlGeneratedContract.Version,\n            Bytecode,\n            Fingerprint,\n            {embedded_baml_toml},\n            {registry});\n\n",
        embedded_baml_toml = embedded_baml_toml
            .map(csharp_string)
            .unwrap_or_else(|| "null".to_string()),
    ));
    for ty in render.type_specs {
        source.push_str(&render_codec(
            render,
            &ty.ty,
            allocated(render.names, &ty.codec_request).source(),
        ));
        source.push('\n');
    }
    for class in render
        .classes
        .iter()
        .filter(|class| !class.generic_params.is_empty())
    {
        if is_resource_projection(class.name) {
            source.push_str(&render_generic_resource_support(render, class));
        } else {
            source.push_str(&render_generic_class_support(render, class));
        }
        source.push('\n');
    }
    source.push_str("}\n");
    source
}

fn render_codec(render: &RenderContext<'_>, ty: &Ty, codec_name: &str) -> String {
    let source_type = render.type_source(ty);
    let (encode, decode) = match ty {
        Ty::Bool { .. } => (
            "            return context.Bool(value);\n".to_string(),
            "            return context.ReadBool(value);\n".to_string(),
        ),
        Ty::Int { .. } => (
            "            return context.Int(value);\n".to_string(),
            "            return context.ReadInt(value);\n".to_string(),
        ),
        Ty::Bigint { .. } => (
            "            return context.BigInt(value);\n".to_string(),
            "            return context.ReadBigInt(value);\n".to_string(),
        ),
        Ty::Float { .. } => (
            "            return context.Float(value);\n".to_string(),
            "            return context.ReadFloat(value);\n".to_string(),
        ),
        Ty::String { .. } => (
            "            return context.String(value);\n".to_string(),
            "            return context.ReadString(value);\n".to_string(),
        ),
        Ty::Uint8Array { .. } => (
            "            return context.Bytes(value.Span);\n".to_string(),
            "            return new global::System.ReadOnlyMemory<byte>(context.ReadBytes(value));\n"
                .to_string(),
        ),
        Ty::Media(MediaKind::Image, _) => (
            "            return context.Media(value);\n".to_string(),
            "            return context.ReadImage(value);\n".to_string(),
        ),
        Ty::Media(MediaKind::Audio, _) => (
            "            return context.Media(value);\n".to_string(),
            "            return context.ReadAudio(value);\n".to_string(),
        ),
        Ty::Media(MediaKind::Video, _) => (
            "            return context.Media(value);\n".to_string(),
            "            return context.ReadVideo(value);\n".to_string(),
        ),
        Ty::Media(MediaKind::Pdf, _) => (
            "            return context.Media(value);\n".to_string(),
            "            return context.ReadPdf(value);\n".to_string(),
        ),
        Ty::Null { .. } => (
            "            if (value is null || value.Kind != global::Baml.BamlValueKind.Null)\n            {\n                return context.Fail<global::Baml.Generated.V1.BamlGeneratedValue>(\n                    \"A generated null codec received a non-null BAML value.\",\n                    \"Standalone BAML null requires BamlValue.Null.\");\n            }\n            return context.Null();\n"
                .to_string(),
            "            if (!value.IsNull)\n            {\n                return context.Fail<global::Baml.BamlValue>(\n                    \"The native bridge returned a non-null value for a generated null position.\",\n                    \"Standalone BAML null requires BamlValue.Null.\");\n            }\n            return context.ReadValue(value);\n"
                .to_string(),
        ),
        Ty::Void { .. } => (
            "            if (value is null || value.Kind != global::Baml.BamlValueKind.Null)\n            {\n                return context.Fail<global::Baml.Generated.V1.BamlGeneratedValue>(\n                    \"A generated void codec received a non-null BAML value.\",\n                    \"BAML void is represented by the null wire value.\");\n            }\n            return context.Null();\n"
                .to_string(),
            "            if (!value.IsNull)\n            {\n                return context.Fail<global::Baml.BamlValue>(\n                    \"The native bridge returned a non-null value for BAML void.\",\n                    \"BAML void is represented by the null wire value.\");\n            }\n            return context.ReadValue(value);\n"
                .to_string(),
        ),
        Ty::Never { .. } => (
            "            return context.Fail<global::Baml.Generated.V1.BamlGeneratedValue>(\n                \"A generated never codec cannot encode a value.\",\n                \"A BAML never position is uninhabited.\");\n"
                .to_string(),
            "            return context.Fail<global::Baml.BamlValue>(\n                \"The native bridge returned from a function declared as never.\",\n                \"A BAML never position is uninhabited.\");\n"
                .to_string(),
        ),
        Ty::BuiltinUnknown { .. } => (
            "            return context.Value(value);\n".to_string(),
            "            return context.ReadValue(value);\n".to_string(),
        ),
        Ty::Literal(literal, ..) => render_literal_codec(literal),
        Ty::TypeAlias(name, _) => {
            let target = render.alias_target(name);
            let field = render.type_field(target);
            (
                format!("            return context.ForwardEncode({field}, value);\n"),
                format!("            return context.Decode({field}, value);\n"),
            )
        }
        Ty::Class(name, _, _) if is_runtime_class_projection(name) => {
            render_builtin_codec(render, ty, name)
        }
        Ty::Class(name, arguments, _) => render_class_codec(render, name, arguments),
        Ty::Enum(name, _) => render_enum_codec(render, name, None),
        Ty::EnumVariant(name, variant, _) => render_enum_codec(render, name, Some(variant)),
        Ty::List(item, _) => render_list_codec(render, item),
        Ty::Map { key, value, .. } => render_map_codec(render, key, value),
        Ty::Union(members, _) => render_union_codec(render, ty, members),
        Ty::Function { params, ret, .. } => render_function_codec(render, params, ret),
        _ => unreachable!("unsupported types are rejected before codec rendering"),
    };
    format!(
        "    private sealed class {codec_name} : global::Baml.Generated.V1.IBamlGeneratedCodec<{source_type}>\n    {{\n        public global::Baml.Generated.V1.BamlGeneratedValue Encode(\n            global::Baml.Generated.V1.BamlGeneratedCodecContext context,\n            {source_type} value)\n        {{\n{encode}        }}\n\n        public {source_type} Decode(\n            global::Baml.Generated.V1.BamlGeneratedCodecContext context,\n            global::Baml.Generated.V1.BamlGeneratedValue value)\n        {{\n{decode}        }}\n    }}\n"
    )
}

fn render_function_codec(
    render: &RenderContext<'_>,
    params: &[CallableParam],
    ret: &Ty,
) -> (String, String) {
    let delegate_type = function_type_source(params, ret, |item| render.type_source(item));
    let descriptors = params
        .iter()
        .map(|parameter| match parameter.mode {
            CodegenFunctionParamMode::Required => {
                format!("context.Required({})", render.type_field(&parameter.ty))
            }
            CodegenFunctionParamMode::Optional => format!(
                "context.Optional({}, {})",
                csharp_string(
                    parameter
                        .name
                        .as_ref()
                        .expect("supported optional callback parameters have wire names")
                        .as_str()
                ),
                render.type_field(&parameter.ty),
            ),
        })
        .collect::<Vec<_>>()
        .join(", ");
    let result = if matches!(ret, Ty::Void { .. }) {
        "context.VoidResult()".to_string()
    } else {
        format!("context.Result({})", render.type_field(ret))
    };
    let mut invocation_arguments = params
        .iter()
        .enumerate()
        .map(|(index, parameter)| {
            let source = render.type_source(&parameter.ty);
            let source = if parameter.mode == CodegenFunctionParamMode::Optional {
                format!("global::Baml.BamlOptional<{source}>")
            } else {
                source
            };
            format!("({source})arguments[{index}]!")
        })
        .collect::<Vec<_>>();
    invocation_arguments.push("cancellationToken".to_string());
    let encode = format!(
        "            return context.HostCallable(\n                value,\n                new global::Baml.Generated.V1.BamlGeneratedHostParameter[] {{ {descriptors} }},\n                {result},\n                static (callback, arguments, cancellationToken) =>\n                    global::Baml.Generated.V1.BamlGeneratedHostCallableRuntime.Await(\n                        (({delegate_type})callback)({invocation})));\n",
        invocation = invocation_arguments.join(", "),
    );
    let parameter_declarations = params
        .iter()
        .enumerate()
        .map(|(index, parameter)| {
            let source = render.type_source(&parameter.ty);
            let source = if parameter.mode == CodegenFunctionParamMode::Optional {
                format!("global::Baml.BamlOptional<{source}>")
            } else {
                source
            };
            format!("{source} argument{index}")
        })
        .chain(std::iter::once(
            "global::System.Threading.CancellationToken cancellationToken".to_string(),
        ))
        .collect::<Vec<_>>()
        .join(", ");
    let argument_encoding = params
        .iter()
        .enumerate()
        .map(|(index, parameter)| {
            let wire_name = csharp_string(
                parameter
                    .name
                    .as_ref()
                    .map_or_else(|| format!("arg{index}"), |name| name.as_str().to_string())
                    .as_str(),
            );
            let encoded = format!(
                "context.EncodeFresh({}, argument{index})",
                render.type_field(&parameter.ty)
            );
            match parameter.mode {
                CodegenFunctionParamMode::Required => format!(
                    "                arguments.Add(new global::System.Collections.Generic.KeyValuePair<string, global::Baml.Generated.V1.BamlGeneratedValue>({wire_name}, {encoded}));\n"
                ),
                CodegenFunctionParamMode::Optional => format!(
                    "                if (argument{index}.TryGetValue(out var value{index}))\n                {{\n                    arguments.Add(new global::System.Collections.Generic.KeyValuePair<string, global::Baml.Generated.V1.BamlGeneratedValue>({wire_name}, context.EncodeFresh({}, value{index})));\n                }}\n",
                    render.type_field(&parameter.ty)
                ),
            }
        })
        .collect::<String>();
    let decode_result = if matches!(ret, Ty::Void { .. }) {
        "                _ = await nativeFunction(arguments, cancellationToken).ConfigureAwait(false);\n".to_string()
    } else {
        format!(
            "                var result = await nativeFunction(arguments, cancellationToken).ConfigureAwait(false);\n                return context.Decode({}, result);\n",
            render.type_field(ret)
        )
    };
    let decode = format!(
        "            var nativeFunction = context.NativeFunction(value);\n            return async ({parameter_declarations}) =>\n            {{\n                var arguments = new global::System.Collections.Generic.List<global::System.Collections.Generic.KeyValuePair<string, global::Baml.Generated.V1.BamlGeneratedValue>>({});\n{argument_encoding}{decode_result}            }};\n",
        params.len()
    );
    (encode, decode)
}

fn render_builtin_codec(render: &RenderContext<'_>, ty: &Ty, name: &Name) -> (String, String) {
    match builtin_projection(name).expect("builtin codec requires a classified projection") {
        BuiltinProjection::StructuralClass | BuiltinProjection::StructuralEnum => {
            unreachable!("structural builtins use generated nominal codecs")
        }
        BuiltinProjection::Resource => {
            let identity = csharp_string(&name.to_string());
            let metadata = byte_array_source(&render.wire_metadata(ty));
            let source = render.type_source(ty);
            let Ty::Class(_, arguments, _) = ty else {
                unreachable!("resource projections are nominal classes")
            };
            let class = render.class(name);
            let public_properties = class
                .properties
                .iter()
                .filter(|property| !property.property.name.as_str().starts_with('_'))
                .collect::<Vec<_>>();
            let mut decode = format!(
                "            global::Baml.Generated.V1.BamlGeneratedResource resource =\n                context.ReadResource(value, {identity}, {metadata});\n            global::System.Collections.Generic.IReadOnlyDictionary<string, global::Baml.Generated.V1.BamlGeneratedValue> fields =\n                context.ReadResourceFields(resource);\n",
            );
            for (index, property) in public_properties.iter().enumerate() {
                decode.push_str(&format!(
                    "            if (!fields.TryGetValue({}, out global::Baml.Generated.V1.BamlGeneratedValue? field{index}))\n            {{\n                return context.Fail<{source}>(\n                    \"The native bridge omitted a required BAML resource field.\",\n                    {});\n            }}\n",
                    csharp_string(property.property.name.as_str()),
                    csharp_string(&format!(
                        "Resource {name} omitted public field {}.",
                        property.property.name
                    )),
                ));
            }
            let decoded_properties = public_properties
                .iter()
                .enumerate()
                .map(|(index, property)| {
                    let property_ty = instantiated_class_property_codec_type(
                        class.name,
                        &class.class.generic_params,
                        arguments,
                        &property.property.ty,
                    );
                    format!(
                        "context.Decode({}, field{index})",
                        render.type_field(&property_ty),
                    )
                })
                .collect::<Vec<_>>();
            decode.push_str(&format!(
                "            return new {source}(\n                resource{comma}{properties});\n",
                comma = if decoded_properties.is_empty() {
                    ""
                } else {
                    ",\n                "
                },
                properties = decoded_properties.join(",\n                "),
            ));
            (
                format!(
                    "            if (value is null)\n            {{\n                return context.Fail<global::Baml.Generated.V1.BamlGeneratedValue>(\n                    \"A generated resource codec received null.\",\n                    \"Resource {name} is non-nullable.\");\n            }}\n            return context.Resource(value.Resource, {identity}, {metadata});\n"
                ),
                decode,
            )
        }
        BuiltinProjection::OpaqueHandle => {
            let identity = csharp_string(&name.to_string());
            let metadata = byte_array_source(&render.wire_metadata(ty));
            (
                format!("            return context.Handle(value, {identity}, {metadata});\n"),
                format!("            return context.ReadHandle(value, {identity}, {metadata});\n"),
            )
        }
        BuiltinProjection::UnsupportedInternal => {
            unreachable!("unsupported builtins are rejected before rendering")
        }
    }
}

fn render_generic_resource_support(render: &RenderContext<'_>, class: &ClassSpec<'_>) -> String {
    let codec = allocated(render.names, &class.generic_codec_request).source();
    let factory = allocated(render.names, &class.generic_factory_request).source();
    let generic_parameters = class
        .generic_params
        .iter()
        .map(|parameter| allocated(render.names, &parameter.request).source())
        .collect::<Vec<_>>();
    let generic_suffix = format!("<{}>", generic_parameters.join(", "));
    let class_source = format!(
        "{}{}",
        render.nominal_source(class.name, true),
        generic_suffix,
    );
    let identity = csharp_string(&class.name.to_string());
    let public_properties = class
        .properties
        .iter()
        .filter(|property| !property.property.name.as_str().starts_with('_'))
        .collect::<Vec<_>>();

    let mut source = format!(
        "    private static global::Baml.Generated.V1.BamlGeneratedTypeFactoryResult {factory}{generic_suffix}(\n        global::Baml.Generated.V1.BamlGeneratedRegistry registry)\n    {{\n"
    );
    for parameter in &class.generic_params {
        let parameter_source = allocated(render.names, &parameter.request).source();
        source.push_str(&format!(
            "        global::Baml.Generated.V1.BamlGeneratedType<{parameter_source}> type_{parameter_source} =\n            registry.ResolveType<{parameter_source}>({position});\n        global::Baml.Generated.V1.BamlGeneratedTypeArgument argument_{parameter_source} =\n            registry.TypeArgument(type_{parameter_source});\n",
            position = csharp_string(&format!("{}.{}", class.name, parameter.name)),
        ));
    }
    for (index, property) in public_properties.iter().enumerate() {
        let projected = property_codec_type(class, &property.property.ty);
        source.push_str(&format!(
            "        global::Baml.Generated.V1.BamlGeneratedType<{}> property_type_{index} =\n            {};\n",
            render.type_source_for(&projected, &class.generic_params),
            render_generic_class_type_token(render, class, &projected),
        ));
    }
    let type_arguments = generic_parameters
        .iter()
        .map(|parameter| format!("argument_{parameter}"))
        .collect::<Vec<_>>();
    let property_tokens = (0..public_properties.len())
        .map(|index| format!("property_type_{index}"))
        .collect::<Vec<_>>();
    let mut codec_arguments = property_tokens;
    codec_arguments.push("type_arguments".to_string());
    source.push_str(&format!(
        "        global::Baml.Generated.V1.BamlGeneratedTypeArgument[] type_arguments =\n        [\n            {}\n        ];\n        return registry.CreateClassTypeFactoryResult<{class_source}>(\n            {identity},\n            new {codec}{generic_suffix}({}),\n            type_arguments);\n    }}\n\n",
        type_arguments.join(", "),
        codec_arguments.join(", "),
    ));

    source.push_str(&format!(
        "    private sealed class {codec}{generic_suffix} :\n        global::Baml.Generated.V1.IBamlGeneratedCodec<{class_source}>\n    {{\n"
    ));
    for (index, property) in public_properties.iter().enumerate() {
        let projected = property_codec_type(class, &property.property.ty);
        source.push_str(&format!(
            "        private readonly global::Baml.Generated.V1.BamlGeneratedType<{}> propertyType{index};\n",
            render.type_source_for(&projected, &class.generic_params),
        ));
    }
    source.push_str(
        "        private readonly global::System.Collections.Generic.IReadOnlyList<global::Baml.Generated.V1.BamlGeneratedTypeArgument> typeArguments;\n\n",
    );
    let mut constructor_parameters = public_properties
        .iter()
        .enumerate()
        .map(|(index, property)| {
            let projected = property_codec_type(class, &property.property.ty);
            format!(
                "global::Baml.Generated.V1.BamlGeneratedType<{}> propertyType{index}",
                render.type_source_for(&projected, &class.generic_params),
            )
        })
        .collect::<Vec<_>>();
    constructor_parameters.push(
        "global::System.Collections.Generic.IReadOnlyList<global::Baml.Generated.V1.BamlGeneratedTypeArgument> typeArguments".to_string(),
    );
    source.push_str(&format!(
        "        internal {codec}(\n            {})\n        {{\n",
        constructor_parameters.join(",\n            "),
    ));
    for index in 0..public_properties.len() {
        source.push_str(&format!(
            "            this.propertyType{index} = propertyType{index};\n"
        ));
    }
    source.push_str("            this.typeArguments = typeArguments;\n        }\n\n");

    source.push_str(&format!(
        "        public global::Baml.Generated.V1.BamlGeneratedValue Encode(\n            global::Baml.Generated.V1.BamlGeneratedCodecContext context,\n            {class_source} value)\n        {{\n            if (value is null)\n            {{\n                return context.Fail<global::Baml.Generated.V1.BamlGeneratedValue>(\n                    \"A generated resource codec received null.\",\n                    \"Resource {} is non-nullable.\");\n            }}\n            return context.Resource(value.Resource, {identity}, typeArguments);\n        }}\n\n",
        class.name,
    ));
    source.push_str(&format!(
        "        public {class_source} Decode(\n            global::Baml.Generated.V1.BamlGeneratedCodecContext context,\n            global::Baml.Generated.V1.BamlGeneratedValue value)\n        {{\n            global::Baml.Generated.V1.BamlGeneratedResource resource =\n                context.ReadResource(value, {identity}, typeArguments);\n            global::System.Collections.Generic.IReadOnlyDictionary<string, global::Baml.Generated.V1.BamlGeneratedValue> fields =\n                context.ReadResourceFields(resource);\n",
    ));
    for (index, property) in public_properties.iter().enumerate() {
        source.push_str(&format!(
            "            if (!fields.TryGetValue({}, out global::Baml.Generated.V1.BamlGeneratedValue? field{index}))\n            {{\n                return context.Fail<{class_source}>(\n                    \"The native bridge omitted a required BAML resource field.\",\n                    {});\n            }}\n",
            csharp_string(property.property.name.as_str()),
            csharp_string(&format!(
                "Resource {} omitted public field {}.",
                class.name, property.property.name
            )),
        ));
    }
    source.push_str(&format!(
        "            return new {class_source}(\n                resource"
    ));
    for index in 0..public_properties.len() {
        source.push_str(&format!(
            ",\n                context.Decode(propertyType{index}, field{index})"
        ));
    }
    source.push_str(");\n        }\n    }\n");
    source
}

