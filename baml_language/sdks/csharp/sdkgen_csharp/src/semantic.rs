#[allow(clippy::too_many_arguments)]
fn generate_program_inner(
    model: &CodegenModel,
    runtime_identities: Option<&RuntimeCallableIdentities>,
    program_bytes: &[u8],
    embedded_baml_toml: Option<&str>,
    cli_version: &str,
    required_bridge_version: &str,
    program_identity: &str,
) -> Result<GeneratedTree, CSharpGenerationError> {
    let normalized_model = normalize_model(model);
    let model = &normalized_model;
    let program_namespace_requests = generated_program_namespace_requests();
    let program_fqn = generated_program_fqn();
    let program_type_request = generated_request(
        program_fqn.clone(),
        "BamlProgram",
        CSharpNameKind::HelperType,
        CSharpScope::Namespace {
            package: BaseName::new("user"),
            path: vec![BaseName::new("Baml"), BaseName::new("Generated")],
        },
    );
    let program_file_request = generated_request(
        program_fqn.clone(),
        "BamlProgram",
        CSharpNameKind::FileStem,
        CSharpScope::Type(program_fqn.clone()),
    );
    let registry_request = helper_request(&program_fqn, "Registry");
    let instance_request = helper_request(&program_fqn, "Instance");
    let deferred_instance_request = helper_request(&program_fqn, "DeferredProgram");

    let classes = collect_classes(model, runtime_identities)?;
    let enums = collect_enums(model)?;
    let functions = collect_functions(model, &program_fqn)?;
    if functions.is_empty() && classes.iter().all(|class| class.methods.is_empty()) {
        return Err(CSharpGenerationError::Unsupported(
            "C# generation requires at least one supported user callable".to_string(),
        ));
    }

    let mut all_types = BTreeSet::new();
    for function in &functions {
        collect_type_closure(&function.result, model, &mut all_types)?;
        if let Some(partial) = &function.stream_partial {
            collect_type_closure(partial, model, &mut all_types)?;
        }
        for argument in &function.arguments {
            collect_argument_type_closure(&argument.ty, model, &mut all_types)?;
        }
    }
    for class in &classes {
        if !is_resource_projection(class.name) {
            for property in &class.class.properties {
                collect_type_closure(
                    &property_codec_type(class, &property.ty),
                    model,
                    &mut all_types,
                )?;
            }
        }
        for method in &class.methods {
            collect_type_closure(&method.result, model, &mut all_types)?;
            if let Some(partial) = &method.stream_partial {
                collect_type_closure(partial, model, &mut all_types)?;
            }
            for argument in &method.arguments {
                collect_argument_type_closure(&argument.ty, model, &mut all_types)?;
            }
            if !method.is_static {
                collect_type_closure(&class_receiver_type(class), model, &mut all_types)?;
            }
        }
    }
    let has_generic_callables = functions
        .iter()
        .any(|function| !function.generic_params.is_empty())
        || classes.iter().any(|class| {
            (!is_resource_projection(class.name) && !class.generic_params.is_empty())
                || class
                    .methods
                    .iter()
                    .any(|method| !method.type_params.is_empty())
        });
    if has_generic_callables {
        for ty in canonical_generic_primitive_types()
            .into_iter()
            .chain(
                classes
                    .iter()
                    .filter(|class| class.generic_params.is_empty())
                    .map(|class| Ty::Class(class.name.clone(), vec![], TyAttr::EMPTY)),
            )
            .chain(
                enums
                    .iter()
                    .map(|enumeration| Ty::Enum(enumeration.name.clone(), TyAttr::EMPTY)),
            )
        {
            collect_type_closure(&ty, model, &mut all_types)?;
        }
    }
    let type_specs = all_types
        .into_iter()
        .map(|ty| {
            let stem = type_helper_stem(&ty);
            TypeSpec {
                ty,
                field_request: helper_request(&program_fqn, &format!("{stem}_type")),
                codec_request: helper_request(&program_fqn, &format!("{stem}_codec")),
            }
        })
        .collect::<Vec<_>>();

    let mut requests = Vec::new();
    requests.extend(program_namespace_requests.iter().cloned());
    requests.extend([
        program_type_request.clone(),
        program_file_request.clone(),
        registry_request.clone(),
        instance_request.clone(),
        deferred_instance_request.clone(),
    ]);
    for ty in &type_specs {
        requests.extend([ty.field_request.clone(), ty.codec_request.clone()]);
    }
    for function in &functions {
        requests.extend(function.namespace_requests.iter().cloned());
        requests.extend([
            function.holder_request.clone(),
            function.file_request.clone(),
            function.method_request.clone(),
            function.async_request.clone(),
            function.cancellation_request.clone(),
            function.field_request.clone(),
            function.locals.function_request.clone(),
            function.locals.arguments_request.clone(),
            function.locals.host_context_request.clone(),
            function.locals.host_encoded_delegate_request.clone(),
            function.locals.host_invoked_delegate_request.clone(),
            function.locals.host_invocation_arguments_request.clone(),
            function.locals.host_invocation_cancellation_request.clone(),
        ]);
        requests.extend(function.locals.type_requests.iter().cloned());
        requests.extend(function.locals.binding_requests.iter().cloned());
        for parameter in &function.generic_params {
            requests.extend([parameter.request.clone(), parameter.field_request.clone()]);
        }
        for argument in &function.arguments {
            requests.extend([
                argument.parameter_request.clone(),
                argument.field_request.clone(),
            ]);
        }
    }
    for class in &classes {
        requests.extend(class.namespace_requests.iter().cloned());
        requests.extend([class.type_request.clone(), class.file_request.clone()]);
        if !class.generic_params.is_empty() {
            requests.extend([
                class.generic_codec_request.clone(),
                class.generic_factory_request.clone(),
            ]);
        }
        requests.extend(
            class
                .generic_params
                .iter()
                .map(|parameter| parameter.request.clone()),
        );
        requests.extend(
            class
                .properties
                .iter()
                .map(|property| property.request.clone()),
        );
        for method in &class.methods {
            requests.extend([
                method.method_request.clone(),
                method.async_request.clone(),
                method.cancellation_request.clone(),
                method.function_field_request.clone(),
                method.locals.function_request.clone(),
                method.locals.arguments_request.clone(),
                method.locals.host_context_request.clone(),
                method.locals.host_encoded_delegate_request.clone(),
                method.locals.host_invoked_delegate_request.clone(),
                method.locals.host_invocation_arguments_request.clone(),
                method.locals.host_invocation_cancellation_request.clone(),
            ]);
            requests.extend(method.locals.type_requests.iter().cloned());
            requests.extend(method.locals.binding_requests.iter().cloned());
            if let Some(receiver) = &method.receiver_field_request {
                requests.push(receiver.clone());
            }
            let inherited = if method.is_static {
                0
            } else {
                class.generic_params.len()
            };
            for (index, parameter) in method.type_params.iter().enumerate() {
                if index >= inherited {
                    requests.push(parameter.request.clone());
                }
                requests.push(parameter.field_request.clone());
            }
            for argument in &method.arguments {
                requests.extend([
                    argument.parameter_request.clone(),
                    argument.field_request.clone(),
                ]);
            }
        }
    }
    for enumeration in &enums {
        requests.extend(enumeration.namespace_requests.iter().cloned());
        requests.extend([
            enumeration.type_request.clone(),
            enumeration.file_request.clone(),
        ]);
        requests.extend(
            enumeration
                .variants
                .iter()
                .map(|variant| variant.request.clone()),
        );
    }
    let names = CSharpNames::allocate(requests);

    let program_route_request = FileRouteRequest::new(
        program_fqn.clone(),
        program_namespace_requests
            .iter()
            .map(|request| allocated(&names, request).clone()),
        allocated(&names, &program_file_request).clone(),
    )?;
    let mut function_routes = BTreeMap::<Vec<String>, FileRouteRequest>::new();
    for function in &functions {
        let key = namespace_key(function.name);
        if function_routes.contains_key(&key) {
            continue;
        }
        function_routes.insert(
            key,
            FileRouteRequest::new(
                BamlFqn::symbol(function.name),
                function
                    .namespace_requests
                    .iter()
                    .map(|request| allocated(&names, request).clone()),
                allocated(&names, &function.file_request).clone(),
            )?,
        );
    }
    let class_routes = classes
        .iter()
        .map(|class| {
            FileRouteRequest::new(
                BamlFqn::symbol(class.name),
                class
                    .namespace_requests
                    .iter()
                    .map(|request| allocated(&names, request).clone()),
                allocated(&names, &class.file_request).clone(),
            )
        })
        .collect::<Result<Vec<_>, _>>()?;
    let enum_routes = enums
        .iter()
        .map(|enumeration| {
            FileRouteRequest::new(
                BamlFqn::symbol(enumeration.name),
                enumeration
                    .namespace_requests
                    .iter()
                    .map(|request| allocated(&names, request).clone()),
                allocated(&names, &enumeration.file_request).clone(),
            )
        })
        .collect::<Result<Vec<_>, _>>()?;

    let routes = CSharpFileRoutes::allocate(
        std::iter::once(program_route_request.clone())
            .chain(function_routes.values().cloned())
            .chain(class_routes.iter().cloned())
            .chain(enum_routes.iter().cloned()),
    )?;
    let plan = CSharpRenderPlan::new(model, &names, &routes)?;
    let render = RenderContext {
        model,
        names: &names,
        type_specs: &type_specs,
        classes: &classes,
        enums: &enums,
    };

    let mut sources = Vec::<RoutedSource>::new();
    for (namespace, request) in &function_routes {
        let leaf_functions = functions
            .iter()
            .filter(|function| namespace_key(function.name) == *namespace)
            .collect::<Vec<_>>();
        sources.push(plan.render_source(request, |_| {
            render_functions(
                &render,
                &leaf_functions,
                &program_namespace_requests,
                &program_type_request,
                &deferred_instance_request,
            )
            .into_bytes()
        })?);
    }
    for (class, request) in classes.iter().zip(&class_routes) {
        sources.push(plan.render_source(request, |_| render_class(&render, class).into_bytes())?);
    }
    for (enumeration, request) in enums.iter().zip(&enum_routes) {
        sources
            .push(plan.render_source(request, |_| render_enum(&render, enumeration).into_bytes())?);
    }

    let carrier = plan.program_carrier(
        &program_route_request,
        render_program(
            &render,
            &functions,
            &program_namespace_requests,
            &program_type_request,
            &registry_request,
            &instance_request,
            &deferred_instance_request,
            embedded_baml_toml,
        ),
    )?;
    plan.prepare(GenerationInput::new(
        CONTRACT_VERSION,
        cli_version,
        required_bridge_version,
        program_identity,
        program_bytes,
        carrier,
        sources,
    ))
    .map_err(Into::into)
}

struct RenderContext<'a> {
    model: &'a CodegenModel,
    names: &'a CSharpNames,
    type_specs: &'a [TypeSpec],
    classes: &'a [ClassSpec<'a>],
    enums: &'a [EnumSpec<'a>],
}

impl RenderContext<'_> {
    fn type_source(&self, ty: &Ty) -> String {
        match ty {
            Ty::Bool { .. } => "bool".to_string(),
            Ty::Int { .. } => "long".to_string(),
            Ty::Bigint { .. } => "global::System.Numerics.BigInteger".to_string(),
            Ty::Float { .. } => "double".to_string(),
            Ty::String { .. } => "string".to_string(),
            Ty::Uint8Array { .. } => "global::System.ReadOnlyMemory<byte>".to_string(),
            Ty::Media(MediaKind::Image, _) => "global::Baml.BamlImage".to_string(),
            Ty::Media(MediaKind::Audio, _) => "global::Baml.BamlAudio".to_string(),
            Ty::Media(MediaKind::Video, _) => "global::Baml.BamlVideo".to_string(),
            Ty::Media(MediaKind::Pdf, _) => "global::Baml.BamlPdf".to_string(),
            Ty::Null { .. } | Ty::BuiltinUnknown { .. } | Ty::Void { .. } | Ty::Never { .. } => {
                "global::Baml.BamlValue".to_string()
            }
            Ty::Literal(literal, ..) => literal_source(literal).to_string(),
            Ty::TypeAlias(name, _) => self.type_source(self.alias_target(name)),
            Ty::Class(name, arguments, _) => {
                let nominal = builtin_type_source(name)
                    .map(str::to_string)
                    .unwrap_or_else(|| self.nominal_source(name, true));
                if arguments.is_empty()
                    || builtin_projection(name) == Some(BuiltinProjection::OpaqueHandle)
                {
                    nominal
                } else {
                    format!(
                        "{nominal}<{}>",
                        arguments
                            .iter()
                            .map(|argument| self.type_source(argument))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                }
            }
            Ty::Enum(name, _) | Ty::EnumVariant(name, ..) => builtin_type_source(name)
                .map(str::to_string)
                .unwrap_or_else(|| self.nominal_source(name, false)),
            Ty::List(item, _) => format!(
                "global::System.Collections.Generic.IReadOnlyList<{}>",
                self.type_source(item)
            ),
            Ty::Map { key, value, .. } => format!(
                "global::System.Collections.Generic.IReadOnlyDictionary<{}, {}>",
                self.type_source(key),
                self.type_source(value)
            ),
            Ty::Union(members, _) => {
                let non_null = members
                    .iter()
                    .filter(|member| !matches!(member, Ty::Null { .. }))
                    .collect::<Vec<_>>();
                if non_null.len() == 1 && non_null.len() != members.len() {
                    format!("{}?", self.type_source(non_null[0]))
                } else {
                    let source = format!(
                        "global::Baml.BamlUnion<{}>",
                        non_null
                            .iter()
                            .map(|member| self.type_source(member))
                            .collect::<Vec<_>>()
                            .join(", ")
                    );
                    if non_null.len() != members.len() {
                        format!("{source}?")
                    } else {
                        source
                    }
                }
            }
            Ty::Function { params, ret, .. } => {
                function_type_source(params, ret, |item| self.type_source(item))
            }
            _ => unreachable!("unsupported types are rejected before rendering"),
        }
    }

    fn type_source_for(&self, ty: &Ty, parameters: &[GenericParamSpec<'_>]) -> String {
        match ty {
            Ty::TypeVar(name, _) => parameters
                .iter()
                .rev()
                .find(|parameter| parameter.name == name.name())
                .map(|parameter| {
                    allocated(self.names, &parameter.request)
                        .source()
                        .to_string()
                })
                .unwrap_or_else(|| panic!("unbound generated type variable {name}")),
            Ty::TypeAlias(name, _) => self.type_source_for(self.alias_target(name), parameters),
            Ty::Class(name, arguments, _) if !arguments.is_empty() => {
                if let Some(source) = builtin_type_source(name) {
                    if builtin_projection(name) == Some(BuiltinProjection::OpaqueHandle) {
                        source.to_string()
                    } else {
                        format!(
                            "{source}<{}>",
                            arguments
                                .iter()
                                .map(|argument| self.type_source_for(argument, parameters))
                                .collect::<Vec<_>>()
                                .join(", ")
                        )
                    }
                } else {
                    format!(
                        "{}<{}>",
                        self.nominal_source(name, true),
                        arguments
                            .iter()
                            .map(|argument| self.type_source_for(argument, parameters))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                }
            }
            Ty::List(item, _) => format!(
                "global::System.Collections.Generic.IReadOnlyList<{}>",
                self.type_source_for(item, parameters)
            ),
            Ty::Map { key, value, .. } => format!(
                "global::System.Collections.Generic.IReadOnlyDictionary<{}, {}>",
                self.type_source_for(key, parameters),
                self.type_source_for(value, parameters)
            ),
            Ty::Union(members, _) => {
                let non_null = members
                    .iter()
                    .filter(|member| !matches!(member, Ty::Null { .. }))
                    .collect::<Vec<_>>();
                if non_null.len() == 1 && non_null.len() != members.len() {
                    let inner = self.type_source_for(non_null[0], parameters);
                    if matches!(non_null[0], Ty::TypeVar(..)) {
                        format!("global::Baml.BamlNullable<{inner}>")
                    } else {
                        format!("{inner}?")
                    }
                } else {
                    let source = format!(
                        "global::Baml.BamlUnion<{}>",
                        non_null
                            .iter()
                            .map(|member| self.type_source_for(member, parameters))
                            .collect::<Vec<_>>()
                            .join(", ")
                    );
                    if non_null.len() != members.len() {
                        format!("{source}?")
                    } else {
                        source
                    }
                }
            }
            Ty::Function { params, ret, .. } => {
                function_type_source(params, ret, |item| self.type_source_for(item, parameters))
            }
            _ => self.type_source(ty),
        }
    }

    fn nominal_source(&self, name: &Name, is_class: bool) -> String {
        if is_class {
            let spec = self
                .classes
                .iter()
                .find(|class| class.name == name)
                .expect("every class type has a generated declaration");
            qualified_name(self.names, &spec.namespace_requests, &spec.type_request)
        } else {
            let spec = self
                .enums
                .iter()
                .find(|enumeration| enumeration.name == name)
                .expect("every enum type has a generated declaration");
            qualified_name(self.names, &spec.namespace_requests, &spec.type_request)
        }
    }

    fn type_field(&self, ty: &Ty) -> &str {
        let codec_ty = codec_type(ty);
        let spec = self
            .type_specs
            .iter()
            .find(|spec| spec.ty == codec_ty)
            .unwrap_or_else(|| panic!("every reachable type has a generated token: {codec_ty:?}"));
        allocated(self.names, &spec.field_request).source()
    }

    fn class(&self, name: &Name) -> &ClassSpec<'_> {
        self.classes
            .iter()
            .find(|class| class.name == name)
            .expect("every class has a generated declaration")
    }

    fn enumeration(&self, name: &Name) -> &EnumSpec<'_> {
        self.enums
            .iter()
            .find(|enumeration| enumeration.name == name)
            .expect("every enum has a generated declaration")
    }

    fn alias_target(&self, name: &Name) -> &Ty {
        let Some(Symbol::TypeAlias(alias)) = self.model.symbols.get(name) else {
            panic!("every alias type has a declaration");
        };
        &alias.resolves_to
    }

    fn wire_type(&self, ty: &Ty) -> Ty {
        match ty {
            Ty::TypeAlias(name, _) => self.wire_type(self.alias_target(name)),
            Ty::Class(name, arguments, attr) => Ty::Class(
                name.clone(),
                arguments
                    .iter()
                    .map(|argument| self.wire_type(argument))
                    .collect(),
                attr.clone(),
            ),
            Ty::List(item, attr) => Ty::List(Box::new(self.wire_type(item)), attr.clone()),
            Ty::Map { key, value, attr } => Ty::Map {
                key: Box::new(self.wire_type(key)),
                value: Box::new(self.wire_type(value)),
                attr: attr.clone(),
            },
            Ty::Union(members, attr) => normalize_ty(&Ty::Union(
                members
                    .iter()
                    .map(|member| self.wire_type(member))
                    .collect(),
                attr.clone(),
            )),
            Ty::Function {
                params,
                ret,
                throws,
                attr,
            } => Ty::Function {
                params: params
                    .iter()
                    .map(|parameter| CallableParam {
                        name: parameter.name.clone(),
                        ty: self.wire_type(&parameter.ty),
                        mode: parameter.mode,
                    })
                    .collect(),
                ret: Box::new(self.wire_type(ret)),
                throws: Box::new(self.wire_type(throws)),
                attr: attr.clone(),
            },
            _ => normalize_ty(ty),
        }
    }

    fn wire_metadata(&self, ty: &Ty) -> Vec<u8> {
        encode_type_metadata(&self.wire_type(ty))
    }

    fn wire_option_name(&self, ty: &Ty) -> String {
        self.wire_type(ty).to_string()
    }

    fn is_value_projection(&self, ty: &Ty) -> bool {
        match ty {
            Ty::TypeAlias(name, _) => self.is_value_projection(self.alias_target(name)),
            Ty::Bool { .. }
            | Ty::Int { .. }
            | Ty::Bigint { .. }
            | Ty::Float { .. }
            | Ty::Uint8Array { .. }
            | Ty::Enum(..)
            | Ty::EnumVariant(..) => true,
            Ty::Literal(Literal::String(_), ..) => false,
            Ty::Literal(..) => true,
            Ty::Union(members, _) => !members
                .iter()
                .any(|member| matches!(member, Ty::Null { .. })),
            Ty::String { .. }
            | Ty::Null { .. }
            | Ty::Media(..)
            | Ty::Class(..)
            | Ty::List(..)
            | Ty::Map { .. }
            | Ty::Function { .. }
            | Ty::BuiltinUnknown { .. }
            | Ty::Void { .. }
            | Ty::Never { .. } => false,
            _ => unreachable!("unsupported type reached projection classification"),
        }
    }
}

fn function_type_source(
    params: &[CallableParam],
    ret: &Ty,
    mut project: impl FnMut(&Ty) -> String,
) -> String {
    let mut arguments = params
        .iter()
        .map(|parameter| {
            let source = project(&parameter.ty);
            if parameter.mode == CodegenFunctionParamMode::Optional {
                format!("global::Baml.BamlOptional<{source}>")
            } else {
                source
            }
        })
        .collect::<Vec<_>>();
    arguments.push("global::System.Threading.CancellationToken".to_string());
    let task = if matches!(ret, Ty::Void { .. }) {
        "global::System.Threading.Tasks.Task".to_string()
    } else {
        format!("global::System.Threading.Tasks.Task<{}>", project(ret))
    };
    arguments.push(task);
    format!("global::System.Func<{}>", arguments.join(", "))
}

fn collect_classes<'a>(
    model: &'a CodegenModel,
    runtime_identities: Option<&RuntimeCallableIdentities>,
) -> Result<Vec<ClassSpec<'a>>, CSharpGenerationError> {
    let mut symbols = model.symbols.iter().collect::<Vec<_>>();
    symbols.sort_by(|left, right| left.0.cmp(right.0));
    let mut classes = Vec::new();
    for (name, symbol) in symbols {
        let Symbol::Class(class) = symbol else {
            continue;
        };
        if name.package().as_str() != "user"
            && !is_structural_class_projection(name)
            && !is_resource_projection(name)
        {
            continue;
        }
        if name.package().as_str() == "user" {
            for property in &class.properties {
                require_unambiguous_csharp_unions(
                    &property.ty,
                    model,
                    &format!("property `{name}.{}`", property.name),
                )?;
            }
        }
        let fqn = BamlFqn::symbol(name);
        let namespace_requests = namespace_requests(name, CSharpNameOrigin::Source);
        let type_request = source_request(
            fqn.clone(),
            BamlWireName::Symbol(name.clone()),
            name.name().as_str(),
            CSharpNameKind::Class,
            CSharpScope::Namespace {
                package: name.package().clone(),
                path: name.namespace().clone(),
            },
        );
        let file_request = generated_request(
            fqn.clone(),
            name.name().as_str(),
            CSharpNameKind::FileStem,
            CSharpScope::Type(fqn.clone()),
        );
        let generic_codec_request = helper_request(
            &generated_program_fqn(),
            &format!("{}_generic_codec", name.name().as_str()),
        );
        let generic_factory_request = helper_request(
            &generated_program_fqn(),
            &format!("{}_generic_factory", name.name().as_str()),
        );
        let generic_params = class
            .generic_params
            .iter()
            .map(|parameter| GenericParamSpec {
                name: parameter,
                request: source_request(
                    fqn.member(parameter),
                    BamlWireName::Key(parameter.clone()),
                    parameter.as_str(),
                    CSharpNameKind::TypeParameter,
                    CSharpScope::Type(fqn.clone()),
                ),
                field_request: helper_request(
                    &fqn,
                    &format!("{}_type_parameter", parameter.as_str()),
                ),
            })
            .collect::<Vec<_>>();
        let properties = class
            .properties
            .iter()
            .map(|property| PropertySpec {
                property,
                request: source_request(
                    fqn.member(&property.name),
                    BamlWireName::Key(property.name.clone()),
                    property.name.as_str(),
                    CSharpNameKind::Property,
                    CSharpScope::Type(fqn.clone()),
                ),
            })
            .collect();
        let methods = collect_methods(model, runtime_identities, name, class, &generic_params)?;
        classes.push(ClassSpec {
            name,
            class,
            generic_params,
            namespace_requests,
            type_request,
            file_request,
            generic_codec_request,
            generic_factory_request,
            properties,
            methods,
        });
    }
    Ok(classes)
}

fn collect_methods<'a>(
    model: &'a CodegenModel,
    runtime_identities: Option<&RuntimeCallableIdentities>,
    owner: &'a Name,
    class: &'a Class,
    class_params: &[GenericParamSpec<'a>],
) -> Result<Vec<MethodSpec<'a>>, CSharpGenerationError> {
    let mut methods = Vec::new();
    for (is_static, method) in class
        .static_methods
        .iter()
        .map(|method| (true, method))
        .chain(class.instance_methods.iter().map(|method| (false, method)))
    {
        let resource_owner = is_resource_projection(owner);
        if resource_owner && method.name.as_str().starts_with('_') {
            continue;
        }
        let key = if is_static {
            CallableKey::StaticMethod {
                owner: owner.clone(),
                wire_name: method.name.clone(),
            }
        } else {
            CallableKey::InstanceMethod {
                owner: owner.clone(),
                wire_name: method.name.clone(),
            }
        };
        let identity = model.callable(&key).ok_or_else(|| {
            CSharpGenerationError::MissingCallable(format!("{owner}.{}", method.name))
        })?;
        let (result, stream_partial) = if is_stream_callable_variant(identity.variant) {
            let Ty::Class(stream_name, stream_types, _) = &method.return_type else {
                return Err(CSharpGenerationError::Unsupported(format!(
                    "C# stream companion `{owner}.{}` must return {AI_STREAM_STREAM}<TPartial, TFinal>",
                    method.name
                )));
            };
            if stream_name.to_string() != AI_STREAM_STREAM || stream_types.len() != 2 {
                return Err(CSharpGenerationError::Unsupported(format!(
                    "C# stream companion `{owner}.{}` must return exact {AI_STREAM_STREAM}<TPartial, TFinal>",
                    method.name
                )));
            }
            (stream_types[1].clone(), Some(stream_types[0].clone()))
        } else {
            (
                project_resource_method_result(owner, class, method, &method.return_type),
                None,
            )
        };
        let result_support = require_supported_type(
            &result,
            model,
            &format!("result of method `{owner}.{}`", method.name),
        );
        result_support?;
        if owner.package().as_str() == "user" {
            require_unambiguous_csharp_unions(
                &result,
                model,
                &format!("result of method `{owner}.{}`", method.name),
            )?;
        }
        if let Some(partial) = &stream_partial {
            let partial_support = require_supported_type(
                partial,
                model,
                &format!("partial result of method `{owner}.{}`", method.name),
            );
            partial_support?;
        }
        let argument_support: Result<(), CSharpGenerationError> =
            method.arguments.iter().try_for_each(|argument| {
                let path = format!(
                    "argument `{}` of method `{owner}.{}`",
                    argument.name, method.name
                );
                require_supported_argument_type(&argument.ty, model, &path)?;
                if owner.package().as_str() == "user" {
                    require_unambiguous_csharp_unions(&argument.ty, model, &path)?;
                }
                Ok(())
            });
        argument_support?;
        let owner_fqn = BamlFqn::symbol(owner);
        let callable_fqn = owner_fqn.member(&method.name);
        let mut type_params = if is_static {
            Vec::new()
        } else {
            class_params.to_vec()
        };
        for parameter in &method.generic_params {
            let shadows_class = class
                .generic_params
                .iter()
                .any(|class_parameter| class_parameter == parameter);
            type_params.push(GenericParamSpec {
                name: parameter,
                request: source_request(
                    callable_fqn.member(parameter),
                    BamlWireName::Key(parameter.clone()),
                    if shadows_class {
                        format!("{}Method", parameter.as_str())
                    } else {
                        parameter.as_str().to_string()
                    },
                    CSharpNameKind::TypeParameter,
                    CSharpScope::Callable(callable_fqn.clone()),
                ),
                field_request: helper_request(
                    &generated_program_fqn(),
                    &format!(
                        "{}_{}_{}_type_parameter",
                        method_helper_owner(owner),
                        callable_source_identity(identity),
                        parameter
                    ),
                ),
            });
        }
        for parameter in type_params
            .iter_mut()
            .take(if is_static { 0 } else { class_params.len() })
        {
            parameter.field_request = helper_request(
                &generated_program_fqn(),
                &format!(
                    "{}_{}_{}_class_type_parameter",
                    method_helper_owner(owner),
                    callable_source_identity(identity),
                    parameter.name
                ),
            );
        }

        let method_request = if identity.variant == CallableVariant::Execute {
            source_request(
                callable_fqn.clone(),
                BamlWireName::Key(identity.family_name.clone()),
                callable_source_identity(identity),
                CSharpNameKind::Function,
                CSharpScope::Type(owner_fqn.clone()),
            )
        } else {
            CSharpNameRequest::new(
                callable_fqn.clone(),
                BamlWireName::Key(identity.wire_name.clone()),
                callable_source_identity(identity),
                CSharpNameKind::Function,
                CSharpVisibility::Public,
                CSharpNameOrigin::CompilerGenerated,
                CSharpScope::Type(owner_fqn.clone()),
            )
        };
        let async_request = generated_request(
            callable_fqn.member(&BaseName::new("$async")),
            format!("{}_async", callable_source_identity(identity)),
            CSharpNameKind::Function,
            CSharpScope::Type(owner_fqn.clone()),
        );
        let cancellation_request = generated_request(
            callable_fqn.member(&BaseName::new("$cancellation")),
            "cancellation_token",
            CSharpNameKind::Parameter,
            CSharpScope::Callable(callable_fqn.clone()),
        );
        let function_field_request = helper_request(
            &generated_program_fqn(),
            &format!(
                "{}_{}_function",
                method_helper_owner(owner),
                callable_source_identity(identity)
            ),
        );
        let receiver_field_request = (!is_static).then(|| {
            helper_request(
                &generated_program_fqn(),
                &format!(
                    "{}_{}_self_argument",
                    method_helper_owner(owner),
                    callable_source_identity(identity)
                ),
            )
        });
        let mut arguments = Vec::new();
        for argument in &method.arguments {
            arguments.push(ArgumentSpec {
                argument,
                ty: argument.ty.clone(),
                optional: argument.default.is_some(),
                parameter_request: source_request(
                    callable_fqn.member(&argument.name),
                    BamlWireName::Key(argument.name.clone()),
                    argument.name.as_str(),
                    CSharpNameKind::Parameter,
                    CSharpScope::Callable(callable_fqn.clone()),
                ),
                field_request: helper_request(
                    &generated_program_fqn(),
                    &format!(
                        "{}_{}_{}_argument",
                        method_helper_owner(owner),
                        callable_source_identity(identity),
                        argument.name
                    ),
                ),
            });
        }
        let type_param_count = type_params.len();
        let wire_identity = match runtime_identities {
            Some(runtime) => runtime
                .method_identity(owner, &identity.wire_name)
                .map_err(CSharpGenerationError::MissingCallable)?,
            None => format!("{owner}.{}", identity.wire_name),
        };
        methods.push(MethodSpec {
            method,
            wire_identity,
            is_static,
            variant: identity.variant,
            result,
            stream_partial,
            type_params,
            method_type_param_count: method.generic_params.len(),
            method_request,
            async_request,
            cancellation_request,
            function_field_request,
            receiver_field_request,
            locals: callable_local_requests(&callable_fqn, type_param_count),
            arguments,
        });
    }
    methods.sort_by(|left, right| {
        left.method
            .origin
            .source_file_path
            .cmp(&right.method.origin.source_file_path)
            .then(
                left.method
                    .origin
                    .span_start
                    .cmp(&right.method.origin.span_start),
            )
            .then(left.method.name.cmp(&right.method.name))
    });
    Ok(methods)
}

fn collect_enums(model: &CodegenModel) -> Result<Vec<EnumSpec<'_>>, CSharpGenerationError> {
    let mut symbols = model.symbols.iter().collect::<Vec<_>>();
    symbols.sort_by(|left, right| left.0.cmp(right.0));
    let mut enums = Vec::new();
    for (name, symbol) in symbols {
        let Symbol::Enum(enumeration) = symbol else {
            continue;
        };
        if name.package().as_str() != "user" && !is_structural_enum_projection(name) {
            continue;
        }
        let fqn = BamlFqn::symbol(name);
        let namespace_requests = namespace_requests(name, CSharpNameOrigin::Source);
        let type_request = source_request(
            fqn.clone(),
            BamlWireName::Symbol(name.clone()),
            name.name().as_str(),
            CSharpNameKind::Enum,
            CSharpScope::Namespace {
                package: name.package().clone(),
                path: name.namespace().clone(),
            },
        );
        let file_request = generated_request(
            fqn.clone(),
            name.name().as_str(),
            CSharpNameKind::FileStem,
            CSharpScope::Enum(fqn.clone()),
        );
        let mut discriminants = BTreeMap::new();
        let mut variants = Vec::new();
        for variant in &enumeration.variants {
            let discriminant = enum_discriminant(name, &variant.name);
            if discriminant == 0 {
                return Err(CSharpGenerationError::InvalidEnum(format!(
                    "zero generated enum discriminant for `{name}.{}`",
                    variant.name
                )));
            }
            if let Some(previous) = discriminants.insert(discriminant, variant.name.as_str()) {
                return Err(CSharpGenerationError::InvalidEnum(format!(
                    "duplicate generated enum discriminant {discriminant} for `{name}.{previous}` and `{name}.{}`",
                    variant.name
                )));
            }
            variants.push(VariantSpec {
                variant,
                request: source_request(
                    fqn.member(&variant.name),
                    BamlWireName::Key(variant.name.clone()),
                    variant.name.as_str(),
                    CSharpNameKind::EnumMember,
                    CSharpScope::Enum(fqn.clone()),
                ),
                discriminant,
            });
        }
        if variants.is_empty() {
            return Err(CSharpGenerationError::InvalidEnum(format!(
                "C# enum `{name}` has no variants"
            )));
        }
        enums.push(EnumSpec {
            name,
            namespace_requests,
            type_request,
            file_request,
            variants,
        });
    }
    Ok(enums)
}

fn collect_functions<'a>(
    model: &'a CodegenModel,
    program_fqn: &BamlFqn,
) -> Result<Vec<FunctionSpec<'a>>, CSharpGenerationError> {
    let mut symbols = model.symbols.iter().collect::<Vec<_>>();
    symbols.sort_by(|left, right| left.0.cmp(right.0));
    let mut functions = Vec::new();
    for (name, symbol) in symbols {
        let stdlib_resource_function = is_public_resource_stdlib_function(name);
        if name.package().as_str() != "user" && !stdlib_resource_function {
            continue;
        }
        let Symbol::Function(function) = symbol else {
            continue;
        };
        let identity = model
            .callable(&CallableKey::Free(name.clone()))
            .ok_or_else(|| CSharpGenerationError::MissingCallable(name.to_string()))?;
        if identity.receiver.is_some() {
            return Err(CSharpGenerationError::Unsupported(format!(
                "C# generation expected a free function without a receiver for `{name}`"
            )));
        }
        let (result, stream_partial) = if is_stream_callable_variant(identity.variant) {
            let Ty::Class(stream_name, stream_types, _) = &function.return_type else {
                return Err(CSharpGenerationError::Unsupported(format!(
                    "C# stream companion `{name}` must return {AI_STREAM_STREAM}<TPartial, TFinal>"
                )));
            };
            if stream_name.to_string() != AI_STREAM_STREAM || stream_types.len() != 2 {
                return Err(CSharpGenerationError::Unsupported(format!(
                    "C# stream companion `{name}` must return exact {AI_STREAM_STREAM}<TPartial, TFinal>"
                )));
            }
            (stream_types[1].clone(), Some(stream_types[0].clone()))
        } else {
            (function.return_type.clone(), None)
        };
        require_supported_type(&result, model, &format!("result of `{name}`"))?;
        if name.package().as_str() == "user" {
            require_unambiguous_csharp_unions(&result, model, &format!("result of `{name}`"))?;
        }
        if let Some(partial) = &stream_partial {
            require_supported_type(partial, model, &format!("partial result of `{name}`"))?;
        }
        let argument_support: Result<(), CSharpGenerationError> =
            function.arguments.iter().try_for_each(|argument| {
                let path = format!("argument `{}` of `{name}`", argument.name);
                require_supported_argument_type(&argument.ty, model, &path)?;
                if name.package().as_str() == "user" {
                    require_unambiguous_csharp_unions(&argument.ty, model, &path)?;
                }
                Ok(())
            });
        argument_support?;
        let namespace_requests = namespace_requests(name, CSharpNameOrigin::Source);
        let holder_fqn = holder_fqn(name);
        let holder_request = public_generated_request(
            holder_fqn.clone(),
            "Functions",
            CSharpNameKind::FunctionsHolder,
            CSharpScope::Namespace {
                package: name.package().clone(),
                path: name.namespace().clone(),
            },
        );
        let file_request = generated_request(
            holder_fqn.clone(),
            "Functions",
            CSharpNameKind::FileStem,
            CSharpScope::Type(holder_fqn.clone()),
        );
        let callable_fqn = BamlFqn::symbol(name);
        let method_request = if identity.variant != CallableVariant::Execute {
            CSharpNameRequest::new(
                callable_fqn.clone(),
                BamlWireName::Symbol(name.clone()),
                callable_source_identity(identity),
                CSharpNameKind::Function,
                CSharpVisibility::Public,
                CSharpNameOrigin::CompilerGenerated,
                CSharpScope::Type(holder_fqn.clone()),
            )
        } else {
            source_request(
                callable_fqn.clone(),
                BamlWireName::Symbol(name.clone()),
                callable_source_identity(identity),
                CSharpNameKind::Function,
                CSharpScope::Type(holder_fqn.clone()),
            )
        };
        let async_request = generated_request(
            callable_fqn.member(&BaseName::new("$async")),
            format!("{}_async", callable_source_identity(identity)),
            CSharpNameKind::Function,
            CSharpScope::Type(holder_fqn),
        );
        let cancellation_request = generated_request(
            callable_fqn.member(&BaseName::new("$cancellation")),
            "cancellation_token",
            CSharpNameKind::Parameter,
            CSharpScope::Callable(callable_fqn.clone()),
        );
        let helper_family = if stdlib_resource_function {
            format!(
                "{}_{}",
                helper_identity(name),
                callable_source_identity(identity)
            )
        } else {
            callable_source_identity(identity).clone()
        };
        let field_request = helper_request(program_fqn, &format!("{helper_family}_function"));
        let generic_params = function
            .generic_params
            .iter()
            .map(|parameter| GenericParamSpec {
                name: parameter,
                request: source_request(
                    callable_fqn.member(parameter),
                    BamlWireName::Key(parameter.clone()),
                    parameter.as_str(),
                    CSharpNameKind::TypeParameter,
                    CSharpScope::Callable(callable_fqn.clone()),
                ),
                field_request: helper_request(
                    program_fqn,
                    &format!("{helper_family}_{parameter}_type_parameter"),
                ),
            })
            .collect::<Vec<_>>();
        let mut arguments = Vec::new();
        for argument in &function.arguments {
            arguments.push(ArgumentSpec {
                argument,
                ty: argument.ty.clone(),
                optional: argument.default.is_some(),
                parameter_request: source_request(
                    callable_fqn.member(&argument.name),
                    BamlWireName::Key(argument.name.clone()),
                    argument.name.as_str(),
                    CSharpNameKind::Parameter,
                    CSharpScope::Callable(callable_fqn.clone()),
                ),
                field_request: helper_request(
                    program_fqn,
                    &format!("{}_{}_argument", helper_family, argument.name),
                ),
            });
        }
        let generic_param_count = generic_params.len();
        functions.push(FunctionSpec {
            name,
            wire_identity: name.to_string(),
            variant: identity.variant,
            result,
            stream_partial,
            generic_params,
            namespace_requests,
            holder_request,
            file_request,
            method_request,
            async_request,
            cancellation_request,
            field_request,
            locals: callable_local_requests(&callable_fqn, generic_param_count),
            arguments,
        });
    }
    Ok(functions)
}

fn require_supported_type(
    ty: &Ty,
    model: &CodegenModel,
    path: &str,
) -> Result<(), CSharpGenerationError> {
    require_supported_type_inner(ty, model, path, false)
}

fn require_supported_argument_type(
    ty: &Ty,
    model: &CodegenModel,
    path: &str,
) -> Result<(), CSharpGenerationError> {
    require_supported_type_inner(
        ty,
        model,
        path,
        matches!(ty, Ty::Function { .. }) && contains_type_var(ty),
    )
}

fn require_supported_type_inner(
    ty: &Ty,
    model: &CodegenModel,
    path: &str,
    allow_generic_host_callable: bool,
) -> Result<(), CSharpGenerationError> {
    match ty {
        Ty::Bool { .. }
        | Ty::Int { .. }
        | Ty::Bigint { .. }
        | Ty::Float { .. }
        | Ty::String { .. }
        | Ty::Uint8Array { .. }
        | Ty::Null { .. }
        | Ty::BuiltinUnknown { .. }
        | Ty::Literal(..)
        | Ty::TypeVar(..)
        | Ty::Void { .. }
        | Ty::Never { .. } => Ok(()),
        Ty::Media(MediaKind::Image | MediaKind::Audio | MediaKind::Video | MediaKind::Pdf, _) => {
            Ok(())
        }
        Ty::Media(MediaKind::Generic, _) => Err(unsupported(path, &format!("type `{ty}`"))),
        Ty::Class(name, arguments, _) => {
            if builtin_projection(name) == Some(BuiltinProjection::UnsupportedInternal) {
                return Err(unsupported(
                    path,
                    &format!("internal standard-library class `{name}`"),
                ));
            }
            match model.symbols.get(name) {
                Some(Symbol::Class(class)) if class.generic_params.len() == arguments.len() => {
                    if name.package().as_str() != "user" && builtin_projection(name).is_none() {
                        return Err(unsupported(
                            path,
                            &format!("unclassified standard-library class `{name}`"),
                        ));
                    }
                    arguments
                        .iter()
                        .try_for_each(|argument| require_supported_type(argument, model, path))
                }
                _ => Err(unsupported(path, &format!("class `{name}`"))),
            }
        }
        Ty::Enum(name, _) | Ty::EnumVariant(name, ..) => match model.symbols.get(name) {
            Some(Symbol::Enum(_))
                if name.package().as_str() == "user" || is_structural_enum_projection(name) =>
            {
                Ok(())
            }
            _ => Err(unsupported(path, &format!("enum `{name}`"))),
        },
        Ty::List(item, _) => require_supported_type(item, model, path),
        Ty::Map { key, value, .. } => {
            require_supported_map_key(key, model, path)?;
            require_supported_type(value, model, path)
        }
        Ty::Union(members, _) => {
            let null_count = members
                .iter()
                .filter(|member| matches!(member, Ty::Null { .. }))
                .count();
            let non_null = members.len() - null_count;
            if null_count > 1 || non_null == 0 || non_null > 32 {
                return Err(unsupported(
                    path,
                    &format!("union with {non_null} non-null arms"),
                ));
            }
            if null_count == 0 && non_null < 2 {
                return Err(unsupported(path, "single-arm structural union"));
            }
            members
                .iter()
                .filter(|member| !matches!(member, Ty::Null { .. }))
                .try_for_each(|member| require_supported_type(member, model, path))
        }
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => {
            if params.len() > 15 {
                return Err(unsupported(
                    path,
                    &format!(
                        "host callable with {} BAML parameters; the C# v1 limit is 15 because CancellationToken occupies CLR Func input 16",
                        params.len()
                    ),
                ));
            }
            if contains_type_var(ty) && !allow_generic_host_callable {
                return Err(unsupported(
                    path,
                    "generic host callable outside a direct callable argument",
                ));
            }
            let mut saw_optional = false;
            for (index, parameter) in params.iter().enumerate() {
                match parameter.mode {
                    CodegenFunctionParamMode::Required if saw_optional => {
                        return Err(unsupported(
                            path,
                            &format!(
                                "host callable required parameter {index} after an optional parameter"
                            ),
                        ));
                    }
                    CodegenFunctionParamMode::Required => {}
                    CodegenFunctionParamMode::Optional => {
                        saw_optional = true;
                        if parameter
                            .name
                            .as_ref()
                            .is_none_or(|name| name.as_str().is_empty())
                        {
                            return Err(unsupported(
                                path,
                                &format!(
                                    "host callable optional parameter {index} without a wire name"
                                ),
                            ));
                        }
                    }
                }
                require_supported_type(&parameter.ty, model, path)?;
            }
            if !matches!(ret.as_ref(), Ty::Void { .. }) {
                require_supported_type(ret, model, path)?;
            }
            if !matches!(throws.as_ref(), Ty::Never { .. } | Ty::Void { .. })
                && !is_host_callable_error(throws)
            {
                require_supported_type(throws, model, path)?;
            }
            Ok(())
        }
        Ty::TypeAlias(name, _) => match model.symbols.get(name) {
            Some(Symbol::TypeAlias(alias)) if !alias.recursive => {
                require_supported_type(&alias.resolves_to, model, path)
            }
            _ => Err(unsupported(path, &format!("recursive type alias `{name}`"))),
        },
        _ => Err(unsupported(path, &format!("type `{ty}`"))),
    }
}

fn contains_type_var(ty: &Ty) -> bool {
    match ty {
        Ty::TypeVar(..) => true,
        Ty::Class(_, arguments, _) | Ty::Union(arguments, _) => {
            arguments.iter().any(contains_type_var)
        }
        Ty::List(item, _) => contains_type_var(item),
        Ty::Map { key, value, .. } => contains_type_var(key) || contains_type_var(value),
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => {
            params
                .iter()
                .any(|parameter| contains_type_var(&parameter.ty))
                || contains_type_var(ret)
                || (!is_synthetic_effect_type(throws) && contains_type_var(throws))
        }
        _ => false,
    }
}

fn is_synthetic_effect_type(ty: &Ty) -> bool {
    matches!(
        ty,
        Ty::TypeVar(name, _) if name.as_str().starts_with("__effect_param_")
    )
}

fn require_supported_map_key(
    ty: &Ty,
    model: &CodegenModel,
    path: &str,
) -> Result<(), CSharpGenerationError> {
    match ty {
        Ty::String { .. } | Ty::Literal(Literal::String(_), ..) => Ok(()),
        Ty::TypeAlias(name, _) => match model.symbols.get(name) {
            Some(Symbol::TypeAlias(alias)) if !alias.recursive => {
                require_supported_map_key(&alias.resolves_to, model, path)
            }
            _ => Err(unsupported(
                path,
                &format!("recursive alias map key `{name}`"),
            )),
        },
        _ => Err(unsupported(path, &format!("map key `{ty}`"))),
    }
}

fn require_unambiguous_csharp_unions(
    ty: &Ty,
    model: &CodegenModel,
    path: &str,
) -> Result<(), CSharpGenerationError> {
    match ty {
        Ty::Union(members, _) => {
            let mut projections = BTreeSet::new();
            for member in members
                .iter()
                .filter(|member| !matches!(member, Ty::Null { .. }))
            {
                let projection = csharp_projection_key(member, model);
                if !projections.insert(projection.clone()) {
                    return Err(unsupported(
                        path,
                        &format!("union whose arms both project to C# type `{projection}`"),
                    ));
                }
                require_unambiguous_csharp_unions(member, model, path)?;
            }
            Ok(())
        }
        Ty::List(item, _) => require_unambiguous_csharp_unions(item, model, path),
        Ty::Map { key, value, .. } => {
            require_unambiguous_csharp_unions(key, model, path)?;
            require_unambiguous_csharp_unions(value, model, path)
        }
        Ty::Class(_, arguments, _) => arguments
            .iter()
            .try_for_each(|argument| require_unambiguous_csharp_unions(argument, model, path)),
        Ty::Function {
            params,
            ret,
            throws,
            ..
        } => {
            for parameter in params {
                require_unambiguous_csharp_unions(&parameter.ty, model, path)?;
            }
            require_unambiguous_csharp_unions(ret, model, path)?;
            require_unambiguous_csharp_unions(throws, model, path)
        }
        Ty::TypeAlias(name, _) => match model.symbols.get(name) {
            Some(Symbol::TypeAlias(alias)) if !alias.recursive => {
                require_unambiguous_csharp_unions(&alias.resolves_to, model, path)
            }
            _ => Ok(()),
        },
        _ => Ok(()),
    }
}

fn csharp_projection_key(ty: &Ty, model: &CodegenModel) -> String {
    match ty {
        Ty::Bool { .. } | Ty::Literal(Literal::Bool(_), ..) => "bool".to_string(),
        Ty::Int { .. } | Ty::Literal(Literal::Int(_), ..) => "long".to_string(),
        Ty::Bigint { .. } | Ty::Literal(Literal::Bigint(_), ..) => {
            "System.Numerics.BigInteger".to_string()
        }
        Ty::Float { .. } | Ty::Literal(Literal::Float(_), ..) => "double".to_string(),
        Ty::String { .. } | Ty::Literal(Literal::String(_), ..) => "string".to_string(),
        Ty::Uint8Array { .. } => "System.ReadOnlyMemory<byte>".to_string(),
        Ty::Null { .. } | Ty::BuiltinUnknown { .. } | Ty::Void { .. } | Ty::Never { .. } => {
            "Baml.BamlValue".to_string()
        }
        Ty::Media(kind, _) => format!("Baml.Media::{kind:?}"),
        Ty::TypeVar(name, _) => format!("type parameter `{name}`"),
        Ty::TypeAlias(name, _) => match model.symbols.get(name) {
            Some(Symbol::TypeAlias(alias)) if !alias.recursive => {
                csharp_projection_key(&alias.resolves_to, model)
            }
            _ => format!("alias `{name}`"),
        },
        Ty::Class(name, arguments, _) => format!(
            "class `{name}`<{}>",
            arguments
                .iter()
                .map(|argument| csharp_projection_key(argument, model))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Ty::Enum(name, _) | Ty::EnumVariant(name, ..) => format!("enum `{name}`"),
        Ty::List(item, _) => format!("list<{}>", csharp_projection_key(item, model)),
        Ty::Map { key, value, .. } => format!(
            "map<{},{}>",
            csharp_projection_key(key, model),
            csharp_projection_key(value, model)
        ),
        Ty::Union(members, _) => format!(
            "union<{}>",
            members
                .iter()
                .map(|member| csharp_projection_key(member, model))
                .collect::<Vec<_>>()
                .join(",")
        ),
        Ty::Function { params, ret, .. } => format!(
            "callable<{}->{}>",
            params
                .iter()
                .map(|parameter| csharp_projection_key(&parameter.ty, model))
                .collect::<Vec<_>>()
                .join(","),
            csharp_projection_key(ret, model)
        ),
        _ => ty.to_string(),
    }
}

