pub(crate) fn render_types(
    leaf: &Leaf,
    symbols: &[(&Name, &Symbol)],
    aliases: &AliasMap<'_>,
) -> String {
    let mut out = String::from("// <auto-generated />\n#nullable enable\n\n");
    let _ = writeln!(out, "namespace {};\n", leaf.namespace);

    let mut emitted_delegates = BTreeSet::new();
    for (name, symbol) in symbols {
        let Symbol::Class(class) = symbol else {
            continue;
        };
        let class_type_variables = allocate_type_parameters(
            &name.to_string(),
            class.generic_params.iter().map(baml_base::Name::as_str),
            &mut BTreeSet::new(),
        );
        for method in class.static_methods.iter().chain(&class.instance_methods) {
            let identity = format!("{}.{}", name, method.name);
            let method_type_variables = allocate_method_type_variables(
                &identity,
                &class_type_variables,
                &method.generic_params,
            );
            for argument in &method.arguments {
                if let Some(callback) = callback_delegate_with_type_variables(
                    &argument.ty,
                    aliases,
                    &identity,
                    argument.name.as_str(),
                    &method_type_variables.combined,
                ) && emitted_delegates.insert(callback.sync_name.clone())
                {
                    callback.render(&mut out);
                }
            }
        }
    }

    for (name, symbol) in symbols {
        match symbol {
            Symbol::Class(class) => render_class(&mut out, name, class, aliases),
            Symbol::Enum(enum_) => render_enum(&mut out, name, enum_, aliases),
            Symbol::TypeAlias(alias) => render_type_alias(&mut out, name, alias, aliases),
            Symbol::Function(_) => unreachable!(),
        }
    }

    out
}

fn render_type_alias(out: &mut String, name: &Name, alias: &TypeAlias, aliases: &AliasMap<'_>) {
    if !alias.recursive {
        return;
    }

    let class_name = aliases.projected_type_name(name);
    let underlying = translate(&alias.resolves_to, aliases);
    let _ = writeln!(
        out,
        "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"BAML\", {})]",
        csharp_string(baml_version::CANONICAL_VERSION)
    );
    let _ = writeln!(
        out,
        "[global::Baml.BamlTypeAliasAttribute({})]",
        csharp_string(&name.to_string())
    );
    let _ = writeln!(
        out,
        "public sealed partial class {class_name} : global::System.IEquatable<{class_name}>, global::Baml.IBamlTypeAliasValue\n{{"
    );
    let _ = writeln!(
        out,
        "    public {class_name}({} value) => Value = value;\n",
        underlying.source
    );
    let _ = writeln!(out, "    public {} Value {{ get; }}\n", underlying.source);
    out.push_str("    public object? UntypedValue => Value;\n\n");
    let _ = writeln!(
        out,
        "    public bool Equals({class_name}? other) => other is not null && Value.Equals(other.Value);\n"
    );
    let _ = writeln!(
        out,
        "    public override bool Equals(object? obj) => obj is {class_name} other && Equals(other);\n"
    );
    out.push_str("    public override int GetHashCode() => Value.GetHashCode();\n\n");
    let _ = writeln!(
        out,
        "    public static implicit operator {class_name}({} value) => new(value);",
        underlying.source
    );
    let _ = writeln!(
        out,
        "    public static explicit operator {}({class_name} value) => value.Value;",
        underlying.source
    );
    out.push_str("}\n\n");
}

fn render_class(out: &mut String, name: &Name, class: &Class, aliases: &AliasMap<'_>) {
    generated_attributes(out, &name.to_string());
    let class_name = aliases.projected_type_name(name);
    let class_type_variables = allocate_type_parameters(
        &name.to_string(),
        class.generic_params.iter().map(baml_base::Name::as_str),
        &mut BTreeSet::new(),
    );
    let generics = if class.generic_params.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            class
                .generic_params
                .iter()
                .map(|parameter| class_type_variables[parameter.as_str()].clone())
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let _ = writeln!(
        out,
        "public sealed partial class {class_name}{generics}\n{{"
    );

    let mut occupied = BTreeSet::new();
    let property_names = allocate_scope(
        class.properties.iter().map(|property| {
            let wire_name = property.name.as_str();
            (
                namespace_segment(wire_name),
                format!("{name}:property:{wire_name}"),
            )
        }),
        &mut occupied,
    );
    let method_names =
        allocate_scope(
            class
                .static_methods
                .iter()
                .flat_map(|method| method_name_requests(name, method, MethodReceiver::Static))
                .chain(class.instance_methods.iter().flat_map(|method| {
                    method_name_requests(name, method, MethodReceiver::Instance)
                })),
            &mut occupied,
        );
    let class_supported = class.properties.iter().all(|property| {
        translate_with_type_variables(&property.ty, aliases, &class_type_variables).primitive_codec
    });
    for (order, property) in class.properties.iter().enumerate() {
        let wire_name = property.name.as_str();
        let projected = &property_names[&format!("{name}:property:{wire_name}")];
        let ty = translate_with_type_variables(&property.ty, aliases, &class_type_variables);
        let _ = writeln!(
            out,
            "    [global::System.Runtime.Serialization.DataMemberAttribute(Name = {}, Order = {order}, IsRequired = true)]",
            csharp_string(wire_name)
        );
        let _ = writeln!(
            out,
            "    public required {} {projected} {{ get; init; }}\n",
            ty.source
        );
    }

    for method in &class.static_methods {
        let context = MethodRenderContext {
            class_name: name,
            receiver: MethodReceiver::Static,
            class_supported,
            class_generic_params: &class.generic_params,
            aliases,
            method_names: &method_names,
            class_type_variables: &class_type_variables,
        };
        render_method_pair(out, &context, method);
    }
    for method in &class.instance_methods {
        let context = MethodRenderContext {
            class_name: name,
            receiver: MethodReceiver::Instance,
            class_supported,
            class_generic_params: &class.generic_params,
            aliases,
            method_names: &method_names,
            class_type_variables: &class_type_variables,
        };
        render_method_pair(out, &context, method);
    }

    out.push_str("}\n\n");
}

fn render_method_pair(
    out: &mut String,
    context: &MethodRenderContext<'_, '_>,
    function: &Function,
) {
    let identity = format!("{}.{}", context.class_name, function.name);
    let method_type_variables = allocate_method_type_variables(
        &identity,
        context.class_type_variables,
        &function.generic_params,
    );
    let projected = &context.method_names[&method_projection_identity(
        context.class_name,
        function,
        context.receiver,
        MethodVariant::Sync,
    )];
    let projected_async = &context.method_names[&method_projection_identity(
        context.class_name,
        function,
        context.receiver,
        MethodVariant::Async,
    )];

    render_method(
        out,
        context,
        function,
        &identity,
        projected,
        MethodVariant::Sync,
        &method_type_variables,
    );
    render_method(
        out,
        context,
        function,
        &identity,
        projected_async,
        MethodVariant::Async,
        &method_type_variables,
    );
    if function.arguments.iter().any(|argument| {
        translate_argument_with_type_variables(
            &argument.ty,
            context.aliases,
            &identity,
            argument.name.as_str(),
            &method_type_variables.combined,
        )
        .async_callback_source
        .is_some()
    }) {
        render_method(
            out,
            context,
            function,
            &identity,
            projected_async,
            MethodVariant::AsyncCallbacks,
            &method_type_variables,
        );
    }
}

fn method_name_requests(
    class_name: &Name,
    function: &Function,
    receiver: MethodReceiver,
) -> [(String, String); 2] {
    let preferred = method_name(function.name.as_str());
    [
        (
            preferred.clone(),
            method_projection_identity(class_name, function, receiver, MethodVariant::Sync),
        ),
        (
            format!("{preferred}Async"),
            method_projection_identity(class_name, function, receiver, MethodVariant::Async),
        ),
    ]
}

fn method_projection_identity(
    class_name: &Name,
    function: &Function,
    receiver: MethodReceiver,
    variant: MethodVariant,
) -> String {
    format!(
        "{class_name}:{}:method:{}:{}",
        receiver.identity_tag(),
        function.name,
        variant.identity_tag()
    )
}

fn render_method(
    out: &mut String,
    context: &MethodRenderContext<'_, '_>,
    function: &Function,
    identity: &str,
    projected: &str,
    variant: MethodVariant,
    type_variables: &MethodTypeVariables,
) {
    let is_static = context.receiver.is_static();
    let is_async = variant.is_async();
    let class_supported = context.class_supported;
    let class_generic_params = context.class_generic_params;
    let aliases = context.aliases;
    let use_async_callback_types = variant.uses_async_callbacks();
    let mut occupied = BTreeSet::new();
    let mut parameters = Vec::new();
    let mut supported = class_supported;
    let mut saw_defaulted = false;
    let parameter_names = allocate_scope(
        function.arguments.iter().map(|argument| {
            let wire_name = argument.name.as_str();
            (
                parameter_name(wire_name),
                format!("{identity}:parameter:{wire_name}"),
            )
        }),
        &mut occupied,
    );
    for argument in &function.arguments {
        if argument.default.is_some() {
            saw_defaulted = true;
        } else {
            assert!(
                !saw_defaulted,
                "C# generation cannot project required parameter `{}` after a defaulted parameter in `{identity}`",
                argument.name
            );
        }
        let wire_name = argument.name.as_str();
        let projected_name = parameter_names[&format!("{identity}:parameter:{wire_name}")].clone();
        let translated = translate_argument_with_type_variables(
            &argument.ty,
            aliases,
            identity,
            wire_name,
            &type_variables.combined,
        );
        supported &= translated.primitive_codec || argument.default.is_some();
        parameters.push(MethodParameter {
            projected: projected_name,
            wire_name: wire_name.to_string(),
            translated,
            defaulted: argument.default.is_some(),
        });
    }

    let return_type =
        translate_with_type_variables(&function.return_type, aliases, &type_variables.combined);
    supported &= return_type.primitive_codec;
    let arguments_local = allocate(
        "arguments",
        &format!("{identity}:generated:arguments"),
        &mut occupied,
    );
    let cancellation_token = allocate(
        "cancellationToken",
        &format!("{identity}:generated:cancellation-token"),
        &mut occupied,
    );

    let rendered_return = if is_async {
        format!(
            "global::System.Threading.Tasks.Task<{}>",
            return_type.source
        )
    } else {
        return_type.source.clone()
    };
    let mut rendered_parameters = parameters
        .iter()
        .map(|parameter| {
            let source = if use_async_callback_types {
                parameter
                    .translated
                    .async_callback_source
                    .as_ref()
                    .unwrap_or(&parameter.translated.source)
            } else {
                &parameter.translated.source
            };
            if parameter.defaulted {
                format!(
                    "global::Baml.BamlOptional<{}> {} = default",
                    source, parameter.projected
                )
            } else {
                format!("{} {}", source, parameter.projected)
            }
        })
        .collect::<Vec<_>>();
    if is_async {
        rendered_parameters.push(format!(
            "global::System.Threading.CancellationToken {cancellation_token} = default"
        ));
    }
    let static_modifier = if is_static { " static" } else { "" };
    let generics = if function.generic_params.is_empty() {
        String::new()
    } else {
        format!(
            "<{}>",
            function
                .generic_params
                .iter()
                .map(|parameter| type_variables.method[parameter.as_str()].clone())
                .collect::<Vec<_>>()
                .join(", ")
        )
    };
    let _ = writeln!(
        out,
        "    public{static_modifier} {rendered_return} {projected}{generics}({})",
        rendered_parameters.join(", ")
    );

    if !supported {
        out.push_str("        => throw new global::System.NotSupportedException(\"This generated method uses a BAML shape that is not supported by the current C# bridge.\");\n\n");
        return;
    }

    if !is_async
        && parameters
            .iter()
            .any(|parameter| parameter.translated.contains_host_callable)
    {
        out.push_str("        => throw new global::System.InvalidOperationException(\"BAML host callables require the generated async method.\");\n\n");
        return;
    }

    out.push_str("    {\n");
    let _ = writeln!(
        out,
        "        var {arguments_local} = new global::System.Collections.Generic.List<(string Name, object? Value)>();"
    );
    if !is_static {
        let _ = writeln!(out, "        {arguments_local}.Add((\"self\", this));");
    }
    for parameter in &parameters {
        if parameter.defaulted {
            let _ = writeln!(
                out,
                "        if ({}.IsSet) {arguments_local}.Add(({}, {}.Value));",
                parameter.projected,
                csharp_string(&parameter.wire_name),
                parameter.projected
            );
        } else {
            let _ = writeln!(
                out,
                "        {arguments_local}.Add(({}, {}));",
                csharp_string(&parameter.wire_name),
                parameter.projected
            );
        }
    }

    let type_arguments = render_type_arguments(
        class_generic_params,
        context.class_type_variables,
        &function.generic_params,
        &type_variables.method,
    );
    let call = if is_async {
        format!(
            "global::BamlSdk.BamlGeneratedProgram.Instance.CallAsync<{}>({}, {arguments_local}.ToArray(), {type_arguments}, {cancellation_token})",
            return_type.source,
            csharp_string(identity)
        )
    } else {
        format!(
            "global::BamlSdk.BamlGeneratedProgram.Instance.Call<{}>({}, {arguments_local}.ToArray(), {type_arguments})",
            return_type.source,
            csharp_string(identity)
        )
    };
    let _ = writeln!(out, "        return {call};");
    out.push_str("    }\n\n");
}

fn render_type_arguments(
    class_parameters: &[baml_base::Name],
    class_names: &BTreeMap<String, String>,
    method_parameters: &[baml_base::Name],
    method_names: &BTreeMap<String, String>,
) -> String {
    if class_parameters.is_empty() && method_parameters.is_empty() {
        return "global::System.Array.Empty<(string Name, global::System.Type Type)>()".to_string();
    }

    format!(
        "new (string Name, global::System.Type Type)[] {{ {} }}",
        class_parameters
            .iter()
            .map(|parameter| (parameter, &class_names[parameter.as_str()]))
            .chain(
                method_parameters
                    .iter()
                    .map(|parameter| (parameter, &method_names[parameter.as_str()])),
            )
            .map(|(parameter, projected)| format!(
                "({}, typeof({projected}))",
                csharp_string(parameter.as_str())
            ))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn allocate_method_type_variables(
    identity: &str,
    class_type_variables: &BTreeMap<String, String>,
    method_parameters: &[baml_base::Name],
) -> MethodTypeVariables {
    let mut occupied = class_type_variables.values().cloned().collect();
    let method = allocate_type_parameters(
        identity,
        method_parameters.iter().map(baml_base::Name::as_str),
        &mut occupied,
    );
    let mut combined = class_type_variables.clone();
    combined.extend(method.clone());
    MethodTypeVariables { combined, method }
}

struct MethodParameter {
    projected: String,
    wire_name: String,
    translated: TranslatedType,
    defaulted: bool,
}

struct MethodRenderContext<'render, 'symbol> {
    class_name: &'render Name,
    receiver: MethodReceiver,
    class_supported: bool,
    class_generic_params: &'render [baml_base::Name],
    aliases: &'render AliasMap<'symbol>,
    method_names: &'render BTreeMap<String, String>,
    class_type_variables: &'render BTreeMap<String, String>,
}

struct MethodTypeVariables {
    combined: BTreeMap<String, String>,
    method: BTreeMap<String, String>,
}

#[derive(Clone, Copy)]
enum MethodReceiver {
    Static,
    Instance,
}

impl MethodReceiver {
    fn is_static(self) -> bool {
        matches!(self, Self::Static)
    }

    fn identity_tag(self) -> &'static str {
        match self {
            Self::Static => "static",
            Self::Instance => "instance",
        }
    }
}

#[derive(Clone, Copy)]
enum MethodVariant {
    Sync,
    Async,
    AsyncCallbacks,
}

impl MethodVariant {
    fn is_async(self) -> bool {
        matches!(self, Self::Async | Self::AsyncCallbacks)
    }

    fn uses_async_callbacks(self) -> bool {
        matches!(self, Self::AsyncCallbacks)
    }

    fn identity_tag(self) -> &'static str {
        match self {
            Self::Sync => "sync",
            Self::Async | Self::AsyncCallbacks => "async",
        }
    }
}

fn render_enum(out: &mut String, name: &Name, enum_: &Enum, aliases: &AliasMap<'_>) {
    generated_attributes(out, &name.to_string());
    let enum_name = aliases.projected_type_name(name);
    let _ = writeln!(out, "public enum {enum_name} : long\n{{");

    let mut occupied = BTreeSet::new();
    let variant_names = allocate_scope(
        enum_.variants.iter().map(|variant| {
            let identity = format!("{name}::{}", variant.name);
            (namespace_segment(variant.name.as_str()), identity)
        }),
        &mut occupied,
    );
    let discriminants =
        allocate_enum_discriminants(name, enum_, |input| Sha256::digest(input).into());
    for variant in &enum_.variants {
        let identity = format!("{}::{}", name, variant.name);
        let discriminant = discriminants[variant.name.as_str()];
        let projected = &variant_names[&identity];
        let _ = writeln!(
            out,
            "    [global::System.Runtime.Serialization.EnumMemberAttribute(Value = {})]",
            csharp_string(&variant.value)
        );
        let _ = writeln!(out, "    {projected} = {discriminant},");
    }

    out.push_str("}\n\n");
}

fn generated_attributes(out: &mut String, wire_name: &str) {
    let _ = writeln!(
        out,
        "[global::System.CodeDom.Compiler.GeneratedCodeAttribute(\"BAML\", {})]",
        csharp_string(baml_version::CANONICAL_VERSION)
    );
    let _ = writeln!(
        out,
        "[global::System.Runtime.Serialization.DataContractAttribute(Name = {})]",
        csharp_string(wire_name)
    );
}

#[cfg(test)]
fn enum_discriminant(name: &Name, variant: &str) -> i64 {
    enum_discriminant_with(name, variant, |input| Sha256::digest(input).into())
}

fn enum_discriminant_with(
    name: &Name,
    variant: &str,
    digest: impl FnOnce(&[u8]) -> [u8; 32],
) -> i64 {
    let mut input = Vec::new();
    push_hash_component(&mut input, 0, b"baml-csharp-enum-discriminant-v1");
    push_hash_component(&mut input, 1, name.pkg.as_str().as_bytes());
    let namespace_count = u32::try_from(name.namespace_path.len())
        .expect("BAML namespace depth must fit in a 32-bit hash component");
    input.push(2);
    input.extend_from_slice(&namespace_count.to_be_bytes());
    for segment in &name.namespace_path {
        push_hash_component(&mut input, 3, segment.as_str().as_bytes());
    }
    push_hash_component(&mut input, 4, name.name.as_str().as_bytes());
    push_hash_component(&mut input, 5, variant.as_bytes());

    let digest = digest(&input);
    let value = u64::from_be_bytes(digest[..8].try_into().unwrap()) & i64::MAX as u64;
    assert!(
        value != 0,
        "C# enum discriminant hashed to reserved zero for {name}::{variant}"
    );
    value.cast_signed()
}

fn push_hash_component(output: &mut Vec<u8>, tag: u8, value: &[u8]) {
    let length = u32::try_from(value.len())
        .expect("BAML identity component length must fit in a 32-bit hash component");
    output.push(tag);
    output.extend_from_slice(&length.to_be_bytes());
    output.extend_from_slice(value);
}

fn allocate_enum_discriminants(
    name: &Name,
    enum_: &Enum,
    digest: impl Fn(&[u8]) -> [u8; 32],
) -> BTreeMap<String, i64> {
    let mut identities = BTreeMap::new();
    let mut discriminants = BTreeMap::new();
    for variant in &enum_.variants {
        let identity = format!("{name}::{}", variant.name);
        let discriminant = enum_discriminant_with(name, variant.name.as_str(), &digest);
        if let Some(previous) = identities.insert(discriminant, identity.clone()) {
            panic!(
                "C# enum discriminant collision in `{name}` between `{previous}` and `{identity}`"
            );
        }
        discriminants.insert(variant.name.to_string(), discriminant);
    }
    discriminants
}

#[cfg(test)]
mod tests {
    use baml_base::Name as BaseName;

    use super::*;

    fn name(pkg: &str, namespace: &[&str], symbol: &str) -> Name {
        Name::new(
            BaseName::new(pkg),
            namespace
                .iter()
                .map(|value| BaseName::new(*value))
                .collect(),
            BaseName::new(symbol),
        )
    }

    #[test]
    fn enum_discriminants_are_positive_nonzero_and_identity_stable() {
        let enum_name = name("user", &["sentiment"], "Label");
        let positive = enum_discriminant(&enum_name, "positive");
        assert!(positive > 0);
        assert_eq!(positive, 3_684_794_946_289_716_079);
        assert_eq!(positive, enum_discriminant(&enum_name, "positive"));
        let negative = enum_discriminant(&enum_name, "negative");
        assert_eq!(negative, 4_780_179_345_900_423_946);
        assert_ne!(positive, negative);
    }

    #[test]
    #[should_panic(expected = "enum discriminant collision")]
    fn injected_enum_discriminant_collision_fails_generation() {
        let enum_name = name("user", &["sentiment"], "Label");
        let enum_ = Enum {
            name: enum_name.clone(),
            docstring: None,
            variants: vec![
                baml_codegen_types::EnumVariant {
                    name: BaseName::new("positive"),
                    docstring: None,
                    value: "positive".to_string(),
                },
                baml_codegen_types::EnumVariant {
                    name: BaseName::new("negative"),
                    docstring: None,
                    value: "negative".to_string(),
                },
            ],
            origin: baml_codegen_types::Origin {
                source_file_path: "collision.baml".to_string(),
                span_start: 0,
            },
        };
        let _ = allocate_enum_discriminants(&enum_name, &enum_, |_| {
            let mut digest = [0; 32];
            digest[0] = 1;
            digest
        });
    }
}
