const BANNER: &str = "// This file was generated by BAML. Do not edit it directly.\n";
pub const MAX_EMBEDDED_BYTECODE_BYTES: usize = 8 * 1024 * 1024;

#[derive(Clone, Debug, Eq, PartialEq)]
pub enum CSharpGenerationError {
    UnsupportedNamingConvention,
    BytecodeTooLarge { actual: usize, maximum: usize },
}

impl std::fmt::Display for CSharpGenerationError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::UnsupportedNamingConvention => {
                formatter.write_str("C# generation requires naming_convention = \"language\"")
            }
            Self::BytecodeTooLarge { actual, maximum } => write!(
                formatter,
                "compiled BAML bytecode is {actual} bytes; the C# source carrier limit is {maximum} bytes"
            ),
        }
    }
}

impl std::error::Error for CSharpGenerationError {}

pub fn to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
) -> std::collections::HashMap<PathBuf, String> {
    try_to_source_code_with_bytecode(pool, baml_bytecode, naming_convention)
        .expect("C# generator inputs must satisfy the public generation contract")
}

pub fn try_to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
) -> Result<std::collections::HashMap<PathBuf, String>, CSharpGenerationError> {
    if !matches!(naming_convention, NamingConvention::Language) {
        return Err(CSharpGenerationError::UnsupportedNamingConvention);
    }
    if baml_bytecode.len() > MAX_EMBEDDED_BYTECODE_BYTES {
        return Err(CSharpGenerationError::BytecodeTooLarge {
            actual: baml_bytecode.len(),
            maximum: MAX_EMBEDDED_BYTECODE_BYTES,
        });
    }

    let mut aliases = pool
        .iter()
        .filter_map(|(name, symbol)| match symbol {
            Symbol::TypeAlias(alias) => Some((name.clone(), alias)),
            _ => None,
        })
        .collect::<AliasMap<'_>>();

    let mut entries: Vec<_> = pool.iter().collect();
    entries.sort_by_key(|(name, _)| *name);
    let routes = RouteMap::new(entries.iter().map(|(name, _)| *name));
    for (name, _) in &entries {
        aliases.set_projected_namespace((*name).clone(), routes.leaf(name).namespace);
    }

    let mut by_leaf: BTreeMap<Leaf, Vec<LeafFunction<'_>>> = BTreeMap::new();
    let mut types_by_leaf: BTreeMap<Leaf, Vec<(&baml_codegen_types::Name, &Symbol)>> =
        BTreeMap::new();
    let mut function_leaves = BTreeSet::new();
    for (name, symbol) in &entries {
        if name.is_local() && matches!(symbol, Symbol::Function(_)) {
            function_leaves.insert(routes.leaf(name));
        }
    }
    let mut type_requests =
        BTreeMap::<Leaf, Vec<(&baml_codegen_types::Name, String, String)>>::new();
    for (name, symbol) in &entries {
        if !name.is_local()
            || !matches!(
                symbol,
                Symbol::Class(_)
                    | Symbol::Enum(_)
                    | Symbol::TypeAlias(baml_codegen_types::TypeAlias {
                        recursive: true,
                        ..
                    })
            )
        {
            continue;
        }
        type_requests.entry(routes.leaf(name)).or_default().push((
            name,
            preferred_type_name(name),
            format!("{name}:type"),
        ));
    }
    for (leaf, requests) in type_requests {
        let mut occupied = BTreeSet::new();
        if function_leaves.contains(&leaf) {
            occupied.insert("Functions".to_string());
        }
        let allocated = names::allocate_scope(
            requests
                .iter()
                .map(|(_, preferred, identity)| (preferred.clone(), identity.clone())),
            &mut occupied,
        );
        for (name, _, identity) in requests {
            aliases.set_projected_type_name(name.clone(), allocated[&identity].clone());
        }
    }
    for (name, symbol) in entries {
        if !name.is_local() {
            continue;
        }
        match symbol {
            Symbol::Function(function) => {
                by_leaf
                    .entry(routes.leaf(name))
                    .or_default()
                    .push(LeafFunction {
                        identity: name,
                        function,
                        projected_name: String::new(),
                        projected_async_name: String::new(),
                    });
            }
            Symbol::Class(_) | Symbol::Enum(_) => {
                types_by_leaf
                    .entry(routes.leaf(name))
                    .or_default()
                    .push((name, symbol));
            }
            Symbol::TypeAlias(alias) if alias.recursive => {
                types_by_leaf
                    .entry(routes.leaf(name))
                    .or_default()
                    .push((name, symbol));
            }
            Symbol::TypeAlias(_) => {}
        }
    }

    let mut output = std::collections::HashMap::new();
    for (leaf, functions) in &mut by_leaf {
        allocate_function_names(functions);
        output.insert(
            functions_path(leaf),
            format!("{BANNER}{}", render_leaf(leaf, functions, &aliases)),
        );
    }
    for (leaf, symbols) in &types_by_leaf {
        output.insert(
            types_path(leaf),
            format!("{BANNER}{}", render_types(leaf, symbols, &aliases)),
        );
    }
    output.insert(
        PathBuf::from("BamlGeneratedProgram.g.cs"),
        format!("{BANNER}{}", render_program(baml_bytecode)),
    );
    Ok(output)
}

pub fn to_source_code(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
) -> std::collections::HashMap<PathBuf, String> {
    to_source_code_with_bytecode(pool, baml_bytecode, naming_convention)
}

fn render_program(bytecode: &[u8]) -> String {
    let encoded = STANDARD.encode(bytecode);
    let fingerprint = Sha256::digest(bytecode);
    let fingerprint = fingerprint
        .iter()
        .map(|byte| format!("0x{byte:02x}"))
        .collect::<Vec<_>>()
        .join(", ");

    let mut out = String::from(
        "// <auto-generated />\n#nullable enable\n\nnamespace BamlSdk;\n\ninternal static class BamlGeneratedProgram\n{\n",
    );
    for (index, chunk) in encoded.as_bytes().chunks(12_000).enumerate() {
        let chunk = std::str::from_utf8(chunk).expect("base64 is ASCII");
        let _ = writeln!(
            out,
            "    private const string Bytecode{index} = \"{chunk}\";"
        );
    }
    out.push_str("\n    private static readonly global::System.Lazy<global::Baml.BamlProgram> Program = new(Create);\n\n");
    out.push_str("    internal static global::Baml.BamlProgram Instance => Program.Value;\n\n");
    out.push_str("    private static global::Baml.BamlProgram Create()\n    {\n");
    let parts = (0..encoded.len().div_ceil(12_000))
        .map(|index| format!("Bytecode{index}"))
        .collect::<Vec<_>>()
        .join(", ");
    let _ = writeln!(
        out,
        "        return global::Baml.BamlBridge.RegisterEncodedProgram(new string[] {{ {parts} }}, new byte[] {{ {fingerprint} }}, {});",
        csharp_string(baml_version::CANONICAL_VERSION)
    );
    out.push_str("    }\n}\n");
    out
}

pub(crate) fn csharp_string(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            ch if ch.is_control() => {
                let _ = write!(out, "\\u{:04x}", ch as u32);
            }
            ch => out.push(ch),
        }
    }
    out.push('"');
    out
}

