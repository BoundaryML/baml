    #[test]
    fn generation_is_identical_across_one_hundred_declaration_orders() {
        let snake = Name::new(
            BaseName::new("user"),
            vec![BaseName::new("foo_bar")],
            BaseName::new("payload"),
        );
        let camel = Name::new(
            BaseName::new("user"),
            vec![BaseName::new("fooBar")],
            BaseName::new("payload"),
        );
        let vendor_named = Name::new(
            BaseName::new("user"),
            vec![BaseName::new("vendor")],
            BaseName::new("payload"),
        );
        let record = Name::new(BaseName::new("user"), Vec::new(), BaseName::new("record"));
        let label = Name::new(BaseName::new("user"), Vec::new(), BaseName::new("label"));
        let function = Name::new(
            BaseName::new("user"),
            Vec::new(),
            BaseName::new("use_payloads"),
        );
        let class_symbol = |name: &Name, span_start| {
            Symbol::Class(Class {
                name: name.clone(),
                generic_params: Vec::new(),
                docstring: None,
                properties: vec![ClassProperty {
                    name: BaseName::new("field"),
                    docstring: None,
                    ty: Ty::String { attr: a() },
                }],
                static_methods: Vec::new(),
                instance_methods: Vec::new(),
                origin: Origin {
                    source_file_path: "ordering.baml".to_string(),
                    span_start,
                },
            })
        };
        let names = [
            snake.clone(),
            camel.clone(),
            vendor_named,
            record,
            label.clone(),
            function,
        ];
        let symbol_at = |index| match index {
            0..=3 => class_symbol(
                &names[index],
                u32::try_from(index).expect("fixture index fits in u32"),
            ),
            4 => Symbol::Enum(Enum {
                name: label.clone(),
                docstring: None,
                variants: vec![EnumVariant {
                    name: BaseName::new("required"),
                    docstring: None,
                    value: "required".to_string(),
                }],
                origin: Origin {
                    source_file_path: "ordering.baml".to_string(),
                    span_start: 4,
                },
            }),
            5 => Symbol::Function(Function {
                name: BaseName::new("use_payloads"),
                generic_params: Vec::new(),
                docstring: None,
                arguments: vec![
                    FunctionArgument {
                        name: BaseName::new("record"),
                        docstring: None,
                        ty: Ty::Class(snake.clone(), Vec::new(), a()),
                        default: None,
                    },
                    FunctionArgument {
                        name: BaseName::new("field"),
                        docstring: None,
                        ty: Ty::Class(camel.clone(), Vec::new(), a()),
                        default: None,
                    },
                ],
                return_type: Ty::Bool { attr: a() },
                throws: None,
                watchers: Vec::new(),
                origin: Origin {
                    source_file_path: "ordering.baml".to_string(),
                    span_start: 5,
                },
            }),
            _ => unreachable!(),
        };

        let mut order = (0..names.len()).collect::<Vec<_>>();
        let mut expected = None;
        for _ in 0..100 {
            let mut pool = SymbolPool::new();
            for &index in &order {
                pool.insert(names[index].clone(), symbol_at(index));
            }
            let output =
                to_source_code_with_bytecode(&pool, b"ordering", NamingConvention::Language);
            if let Some(expected) = &expected {
                assert_eq!(&output, expected);
            } else {
                let functions = &output[&PathBuf::from("Functions.g.cs")];
                assert_eq!(functions.matches("global::BamlSdk.FooBar_").count(), 4);
                assert!(
                    output
                        .keys()
                        .filter(|path| path.ends_with("Types.g.cs"))
                        .any(|path| path.to_string_lossy().starts_with("Vendor_"))
                );
                expected = Some(output);
            }
            next_permutation(&mut order);
        }
    }

    #[test]
    fn allocates_colliding_generic_parameters_and_preserves_wire_names() {
        let function_name = Name::new(
            BaseName::new("user"),
            Vec::new(),
            BaseName::new("generic_collision"),
        );
        let class_name = Name::new(
            BaseName::new("user"),
            Vec::new(),
            BaseName::new("generic_holder"),
        );
        let generic_params = vec![BaseName::new("foo_bar"), BaseName::new("fooBar")];
        let mut pool = SymbolPool::new();
        pool.insert(
            function_name,
            Symbol::Function(Function {
                name: BaseName::new("generic_collision"),
                generic_params: generic_params.clone(),
                docstring: None,
                arguments: vec![
                    FunctionArgument {
                        name: BaseName::new("left"),
                        docstring: None,
                        ty: Ty::TypeVar(generic_params[0].clone(), a()),
                        default: None,
                    },
                    FunctionArgument {
                        name: BaseName::new("right"),
                        docstring: None,
                        ty: Ty::TypeVar(generic_params[1].clone(), a()),
                        default: None,
                    },
                ],
                return_type: Ty::Bool { attr: a() },
                throws: None,
                watchers: Vec::new(),
                origin: Origin {
                    source_file_path: "generic-collision.baml".to_string(),
                    span_start: 0,
                },
            }),
        );
        pool.insert(
            class_name.clone(),
            Symbol::Class(Class {
                name: class_name,
                generic_params: generic_params.clone(),
                docstring: None,
                properties: vec![
                    ClassProperty {
                        name: BaseName::new("left"),
                        docstring: None,
                        ty: Ty::TypeVar(generic_params[0].clone(), a()),
                    },
                    ClassProperty {
                        name: BaseName::new("right"),
                        docstring: None,
                        ty: Ty::TypeVar(generic_params[1].clone(), a()),
                    },
                ],
                static_methods: Vec::new(),
                instance_methods: Vec::new(),
                origin: Origin {
                    source_file_path: "generic-collision.baml".to_string(),
                    span_start: 1,
                },
            }),
        );

        let output =
            to_source_code_with_bytecode(&pool, b"generic-collision", NamingConvention::Language);
        let functions = &output[&PathBuf::from("Functions.g.cs")];
        let signature = functions
            .lines()
            .find(|line| line.contains(" GenericCollision<"))
            .expect("generic collision signature");
        let types = &output[&PathBuf::from("Types.g.cs")];
        let class_declaration = types
            .lines()
            .find(|line| line.starts_with("public sealed partial class GenericHolder<"))
            .expect("generic collision class");

        assert_eq!(signature.matches("FooBar_").count(), 4);
        assert_eq!(class_declaration.matches("FooBar_").count(), 2);
        assert!(functions.contains("(\"foo_bar\", typeof(FooBar_"));
        assert!(functions.contains("(\"fooBar\", typeof(FooBar_"));
    }

    fn next_permutation(values: &mut [usize]) {
        let pivot = (0..values.len() - 1)
            .rev()
            .find(|&index| values[index] < values[index + 1])
            .expect("the first 100 of 720 permutations never exhaust the sequence");
        let successor = (pivot + 1..values.len())
            .rev()
            .find(|&index| values[pivot] < values[index])
            .unwrap();
        values.swap(pivot, successor);
        values[pivot + 1..].reverse();
    }
