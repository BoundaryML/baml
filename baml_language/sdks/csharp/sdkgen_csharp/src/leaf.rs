use std::{collections::BTreeSet, fmt::Write as _};

use baml_codegen_types::{Function, FunctionArgumentDefault, Name};

use crate::{
    csharp_string,
    names::{allocate, allocate_scope, allocate_type_parameters, method_name, parameter_name},
    routing::Leaf,
    translate_ty::{
        AliasMap, TranslatedType, callback_delegate_with_type_variables,
        translate_argument_with_type_variables, translate_with_type_variables,
    },
};

pub(crate) struct LeafFunction<'a> {
    pub(crate) identity: &'a Name,
    pub(crate) function: &'a Function,
    pub(crate) projected_name: String,
    pub(crate) projected_async_name: String,
}

pub(crate) fn allocate_function_names(functions: &mut [LeafFunction<'_>]) {
    let mut occupied = BTreeSet::new();
    let requests = functions
        .iter()
        .flat_map(|function| {
            let preferred = method_name(function.identity.name.as_str());
            let identity = function.identity.to_string();
            [
                (preferred.clone(), format!("{identity}:method:sync")),
                (
                    format!("{preferred}Async"),
                    format!("{identity}:method:async"),
                ),
            ]
        })
        .collect::<Vec<_>>();
    let allocated = allocate_scope(requests, &mut occupied);
    for function in functions {
        let preferred = method_name(function.identity.name.as_str());
        let identity = function.identity.to_string();
        function
            .projected_name
            .clone_from(&allocated[&format!("{identity}:method:sync")]);
        function
            .projected_async_name
            .clone_from(&allocated[&format!("{identity}:method:async")]);
        debug_assert!(
            function.projected_name == preferred || function.projected_name.starts_with(&preferred)
        );
    }
}

pub(crate) fn render_leaf(
    leaf: &Leaf,
    functions: &[LeafFunction<'_>],
    aliases: &AliasMap<'_>,
) -> String {
    let mut out = String::new();
    out.push_str("// <auto-generated />\n#nullable enable\n\n");
    let _ = writeln!(out, "namespace {};\n", leaf.namespace);
    let mut emitted_delegates = BTreeSet::new();
    for function in functions {
        let identity = function.identity.to_string();
        let type_variables = allocate_type_parameters(
            &identity,
            function
                .function
                .generic_params
                .iter()
                .map(baml_base::Name::as_str),
            &mut BTreeSet::new(),
        );
        for argument in &function.function.arguments {
            if let Some(callback) = callback_delegate_with_type_variables(
                &argument.ty,
                aliases,
                &identity,
                argument.name.as_str(),
                &type_variables,
            ) && emitted_delegates.insert(callback.sync_name.clone())
            {
                callback.render(&mut out);
            }
        }
    }
    out.push_str("public static partial class Functions\n{\n");
    for function in functions {
        render_function(&mut out, function, aliases);
    }
    out.push_str("}\n");
    out
}

fn render_function(out: &mut String, emitted: &LeafFunction<'_>, aliases: &AliasMap<'_>) {
    let function = emitted.function;
    let mut occupied = BTreeSet::new();
    let mut parameters = Vec::new();
    let mut supported = true;
    let mut saw_defaulted = false;
    let type_variables = allocate_type_parameters(
        &emitted.identity.to_string(),
        function.generic_params.iter().map(baml_base::Name::as_str),
        &mut BTreeSet::new(),
    );
    let parameter_names = allocate_scope(
        function.arguments.iter().map(|argument| {
            let wire_name = argument.name.as_str();
            (
                parameter_name(wire_name),
                format!("{}:parameter:{wire_name}", emitted.identity),
            )
        }),
        &mut occupied,
    );

    for argument in &function.arguments {
        if argument.default.is_some() {
            saw_defaulted = true;
        } else {
            assert!(
                !saw_defaulted,
                "C# generation cannot project required parameter `{}` after a defaulted parameter in `{}`",
                argument.name, emitted.identity,
            );
        }
        let wire_name = argument.name.as_str();
        let projected =
            parameter_names[&format!("{}:parameter:{wire_name}", emitted.identity)].clone();
        let translated = translate_argument_with_type_variables(
            &argument.ty,
            aliases,
            &emitted.identity.to_string(),
            wire_name,
            &type_variables,
        );
        supported &= translated.primitive_codec || argument.default.is_some();
        parameters.push(Parameter {
            projected,
            wire_name: wire_name.to_string(),
            translated,
            defaulted: argument.default.is_some(),
        });
    }
    let return_type =
        translate_with_type_variables(&function.return_type, aliases, &type_variables);
    supported &= return_type.primitive_codec;
    let arguments_local = allocate(
        "arguments",
        &format!("{}:generated:arguments", emitted.identity),
        &mut occupied,
    );
    let cancellation_token = allocate(
        "cancellationToken",
        &format!("{}:generated:cancellation-token", emitted.identity),
        &mut occupied,
    );

    let context = CallableRenderContext {
        emitted,
        parameters: &parameters,
        return_type: &return_type,
        supported,
        arguments_local: &arguments_local,
        cancellation_token: &cancellation_token,
        type_variables: &type_variables,
    };
    render_callable(out, &context, CallableVariant::Sync);
    render_callable(out, &context, CallableVariant::Async);
    if parameters
        .iter()
        .any(|parameter| parameter.translated.async_callback_source.is_some())
    {
        render_callable(out, &context, CallableVariant::AsyncCallbacks);
    }
}

fn render_callable(
    out: &mut String,
    context: &CallableRenderContext<'_, '_>,
    variant: CallableVariant,
) {
    let emitted = context.emitted;
    let parameters = context.parameters;
    let return_type = context.return_type;
    let is_async = variant.is_async();
    let supported = context.supported;
    let arguments_local = context.arguments_local;
    let cancellation_token = context.cancellation_token;
    let use_async_callback_types = variant.uses_async_callbacks();
    let mut method_name = if is_async {
        emitted.projected_async_name.clone()
    } else {
        emitted.projected_name.clone()
    };
    if !emitted.function.generic_params.is_empty() {
        method_name.push('<');
        method_name.push_str(
            &emitted
                .function
                .generic_params
                .iter()
                .map(|parameter| context.type_variables[parameter.as_str()].clone())
                .collect::<Vec<_>>()
                .join(", "),
        );
        method_name.push('>');
    }
    let rendered_return = if is_async {
        format!(
            "global::System.Threading.Tasks.Task<{}>",
            return_type.source
        )
    } else {
        return_type.source.clone()
    };
    let mut rendered_parameters = Vec::new();
    for parameter in parameters {
        let source = if use_async_callback_types {
            parameter
                .translated
                .async_callback_source
                .as_ref()
                .unwrap_or(&parameter.translated.source)
        } else {
            &parameter.translated.source
        };
        let ty = if parameter.defaulted {
            format!("global::Baml.BamlOptional<{source}>")
        } else {
            source.clone()
        };
        let default = if parameter.defaulted {
            " = default"
        } else {
            ""
        };
        rendered_parameters.push(format!("{ty} {}{default}", parameter.projected));
    }
    if is_async {
        rendered_parameters.push(format!(
            "global::System.Threading.CancellationToken {cancellation_token} = default"
        ));
    }

    let _ = writeln!(
        out,
        "    public static {rendered_return} {method_name}({})",
        rendered_parameters.join(", ")
    );

    if !supported {
        out.push_str("        => throw new global::System.NotSupportedException(\"This generated callable uses a BAML shape that is not supported by the current C# bridge.\");\n\n");
        return;
    }

    if !is_async
        && parameters
            .iter()
            .any(|parameter| parameter.translated.contains_host_callable)
    {
        out.push_str("        => throw new global::System.InvalidOperationException(\"BAML host callables require the generated async method.\");\n\n");
        return;
    }

    let has_defaulted = parameters.iter().any(|parameter| parameter.defaulted);
    if has_defaulted {
        out.push_str("    {\n");
        let _ = writeln!(
            out,
            "        var {arguments_local} = new global::System.Collections.Generic.List<(string Name, object? Value)>();"
        );
        for parameter in parameters {
            if parameter.defaulted {
                let _ = writeln!(
                    out,
                    "        if ({}.IsSet) {arguments_local}.Add(({}, {}.Value));",
                    parameter.projected,
                    csharp_string(&parameter.wire_name),
                    parameter.projected,
                );
            } else {
                let _ = writeln!(
                    out,
                    "        {arguments_local}.Add(({}, {}));",
                    csharp_string(&parameter.wire_name),
                    parameter.projected,
                );
            }
        }
        let call = call_expression(
            emitted,
            return_type,
            is_async,
            &format!("{arguments_local}.ToArray()"),
            cancellation_token,
            context.type_variables,
        );
        let _ = writeln!(out, "        return {call};");
        out.push_str("    }\n\n");
    } else {
        let arguments = if parameters.is_empty() {
            "global::System.Array.Empty<(string Name, object? Value)>()".to_string()
        } else {
            format!(
                "new (string Name, object? Value)[] {{ {} }}",
                parameters
                    .iter()
                    .map(|parameter| format!(
                        "({}, {})",
                        csharp_string(&parameter.wire_name),
                        parameter.projected
                    ))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        };
        let call = call_expression(
            emitted,
            return_type,
            is_async,
            &arguments,
            cancellation_token,
            context.type_variables,
        );
        let _ = writeln!(out, "        => {call};\n");
    }
}

fn call_expression(
    emitted: &LeafFunction<'_>,
    return_type: &TranslatedType,
    is_async: bool,
    arguments: &str,
    cancellation_token: &str,
    type_variables: &std::collections::BTreeMap<String, String>,
) -> String {
    let fqn = csharp_string(&emitted.identity.to_string());
    let type_arguments = render_type_arguments(&emitted.function.generic_params, type_variables);
    if is_async {
        format!(
            "global::BamlSdk.BamlGeneratedProgram.Instance.CallAsync<{}>({fqn}, {arguments}, {type_arguments}, {cancellation_token})",
            return_type.source
        )
    } else {
        format!(
            "global::BamlSdk.BamlGeneratedProgram.Instance.Call<{}>({fqn}, {arguments}, {type_arguments})",
            return_type.source
        )
    }
}

fn render_type_arguments(
    parameters: &[baml_base::Name],
    type_variables: &std::collections::BTreeMap<String, String>,
) -> String {
    if parameters.is_empty() {
        return "global::System.Array.Empty<(string Name, global::System.Type Type)>()".to_string();
    }

    format!(
        "new (string Name, global::System.Type Type)[] {{ {} }}",
        parameters
            .iter()
            .map(|parameter| format!(
                "({}, typeof({}))",
                csharp_string(parameter.as_str()),
                type_variables[parameter.as_str()]
            ))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

struct Parameter {
    projected: String,
    wire_name: String,
    translated: TranslatedType,
    defaulted: bool,
}

struct CallableRenderContext<'render, 'symbol> {
    emitted: &'render LeafFunction<'symbol>,
    parameters: &'render [Parameter],
    return_type: &'render TranslatedType,
    supported: bool,
    arguments_local: &'render str,
    cancellation_token: &'render str,
    type_variables: &'render std::collections::BTreeMap<String, String>,
}

#[derive(Clone, Copy)]
enum CallableVariant {
    Sync,
    Async,
    AsyncCallbacks,
}

impl CallableVariant {
    fn is_async(self) -> bool {
        matches!(self, Self::Async | Self::AsyncCallbacks)
    }

    fn uses_async_callbacks(self) -> bool {
        matches!(self, Self::AsyncCallbacks)
    }
}

#[allow(dead_code)]
fn _assert_default_exhaustive(default: &FunctionArgumentDefault) {
    match default {
        FunctionArgumentDefault::Null
        | FunctionArgumentDefault::Literal(_)
        | FunctionArgumentDefault::Expression { .. } => {}
    }
}
