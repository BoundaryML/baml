using System.Buffers.Binary;
using System.Globalization;
using System.Security.Cryptography;
using System.Text;

const string Usage =
    """
    usage:
      Baml.BytecodeCarrierEmitter <bytecode> <BamlProgram.g.cs> <version>
      Baml.BytecodeCarrierEmitter --synthesize <byte-count> <bytecode> <BamlProgram.g.cs> <version>
    """;

if (args.Length is not (3 or 5)
    || (args.Length == 5
        && !StringComparer.Ordinal.Equals(args[0], "--synthesize")))
{
    Console.Error.WriteLine(Usage);
    return 2;
}

bool synthesize = args.Length == 5;
int argumentOffset = synthesize ? 2 : 0;
string input = RequireAbsolutePath(
    args[argumentOffset],
    mustExist: !synthesize);
string output = RequireAbsolutePath(
    args[argumentOffset + 1],
    mustExist: false);
string version = args[argumentOffset + 2];
if (String.IsNullOrWhiteSpace(version)
    || version.Any(character => character is '"' or '\\' or '\r' or '\n'))
{
    throw new ArgumentException("version is not a safe generated constant");
}

if (synthesize)
{
    long requestedLength = Int64.Parse(
        args[1],
        NumberStyles.None,
        CultureInfo.InvariantCulture);
    if (requestedLength is <= 0 or > Int32.MaxValue)
    {
        throw new ArgumentOutOfRangeException(
            nameof(args),
            requestedLength,
            "evidence payload length must fit one non-empty managed byte array");
    }

    WriteSyntheticPayload(input, checked((int)requestedLength));
    Console.WriteLine(
        $"synthetic_algorithm=xorshift64star-little-endian-v1");
    Console.WriteLine($"synthetic_payload={input}");
}

byte[] bytes = File.ReadAllBytes(input);
if (bytes.Length == 0)
{
    throw new InvalidDataException("canonical bytecode must not be empty");
}

string fingerprint = Convert.ToHexString(
        SHA256.HashData(bytes))
    .ToLowerInvariant();
Directory.CreateDirectory(
    Path.GetDirectoryName(output)
    ?? throw new InvalidOperationException("output has no parent"));
WriteSource(
    output,
    bytes,
    fingerprint,
    version);

Console.WriteLine($"bytecode_bytes={bytes.Length}");
Console.WriteLine($"fingerprint={fingerprint}");
Console.WriteLine($"generated_source={output}");
return 0;

static void WriteSource(
    string output,
    ReadOnlySpan<byte> bytes,
    string fingerprint,
    string version)
{
    using StreamWriter source = new(
        output,
        append: false,
        new UTF8Encoding(
            encoderShouldEmitUTF8Identifier: false,
            throwOnInvalidBytes: true));
    source.NewLine = "\n";
    source.WriteLine("// <auto-generated />");
    source.WriteLine("#nullable enable");
    source.WriteLine();
    source.WriteLine("namespace Baml.Generated;");
    source.WriteLine();
    source.WriteLine(
        $"[global::System.CodeDom.Compiler.GeneratedCode(\"Baml\", \"{version}\")]");
    source.WriteLine(
        "[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
    source.WriteLine("internal static class BamlGeneratedProgram");
    source.WriteLine("{");
    source.WriteLine(
        $"    internal const string GeneratedWithVersion = \"{version}\";");
    source.WriteLine(
        $"    internal const string RequiredBridgeVersion = \"{version}\";");
    source.WriteLine(
        $"    internal const string ProgramFingerprint = \"{fingerprint}\";");
    source.WriteLine();
    source.WriteLine("    private static readonly byte[] s_bytecode =");
    source.WriteLine("    [");
    char[] line = new char[104];
    const string Hex = "0123456789abcdef";
    for (int offset = 0; offset < bytes.Length; offset += 16)
    {
        int position = 0;
        for (; position < 8; position++)
        {
            line[position] = ' ';
        }

        int lineLength = Math.Min(16, bytes.Length - offset);
        for (int index = 0; index < lineLength; index++)
        {
            byte value = bytes[offset + index];
            line[position++] = '0';
            line[position++] = 'x';
            line[position++] = Hex[value >> 4];
            line[position++] = Hex[value & 0x0f];
            line[position++] = ',';
            if (index != lineLength - 1)
            {
                line[position++] = ' ';
            }
        }

        source.WriteLine(line.AsSpan(0, position));
    }

    source.WriteLine("    ];");
    source.WriteLine();
    source.WriteLine(
        "    private static readonly global::System.Lazy<global::ProgramProbe> s_program =");
    source.WriteLine(
        "        new(CreateProgram, global::System.Threading.LazyThreadSafetyMode.ExecutionAndPublication);");
    source.WriteLine();
    source.WriteLine(
        "    internal static global::ProgramProbe Program => s_program.Value;");
    source.WriteLine();
    source.WriteLine(
        "    private static global::ProgramProbe CreateProgram() =>");
    source.WriteLine(
        "        global::ProgramProbeRuntime.RegisterProgram(");
    source.WriteLine("            s_bytecode,");
    source.WriteLine("            ProgramFingerprint,");
    source.WriteLine("            GeneratedWithVersion);");
    source.WriteLine("}");
}

static void WriteSyntheticPayload(string output, int length)
{
    Directory.CreateDirectory(
        Path.GetDirectoryName(output)
        ?? throw new InvalidOperationException("payload has no parent"));
    using FileStream stream = new(
        output,
        FileMode.Create,
        FileAccess.Write,
        FileShare.None);
    byte[] buffer = new byte[1024 * 1024];
    byte[] finalWord = new byte[sizeof(ulong)];
    ulong state = 0x4d595df4d0f33173UL;
    int remaining = length;
    while (remaining != 0)
    {
        int count = Math.Min(buffer.Length, remaining);
        int offset = 0;
        while (offset < count)
        {
            state ^= state >> 12;
            state ^= state << 25;
            state ^= state >> 27;
            ulong value = state * 0x2545f4914f6cdd1dUL;
            int wordLength = Math.Min(sizeof(ulong), count - offset);
            if (wordLength == sizeof(ulong))
            {
                BinaryPrimitives.WriteUInt64LittleEndian(
                    buffer.AsSpan(offset, wordLength),
                    value);
            }
            else
            {
                BinaryPrimitives.WriteUInt64LittleEndian(finalWord, value);
                finalWord.AsSpan(0, wordLength).CopyTo(
                    buffer.AsSpan(offset, wordLength));
            }

            offset += wordLength;
        }

        stream.Write(buffer, 0, count);
        remaining -= count;
    }
}

static string RequireAbsolutePath(string value, bool mustExist)
{
    if (!Path.IsPathFullyQualified(value))
    {
        throw new ArgumentException($"path must be absolute: {value}");
    }

    string path = Path.GetFullPath(value);
    if (mustExist && !File.Exists(path))
    {
        throw new FileNotFoundException("input does not exist", path);
    }

    return path;
}
