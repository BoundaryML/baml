using System.Text;

if (args.Length != 1)
{
    Console.Error.WriteLine("usage: Baml.Union.Generate <output.cs>");
    return 2;
}

var outputPath = Path.GetFullPath(args[0]);
var output = new StringBuilder("// <auto-generated />\n#nullable enable\n\nnamespace Baml;\n\n");
for (var arity = 2; arity <= 32; arity++)
{
    RenderUnion(output, arity);
}

Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
var generated = output.ToString().TrimEnd('\r', '\n') + "\n";
File.WriteAllText(outputPath, generated, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
return 0;

static void RenderUnion(StringBuilder output, int arity)
{
    var types = Enumerable.Range(0, arity).Select(static index => $"T{index}").ToArray();
    var typeList = string.Join(", ", types);
    var unionType = $"BamlUnion<{typeList}>";
    output.AppendLine($"public readonly struct {unionType} : global::System.IEquatable<{unionType}>, Bridge.IBamlUnionValue");
    output.AppendLine("{");
    foreach (var (type, index) in types.Select(static (type, index) => (type, index)))
    {
        output.AppendLine($"    private readonly {type}? _value{index};");
    }

    output.AppendLine("    private readonly byte _activeCase;");
    output.AppendLine();
    output.AppendLine($"    private BamlUnion(byte activeCase, {string.Join(", ", types.Select(static (type, index) => $"{type}? value{index}"))})");
    output.AppendLine("    {");
    output.AppendLine("        _activeCase = activeCase;");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"        _value{index} = value{index};");
    }

    output.AppendLine("    }");
    output.AppendLine();
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"    public bool IsT{index} => _activeCase == {index + 1};");
        output.AppendLine();
        output.AppendLine($"    public T{index} AsT{index} => IsT{index}");
        output.AppendLine($"        ? _value{index}!");
        output.AppendLine($"        : throw WrongCase({index});");
        output.AppendLine();
    }

    output.AppendLine("    int Bridge.IBamlUnionValue.ActiveCase => _activeCase;");
    output.AppendLine();
    output.AppendLine("    object? Bridge.IBamlUnionValue.Value => _activeCase switch");
    output.AppendLine("    {");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"        {index + 1} => _value{index},");
    }

    output.AppendLine("        _ => throw InvalidDefault(),");
    output.AppendLine("    };");
    output.AppendLine();
    foreach (var index in Enumerable.Range(0, arity))
    {
        var values = Enumerable.Range(0, arity)
            .Select(candidate => candidate == index ? "value" : "default");
        output.AppendLine($"    public static {unionType} FromT{index}(T{index} value) => new({index + 1}, {string.Join(", ", values)});");
        output.AppendLine();
    }

    output.AppendLine($"    public TResult Match<TResult>({string.Join(", ", types.Select(static (type, index) => $"global::System.Func<{type}, TResult> onT{index}"))})");
    output.AppendLine("    {");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"        global::System.ArgumentNullException.ThrowIfNull(onT{index});");
    }

    output.AppendLine("        return _activeCase switch");
    output.AppendLine("        {");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"            {index + 1} => onT{index}(_value{index}!),");
    }

    output.AppendLine("            _ => throw InvalidDefault(),");
    output.AppendLine("        };");
    output.AppendLine("    }");
    output.AppendLine();
    output.AppendLine($"    public void Switch({string.Join(", ", types.Select(static (type, index) => $"global::System.Action<{type}> onT{index}"))})");
    output.AppendLine("    {");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"        global::System.ArgumentNullException.ThrowIfNull(onT{index});");
    }

    output.AppendLine("        switch (_activeCase)");
    output.AppendLine("        {");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"            case {index + 1}:");
        output.AppendLine($"                onT{index}(_value{index}!);");
        output.AppendLine("                break;");
    }

    output.AppendLine("            default:");
    output.AppendLine("                throw InvalidDefault();");
    output.AppendLine("        }");
    output.AppendLine("    }");
    output.AppendLine();
    output.AppendLine($"    public bool Equals({unionType} other)");
    output.AppendLine("    {");
    output.AppendLine("        if (_activeCase != other._activeCase)");
    output.AppendLine("        {");
    output.AppendLine("            return false;");
    output.AppendLine("        }");
    output.AppendLine();
    output.AppendLine("        return _activeCase switch");
    output.AppendLine("        {");
    output.AppendLine("            0 => true,");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"            {index + 1} => global::System.Collections.Generic.EqualityComparer<T{index}>.Default.Equals(_value{index}!, other._value{index}!),");
    }

    output.AppendLine("            _ => false,");
    output.AppendLine("        };");
    output.AppendLine("    }");
    output.AppendLine();
    output.AppendLine($"    public override bool Equals(object? obj) => obj is {unionType} other && Equals(other);");
    output.AppendLine();
    output.AppendLine("    public override int GetHashCode() => _activeCase switch");
    output.AppendLine("    {");
    output.AppendLine("        0 => 0,");
    foreach (var index in Enumerable.Range(0, arity))
    {
        output.AppendLine($"        {index + 1} => global::System.HashCode.Combine({index + 1}, global::System.Collections.Generic.EqualityComparer<T{index}>.Default.GetHashCode(_value{index}!)),");
