using System.Text;

if (args.Length != 2 || args[0] is not ("--check" or "--write"))
{
    Console.Error.WriteLine(
        "usage: Baml.UnionGenerator <--check|--write> <BamlUnion.cs>");
    return 2;
}

string outputPath = Path.GetFullPath(args[1]);
string expected = GenerateUnionSource();
if (args[0] == "--write")
{
    Directory.CreateDirectory(Path.GetDirectoryName(outputPath)!);
    File.WriteAllText(outputPath, expected, new UTF8Encoding(false));
    Console.WriteLine($"generated {outputPath}");
    return 0;
}

if (!File.Exists(outputPath))
{
    Console.Error.WriteLine($"generated union source is missing: {outputPath}");
    return 1;
}

string actual = File.ReadAllText(outputPath, Encoding.UTF8);
if (!StringComparer.Ordinal.Equals(actual, expected))
{
    Console.Error.WriteLine(
        $"generated union source is stale: {outputPath}\n"
        + "Run this tool with --write and commit the result.");
    return 1;
}

Console.WriteLine("csharp_union_source=up_to_date");
return 0;

static string GenerateUnionSource()
{
    var source = new StringBuilder(capacity: 512_000);
    Line("// <auto-generated />");
    Line("#nullable enable");
    Line();
    Line("namespace Baml;");
    Line();

    for (int arity = 2; arity <= 32; arity++)
    {
        string types = Join(arity, index => $"T{index}");
        string union = $"BamlUnion<{types}>";
        Line($"/// <summary>A typed BAML union with {arity} explicitly addressable cases.</summary>");
        Line($"public readonly struct {union} : IEquatable<{union}>");
        Line("{");
        Line("    private readonly byte caseIndex;");
        for (int index = 0; index < arity; index++)
        {
            Line($"    private readonly T{index} value{index};");
        }
        Line();

        string constructorParameters = Join(
            arity,
            index => $"T{index} value{index}");
        Line($"    private BamlUnion(byte caseIndex, {constructorParameters})");
        Line("    {");
        Line("        this.caseIndex = caseIndex;");
        for (int index = 0; index < arity; index++)
        {
            Line($"        this.value{index} = value{index};");
        }
        Line("    }");
        Line();

        for (int index = 0; index < arity; index++)
        {
            Line($"    public bool IsT{index} => caseIndex == {index + 1};");
            Line();
            Line($"    public T{index} AsT{index} => caseIndex == {index + 1}");
            Line($"        ? value{index}");
            Line($"        : throw InvalidCase({index});");
            Line();
        }

        for (int index = 0; index < arity; index++)
        {
            string arguments = Join(
                arity,
                argument => argument == index ? "value" : "default!");
            Line($"    public static {union} FromT{index}(T{index} value) =>");
            Line($"        new({index + 1}, {arguments});");
            Line();
        }

        Line("    public TResult Match<TResult>(");
        for (int index = 0; index < arity; index++)
        {
            string comma = index + 1 == arity ? string.Empty : ",";
            string close = index + 1 == arity ? ")" : string.Empty;
            Line($"        Func<T{index}, TResult> onT{index}{comma}{close}");
        }
        Line("    {");
        for (int index = 0; index < arity; index++)
        {
            Line($"        ArgumentNullException.ThrowIfNull(onT{index});");
        }
        Line("        return caseIndex switch");
        Line("        {");
        for (int index = 0; index < arity; index++)
        {
            Line($"            {index + 1} => onT{index}(value{index}),");
        }
        Line("            _ => throw InvalidCaseForOperation(),");
        Line("        };");
        Line("    }");
        Line();

        Line("    public void Switch(");
        for (int index = 0; index < arity; index++)
        {
            string comma = index + 1 == arity ? string.Empty : ",";
            string close = index + 1 == arity ? ")" : string.Empty;
            Line($"        Action<T{index}> onT{index}{comma}{close}");
        }
        Line("    {");
        for (int index = 0; index < arity; index++)
        {
            Line($"        ArgumentNullException.ThrowIfNull(onT{index});");
        }
        Line("        switch (caseIndex)");
        Line("        {");
        for (int index = 0; index < arity; index++)
        {
            Line($"            case {index + 1}:");
            Line($"                onT{index}(value{index});");
            Line("                return;");
        }
        Line("            default:");
        Line("                throw InvalidCaseForOperation();");
        Line("        }");
        Line("    }");
        Line();

        for (int index = 0; index < arity; index++)
        {
            Line($"    public static implicit operator {union}(T{index} value) =>");
            Line($"        FromT{index}(value);");
            Line();
        }

        Line($"    public bool Equals({union} other) =>");
        Line("        caseIndex == other.caseIndex");
        Line("        && caseIndex switch");
        Line("        {");
        Line("            0 => true,");
        for (int index = 0; index < arity; index++)
        {
            Line(
                $"            {index + 1} => EqualityComparer<T{index}>.Default.Equals(value{index}, other.value{index}),");
        }
        Line("            _ => false,");
        Line("        };");
        Line();

        Line("    public override bool Equals(object? obj) =>");
        Line($"        obj is {union} other && Equals(other);");
        Line();

        Line("    public override int GetHashCode() =>");
        Line("        caseIndex switch");
        Line("        {");
        Line("            0 => 0,");
        for (int index = 0; index < arity; index++)
        {
            Line(
                $"            {index + 1} => HashCode.Combine({index + 1}, EqualityComparer<T{index}>.Default.GetHashCode(value{index}!)),");
        }
        Line("            _ => 0,");
        Line("        };");
        Line();

        Line($"    public static bool operator ==({union} left, {union} right) =>");
        Line("        left.Equals(right);");
        Line();
        Line($"    public static bool operator !=({union} left, {union} right) =>");
        Line("        !left.Equals(right);");
        Line();

        Line("    internal int ActiveCaseForCodec => caseIndex switch");
        Line("    {");
        for (int index = 0; index < arity; index++)
        {
            Line($"        {index + 1} => {index},");
        }
        Line("        _ => throw InvalidCaseForOperation(),");
        Line("    };");
        Line();

        Line("    internal object? ValueForCodec => caseIndex switch");
        Line("    {");
        for (int index = 0; index < arity; index++)
        {
            Line($"        {index + 1} => value{index},");
        }
        Line("        _ => throw InvalidCaseForOperation(),");
        Line("    };");
        Line();

        Line("    private InvalidOperationException InvalidCase(int requested) =>");
        Line("        new(");
        Line("            caseIndex == 0");
        Line("                ? \"The BAML union is uninitialized.\"");
        Line("                : $\"The BAML union does not contain T{requested}.\");");
        Line();
        Line("    private InvalidOperationException InvalidCaseForOperation() =>");
        Line("        new(\"The BAML union is uninitialized.\");");
        Line("}");
        // Preserve the established checked-in byte layout. The first three
        // declarations are contiguous; later declarations have a separator.
        if (arity is >= 4 and < 32)
        {
            Line();
        }
    }

    return source.ToString();

    void Line(string text = "") => source.Append(text).Append('\n');
}

static string Join(int count, Func<int, string> render) =>
    string.Join(", ", Enumerable.Range(0, count).Select(render));
