//! Rust SDK code generator for BAML.
//!
//! Consumes the language-agnostic [`baml_codegen_types::SymbolPool`] and
//! emits a standalone Cargo crate — the generated `baml_sdk` — whose code
//! links against the `bridge_rust` runtime crate (library name `baml_rs`).
//!
//! The emitter surface mirrors `sdkgen_python_pydantic2` /
//! `sdkgen_typescript_node`: one entry point returning a map of
//! output-root-relative paths to file contents. Unlike those two, the
//! generated artifact is a complete Cargo *crate* (`Cargo.toml` + `src/`
//! tree): a Rust SDK cannot exist as a bare source tree because it needs a
//! manifest to carry its dependency on the runtime. Callers inject the
//! `bridge_rust` dependency spec via [`RustGenOptions::baml_rs_dep`] — the
//! CLI pins the release version, while `sdk_tests` uses a path dependency.
//!
//! Symbols that reference BAML types the Rust SDK cannot represent yet are
//! skipped rather than failing codegen: each skip is reported through
//! [`Generated::warnings`] so callers can surface them, and the rest of the
//! SDK still compiles.

use std::{collections::HashMap, path::PathBuf};

pub use baml_codegen_types::NamingConvention;
use baml_codegen_types::SymbolPool;

/// Caller-provided knobs for the generated crate.
pub struct RustGenOptions {
    /// Only [`NamingConvention::PreserveCase`] is wired up (same as the
    /// python and typescript emitters); the entry point asserts this.
    pub naming_convention: NamingConvention,
    /// Cargo package name for the generated crate. The library target is
    /// always named `baml_sdk` (import-name parity with the python/TS
    /// SDKs) regardless of the package name, so callers can de-collide
    /// package names without changing how user code imports the SDK.
    pub package_name: String,
    /// Dependency spec for the `bridge_rust` runtime crate, verbatim TOML
    /// to the right of the `=`: e.g. `"1.2.3"` or
    /// `{ path = "../../sdks/rust/bridge_rust" }`.
    pub baml_rs_dep: String,
    /// Extra TOML appended verbatim at the end of the generated
    /// `Cargo.toml`. Must only introduce new tables (TOML cannot reopen
    /// earlier ones). The `sdk_tests` harness uses this for
    /// `[dev-dependencies]` of the ported test suite.
    pub manifest_extra: Option<String>,
    /// Rust edition stamped into the generated crate's `[package]`.
    pub edition: String,
}

/// A symbol the emitter skipped because it references a BAML type the Rust
/// SDK cannot represent yet (media, non-null unions, generics, …).
pub struct SkipWarning {
    /// Fully qualified BAML name of the skipped symbol.
    pub fqn: String,
    /// Human-readable reason, e.g. `unsupported type: media`.
    pub reason: String,
}

/// Emitter output: the generated file tree plus any skip warnings.
pub struct Generated {
    /// Output-root-relative path → file contents. Includes `Cargo.toml`
    /// at the root and the source tree under `src/`.
    pub files: HashMap<PathBuf, String>,
    /// Symbols that were skipped, for the caller to surface.
    pub warnings: Vec<SkipWarning>,
}

const RUST_BANNER: &str = "\
// ----------------------------------------------------------------------------
//
//  Welcome to Baml! This crate is your generated SDK: add it to your
//  project as a path dependency and call your BAML functions from Rust.
//
// ----------------------------------------------------------------------------

// This file was generated by BAML: please do not edit it. Instead, edit the
// BAML files and re-generate this code using: baml-cli generate

";

/// Render a Rust source file from structured tokens.
///
/// All Rust code this generator (and the `sdk_tests` harness) produces is
/// built as a `TokenStream` via `quote` — never by string interpolation —
/// so malformed output fails here, at generation time, instead of
/// surfacing as a rustc error in a file the user didn't write. The tokens
/// are parsed back as a full file and pretty-printed; `prettyplease` is
/// the canonical format for generated code (it is not guaranteed to be
/// rustfmt-identical).
///
/// `header` is prepended verbatim: plain `//` comments are the one thing
/// a `TokenStream` cannot carry, so banners and per-file notes travel as
/// a string block above the code.
///
/// Panics when the tokens do not parse as a Rust file — that is a bug in
/// the emitter, never an input-dependent condition.
pub fn render_rust_file(header: &str, tokens: proc_macro2::TokenStream) -> String {
    let file: syn::File = syn::parse2(tokens)
        .unwrap_or_else(|e| panic!("generated tokens do not parse as a Rust file: {e}"));
    format!("{header}{}", prettyplease::unparse(&file))
}

/// Generate the SDK crate for `pool`, embedding `baml_bytecode` (the
/// borsh-encoded `Program` the runtime boots from).
///
/// Symbol emission is not implemented yet: this currently produces the
/// crate skeleton (manifest + empty library root) so the `sdk_tests`
/// pipeline can run end-to-end. The signature is final.
pub fn to_source_code_with_bytecode(
    _pool: &SymbolPool,
    _baml_bytecode: &[u8],
    options: &RustGenOptions,
) -> Generated {
    assert!(
        matches!(options.naming_convention, NamingConvention::PreserveCase),
        "only NamingConvention::PreserveCase is supported"
    );

    let mut files = HashMap::new();
    files.insert(PathBuf::from("Cargo.toml"), render_manifest(options));
    files.insert(
        PathBuf::from("src/lib.rs"),
        render_rust_file(
            RUST_BANNER,
            quote::quote! {
                #![allow(non_camel_case_types, non_snake_case)]
            },
        ),
    );
    Generated {
        files,
        warnings: Vec::new(),
    }
}

fn render_manifest(options: &RustGenOptions) -> String {
    let RustGenOptions {
        naming_convention: _,
        package_name,
        baml_rs_dep,
        manifest_extra,
        edition,
    } = options;
    let mut manifest = format!(
        r#"# This file was generated by BAML: please do not edit it. Instead, edit the
# BAML files and re-generate this code using: baml-cli generate

[package]
name = "{package_name}"
version = "0.1.0"
edition = "{edition}"
publish = false

[lib]
name = "baml_sdk"
path = "src/lib.rs"
doctest = false

# The generated crate is its own workspace root. Without this, a cargo
# invocation inside the crate walks up the directory tree, finds an
# unrelated enclosing workspace, and refuses to build because this
# package is not one of its members. Consume the crate as a *path
# dependency*, not a workspace member.
[workspace]

[dependencies]
bridge_rust = {baml_rs_dep}
"#
    );
    if let Some(extra) = manifest_extra {
        manifest.push('\n');
        manifest.push_str(extra);
        if !extra.ends_with('\n') {
            manifest.push('\n');
        }
    }
    manifest
}

#[cfg(test)]
mod tests {
    use super::*;

    fn options() -> RustGenOptions {
        RustGenOptions {
            naming_convention: NamingConvention::PreserveCase,
            package_name: "baml_sdk".to_string(),
            baml_rs_dep: "{ path = \"../bridge_rust\" }".to_string(),
            manifest_extra: None,
            edition: "2024".to_string(),
        }
    }

    #[test]
    fn empty_pool_emits_crate_skeleton() {
        let pool = SymbolPool::default();
        let generated = to_source_code_with_bytecode(&pool, &[], &options());
        assert!(generated.warnings.is_empty());
        let mut paths: Vec<_> = generated
            .files
            .keys()
            .map(|p| p.display().to_string())
            .collect();
        paths.sort();
        assert_eq!(paths, ["Cargo.toml", "src/lib.rs"]);
    }

    #[test]
    fn manifest_is_standalone_workspace_with_injected_dep() {
        let manifest = render_manifest(&options());
        assert!(manifest.contains("[workspace]"));
        assert!(manifest.contains("name = \"baml_sdk\""));
        assert!(manifest.contains("bridge_rust = { path = \"../bridge_rust\" }"));
    }

    #[test]
    fn manifest_extra_is_appended_with_trailing_newline() {
        let mut opts = options();
        opts.manifest_extra = Some("[dev-dependencies]\ntokio = \"1\"".to_string());
        let manifest = render_manifest(&opts);
        assert!(manifest.ends_with("[dev-dependencies]\ntokio = \"1\"\n"));
    }
}
