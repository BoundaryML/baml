//! Build-diagnostics manifest for skipped symbols.
//!
//! The fixpoint's skip posture means an unsupported construct produces
//! absent API — the generated package always compiles, but a symbol can
//! vanish with no trace. This module makes every skip loud: each one is
//! recorded with the concrete type that failed translation, and the
//! manifest is emitted into the generated output as
//! `_BamlSkipped.swift` — with a `#warning` so consumers see the count
//! at every build of the package, not just when they go looking.
//!
//! Reasons are computed *after* a render declines (the render paths
//! stay `Option`-shaped); each probe re-walks the failing signature in
//! the same order the renderer does, so the first reported cause is the
//! same one that made the renderer bail.

use std::fmt::Write as _;

use baml_codegen_types::{Class, Function, Ty, TypeAlias};

use crate::{
    emit::ty_contains_type_var,
    translate_ty::{TranslateCtx, translate_optional_arg_inner, translate_ty},
};

pub(crate) struct Skip {
    pub fqn: String,
    /// "function" | "class" | "type alias" | "static method" |
    /// "instance method"
    pub kind: &'static str,
    pub reason: String,
    /// Symbols from the `user` package are the ones a project author
    /// wrote; skips there get the `#warning`. Stdlib/vendored skips are
    /// engine-wide deferrals — listed for the record, never warned.
    pub is_user: bool,
}

/// Why `render_callable` returned `None` for this function. Probes in
/// the renderer's own order: generic coverage, then parameters, then
/// the return type.
pub(crate) fn callable_skip_reason(function: &Function, ctx: &TranslateCtx) -> String {
    for param in &function.generic_params {
        let covered = function
            .arguments
            .iter()
            .any(|arg| arg.default.is_none() && ty_contains_type_var(&arg.ty, param.as_str()));
        if !covered {
            return format!(
                "generic parameter `{}` appears only in the return type — \
                 the engine has no argument value to infer it from \
                 (needs the wire type-hint hook)",
                param.as_str()
            );
        }
    }
    for arg in &function.arguments {
        let ok = if arg.default.is_some() {
            translate_optional_arg_inner(&arg.ty, ctx).is_some()
        } else {
            // Callable params succeed iff every piece of their own
            // signature translates — same probe either way.
            translate_ty(&arg.ty, ctx).is_some()
        };
        if !ok {
            return format!(
                "parameter `{}`: type `{}` is not representable in Swift",
                arg.name.as_str(),
                arg.ty
            );
        }
    }
    match &function.return_type {
        Ty::Void { .. } | Ty::Never { .. } => {}
        ret if translate_ty(ret, ctx).is_none() => {
            return format!("return type `{ret}` is not representable in Swift");
        }
        _ => {}
    }
    // Renderer and probe disagree — still never silent.
    "signature uses an unsupported construct (unclassified — file a bug)".to_string()
}

/// Why the fixpoint dropped this class.
pub(crate) fn class_skip_reason(class: &Class, ctx: &TranslateCtx) -> String {
    for prop in &class.properties {
        if translate_ty(&prop.ty, ctx).is_none() {
            return format!(
                "field `{}`: type `{}` is not representable in Swift",
                prop.name.as_str(),
                prop.ty
            );
        }
    }
    "definition uses an unsupported construct (unclassified — file a bug)".to_string()
}

/// Why the fixpoint dropped this alias.
pub(crate) fn alias_skip_reason(alias: &TypeAlias, ctx: &TranslateCtx) -> String {
    match crate::recursive_union_alias_arms(alias) {
        None if alias.recursive => {
            return "recursive alias that is not a >=2-arm union — Swift `typealias` \
                    cannot self-reference and only union-backed recursion gets a \
                    nominal enum"
                .to_string();
        }
        Some((arms, _)) => {
            if let Some(arm) = arms.iter().find(|arm| translate_ty(arm, ctx).is_none()) {
                return format!("union arm `{arm}` is not representable in Swift");
            }
        }
        None => {}
    }
    format!(
        "target type `{}` is not representable in Swift",
        alias.resolves_to
    )
}

/// Render the manifest file. Always emitted: an empty manifest is the
/// positive signal that nothing was skipped.
pub(crate) fn render_manifest(skips: &[Skip]) -> String {
    let mut out = String::from(
        "// Generated by BAML. DO NOT EDIT.\n\
         //\n\
         // Build-diagnostics manifest: BAML symbols that could not be\n\
         // represented in Swift and were therefore NOT emitted into this\n\
         // SDK. Each entry names the symbol and the concrete type that\n\
         // failed translation. A symbol listed here is absent from the\n\
         // generated API on purpose — calling it from Swift is impossible,\n\
         // not broken.\n",
    );
    if skips.is_empty() {
        out.push_str("//\n// All symbols were emitted; nothing was skipped.\n");
        return out;
    }
    let (user, toolchain): (Vec<_>, Vec<_>) = skips.iter().partition(|s| s.is_user);
    // Only skips in the author's own package warn: the stdlib/vendor
    // baseline is a constant, engine-wide deferral set — warning on it
    // every build would teach people to ignore the warning.
    if !user.is_empty() {
        let _ = write!(
            out,
            "\n#warning(\"BAML codegen skipped {} symbol{} from this project — \
             see _BamlSkipped.swift for reasons\")\n",
            user.len(),
            if user.len() == 1 { "" } else { "s" }
        );
        out.push_str("\n// ===== This project =====\n");
        for skip in &user {
            let _ = write!(
                out,
                "// SKIPPED {} `{}`\n//   {}\n",
                skip.kind, skip.fqn, skip.reason
            );
        }
    } else {
        out.push_str("//\n// All symbols in this project's own package were emitted.\n");
    }
    if !toolchain.is_empty() {
        out.push_str(
            "\n// ===== Toolchain packages (baml stdlib / vendored) =====\n\
             // Known engine-wide deferrals; identical across projects.\n",
        );
        for skip in &toolchain {
            let _ = write!(
                out,
                "// SKIPPED {} `{}`\n//   {}\n",
                skip.kind, skip.fqn, skip.reason
            );
        }
    }
    out
}
