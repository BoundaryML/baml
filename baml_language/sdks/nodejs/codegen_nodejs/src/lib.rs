//! Node.js + TypeScript SDK emitter. Phase 2 produces a structurally
//! correct `baml_sdk/` tree from a `SymbolPool`: one `index.ts` (plus a
//! `.d.ts` companion) per directory, a root-only `_inlinedbaml.ts` +
//! `_typemap.ts`, and per-symbol placeholder lines. Phase 3 fills in
//! real types; Phase 4 fills in real bindings; Phase 5 wires codec.

