    #[test]
    fn inlinedbaml_round_trips() {
        let pool: SymbolPool = HashMap::new();
        let files = vec![
            (PathBuf::from("main.baml"), "class Foo {}\n".to_string()),
            (
                PathBuf::from("lorem").join("bar.baml"),
                "function foo() -> int { 1 }\n".to_string(),
            ),
        ];
        let out = to_source_code(&pool, &files, NamingConvention::PreserveCase);

        let inl = &out[&PathBuf::from("_inlinedbaml.ts")];
        assert!(inl.starts_with(HEADER));
        assert!(inl.contains("export const FILES: Record<string, string> = {"));
        #[cfg(windows)]
        let nested_key = "lorem\\\\bar.baml";
        #[cfg(not(windows))]
        let nested_key = "lorem/bar.baml";
        let lo = inl.find(nested_key).unwrap();
        let mo = inl.find("main.baml").unwrap();
        assert!(lo < mo);
        assert!(inl.contains("\"class Foo {}\\n\""));
    }

    #[test]
    fn ts_string_escapes() {
        assert_eq!(ts_string("hello"), "\"hello\"");
        assert_eq!(ts_string("a\\b"), "\"a\\\\b\"");
        assert_eq!(ts_string("a\"b"), "\"a\\\"b\"");
        assert_eq!(ts_string("a\nb"), "\"a\\nb\"");
    }
