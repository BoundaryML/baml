    #[test]
    fn function_fans_out_sync_and_async() {
        let mut pool: SymbolPool = HashMap::new();
        let n = cg_name("user", &["lorem"], "extract_resume");
        pool.insert(n, func_sym("extract_resume", "x.baml", 0));

        let out = to_source_code(&pool, &[], NamingConvention::PreserveCase);
        let leaf = &out[&PathBuf::from("lorem/index.ts")];
        // Param array and typed assertion must be populated end-to-end —
        // regression guard for the bug where `func_sym`'s `arguments`
        // never reached the renderer.
        assert!(
            leaf.contains(
                "export const extract_resume = defineFunction(\"user.lorem.extract_resume\", \"sync\", [\"x\"]) as (x: number) => number;"
            ),
            "{leaf}"
        );
        assert!(
            leaf.contains(
                "export const extract_resume_async = defineFunction(\"user.lorem.extract_resume\", \"async\", [\"x\"]) as (x: number) => Promise<number>;"
            ),
            "{leaf}"
        );
        let dts = &out[&PathBuf::from("lorem/index.d.ts")];
        assert!(
            dts.contains("export declare const extract_resume: (x: number) => number;"),
            "{dts}"
        );
        assert!(
            dts.contains(
                "export declare const extract_resume_async: (x: number) => Promise<number>;"
            ),
            "{dts}"
        );
    }

