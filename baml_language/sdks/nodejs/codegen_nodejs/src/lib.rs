//! Node.js + TypeScript SDK emitter. Produces a structurally correct
//! `baml_sdk/` tree from a `SymbolPool`: one `index.ts` (and `.d.ts`
//! companion) per namespace directory, plus `_inlinedbaml.ts` and
//! `_typemap.ts` at the SDK root.
//!
//! Phase 2 emits **scaffolding only** — every BAML top renders as a
//! `// kind Name` comment plus an `export const Name: any = BAML_PLACEHOLDER;`
//! stub (the five runtime-owned stdlib types re-export from
//! `@boundaryml/baml-core` instead). Phase 3 wires `translate_ty`; Phase 4
//! replaces stubs with real `export class` / `defineFunction(...)` bodies.
//!
//! This is a near-1:1 port of `codegen_python`; the only structural
//! difference is the in-directory filename (`__init__.py(i)` → `index.ts(.d.ts)`)
//! and TS-flavored re-export syntax (`export * as child from "./child"`).

mod emit;
mod leaf;
mod routing;
mod translate_ty;

use std::{
    collections::{BTreeMap, BTreeSet, HashMap},
    fmt::Write as _,
    path::PathBuf,
};

use baml_codegen_types::SymbolPool;
pub use baml_codegen_types::{NamingConvention, OutputType};

use crate::{
    emit::{build_emitted, typemap_file::render_typemap_module},
    leaf::{LeafBody, group_and_sort, render_leaf_body, render_leaf_body_dts},
    routing::{LeafPath, route},
};

/// Banner prepended to every generated `.ts` / `.d.ts` file. Mirrors the
/// Python `PYTHON_BANNER` (and the legacy TS emitter's `CONTENT_PREFIX`).
/// `@ts-nocheck` is intentionally NOT included — Phase 2 output is meant
/// to typecheck cleanly under `tsc --noEmit` because every placeholder is
/// `: any`, and a blanket `@ts-nocheck` would gut Phase 4's type-checking.
const NODE_BANNER: &str = "\
/* eslint-disable */
// prettier-ignore
// ----------------------------------------------------------------------------
//
//  Welcome to Baml! To use this generated code, please run the following:
//
//  $ pnpm add @boundaryml/baml-core
//
// ----------------------------------------------------------------------------
// This file was generated by BAML: please do not edit it. Instead, edit the
// BAML files and re-generate this code using: baml-cli generate
// baml-cli is available with the baml package.

";

/// A user BAML source file as it should appear in `_inlinedbaml.ts`.
/// `rel_path` is relative to the `baml_src/` root (e.g. `"lorem/foo.baml"`).
pub type UserBamlFile = (PathBuf, String);

/// Build the Node.js/TypeScript SDK output tree for `pool`. Returned
/// paths are relative to the `baml_sdk/` output root.
pub fn to_source_code(
    pool: &SymbolPool,
    user_baml_files: &[UserBamlFile],
    naming_convention: NamingConvention,
) -> HashMap<PathBuf, String> {
    // Only `PreserveCase` is wired up so far.
    assert!(
        matches!(naming_convention, NamingConvention::PreserveCase),
        "codegen_nodejs only supports naming_convention = PreserveCase \
         (got {naming_convention})",
    );
    let mut out: HashMap<PathBuf, String> = HashMap::new();

    // Every symbol routes to exactly one leaf. Dedup via `BTreeSet`.
    let mut leaves: BTreeSet<LeafPath> = BTreeSet::new();
    for (key, symbol) in pool {
        leaves.insert(route(key, symbol));
    }

    // `baml/` and the root leaf are always emitted.
    leaves.insert(LeafPath {
        segments: vec!["baml".to_string()],
    });
    leaves.insert(LeafPath {
        segments: Vec::new(),
    });

    // Walk every leaf's ancestor chain to discover all directories that
    // need an `index.ts` and the set of immediate subdirectory children.
    let mut all_dirs: BTreeSet<Vec<String>> = BTreeSet::new();
    let mut children: BTreeMap<Vec<String>, BTreeSet<String>> = BTreeMap::new();

    children.entry(Vec::new()).or_default();
    all_dirs.insert(Vec::new());

    for leaf in &leaves {
        all_dirs.insert(leaf.segments.clone());
        for i in 0..leaf.segments.len() {
            let prefix: Vec<String> = leaf.segments[..i].to_vec();
            children
                .entry(prefix.clone())
                .or_default()
                .insert(leaf.segments[i].clone());
            all_dirs.insert(prefix);
        }
    }

    // Build the populated-leaf bodies.
    let triples = build_emitted(pool);
    let bodies: BTreeMap<LeafPath, LeafBody> = group_and_sort(triples);

    // Emit every directory's `index.ts` and a sibling `index.d.ts`.
    for dir in &all_dirs {
        let kids = children.get(dir).cloned().unwrap_or_default();
        let leaf_path = LeafPath {
            segments: dir.clone(),
        };
        let empty_body = LeafBody {
            leaf: leaf_path.clone(),
            symbols: Vec::new(),
        };
        let body = bodies.get(&leaf_path).unwrap_or(&empty_body);
        let is_root = dir.is_empty();

        // `.ts` — container barrel (child re-exports) or root runtime init,
        // then the leaf's own symbol placeholders.
        let mut content = if is_root {
            render_root_index(&kids)
        } else {
            render_package_index(&kids)
        };
        // The root preamble already imports BAML_PLACEHOLDER, so the root
        // leaf body must not re-import it.
        content.push_str(&render_leaf_body(body, !is_root));
        out.insert(init_ts_path(dir), content);

        // `.d.ts` — child re-exports only (no runtime init; `.d.ts` may
        // not contain executable statements), then type-position
        // placeholders.
        let mut dts = render_index_dts(&kids);
        dts.push_str(&render_leaf_body_dts(body));
        out.insert(init_dts_path(dir), dts);
    }

    // Root-only data modules.
    out.insert(
        PathBuf::from("_inlinedbaml.ts"),
        render_inlinedbaml(user_baml_files),
    );
    out.insert(
        PathBuf::from("_typemap.ts"),
        render_typemap_module(&bodies, "baml_sdk"),
    );

    // Prepend the do-not-edit banner to every `.ts` / `.d.ts` file
    // (`index.d.ts`'s extension is `ts`, so this covers both).
    for (path, content) in &mut out {
        let is_ts = path
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| e == "ts");
        if is_ts {
            content.insert_str(0, NODE_BANNER);
        }
    }

    out
}

fn init_ts_path(dir: &[String]) -> PathBuf {
    let mut path = PathBuf::new();
    for seg in dir {
        path.push(seg);
    }
    path.push("index.ts");
    path
}

fn init_dts_path(dir: &[String]) -> PathBuf {
    let mut path = PathBuf::new();
    for seg in dir {
        path.push(seg);
    }
    path.push("index.d.ts");
    path
}

/// Render a non-root container `index.ts`: child namespace re-exports
/// ONLY. Never `export * from "./child"` (which would flatten the
/// child's symbols into this parent).
fn render_package_index(children: &BTreeSet<String>) -> String {
    let mut out = String::new();
    for c in children {
        let _ = writeln!(out, "export * as {c} from \"./{c}\";");
    }
    out
}

/// Render the SDK root `index.ts`: wires up the runtime + typemap, then
/// re-exports top-level child namespaces. The root does NOT build an
/// aggregated `b` client object — the package module is the client.
fn render_root_index(top_children: &BTreeSet<String>) -> String {
    let mut out = String::new();
    out.push_str(
        "import { initializeRuntime, setTypeMap, BAML_PLACEHOLDER } from \"@boundaryml/baml-core\";\n",
    );
    out.push_str("import * as _inlinedbaml from \"./_inlinedbaml\";\n");
    out.push_str("import { _TYPE_MAP } from \"./_typemap\";\n\n");
    out.push_str("initializeRuntime(\"baml_src\", _inlinedbaml.FILES);\n");
    out.push_str("setTypeMap(_TYPE_MAP);\n");
    if !top_children.is_empty() {
        out.push('\n');
        for c in top_children {
            let _ = writeln!(out, "export * as {c} from \"./{c}\";");
        }
    }
    out
}

/// Render an `index.d.ts` (root or container alike): child namespace
/// re-exports only. No runtime init — `.d.ts` may not carry executable
/// statements.
fn render_index_dts(children: &BTreeSet<String>) -> String {
    let mut out = String::new();
    for c in children {
        let _ = writeln!(out, "export * as {c} from \"./{c}\";");
    }
    out
}

fn render_inlinedbaml(files: &[UserBamlFile]) -> String {
    let mut entries: Vec<(&PathBuf, &String)> = files.iter().map(|(p, c)| (p, c)).collect();
    entries.sort_by(|a, b| a.0.cmp(b.0));

    let mut out = String::new();
    out.push_str("export const FILES: Record<string, string> = {\n");
    for (rel, contents) in entries {
        let _ = writeln!(
            out,
            "  {}: {},",
            ts_string(&rel.to_string_lossy()),
            ts_string(contents),
        );
    }
    out.push_str("};\n");
    out
}

/// Render `s` as a TypeScript double-quoted string literal. JS escaping
/// rules are byte-compatible with Python's for the ASCII range.
pub(crate) fn ts_string(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => {
                let _ = write!(out, "\\x{:02x}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

#[cfg(test)]
mod tests {
    use std::path::PathBuf;

    use baml_base::Name as BaseName;
    use baml_codegen_types::{
        Class, Enum, EnumVariant, Function, FunctionArgument, Name, Origin, Symbol, SymbolPool, Ty,
    };

    use super::*;

    const HEADER_LEN_MARKER: &str = "/* eslint-disable */";

    fn name(pkg: &str, ns: &[&str], n: &str) -> Name {
        Name::new(
            BaseName::new(pkg),
            ns.iter().map(|s| BaseName::new(*s)).collect(),
            BaseName::new(n),
        )
    }

    fn origin(span: u32) -> Origin {
        Origin {
            source_file_path: "main.baml".to_string(),
            span_start: span,
        }
    }

    fn class_sym(n: &Name, span: u32) -> Symbol {
        Symbol::Class(Class {
            name: n.clone(),
            generic_params: Vec::new(),
            docstring: None,
            properties: Vec::new(),
            static_methods: Vec::new(),
            instance_methods: Vec::new(),
            origin: origin(span),
        })
    }

    fn enum_sym(n: &Name, span: u32) -> Symbol {
        Symbol::Enum(Enum {
            name: n.clone(),
            docstring: None,
            variants: vec![EnumVariant {
                name: BaseName::new("POSITIVE"),
                docstring: None,
                value: "POSITIVE".to_string(),
            }],
            origin: origin(span),
        })
    }

    fn func_sym(span: u32) -> Symbol {
        Symbol::Function(Function {
            name: BaseName::new("extract_resume"),
            generic_params: Vec::new(),
            docstring: None,
            arguments: vec![FunctionArgument {
                name: BaseName::new("x"),
                docstring: None,
                ty: Ty::Int,
                default: None,
            }],
            return_type: Ty::Int,
            throws: None,
            watchers: Vec::new(),
            origin: origin(span),
        })
    }

    fn emit_sdk(pool: &SymbolPool) -> HashMap<PathBuf, String> {
        to_source_code(pool, &[], NamingConvention::PreserveCase)
    }

    #[test]
    fn empty_pool_emits_structural_files() {
        let out = emit_sdk(&SymbolPool::new());
        for f in [
            "index.ts",
            "index.d.ts",
            "_inlinedbaml.ts",
            "_typemap.ts",
            "baml/index.ts",
        ] {
            assert!(out.contains_key(&PathBuf::from(f)), "missing {f}");
        }
        let root = &out[&PathBuf::from("index.ts")];
        assert!(root.contains(HEADER_LEN_MARKER));
        assert!(root.contains(
            "import { initializeRuntime, setTypeMap, BAML_PLACEHOLDER } from \"@boundaryml/baml-core\";"
        ));
        assert!(root.contains("initializeRuntime(\"baml_src\", _inlinedbaml.FILES);"));
        assert!(root.contains("setTypeMap(_TYPE_MAP);"));
        assert!(root.contains("export * as baml from \"./baml\";"));
        assert!(!root.contains("export const b"));
    }

    #[test]
    fn class_body_renders_in_leaf() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "Resume");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        let leaf = &out[&PathBuf::from("lorem/index.ts")];
        assert!(leaf.contains("// class Resume\nexport const Resume: any = BAML_PLACEHOLDER;\n"));
    }

    #[test]
    fn enum_body_renders_in_leaf() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["ipsum"], "Sentiment");
        pool.insert(n.clone(), enum_sym(&n, 0));
        let out = emit_sdk(&pool);
        let leaf = &out[&PathBuf::from("ipsum/index.ts")];
        assert!(
            leaf.contains("// enum Sentiment\nexport const Sentiment: any = BAML_PLACEHOLDER;\n")
        );
    }

    #[test]
    fn function_fans_out_sync_and_async() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "extract_resume");
        pool.insert(n, func_sym(0));
        let out = emit_sdk(&pool);
        let leaf = &out[&PathBuf::from("lorem/index.ts")];
        assert!(leaf.contains("export const extract_resume: any = BAML_PLACEHOLDER;"));
        assert!(leaf.contains("export const extract_resume_async: any = BAML_PLACEHOLDER;"));
    }

    #[test]
    fn leaf_namespace_is_directory_with_index() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "Resume");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        assert!(out.contains_key(&PathBuf::from("lorem/index.ts")));
        assert!(!out.contains_key(&PathBuf::from("lorem.ts")));
    }

    #[test]
    fn container_index_only_reexports_children() {
        let mut pool = SymbolPool::new();
        let n = name("aws", &["s3"], "Bucket");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        let vendor = &out[&PathBuf::from("vendor/index.ts")];
        assert!(vendor.contains("export * as aws from \"./aws\";"));
        assert!(!vendor.contains("export const"));
        assert!(!vendor.contains("export * from"));
    }

    #[test]
    fn vendor_creates_interior_containers() {
        let mut pool = SymbolPool::new();
        let n = name("aws", &["s3"], "Bucket");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        assert!(out.contains_key(&PathBuf::from("vendor/index.ts")));
        assert!(out.contains_key(&PathBuf::from("vendor/aws/index.ts")));
        assert!(out.contains_key(&PathBuf::from("vendor/aws/s3/index.ts")));
        assert!(
            out[&PathBuf::from("vendor/aws/index.ts")].contains("export * as s3 from \"./s3\";")
        );
        assert!(
            out[&PathBuf::from("vendor/aws/s3/index.ts")]
                .contains("export const Bucket: any = BAML_PLACEHOLDER;")
        );
    }

    #[test]
    fn root_namespace_symbol_in_root_index() {
        let mut pool = SymbolPool::new();
        let n = name("user", &[], "Foo");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        let root = &out[&PathBuf::from("index.ts")];
        assert!(root.contains("export const Foo: any = BAML_PLACEHOLDER;"));
        assert!(!root.contains("export const b"));
    }

    #[test]
    fn stream_class_routes_to_stream_types() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "Resume$stream");
        pool.insert(n.clone(), class_sym(&n, 0));
        let out = emit_sdk(&pool);
        let leaf = &out[&PathBuf::from("stream_types/lorem/index.ts")];
        assert!(leaf.contains("export const Resume: any = BAML_PLACEHOLDER;"));
        let typemap = &out[&PathBuf::from("_typemap.ts")];
        assert!(typemap.contains(
            "\"user.lorem.Resume$stream\": [\"baml_sdk/stream_types/lorem\", \"Resume\"],"
        ));
    }

    #[test]
    fn inlinedbaml_round_trips() {
        let files = vec![
            (
                PathBuf::from("lorem/types.baml"),
                "class Resume {}\n".to_string(),
            ),
            (PathBuf::from("main.baml"), "class Foo {}\n".to_string()),
        ];
        let out = to_source_code(&SymbolPool::new(), &files, NamingConvention::PreserveCase);
        let inlined = &out[&PathBuf::from("_inlinedbaml.ts")];
        // Sorted by path: main.baml comes after lorem/types.baml.
        let lorem_at = inlined.find("\"lorem/types.baml\"").unwrap();
        let main_at = inlined.find("\"main.baml\"").unwrap();
        assert!(lorem_at < main_at);
        assert!(inlined.contains("export const FILES: Record<string, string> = {"));
        assert!(inlined.contains("\"class Foo {}\\n\""));
    }

    #[test]
    fn ts_string_escapes() {
        assert_eq!(ts_string("a\"b\\c\n"), "\"a\\\"b\\\\c\\n\"");
        assert_eq!(ts_string("\t\r"), "\"\\t\\r\"");
        assert_eq!(ts_string("\u{1}"), "\"\\x01\"");
    }
}
