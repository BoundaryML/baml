/// A user BAML source file as it should appear in the emitter's
/// inlined-baml output. `rel_path` is relative to the `baml_src/` root.
pub type UserBamlFile = (PathBuf, String);

/// Banner prepended to every generated `.java` file. Mirrors the TS
/// emitter's `NODE_BANNER`.
const JAVA_BANNER: &str = "\
// ----------------------------------------------------------------------------
//
//  Welcome to Baml! To use this generated code, add the baml-bridge
//  dependency to your build.
//
// ----------------------------------------------------------------------------
// This file was generated by BAML: please do not edit it. Instead, edit the
// BAML files and re-generate this code using: baml-cli generate
// baml-cli is available with the baml package.

";

/// The five runtime-owned stdlib types. Their bodies live in the
/// `baml-bridge` runtime library (callers need the runtime's
/// constructors and handle identity — a generated structural class
/// would not round-trip), so codegen must not emit a class for them.
/// Mirrors the TS emitter's re-export set; how the runtime library
/// claims these package paths is a `bridge_java` decision.
const RUNTIME_OWNED_FQNS: &[&str] = &[
    "baml.media.Image",
    "baml.media.Audio",
    "baml.media.Video",
    "baml.media.Pdf",
    "baml.llm.Stream",
];

/// Build the Java SDK output tree for `pool`. Returned paths are
/// relative to the `baml_sdk/` output root.
pub fn to_source_code(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
) -> HashMap<PathBuf, String> {
    // Only `PreserveCase` is wired up so far.
    assert!(
        matches!(naming_convention, NamingConvention::PreserveCase),
        "sdkgen_java only supports naming_convention = PreserveCase (got {naming_convention})",
    );
    let mut out: HashMap<PathBuf, String> = HashMap::new();

    // Group symbols per package. BTreeMap/BTreeSet for deterministic
    // output independent of the pool's HashMap iteration order.
    let mut fns_packages: BTreeSet<PackagePath> = BTreeSet::new();
    let mut type_idents_per_package: BTreeMap<PackagePath, BTreeSet<String>> = BTreeMap::new();
    let mut type_files: Vec<(PackagePath, String, String)> = Vec::new(); // (pkg, ident, body)

    for (name, symbol) in pool {
        let pkg = route(name);
        let symbol_fqn = {
            let mut s = String::from(name.pkg.as_str());
            for seg in &name.namespace_path {
                s.push('.');
                s.push_str(seg.as_str());
            }
            s.push('.');
            s.push_str(name.name.as_str());
            s
        };
        let is_runtime_owned = RUNTIME_OWNED_FQNS.contains(&symbol_fqn.as_str());

        match symbol {
            Symbol::Class(class) => {
                if is_runtime_owned {
                    continue;
                }
                let ident = java_identifier(class.name.name.as_str());
                type_idents_per_package
                    .entry(pkg.clone())
                    .or_default()
                    .insert(ident.clone());
                type_files.push((pkg, ident, render_class(class)));
            }
            Symbol::Enum(enum_) => {
                let ident = java_identifier(enum_.name.name.as_str());
                type_idents_per_package
                    .entry(pkg.clone())
                    .or_default()
                    .insert(ident.clone());
                type_files.push((pkg, ident, render_enum(enum_)));
            }
            Symbol::Function(_) => {
                fns_packages.insert(pkg);
            }
            // Java has no type-alias mechanism; aliases are erased to
            // their underlying type at every use site by translate_ty.
            Symbol::TypeAlias(_) => {}
        }
    }

    for (pkg, ident, body) in type_files {
        out.insert(java_file_path(&pkg, &ident), with_package(&pkg, &body));
    }

    // Per-package free-function holders. `Fns$` when a generated type
    // in the same package is already named `Fns`.
    for pkg in &fns_packages {
        let taken = type_idents_per_package.get(pkg);
        let holder = if taken.is_some_and(|set| set.contains("Fns")) {
            "Fns$"
        } else {
            "Fns"
        };
        out.insert(
            java_file_path(pkg, holder),
            with_package(pkg, &render_fns_holder(holder, &pkg.java_package())),
        );
    }

    // Root runtime anchor. Loading any generated class must (in later
    // phases) trigger idempotent runtime initialization from the
    // embedded bytecode — the Java analog of Python's root-package
    // import side effect. Phase 2 reserves the name.
    let root = PackagePath {
        segments: Vec::new(),
    };
    out.insert(
        java_file_path(&root, "Baml"),
        with_package(
            &root,
            "/**\n * Runtime anchor for the generated SDK. In a later phase this\n * class initializes the BAML runtime from the embedded bytecode\n * resource (`inlinedbaml.b64`) and installs the type map.\n */\npublic final class Baml {\n    private Baml() {}\n}\n",
        ),
    );

    // Compiled BAML bytecode as a base64 text resource. Base64 keeps
    // the emitter's `HashMap<PathBuf, String>` contract (raw bytecode
    // is not valid UTF-8) and dodges Java's 64KB static-initializer /
    // constant-pool limits that rule out a byte-array literal.
    out.insert(
        PathBuf::from("inlinedbaml.b64"),
        base64_encode(baml_bytecode),
    );

    // Prepend the do-not-edit banner to every `.java` file.
    for (path, content) in &mut out {
        let is_java = path
            .extension()
            .and_then(|e| e.to_str())
            .is_some_and(|e| e == "java");
        if is_java {
            content.insert_str(0, JAVA_BANNER);
        }
    }

    out
}

pub fn to_source_code_with_bytecode(
    pool: &SymbolPool,
    baml_bytecode: &[u8],
    naming_convention: NamingConvention,
) -> HashMap<PathBuf, String> {
    to_source_code(pool, baml_bytecode, naming_convention)
}

fn java_file_path(pkg: &PackagePath, ident: &str) -> PathBuf {
    let mut path = PathBuf::new();
    for seg in &pkg.segments {
        path.push(seg);
    }
    path.push(format!("{ident}.java"));
    path
}

fn with_package(pkg: &PackagePath, body: &str) -> String {
    format!("package {};\n\n{body}", pkg.java_package())
}

/// Standard-alphabet base64 with padding, dependency-free. The
/// bytecode payload is written once per fixture at build time, so
/// encoder throughput is irrelevant.
fn base64_encode(data: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(data.len().div_ceil(3) * 4);
    for chunk in data.chunks(3) {
        let b = [
            chunk[0],
            chunk.get(1).copied().unwrap_or(0),
            chunk.get(2).copied().unwrap_or(0),
        ];
        let n = (u32::from(b[0]) << 16) | (u32::from(b[1]) << 8) | u32::from(b[2]);
        out.push(ALPHABET[(n >> 18) as usize & 63] as char);
        out.push(ALPHABET[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            ALPHABET[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            ALPHABET[n as usize & 63] as char
        } else {
            '='
        });
    }
    out
}

#[cfg(test)]
mod tests {
    use baml_base::Name as BaseName;
    use baml_codegen_types::{
        Class, Enum, EnumVariant, Function, FunctionArgument, Name, Origin, Symbol, SymbolPool, Ty,
    };

    use super::*;

    fn name(pkg: &str, ns: &[&str], n: &str) -> Name {
        Name::new(
            BaseName::new(pkg),
            ns.iter().map(|s| BaseName::new(*s)).collect(),
            BaseName::new(n),
        )
    }

    fn origin(span: u32) -> Origin {
        Origin {
            source_file_path: "main.baml".to_string(),
            span_start: span,
        }
    }

    fn class_sym(n: &Name, generic_params: &[&str], span: u32) -> Symbol {
        Symbol::Class(Class {
            name: n.clone(),
            generic_params: generic_params.iter().map(|p| BaseName::new(*p)).collect(),
            docstring: None,
            properties: Vec::new(),
            static_methods: Vec::new(),
            instance_methods: Vec::new(),
            origin: origin(span),
        })
    }

    fn enum_sym(n: &Name, span: u32) -> Symbol {
        Symbol::Enum(Enum {
            name: n.clone(),
            docstring: None,
            variants: vec![
                EnumVariant {
                    name: BaseName::new("Positive"),
                    docstring: None,
                    value: "Positive".to_string(),
                },
                EnumVariant {
                    name: BaseName::new("new"),
                    docstring: None,
                    value: "new".to_string(),
                },
            ],
            origin: origin(span),
        })
    }

    fn func_sym(span: u32) -> Symbol {
        Symbol::Function(Function {
            name: BaseName::new("extract_resume"),
            generic_params: Vec::new(),
            docstring: None,
            arguments: vec![FunctionArgument {
                name: BaseName::new("x"),
                docstring: None,
                ty: Ty::Int,
                default: None,
            }],
            return_type: Ty::Int,
            throws: None,
            watchers: Vec::new(),
            origin: origin(span),
        })
    }

    fn emit_sdk(pool: &SymbolPool) -> HashMap<PathBuf, String> {
        to_source_code(pool, &[], NamingConvention::PreserveCase)
    }

    #[test]
    fn empty_pool_emits_structural_files() {
        let out = emit_sdk(&SymbolPool::new());
        assert!(out.contains_key(&PathBuf::from("Baml.java")));
        assert!(out.contains_key(&PathBuf::from("inlinedbaml.b64")));
        let anchor = &out[&PathBuf::from("Baml.java")];
        assert!(anchor.starts_with("// ---"));
        assert!(anchor.contains("package baml_sdk;"));
        assert!(anchor.contains("public final class Baml {"));
    }

    #[test]
    fn class_renders_as_own_file_with_package() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "Resume");
        pool.insert(n.clone(), class_sym(&n, &[], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("lorem/Resume.java")];
        assert!(file.contains("package baml_sdk.lorem;"));
        assert!(file.contains("public class Resume {"));
        // Java needs no barrel files.
        assert!(!out.keys().any(|p| p.to_string_lossy().contains("index")));
    }

    #[test]
    fn generic_class_declares_type_params() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["generics"], "Wrapper");
        pool.insert(n.clone(), class_sym(&n, &["T"], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("generics/Wrapper.java")];
        assert!(file.contains("public class Wrapper<T> {"));
    }

    #[test]
    fn enum_renders_variants_with_keyword_escape() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["ipsum"], "Sentiment");
        pool.insert(n.clone(), enum_sym(&n, 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("ipsum/Sentiment.java")];
        assert!(file.contains("public enum Sentiment {"));
        assert!(file.contains("    Positive,"));
        assert!(file.contains("    new$,"));
    }

    #[test]
    fn function_emits_fns_holder() {
        let mut pool = SymbolPool::new();
        pool.insert(name("user", &["lorem"], "extract_resume"), func_sym(0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("lorem/Fns.java")];
        assert!(file.contains("package baml_sdk.lorem;"));
        assert!(file.contains("public final class Fns {"));
    }

    #[test]
    fn fns_holder_escapes_on_user_class_collision() {
        let mut pool = SymbolPool::new();
        let cls = name("user", &["lorem"], "Fns");
        pool.insert(cls.clone(), class_sym(&cls, &[], 0));
        pool.insert(name("user", &["lorem"], "extract_resume"), func_sym(1));
        let out = emit_sdk(&pool);
        assert!(out.contains_key(&PathBuf::from("lorem/Fns.java"))); // the user class
        let holder = &out[&PathBuf::from("lorem/Fns$.java")];
        assert!(holder.contains("public final class Fns$ {"));
    }

    #[test]
    fn vendor_symbol_routes_under_vendor_dirs() {
        let mut pool = SymbolPool::new();
        let n = name("aws", &["s3"], "Bucket");
        pool.insert(n.clone(), class_sym(&n, &[], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("vendor/aws/s3/Bucket.java")];
        assert!(file.contains("package baml_sdk.vendor.aws.s3;"));
    }

    #[test]
    fn root_namespace_symbol_in_root_package() {
        let mut pool = SymbolPool::new();
        let n = name("user", &[], "Foo");
        pool.insert(n.clone(), class_sym(&n, &[], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("Foo.java")];
        assert!(file.contains("package baml_sdk;"));
        assert!(file.contains("public class Foo {"));
    }

    #[test]
    fn stream_class_emits_beside_base_with_suffix() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["lorem"], "Resume$stream");
        pool.insert(n.clone(), class_sym(&n, &[], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("lorem/Resume$stream.java")];
        assert!(file.contains("public class Resume$stream {"));
    }

    #[test]
    fn keyword_namespace_routes_to_escaped_package_dir() {
        let mut pool = SymbolPool::new();
        let n = name("user", &["void"], "VoidProbe");
        pool.insert(n.clone(), class_sym(&n, &[], 0));
        let out = emit_sdk(&pool);
        let file = &out[&PathBuf::from("void$/VoidProbe.java")];
        assert!(file.contains("package baml_sdk.void$;"));
    }

    #[test]
    fn runtime_owned_stdlib_types_are_not_emitted() {
        let mut pool = SymbolPool::new();
        let img = name("baml", &["media"], "Image");
        pool.insert(img.clone(), class_sym(&img, &[], 0));
        let resp = name("baml", &["http"], "Response");
        pool.insert(resp.clone(), class_sym(&resp, &[], 1));
        let out = emit_sdk(&pool);
        assert!(!out.contains_key(&PathBuf::from("baml/media/Image.java")));
        assert!(out.contains_key(&PathBuf::from("baml/http/Response.java")));
    }

    #[test]
    fn inlinedbaml_is_base64() {
        let out = to_source_code(
            &SymbolPool::new(),
            &[0, 1, 2, 253, 254, 255],
            NamingConvention::PreserveCase,
        );
        assert_eq!(out[&PathBuf::from("inlinedbaml.b64")], "AAEC/f7/");
    }

    #[test]
    fn base64_padding() {
        assert_eq!(base64_encode(b""), "");
        assert_eq!(base64_encode(b"f"), "Zg==");
        assert_eq!(base64_encode(b"fo"), "Zm8=");
        assert_eq!(base64_encode(b"foo"), "Zm9v");
    }
}
