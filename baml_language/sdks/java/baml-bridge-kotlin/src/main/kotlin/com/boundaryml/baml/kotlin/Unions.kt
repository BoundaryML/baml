/*
 * Kotlin ergonomics for the runtime's generic union arity family
 * (`baml_bridge.Union2` … `Union10`). Each anonymous multi-arm BAML union renders
 * as a sealed `UnionN<T0, …>` with one `ArmI(value)` record per positional arm
 * (BAML declaration order, `null` arm stripped).
 *
 * - `fold`: exhaustive by signature — one lambda per arm, returning a common `R`.
 *   The `else` branch is unreachable (the family is sealed) and only guards
 *   against a hypothetical unknown arm; it never fires for a valid union value.
 * - `armIOrNull`: the I-th arm's value, or `null` when the union holds another
 *   arm — the idiomatic `getOrNull`-style narrowing accessor.
 *
 * The `value as TI` casts are unchecked (the arm records erase their component
 * type) but sound: an `ArmI` wraps exactly a `TI`, so matching the arm and
 * reading its component always yields a `TI`.
 *
 * Generated by hand-equivalent script; keep formatting tight. Do not edit by
 * hand — regenerate to change all arities in lockstep.
 */

