//! The single filesystem boundary for generated SDK output.
//!
//! Language generators only produce relative paths and bytes. This module
//! validates and installs those files, records ownership, and removes files
//! that a later generation no longer emits.

use std::{
    collections::{BTreeMap, BTreeSet, HashSet, hash_map::DefaultHasher},
    fmt,
    fs::{self, File, OpenOptions},
    hash::{Hash, Hasher},
    io::{self, Write},
    path::{Component, Path, PathBuf},
    sync::{
        Mutex,
        atomic::{AtomicBool, AtomicUsize, Ordering},
    },
    time::{SystemTime, UNIX_EPOCH},
};

#[cfg(not(target_arch = "wasm32"))]
use fs2::FileExt as _;
use serde::{Deserialize, Serialize};

/// Filesystem inventory written into every generated SDK directory.
pub const OUTPUT_MANIFEST_FILE: &str = ".baml-generator-output.json";

/// Every generated SDK directory is ignored as a unit. The exception keeps
/// the policy itself visible if callers choose to commit an empty directory.
pub const GENERATED_GITIGNORE: &str = "# Generated by BAML. Do not edit.\n*\n!.gitignore\n";

const GITIGNORE_FILE: &str = ".gitignore";
const PENDING_PREFIX: &str = ".baml-generator-output.pending-";
const PENDING_SUFFIX: &str = ".json";
const TEMP_PREFIX: &str = ".baml-write-";
const MANIFEST_VERSION: u32 = 1;

/// One file produced by an SDK generator.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct GeneratedOutputFile {
    pub relative_path: PathBuf,
    pub contents: Vec<u8>,
}

impl GeneratedOutputFile {
    #[must_use]
    pub fn new(relative_path: impl Into<PathBuf>, contents: impl Into<Vec<u8>>) -> Self {
        Self {
            relative_path: relative_path.into(),
            contents: contents.into(),
        }
    }
}

/// Result of a completed output transaction.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OutputWriterReport {
    /// Generator-produced paths, excluding the writer-owned manifest and
    /// `.gitignore`.
    pub written_files: Vec<PathBuf>,
    /// Previously owned paths removed because this generation omitted them.
    pub removed_files: Vec<PathBuf>,
    /// True when a pre-manifest output tree was adopted during migration.
    pub adopted_legacy_output: bool,
}

#[derive(Debug)]
pub enum OutputWriterError {
    UnsafeOutputPath(PathBuf),
    ReservedOutputPath(PathBuf),
    DuplicateOutputPath(PathBuf),
    CaseInsensitivePathCollision(PathBuf),
    FileDirectoryPathCollision(PathBuf),
    Symlink(PathBuf),
    UnexpectedFileType(PathBuf),
    InvalidManifest {
        path: PathBuf,
        message: String,
    },
    Io {
        operation: &'static str,
        path: PathBuf,
        source: io::Error,
    },
}

impl fmt::Display for OutputWriterError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsafeOutputPath(path) => {
                write!(
                    formatter,
                    "unsafe generated output path `{}`",
                    path.display()
                )
            }
            Self::ReservedOutputPath(path) => write!(
                formatter,
                "generated output path `{}` is reserved by the output writer",
                path.display()
            ),
            Self::DuplicateOutputPath(path) => {
                write!(
                    formatter,
                    "duplicate generated output path `{}`",
                    path.display()
                )
            }
            Self::CaseInsensitivePathCollision(path) => write!(
                formatter,
                "case-insensitive generated output collision at `{}`",
                path.display()
            ),
            Self::FileDirectoryPathCollision(path) => write!(
                formatter,
                "generated output path is both a file and directory at `{}`",
                path.display()
            ),
            Self::Symlink(path) => write!(
                formatter,
                "refusing to follow symlink in generated output at `{}`",
                path.display()
            ),
            Self::UnexpectedFileType(path) => write!(
                formatter,
                "unexpected filesystem entry in generated output at `{}`",
                path.display()
            ),
            Self::InvalidManifest { path, message } => {
                write!(
                    formatter,
                    "invalid output manifest `{}`: {message}",
                    path.display()
                )
            }
            Self::Io {
                operation,
                path,
                source,
            } => write!(formatter, "{operation} `{}`: {source}", path.display()),
        }
    }
}

impl std::error::Error for OutputWriterError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            _ => None,
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
struct OwnershipManifest {
    schema_version: u32,
    /// Exact inventory installed by a completed transaction.
    committed_files: Vec<String>,
    /// Superset safe to remove when recovering an interrupted transaction.
    recovery_files: Vec<String>,
}

struct ValidatedFiles {
    generated: BTreeMap<String, Vec<u8>>,
    public_paths: Vec<String>,
}

/// Write one complete generated SDK inventory.
///
/// Calls targeting the same output directory are serialized across processes.
/// File writes and stale removals use a bounded number of worker threads.
/// Unknown files are preserved after ownership has been established. On the
/// first invocation after upgrading from the legacy writer, existing regular
/// files are adopted as generated output so stale legacy files cannot survive.
pub fn write_generated_output(
    output_directory: &Path,
    files: Vec<GeneratedOutputFile>,
) -> Result<OutputWriterReport, OutputWriterError> {
    prepare_output_root(output_directory)?;
    let output_directory = fs::canonicalize(output_directory)
        .map_err(|source| io_error("canonicalize output directory", output_directory, source))?;
    let _lock = acquire_output_lock(&output_directory)?;
    cleanup_interrupted_temp_files(&output_directory, &output_directory)?;

    let pending_paths = pending_manifest_paths(&output_directory)?;
    let committed_path = output_directory.join(OUTPUT_MANIFEST_FILE);
    let committed = read_optional_manifest(&committed_path)?;
    let pending = pending_paths
        .iter()
        .map(|path| read_required_manifest(path))
        .collect::<Result<Vec<_>, _>>()?;

    let mut previous_owned = BTreeSet::new();
    if let Some(manifest) = &committed {
        previous_owned.extend(validate_manifest_paths(
            &committed_path,
            &manifest.committed_files,
        )?);
    }
    for (path, manifest) in pending_paths.iter().zip(&pending) {
        previous_owned.extend(validate_manifest_paths(path, &manifest.recovery_files)?);
    }

    let adopted_legacy_output = committed.is_none() && pending.is_empty();
    if adopted_legacy_output {
        inventory_legacy_files(&output_directory, &output_directory, &mut previous_owned)?;
    }

    let ValidatedFiles {
        mut generated,
        public_paths,
    } = validate_generated_files(files)?;
    generated.insert(
        GITIGNORE_FILE.to_string(),
        GENERATED_GITIGNORE.as_bytes().to_vec(),
    );
    let next_owned = generated.keys().cloned().collect::<BTreeSet<_>>();
    let recovery_files = previous_owned
        .union(&next_owned)
        .cloned()
        .collect::<Vec<_>>();
    let journal_manifest = OwnershipManifest {
        schema_version: MANIFEST_VERSION,
        committed_files: next_owned.iter().cloned().collect(),
        recovery_files,
    };
    let journal_path = write_recovery_journal(&output_directory, &journal_manifest)?;

    let generated_entries = generated.into_iter().collect::<Vec<_>>();
    parallel_try_for_each(&generated_entries, |index, (relative, contents)| {
        write_one_file(&output_directory, relative, contents, index)
    })?;

    let stale = previous_owned
        .difference(&next_owned)
        .cloned()
        .collect::<Vec<_>>();
    parallel_try_for_each(&stale, |_index, relative| {
        remove_owned_file(&output_directory, relative)
    })?;
    prune_empty_owned_directories(&output_directory, &stale)?;

    install_committed_manifest(&journal_path, &committed_path)?;
    sync_directory(&output_directory)?;
    for path in pending_paths {
        if path != journal_path && path.exists() {
            fs::remove_file(&path)
                .map_err(|source| io_error("remove recovery journal", &path, source))?;
        }
    }

    Ok(OutputWriterReport {
        written_files: public_paths.into_iter().map(PathBuf::from).collect(),
        removed_files: stale
            .into_iter()
            .filter(|path| path != GITIGNORE_FILE)
            .map(PathBuf::from)
            .collect(),
        adopted_legacy_output,
    })
}

fn prepare_output_root(output_directory: &Path) -> Result<(), OutputWriterError> {
    if output_directory.as_os_str().is_empty() {
        return Err(OutputWriterError::UnsafeOutputPath(
            output_directory.to_path_buf(),
        ));
    }
    match fs::symlink_metadata(output_directory) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(OutputWriterError::Symlink(output_directory.to_path_buf()));
        }
        Ok(metadata) if !metadata.is_dir() => {
            return Err(OutputWriterError::UnexpectedFileType(
                output_directory.to_path_buf(),
            ));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            fs::create_dir_all(output_directory)
                .map_err(|source| io_error("create output directory", output_directory, source))?;
        }
        Err(source) => {
            return Err(io_error(
                "inspect output directory",
                output_directory,
                source,
            ));
        }
    }
    Ok(())
}

fn validate_generated_files(
    files: Vec<GeneratedOutputFile>,
) -> Result<ValidatedFiles, OutputWriterError> {
    let mut generated = BTreeMap::new();
    let mut case_insensitive = HashSet::new();
    for file in files {
        let portable = validate_relative_path(&file.relative_path)?;
        if is_reserved_path(&file.relative_path) {
            return Err(OutputWriterError::ReservedOutputPath(file.relative_path));
        }
        if generated.insert(portable.clone(), file.contents).is_some() {
            return Err(OutputWriterError::DuplicateOutputPath(file.relative_path));
        }
        if !case_insensitive.insert(portable.to_lowercase()) {
            return Err(OutputWriterError::CaseInsensitivePathCollision(
                file.relative_path,
            ));
        }
    }

    let mut lowercase_paths = generated
        .keys()
        .map(|path| path.to_lowercase())
        .collect::<Vec<_>>();
    lowercase_paths.sort();
    for pair in lowercase_paths.windows(2) {
        if pair[1].starts_with(&format!("{}/", pair[0])) {
            return Err(OutputWriterError::FileDirectoryPathCollision(
                PathBuf::from(&pair[0]),
            ));
        }
    }
    let public_paths = generated.keys().cloned().collect();
    Ok(ValidatedFiles {
        generated,
        public_paths,
    })
}

fn validate_relative_path(path: &Path) -> Result<String, OutputWriterError> {
    if path.as_os_str().is_empty() || path.is_absolute() {
        return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
    }
    let mut segments = Vec::new();
    for component in path.components() {
        let Component::Normal(segment) = component else {
            return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
        };
        let segment = segment
            .to_str()
            .ok_or_else(|| OutputWriterError::UnsafeOutputPath(path.to_path_buf()))?;
        if !is_safe_portable_segment(segment) {
            return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
        }
        segments.push(segment);
    }
    if segments.is_empty() {
        return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
    }
    Ok(segments.join("/"))
}

fn is_safe_portable_segment(segment: &str) -> bool {
    if segment.is_empty()
        || segment.ends_with([' ', '.'])
        || segment
            .chars()
            .any(|character| character.is_control() || r#"<>:"/\|?*"#.contains(character))
    {
        return false;
    }
    let stem = segment
        .split_once('.')
        .map_or(segment, |(stem, _extension)| stem)
        .to_ascii_uppercase();
    !matches!(stem.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        && !(stem.len() == 4
            && (stem.starts_with("COM") || stem.starts_with("LPT"))
            && matches!(stem.as_bytes()[3], b'1'..=b'9'))
}

fn is_reserved_path(path: &Path) -> bool {
    path.components().any(|component| {
        let Component::Normal(segment) = component else {
            return true;
        };
        let Some(segment) = segment.to_str() else {
            return true;
        };
        let segment = segment.to_ascii_lowercase();
        segment == GITIGNORE_FILE
            || segment == OUTPUT_MANIFEST_FILE
            || segment.starts_with(PENDING_PREFIX)
            || segment.starts_with(TEMP_PREFIX)
    })
}

fn acquire_output_lock(output_directory: &Path) -> Result<File, OutputWriterError> {
    let lock_directory = std::env::temp_dir().join("baml-codegen-output-locks");
    match fs::symlink_metadata(&lock_directory) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(OutputWriterError::Symlink(lock_directory));
        }
        Ok(metadata) if !metadata.is_dir() => {
            return Err(OutputWriterError::UnexpectedFileType(lock_directory));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            fs::create_dir_all(&lock_directory).map_err(|source| {
                io_error("create output lock directory", &lock_directory, source)
            })?;
        }
        Err(source) => {
            return Err(io_error(
                "inspect output lock directory",
                &lock_directory,
                source,
            ));
        }
    }
    let mut hasher = DefaultHasher::new();
    output_directory
        .to_string_lossy()
        .to_lowercase()
        .hash(&mut hasher);
    let lock_path = lock_directory.join(format!("{:016x}.lock", hasher.finish()));
    if fs::symlink_metadata(&lock_path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(OutputWriterError::Symlink(lock_path));
    }
    let lock = OpenOptions::new()
        .create(true)
        .read(true)
        .write(true)
        .truncate(false)
        .open(&lock_path)
        .map_err(|source| io_error("open output lock", &lock_path, source))?;
    #[cfg(not(target_arch = "wasm32"))]
    lock.lock_exclusive()
        .map_err(|source| io_error("acquire output lock", &lock_path, source))?;
    Ok(lock)
}

fn pending_manifest_paths(output_directory: &Path) -> Result<Vec<PathBuf>, OutputWriterError> {
    let mut paths = Vec::new();
    let entries = fs::read_dir(output_directory)
        .map_err(|source| io_error("read output directory", output_directory, source))?;
    for entry in entries {
        let entry = entry
            .map_err(|source| io_error("read output directory entry", output_directory, source))?;
        let name = entry.file_name();
        let Some(name) = name.to_str() else {
            continue;
        };
        if name.starts_with(PENDING_PREFIX) && name.ends_with(PENDING_SUFFIX) {
            let path = entry.path();
            let metadata = fs::symlink_metadata(&path)
                .map_err(|source| io_error("inspect recovery journal", &path, source))?;
            if metadata.file_type().is_symlink() {
                return Err(OutputWriterError::Symlink(path));
            }
            if !metadata.is_file() {
                return Err(OutputWriterError::UnexpectedFileType(path));
            }
            paths.push(path);
        }
    }
    paths.sort();
    Ok(paths)
}

fn cleanup_interrupted_temp_files(root: &Path, directory: &Path) -> Result<(), OutputWriterError> {
    let entries = fs::read_dir(directory)
        .map_err(|source| io_error("read generated output directory", directory, source))?;
    for entry in entries {
        let entry =
            entry.map_err(|source| io_error("read generated output entry", directory, source))?;
        let path = entry.path();
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect generated output entry", &path, source))?;
        if metadata.file_type().is_symlink() {
            if entry
                .file_name()
                .to_str()
                .is_some_and(|name| name.starts_with(TEMP_PREFIX))
            {
                return Err(OutputWriterError::Symlink(path));
            }
        } else if metadata.is_dir() {
            cleanup_interrupted_temp_files(root, &path)?;
        } else if metadata.is_file()
            && entry
                .file_name()
                .to_str()
                .is_some_and(|name| name.starts_with(TEMP_PREFIX))
        {
            let relative = path
                .strip_prefix(root)
                .expect("temporary file is below output root");
            validate_relative_path(relative)?;
            fs::remove_file(&path)
                .map_err(|source| io_error("remove interrupted temporary file", &path, source))?;
        } else if !metadata.is_file() {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
    }
    Ok(())
}

fn read_optional_manifest(path: &Path) -> Result<Option<OwnershipManifest>, OutputWriterError> {
    match fs::read(path) {
        Ok(bytes) => parse_manifest(path, &bytes).map(Some),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(source) => Err(io_error("read output manifest", path, source)),
    }
}

fn read_required_manifest(path: &Path) -> Result<OwnershipManifest, OutputWriterError> {
    let bytes = fs::read(path).map_err(|source| io_error("read recovery journal", path, source))?;
    parse_manifest(path, &bytes)
}

fn parse_manifest(path: &Path, bytes: &[u8]) -> Result<OwnershipManifest, OutputWriterError> {
    if fs::symlink_metadata(path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(OutputWriterError::Symlink(path.to_path_buf()));
    }
    let manifest: OwnershipManifest =
        serde_json::from_slice(bytes).map_err(|error| OutputWriterError::InvalidManifest {
            path: path.to_path_buf(),
            message: error.to_string(),
        })?;
    if manifest.schema_version != MANIFEST_VERSION {
        return Err(OutputWriterError::InvalidManifest {
            path: path.to_path_buf(),
            message: format!(
                "unsupported schema version {} (expected {MANIFEST_VERSION})",
                manifest.schema_version
            ),
        });
    }
    Ok(manifest)
}

fn validate_manifest_paths(
    manifest_path: &Path,
    paths: &[String],
) -> Result<BTreeSet<String>, OutputWriterError> {
    let mut validated = BTreeSet::new();
    for path in paths {
        let portable = validate_relative_path(Path::new(path)).map_err(|error| {
            OutputWriterError::InvalidManifest {
                path: manifest_path.to_path_buf(),
                message: error.to_string(),
            }
        })?;
        let reserved = Path::new(path).components().any(|component| {
            let Component::Normal(segment) = component else {
                return true;
            };
            let segment = segment.to_string_lossy().to_ascii_lowercase();
            segment == OUTPUT_MANIFEST_FILE
                || segment.starts_with(PENDING_PREFIX)
                || segment.starts_with(TEMP_PREFIX)
                || (segment == GITIGNORE_FILE && path != GITIGNORE_FILE)
        });
        if portable != *path || reserved {
            return Err(OutputWriterError::InvalidManifest {
                path: manifest_path.to_path_buf(),
                message: format!("unsafe owned path `{path}`"),
            });
        }
        if !validated.insert(path.clone()) {
            return Err(OutputWriterError::InvalidManifest {
                path: manifest_path.to_path_buf(),
                message: format!("duplicate owned path `{path}`"),
            });
        }
    }
    Ok(validated)
}

fn inventory_legacy_files(
    root: &Path,
    directory: &Path,
    files: &mut BTreeSet<String>,
) -> Result<(), OutputWriterError> {
    let entries = fs::read_dir(directory)
        .map_err(|source| io_error("read legacy output directory", directory, source))?;
    for entry in entries {
        let entry =
            entry.map_err(|source| io_error("read legacy output entry", directory, source))?;
        let path = entry.path();
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect legacy output entry", &path, source))?;
        if metadata.file_type().is_symlink() {
            continue;
        }
        if metadata.is_dir() {
            inventory_legacy_files(root, &path, files)?;
        } else if metadata.is_file() {
            let relative = path
                .strip_prefix(root)
                .expect("inventoried path is below output root");
            let portable = validate_relative_path(relative)?;
            if portable != OUTPUT_MANIFEST_FILE
                && !(portable.starts_with(PENDING_PREFIX) && portable.ends_with(PENDING_SUFFIX))
            {
                files.insert(portable);
            }
        } else {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
    }
    Ok(())
}

fn write_recovery_journal(
    output_directory: &Path,
    manifest: &OwnershipManifest,
) -> Result<PathBuf, OutputWriterError> {
    let bytes = manifest_bytes(manifest)?;
    for attempt in 0..1000_u32 {
        let timestamp = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap_or_default()
            .as_nanos();
        let path = output_directory.join(format!(
            "{PENDING_PREFIX}{}-{timestamp}-{attempt}{PENDING_SUFFIX}",
            std::process::id()
        ));
        match OpenOptions::new().create_new(true).write(true).open(&path) {
            Ok(mut file) => {
                file.write_all(&bytes)
                    .and_then(|()| file.sync_all())
                    .map_err(|source| io_error("write recovery journal", &path, source))?;
                sync_directory(output_directory)?;
                return Ok(path);
            }
            Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
            Err(source) => {
                return Err(io_error("create recovery journal", &path, source));
            }
        }
    }
    Err(io_error(
        "create recovery journal",
        output_directory,
        io::Error::new(
            io::ErrorKind::AlreadyExists,
            "could not allocate a unique recovery journal",
        ),
    ))
}

fn manifest_bytes(manifest: &OwnershipManifest) -> Result<Vec<u8>, OutputWriterError> {
    let mut bytes = serde_json::to_vec_pretty(manifest).map_err(|error| {
        OutputWriterError::InvalidManifest {
            path: PathBuf::from(OUTPUT_MANIFEST_FILE),
            message: error.to_string(),
        }
    })?;
    bytes.push(b'\n');
    Ok(bytes)
}

#[cfg(not(windows))]
fn install_committed_manifest(
    journal_path: &Path,
    committed_path: &Path,
) -> Result<(), OutputWriterError> {
    fs::rename(journal_path, committed_path)
        .map_err(|source| io_error("install output manifest", committed_path, source))
}

#[cfg(windows)]
fn install_committed_manifest(
    journal_path: &Path,
    committed_path: &Path,
) -> Result<(), OutputWriterError> {
    match fs::rename(journal_path, committed_path) {
        Ok(()) => Ok(()),
        Err(first_error) => {
            let metadata = fs::symlink_metadata(committed_path).map_err(|source| {
                io_error("inspect prior output manifest", committed_path, source)
            })?;
            if metadata.file_type().is_symlink() {
                return Err(OutputWriterError::Symlink(committed_path.to_path_buf()));
            }
            if !metadata.is_file() {
                return Err(OutputWriterError::UnexpectedFileType(
                    committed_path.to_path_buf(),
                ));
            }
            fs::remove_file(committed_path)
                .map_err(|source| io_error("replace output manifest", committed_path, source))?;
            fs::rename(journal_path, committed_path).map_err(|source| OutputWriterError::Io {
                operation: "install output manifest after replacement",
                path: committed_path.to_path_buf(),
                source: io::Error::new(
                    source.kind(),
                    format!("{source}; initial rename failed: {first_error}"),
                ),
            })
        }
    }
}

fn parallel_try_for_each<T: Sync>(
    items: &[T],
    operation: impl Fn(usize, &T) -> Result<(), OutputWriterError> + Sync,
) -> Result<(), OutputWriterError> {
    if items.is_empty() {
        return Ok(());
    }
    let workers = std::thread::available_parallelism()
        .map_or(1, std::num::NonZeroUsize::get)
        .min(items.len());
    let next = AtomicUsize::new(0);
    let failed = AtomicBool::new(false);
    let first_error = Mutex::new(None);
    std::thread::scope(|scope| {
        for _ in 0..workers {
            scope.spawn(|| {
                while !failed.load(Ordering::Acquire) {
                    let index = next.fetch_add(1, Ordering::Relaxed);
                    let Some(item) = items.get(index) else {
                        break;
                    };
                    if let Err(error) = operation(index, item) {
                        failed.store(true, Ordering::Release);
                        let mut slot = first_error.lock().expect("output error mutex poisoned");
                        if slot.is_none() {
                            *slot = Some(error);
                        }
                        break;
                    }
                }
            });
        }
    });
    first_error
        .into_inner()
        .expect("output error mutex poisoned")
        .map_or(Ok(()), Err)
}

fn write_one_file(
    root: &Path,
    relative: &str,
    contents: &[u8],
    index: usize,
) -> Result<(), OutputWriterError> {
    let relative_path = Path::new(relative);
    let destination = root.join(relative_path);
    let parent = destination
        .parent()
        .expect("validated generated path has an output parent");
    ensure_safe_directories(root, parent)?;
    reject_symlink_or_directory(&destination)?;

    let temp = parent.join(format!("{TEMP_PREFIX}{}-{index}", std::process::id()));
    if fs::symlink_metadata(&temp).is_ok() {
        return Err(OutputWriterError::UnexpectedFileType(temp));
    }
    let result = (|| {
        let mut file = OpenOptions::new()
            .create_new(true)
            .write(true)
            .open(&temp)
            .map_err(|source| io_error("create temporary generated file", &temp, source))?;
        file.write_all(contents)
            .and_then(|()| file.sync_all())
            .map_err(|source| io_error("write temporary generated file", &temp, source))?;
        replace_file(&temp, &destination)?;
        sync_directory(parent)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temp);
    }
    result
}

#[cfg(not(windows))]
fn replace_file(temp: &Path, destination: &Path) -> Result<(), OutputWriterError> {
    fs::rename(temp, destination)
        .map_err(|source| io_error("install generated file", destination, source))
}

#[cfg(windows)]
fn replace_file(temp: &Path, destination: &Path) -> Result<(), OutputWriterError> {
    match fs::rename(temp, destination) {
        Ok(()) => Ok(()),
        Err(first_error) if destination.exists() => {
            reject_symlink_or_directory(destination)?;
            fs::remove_file(destination)
                .map_err(|source| io_error("replace generated file", destination, source))?;
            fs::rename(temp, destination).map_err(|source| OutputWriterError::Io {
                operation: "install generated file after replacement",
                path: destination.to_path_buf(),
                source: io::Error::new(
                    source.kind(),
                    format!("{source}; initial rename failed: {first_error}"),
                ),
            })
        }
        Err(source) => Err(io_error("install generated file", destination, source)),
    }
}

fn ensure_safe_directories(root: &Path, directory: &Path) -> Result<(), OutputWriterError> {
    let relative = directory
        .strip_prefix(root)
        .map_err(|_| OutputWriterError::UnsafeOutputPath(directory.to_path_buf()))?;
    let mut current = root.to_path_buf();
    for component in relative.components() {
        let Component::Normal(segment) = component else {
            return Err(OutputWriterError::UnsafeOutputPath(directory.to_path_buf()));
        };
        current.push(segment);
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(OutputWriterError::Symlink(current));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(OutputWriterError::UnexpectedFileType(current));
            }
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                match fs::create_dir(&current) {
                    Ok(()) => {}
                    Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
                    Err(source) => {
                        return Err(io_error(
                            "create generated output directory",
                            &current,
                            source,
                        ));
                    }
                }
                let metadata = fs::symlink_metadata(&current).map_err(|source| {
                    io_error("inspect generated output directory", &current, source)
                })?;
                if metadata.file_type().is_symlink() {
                    return Err(OutputWriterError::Symlink(current));
                }
                if !metadata.is_dir() {
                    return Err(OutputWriterError::UnexpectedFileType(current));
                }
            }
            Err(source) => {
                return Err(io_error(
                    "inspect generated output directory",
                    &current,
                    source,
                ));
            }
        }
    }
    Ok(())
}

fn reject_symlink_or_directory(path: &Path) -> Result<(), OutputWriterError> {
    match fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            Err(OutputWriterError::Symlink(path.to_path_buf()))
        }
        Ok(metadata) if !metadata.is_file() => {
            Err(OutputWriterError::UnexpectedFileType(path.to_path_buf()))
        }
        Ok(_) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(source) => Err(io_error("inspect generated output path", path, source)),
    }
}

fn remove_owned_file(root: &Path, relative: &str) -> Result<(), OutputWriterError> {
    let path = root.join(relative);
    if let Some(parent) = path.parent() {
        ensure_existing_directories_are_safe(root, parent)?;
    }
    match fs::symlink_metadata(&path) {
        Ok(metadata) if metadata.file_type().is_symlink() => Err(OutputWriterError::Symlink(path)),
        Ok(metadata) if metadata.is_file() => {
            fs::remove_file(&path)
                .map_err(|source| io_error("remove stale generated file", &path, source))?;
            if let Some(parent) = path.parent() {
                sync_directory(parent)?;
            }
            Ok(())
        }
        Ok(_) => Err(OutputWriterError::UnexpectedFileType(path)),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(()),
        Err(source) => Err(io_error("inspect stale generated file", &path, source)),
    }
}

fn ensure_existing_directories_are_safe(
    root: &Path,
    directory: &Path,
) -> Result<(), OutputWriterError> {
    let relative = directory
        .strip_prefix(root)
        .map_err(|_| OutputWriterError::UnsafeOutputPath(directory.to_path_buf()))?;
    let mut current = root.to_path_buf();
    for component in relative.components() {
        current.push(component.as_os_str());
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(OutputWriterError::Symlink(current));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(OutputWriterError::UnexpectedFileType(current));
            }
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(()),
            Err(source) => {
                return Err(io_error(
                    "inspect generated output directory",
                    &current,
                    source,
                ));
            }
        }
    }
    Ok(())
}

fn prune_empty_owned_directories(root: &Path, stale: &[String]) -> Result<(), OutputWriterError> {
    let mut directories = BTreeSet::new();
    for relative in stale {
        let mut parent = Path::new(relative).parent();
        while let Some(path) = parent {
            if path.as_os_str().is_empty() {
                break;
            }
            directories.insert(path.to_path_buf());
            parent = path.parent();
        }
    }
    let mut directories = directories.into_iter().collect::<Vec<_>>();
    directories.sort_by_key(|path| std::cmp::Reverse(path.components().count()));
    for relative in directories {
        let path = root.join(relative);
        match fs::symlink_metadata(&path) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(OutputWriterError::Symlink(path));
            }
            Ok(metadata) if metadata.is_dir() => match fs::remove_dir(&path) {
                Ok(()) => {}
                Err(error)
                    if matches!(
                        error.kind(),
                        io::ErrorKind::DirectoryNotEmpty | io::ErrorKind::NotFound
                    ) => {}
                Err(source) => {
                    return Err(io_error(
                        "remove empty generated output directory",
                        &path,
                        source,
                    ));
                }
            },
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {}
            Err(source) => {
                return Err(io_error(
                    "inspect generated output directory",
                    &path,
                    source,
                ));
            }
        }
    }
    Ok(())
}

fn io_error(operation: &'static str, path: &Path, source: io::Error) -> OutputWriterError {
    OutputWriterError::Io {
        operation,
        path: path.to_path_buf(),
        source,
    }
}

#[cfg(unix)]
fn sync_directory(path: &Path) -> Result<(), OutputWriterError> {
    File::open(path)
        .and_then(|directory| directory.sync_all())
        .map_err(|source| io_error("sync generated output directory", path, source))
}

#[cfg(not(unix))]
fn sync_directory(_path: &Path) -> Result<(), OutputWriterError> {
    Ok(())
}

