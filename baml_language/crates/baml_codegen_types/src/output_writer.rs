/// Result of a completed output transaction.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OutputWriterReport {
    /// Generator-produced paths, excluding writer-owned infrastructure.
    pub written_files: Vec<PathBuf>,
    /// Previously owned paths removed because this generation omitted them.
    pub removed_files: Vec<PathBuf>,
    /// True when a recognized legacy manifest proved ownership during migration.
    pub adopted_legacy_output: bool,
}

#[derive(Debug)]
pub enum OutputWriterError {
    UnsafeOutputPath(PathBuf),
    ReservedOutputPath(PathBuf),
    DuplicateOutputPath(PathBuf),
    CaseInsensitivePathCollision(PathBuf),
    FileDirectoryPathCollision(PathBuf),
    UnownedPathCollision(PathBuf),
    Symlink(PathBuf),
    UnexpectedFileType(PathBuf),
    UnownedTransactionPath(PathBuf),
    InvalidManifest {
        path: PathBuf,
        message: String,
    },
    Io {
        operation: &'static str,
        path: PathBuf,
        source: io::Error,
    },
    ReplacementRollbackFailed {
        replacement: io::Error,
        rollback: io::Error,
        backup: PathBuf,
    },
}

impl fmt::Display for OutputWriterError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnsafeOutputPath(path) => {
                write!(
                    formatter,
                    "unsafe generated output path `{}`",
                    path.display()
                )
            }
            Self::ReservedOutputPath(path) => write!(
                formatter,
                "generated output path `{}` is reserved by the output writer",
                path.display()
            ),
            Self::DuplicateOutputPath(path) => {
                write!(
                    formatter,
                    "duplicate generated output path `{}`",
                    path.display()
                )
            }
            Self::CaseInsensitivePathCollision(path) => write!(
                formatter,
                "case-insensitive generated output collision at `{}`",
                path.display()
            ),
            Self::FileDirectoryPathCollision(path) => write!(
                formatter,
                "generated output path is both a file and directory at `{}`",
                path.display()
            ),
            Self::UnownedPathCollision(path) => write!(
                formatter,
                "generated output conflicts with preserved file `{}`",
                path.display()
            ),
            Self::Symlink(path) => write!(
                formatter,
                "refusing to follow symlink in generated output at `{}`",
                path.display()
            ),
            Self::UnexpectedFileType(path) => write!(
                formatter,
                "unexpected filesystem entry in generated output at `{}`",
                path.display()
            ),
            Self::UnownedTransactionPath(path) => write!(
                formatter,
                "refusing to recover unowned transaction path `{}`",
                path.display()
            ),
            Self::InvalidManifest { path, message } => {
                write!(
                    formatter,
                    "invalid output manifest `{}`: {message}",
                    path.display()
                )
            }
            Self::Io {
                operation,
                path,
                source,
            } => write!(formatter, "{operation} `{}`: {source}", path.display()),
            Self::ReplacementRollbackFailed {
                replacement,
                rollback,
                backup,
            } => write!(
                formatter,
                "output replacement failed ({replacement}) and rollback failed ({rollback}); last complete output remains at `{}`",
                backup.display()
            ),
        }
    }
}

impl std::error::Error for OutputWriterError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io { source, .. } => Some(source),
            Self::ReplacementRollbackFailed { replacement, .. } => Some(replacement),
            _ => None,
        }
    }
}

#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
struct OwnedFile {
    relative_path: String,
    sha256: String,
}

/// Version 2 is the whole-tree transaction manifest; version 3 adds the
/// provenance a freshness check needs. The legacy string inventories remain
/// deserializable so an interrupted version-1 in-place write can be safely
/// replaced by the first whole-tree transaction.
///
/// Every added field is optional, so a version-2 manifest still loads and
/// simply reports [`ProvenanceStatus::Untracked`].
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
struct OwnershipManifest {
    schema_version: u32,
    #[serde(default)]
    files: Vec<OwnedFile>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    input_fingerprint: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    toolchain_version: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    generator_name: Option<String>,
}

impl OwnershipManifest {
    fn provenance(&self) -> ProvenanceStatus {
        match (
            &self.input_fingerprint,
            &self.toolchain_version,
            &self.generator_name,
        ) {
            (Some(input_fingerprint), Some(toolchain_version), Some(generator_name)) => {
                ProvenanceStatus::Known(OutputProvenance {
                    input_fingerprint: input_fingerprint.clone(),
                    toolchain_version: toolchain_version.clone(),
                    generator_name: generator_name.clone(),
                })
            }
            // A partially-populated manifest is not evidence of anything.
            _ => ProvenanceStatus::Untracked,
        }
    }
}

