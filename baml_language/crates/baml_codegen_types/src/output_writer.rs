    #[cfg(not(target_arch = "wasm32"))]
    #[test]
    fn concurrent_transactions_cannot_leave_a_mixed_inventory() {
        let root = TempDir::new().unwrap();
        let output = Arc::new(root.path().join("sdk"));
        let barrier = Arc::new(Barrier::new(3));
        let threads = [("first.go", "first"), ("second.go", "second")]
            .into_iter()
            .map(|(path, contents)| {
                let output = Arc::clone(&output);
                let barrier = Arc::clone(&barrier);
                std::thread::spawn(move || {
                    barrier.wait();
                    write(&output, vec![file(path, contents)]).unwrap();
                })
            })
            .collect::<Vec<_>>();
        barrier.wait();
        for thread in threads {
            thread.join().unwrap();
        }

        let first = output.join("first.go").is_file();
        let second = output.join("second.go").is_file();
        assert_ne!(
            first, second,
            "final output must be one complete transaction"
        );
    }

