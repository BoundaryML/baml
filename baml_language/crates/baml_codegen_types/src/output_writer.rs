/// Filesystem inventory written into every generated SDK directory.
pub const OUTPUT_MANIFEST_FILE: &str = ".baml-generator-output.json";

/// Every generated SDK directory is ignored as a unit. The exception keeps
/// the policy itself visible if callers choose to commit an empty directory.
pub const GENERATED_GITIGNORE: &str = "# Generated by BAML. Do not edit.\n*\n!.gitignore\n";

/// The `vcs = "commit"` counterpart: a header claiming the file as
/// writer-owned while ignoring nothing, so the whole tree (including the
/// manifest that `--check` reads) stays tracked.
pub const COMMITTED_GITIGNORE: &str = "# Generated by BAML. Do not edit.\n# This bridge is committed on purpose (`[bridge] vcs = \"commit\"`).\n";

/// Whether a generated bridge is ignored by version control or committed.
///
/// A team that commits its bridge needs the tree *and* the manifest tracked,
/// or a freshness check cannot run from a clean checkout.
#[derive(Clone, Copy, Debug, Default, Eq, PartialEq)]
pub enum VcsPolicy {
    /// Ignore the generated tree as a unit.
    #[default]
    Ignore,
    /// Track the generated tree; ignore nothing.
    Commit,
}

impl VcsPolicy {
    const fn gitignore(self) -> &'static str {
        match self {
            Self::Ignore => GENERATED_GITIGNORE,
            Self::Commit => COMMITTED_GITIGNORE,
        }
    }
}

/// What a generated tree records about the inputs it was built from.
///
/// Stored in the ownership manifest so a later invocation can decide whether
/// the bridge is stale without recompiling anything.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct OutputProvenance {
    /// Hash of the codegen inputs; see the CLI's bridge fingerprint.
    pub input_fingerprint: String,
    /// `baml_version::CANONICAL_VERSION` of the toolchain that generated this.
    pub toolchain_version: String,
    /// The `[generator.<name>]` section this tree was written for.
    pub generator_name: String,
}

/// Everything about one generation transaction beyond the file bytes.
#[derive(Clone, Debug)]
pub struct OutputOptions {
    pub provenance: OutputProvenance,
    pub vcs: VcsPolicy,
}

/// What a generated directory can tell us about how it was produced.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum ProvenanceStatus {
    /// No manifest: nothing was ever generated here.
    NeverGenerated,
    /// A manifest that records no provenance — either written by a toolchain
    /// from before freshness tracking, or hand-edited since.
    ///
    /// This is *not* a third freshness answer. A bridge we cannot vouch for
    /// is one that needs regenerating, so callers report it as stale. The
    /// alternative — "cannot prove stale, so pass" — makes a CI gate say it
    /// succeeded without having verified anything.
    Untracked,
    Known(OutputProvenance),
}

/// A recorded file that no longer matches what the manifest says.
#[derive(Clone, Debug, Eq, PartialEq)]
pub enum FileDrift {
    /// Present but its bytes changed: hand-edited, truncated, or reverted.
    Modified(PathBuf),
    /// Recorded by the manifest but no longer on disk.
    Missing(PathBuf),
}

impl FileDrift {
    #[must_use]
    pub fn path(&self) -> &Path {
        match self {
            Self::Modified(path) | Self::Missing(path) => path,
        }
    }
}

