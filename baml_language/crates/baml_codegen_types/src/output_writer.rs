/// Write one complete generated SDK inventory.
///
/// Calls targeting the same output directory are serialized across processes.
/// A complete sibling tree is built with bounded parallel writes, validated,
/// and installed through a backup that can be rolled back or recovered after
/// interruption. Files not listed in the prior generator manifest are copied
/// forward. On the first invocation after upgrading from a legacy writer,
/// existing files remain unowned unless a recognized legacy manifest proves
/// which files were generated.
pub fn write_generated_output(
    output_directory: &Path,
    files: Vec<GeneratedOutputFile>,
    options: &OutputOptions,
) -> Result<OutputWriterReport, OutputWriterError> {
    write_generated_output_with_rename(output_directory, files, options, |from, to| {
        fs::rename(from, to)
    })
}

fn write_generated_output_with_rename(
    output_directory: &Path,
    files: Vec<GeneratedOutputFile>,
    options: &OutputOptions,
    mut rename: impl FnMut(&Path, &Path) -> io::Result<()>,
) -> Result<OutputWriterReport, OutputWriterError> {
    let ValidatedFiles {
        mut generated,
        public_paths,
    } = validate_generated_files(files)?;
    // The `.gitignore` is writer-owned and rewritten every transaction, so
    // flipping the vcs policy takes effect on the next generate.
    generated.insert(
        GITIGNORE_FILE.to_string(),
        options.vcs.gitignore().as_bytes().to_vec(),
    );

    let paths = transaction_paths(output_directory)?;
    let _lock = acquire_output_lock(&paths.target)?;
    recover_prior_transaction(&paths, &mut rename)?;

    let (previous_owned, adopted_legacy_output) = previous_owned_files(&paths.target)?;
    let next_owned = generated.keys().cloned().collect::<BTreeSet<_>>();
    let unknown = collect_unknown_files(&paths.target, &previous_owned, &next_owned)?;
    validate_preserved_paths(&unknown, &next_owned)?;
    let stale = previous_owned
        .difference(&next_owned)
        .cloned()
        .collect::<Vec<_>>();

    create_staging_tree(&paths.staging, &unknown, &generated)?;
    let manifest = manifest_for_generated(&generated, &options.provenance);
    write_internal_file(
        &paths.staging,
        OUTPUT_MANIFEST_FILE,
        &manifest_bytes(&manifest)?,
    )?;
    validate_staging_tree(&paths.staging, &manifest, &unknown)?;

    install_staging_tree(&paths, &mut rename)?;

    Ok(OutputWriterReport {
        written_files: public_paths.into_iter().map(PathBuf::from).collect(),
        removed_files: stale
            .into_iter()
            .filter(|path| path != GITIGNORE_FILE)
            .map(PathBuf::from)
            .collect(),
        adopted_legacy_output,
    })
}

/// Read what a generated directory records about its own inputs.
///
/// One small file read, no compile: this is the cheap depth used by the
/// passive freshness check on ordinary commands.
pub fn read_output_provenance(
    output_directory: &Path,
) -> Result<ProvenanceStatus, OutputWriterError> {
    let manifest_path = output_directory.join(OUTPUT_MANIFEST_FILE);
    match read_optional_manifest(&manifest_path)? {
        None => Ok(ProvenanceStatus::NeverGenerated),
        Some(manifest) => Ok(manifest.provenance()),
    }
}

/// Re-hash every file the manifest claims and report what no longer matches.
///
/// This is what turns "assume the generated files are untouched" into a
/// verified fact, so a hand-edited or truncated bridge is caught even when
/// the inputs are unchanged. Costs one read per generated file, so it is the
/// deep depth used by `--check`, not by the passive warning.
pub fn verify_recorded_files(output_directory: &Path) -> Result<Vec<FileDrift>, OutputWriterError> {
    let manifest_path = output_directory.join(OUTPUT_MANIFEST_FILE);
    let Some(manifest) = read_optional_manifest(&manifest_path)? else {
        return Ok(Vec::new());
    };
    // Schema 1 recorded names without hashes, so there is nothing to verify.

    let mut drift = Vec::new();
    for entry in &manifest.files {
        let path = output_directory.join(&entry.relative_path);
        match fs::read(&path) {
            Ok(contents) if sha256(&contents) == entry.sha256 => {}
            Ok(_) => drift.push(FileDrift::Modified(PathBuf::from(&entry.relative_path))),
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                drift.push(FileDrift::Missing(PathBuf::from(&entry.relative_path)));
            }
            Err(source) => return Err(io_error("read generated file", &path, source)),
        }
    }
    Ok(drift)
}

fn transaction_paths(output_directory: &Path) -> Result<TransactionPaths, OutputWriterError> {
    if output_directory.as_os_str().is_empty() {
        return Err(OutputWriterError::UnsafeOutputPath(
            output_directory.to_path_buf(),
        ));
    }
    if fs::symlink_metadata(output_directory)
        .is_ok_and(|metadata| metadata.file_type().is_symlink())
    {
        return Err(OutputWriterError::Symlink(output_directory.to_path_buf()));
    }
    let parent = output_directory
        .parent()
        .filter(|path| !path.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    fs::create_dir_all(parent)
        .map_err(|source| io_error("create output parent", parent, source))?;
    let canonical_parent = fs::canonicalize(parent)
        .map_err(|source| io_error("canonicalize output parent", parent, source))?;
    let stem = output_directory
        .file_name()
        .and_then(|name| name.to_str())
        .filter(|name| !name.is_empty())
        .ok_or_else(|| OutputWriterError::UnsafeOutputPath(output_directory.to_path_buf()))?;
    if !is_safe_portable_segment(stem) {
        return Err(OutputWriterError::UnsafeOutputPath(
            output_directory.to_path_buf(),
        ));
    }
    let target = canonical_parent.join(stem);
    Ok(TransactionPaths {
        target,
        parent: canonical_parent.clone(),
        staging: canonical_parent.join(format!(".{stem}.baml-staging")),
        backup: canonical_parent.join(format!(".{stem}.baml-backup")),
    })
}

fn validate_generated_files(
    files: Vec<GeneratedOutputFile>,
) -> Result<ValidatedFiles, OutputWriterError> {
    let mut generated = BTreeMap::new();
    let mut case_insensitive = HashSet::new();
    for file in files {
        let portable = validate_relative_path(&file.relative_path)?;
        if is_reserved_path(&file.relative_path) {
            return Err(OutputWriterError::ReservedOutputPath(file.relative_path));
        }
        if generated.insert(portable.clone(), file.contents).is_some() {
            return Err(OutputWriterError::DuplicateOutputPath(file.relative_path));
        }
        if !case_insensitive.insert(portable.to_lowercase()) {
            return Err(OutputWriterError::CaseInsensitivePathCollision(
                file.relative_path,
            ));
        }
    }
    validate_no_file_directory_collisions(generated.keys().map(String::as_str))?;
    let public_paths = generated.keys().cloned().collect();
    Ok(ValidatedFiles {
        generated,
        public_paths,
    })
}

fn validate_relative_path(path: &Path) -> Result<String, OutputWriterError> {
    if path.as_os_str().is_empty() || path.is_absolute() {
        return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
    }
    let mut segments = Vec::new();
    for component in path.components() {
        let Component::Normal(segment) = component else {
            return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
        };
        let segment = segment
            .to_str()
            .ok_or_else(|| OutputWriterError::UnsafeOutputPath(path.to_path_buf()))?;
        if !is_safe_portable_segment(segment) {
            return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
        }
        segments.push(segment);
    }
    if segments.is_empty() {
        return Err(OutputWriterError::UnsafeOutputPath(path.to_path_buf()));
    }
    Ok(segments.join("/"))
}

fn is_safe_portable_segment(segment: &str) -> bool {
    if segment.is_empty()
        || segment.ends_with([' ', '.'])
        || segment
            .chars()
            .any(|character| character.is_control() || r#"<>:"/\|?*"#.contains(character))
    {
        return false;
    }
    let stem = segment
        .split_once('.')
        .map_or(segment, |(stem, _extension)| stem)
        .to_ascii_uppercase();
    !matches!(stem.as_str(), "CON" | "PRN" | "AUX" | "NUL")
        && !(stem.len() == 4
            && (stem.starts_with("COM") || stem.starts_with("LPT"))
            && matches!(stem.as_bytes()[3], b'1'..=b'9'))
}

fn is_reserved_path(path: &Path) -> bool {
    path.components().any(|component| {
        let Component::Normal(segment) = component else {
            return true;
        };
        let Some(segment) = segment.to_str() else {
            return true;
        };
        let segment = segment.to_ascii_lowercase();
        segment == GITIGNORE_FILE
            || segment == OUTPUT_MANIFEST_FILE
            || segment == OWNERSHIP_MARKER_FILE
            || segment == LEGACY_CSHARP_MANIFEST
            || segment == LEGACY_CSHARP_STAGING_MARKER
            || segment.starts_with(PENDING_PREFIX)
            || segment.starts_with(TEMP_PREFIX)
    })
}

fn is_root_writer_infrastructure(path: &Path) -> bool {
    let mut components = path.components();
    let Some(Component::Normal(segment)) = components.next() else {
        return false;
    };
    if components.next().is_some() {
        return false;
    }
    let Some(segment) = segment.to_str() else {
        return false;
    };
    let segment = segment.to_ascii_lowercase();
    segment == GITIGNORE_FILE
        || segment == OUTPUT_MANIFEST_FILE
        || segment == OWNERSHIP_MARKER_FILE
        || segment == LEGACY_CSHARP_MANIFEST
        || segment == LEGACY_CSHARP_STAGING_MARKER
        || segment.starts_with(PENDING_PREFIX)
        || segment.starts_with(TEMP_PREFIX)
}

fn validate_no_file_directory_collisions<'a>(
    paths: impl IntoIterator<Item = &'a str>,
) -> Result<(), OutputWriterError> {
    let lowercase = paths
        .into_iter()
        .map(str::to_lowercase)
        .collect::<BTreeSet<_>>();
    for path in &lowercase {
        for (separator, _) in path.match_indices('/') {
            let ancestor = &path[..separator];
            if lowercase.contains(ancestor) {
                return Err(OutputWriterError::FileDirectoryPathCollision(
                    PathBuf::from(ancestor),
                ));
            }
        }
    }
    Ok(())
}

fn acquire_output_lock(output_directory: &Path) -> Result<File, OutputWriterError> {
    let lock_directory = std::env::temp_dir().join("baml-codegen-output-locks");
    match fs::symlink_metadata(&lock_directory) {
        Ok(metadata) if metadata.file_type().is_symlink() => {
            return Err(OutputWriterError::Symlink(lock_directory));
        }
        Ok(metadata) if !metadata.is_dir() => {
            return Err(OutputWriterError::UnexpectedFileType(lock_directory));
        }
        Ok(_) => {}
        Err(error) if error.kind() == io::ErrorKind::NotFound => {
            fs::create_dir_all(&lock_directory).map_err(|source| {
                io_error("create output lock directory", &lock_directory, source)
            })?;
        }
        Err(source) => {
            return Err(io_error(
                "inspect output lock directory",
                &lock_directory,
                source,
            ));
        }
    }
    let mut hasher = DefaultHasher::new();
    output_directory
        .to_string_lossy()
        .to_lowercase()
        .hash(&mut hasher);
    let lock_path = lock_directory.join(format!("{:016x}.lock", hasher.finish()));
    if fs::symlink_metadata(&lock_path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(OutputWriterError::Symlink(lock_path));
    }
    let lock = OpenOptions::new()
        .create(true)
        .read(true)
        .write(true)
        .truncate(false)
        .open(&lock_path)
        .map_err(|source| io_error("open output lock", &lock_path, source))?;
    #[cfg(not(target_arch = "wasm32"))]
    lock.lock_exclusive()
        .map_err(|source| io_error("acquire output lock", &lock_path, source))?;
    Ok(lock)
}

fn recover_prior_transaction(
    paths: &TransactionPaths,
    rename: &mut impl FnMut(&Path, &Path) -> io::Result<()>,
) -> Result<(), OutputWriterError> {
    if path_lexists(&paths.backup) {
        let empty_residue = transaction_tree_is_empty(&paths.backup)?;
        if !empty_residue {
            require_owned_transaction_tree(&paths.backup)?;
        } else if !path_lexists(&paths.target) {
            return Err(OutputWriterError::UnownedTransactionPath(
                paths.backup.clone(),
            ));
        }
        if path_lexists(&paths.target) {
            require_owned_transaction_tree(&paths.target)?;
            if empty_residue {
                remove_empty_transaction_tree(&paths.backup)?;
            } else {
                remove_owned_transaction_tree(&paths.backup)?;
            }
        } else {
            rename_with_retry(rename, &paths.backup, &paths.target)
                .map_err(|source| io_error("recover prior output backup", &paths.backup, source))?;
            sync_directory(&paths.parent)?;
        }
    }
    if path_lexists(&paths.staging) {
        if transaction_tree_is_empty(&paths.staging)? {
            remove_empty_transaction_tree(&paths.staging)?;
        } else {
            require_owned_transaction_tree(&paths.staging)?;
            remove_owned_transaction_tree(&paths.staging)?;
        }
    }
    Ok(())
}

fn require_owned_transaction_tree(path: &Path) -> Result<PathBuf, OutputWriterError> {
    let metadata = fs::symlink_metadata(path)
        .map_err(|source| io_error("inspect transaction tree", path, source))?;
    if metadata.file_type().is_symlink() {
        return Err(OutputWriterError::Symlink(path.to_path_buf()));
    }
    if !metadata.is_dir() {
        return Err(OutputWriterError::UnexpectedFileType(path.to_path_buf()));
    }
    let marker = path.join(OWNERSHIP_MARKER_FILE);
    if regular_file_has_contents(&marker, OWNERSHIP_MARKER_CONTENT)? {
        return Ok(marker);
    }
    let legacy_marker = path.join(LEGACY_CSHARP_STAGING_MARKER);
    if regular_file_has_contents(&legacy_marker, LEGACY_CSHARP_STAGING_MARKER_CONTENT)? {
        return Ok(legacy_marker);
    }
    let legacy_manifest = path.join(LEGACY_CSHARP_MANIFEST);
    if validate_legacy_csharp_transaction_tree(path, &legacy_manifest)? {
        return Ok(legacy_manifest);
    }
    Err(OutputWriterError::UnownedTransactionPath(
        path.to_path_buf(),
    ))
}

fn regular_file_has_contents(path: &Path, expected: &[u8]) -> Result<bool, OutputWriterError> {
    let metadata = match fs::symlink_metadata(path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(false),
        Err(source) => {
            return Err(io_error(
                "inspect transaction ownership proof",
                path,
                source,
            ));
        }
    };
    if metadata.file_type().is_symlink() {
        return Err(OutputWriterError::Symlink(path.to_path_buf()));
    }
    if !metadata.is_file() {
        return Err(OutputWriterError::UnexpectedFileType(path.to_path_buf()));
    }
    fs::read(path)
        .map(|contents| contents == expected)
        .map_err(|source| io_error("read transaction ownership proof", path, source))
}

fn validate_legacy_csharp_transaction_tree(
    root: &Path,
    manifest_path: &Path,
) -> Result<bool, OutputWriterError> {
    let Some(expected) = legacy_csharp_owned_files(root, manifest_path)? else {
        return Ok(false);
    };

    let mut actual = BTreeSet::new();
    collect_tree_files(root, root, &mut actual)?;
    for infrastructure in [
        LEGACY_CSHARP_MANIFEST,
        OUTPUT_MANIFEST_FILE,
        GITIGNORE_FILE,
        LEGACY_CSHARP_STAGING_MARKER,
    ] {
        actual.remove(infrastructure);
    }
    if actual != expected {
        return Err(invalid_manifest(
            manifest_path,
            "legacy C# tree differs from its file inventory".to_string(),
        ));
    }
    Ok(true)
}

fn legacy_csharp_owned_files(
    root: &Path,
    manifest_path: &Path,
) -> Result<Option<BTreeSet<String>>, OutputWriterError> {
    let metadata = match fs::symlink_metadata(manifest_path) {
        Ok(metadata) => metadata,
        Err(error) if error.kind() == io::ErrorKind::NotFound => return Ok(None),
        Err(source) => {
            return Err(io_error(
                "inspect legacy C# manifest",
                manifest_path,
                source,
            ));
        }
    };
    if metadata.file_type().is_symlink() {
        return Err(OutputWriterError::Symlink(manifest_path.to_path_buf()));
    }
    if !metadata.is_file() {
        return Err(OutputWriterError::UnexpectedFileType(
            manifest_path.to_path_buf(),
        ));
    }
    let bytes = match fs::read(manifest_path) {
        Ok(bytes) => bytes,
        Err(source) => return Err(io_error("read legacy C# manifest", manifest_path, source)),
    };
    let manifest: LegacyCsharpManifest = serde_json::from_slice(&bytes)
        .map_err(|error| invalid_manifest(manifest_path, error.to_string()))?;
    if manifest.schema_version == 0
        || manifest.cli_version.is_empty()
        || manifest.required_bridge_version.is_empty()
        || manifest.program_identity.is_empty()
        || !is_lower_hex_sha256(&manifest.program_fingerprint)
        || manifest.files.is_empty()
    {
        return Err(invalid_manifest(
            manifest_path,
            "invalid legacy C# generation metadata".to_string(),
        ));
    }

    let mut expected = BTreeSet::new();
    let mut case_insensitive = HashSet::new();
    let mut previous = None::<&str>;
    for entry in &manifest.files {
        let portable = validate_manifest_path(manifest_path, &entry.relative_path)?;
        if previous.is_some_and(|value| value >= portable.as_str())
            || !expected.insert(portable.clone())
            || !case_insensitive.insert(portable.to_lowercase())
            || !portable.ends_with(".g.cs")
            || !is_lower_hex_sha256(&entry.sha256)
        {
            return Err(invalid_manifest(
                manifest_path,
                "legacy C# file inventory must be strictly sorted, case-insensitively unique, use `.g.cs` paths, and be hashed".to_string(),
            ));
        }
        previous = Some(&entry.relative_path);
        let generated_path = root.join(&portable);
        let metadata = fs::symlink_metadata(&generated_path).map_err(|source| {
            io_error("inspect legacy C# generated file", &generated_path, source)
        })?;
        if metadata.file_type().is_symlink() {
            return Err(OutputWriterError::Symlink(generated_path));
        }
        if !metadata.is_file() {
            return Err(OutputWriterError::UnexpectedFileType(generated_path));
        }
        let contents = fs::read(&generated_path)
            .map_err(|source| io_error("read legacy C# generated file", &generated_path, source))?;
        if sha256(&contents) != entry.sha256 {
            return Err(invalid_manifest(
                manifest_path,
                format!("legacy C# file hash differs for `{portable}`"),
            ));
        }
        if !contents.starts_with(LEGACY_CSHARP_GENERATED_HEADER) {
            return Err(invalid_manifest(
                manifest_path,
                format!("legacy C# generated header is missing for `{portable}`"),
            ));
        }
    }

    Ok(Some(expected))
}

fn remove_owned_transaction_tree(path: &Path) -> Result<(), OutputWriterError> {
    let accepted_proof = require_owned_transaction_tree(path)?;
    let proof = path.join(OWNERSHIP_MARKER_FILE);
    if accepted_proof != proof {
        write_internal_file(path, OWNERSHIP_MARKER_FILE, OWNERSHIP_MARKER_CONTENT)?;
    }
    remove_transaction_contents(path, path, &proof)?;
    retry_transient_io(|| fs::remove_file(&proof))
        .map_err(|source| io_error("remove transaction ownership proof", &proof, source))?;
    retry_transient_io(|| fs::remove_dir(path))
        .map_err(|source| io_error("remove owned transaction tree", path, source))
}

fn remove_transaction_contents(
    root: &Path,
    directory: &Path,
    proof: &Path,
) -> Result<(), OutputWriterError> {
    let mut entries = fs::read_dir(directory)
        .map_err(|source| io_error("read owned transaction tree", directory, source))?
        .collect::<Result<Vec<_>, _>>()
        .map_err(|source| io_error("read owned transaction entry", directory, source))?;
    entries.sort_by_key(fs::DirEntry::file_name);
    for entry in entries {
        let path = entry.path();
        if path == proof {
            continue;
        }
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect owned transaction entry", &path, source))?;
        if metadata.is_dir() && !metadata.file_type().is_symlink() {
            remove_transaction_contents(root, &path, proof)?;
            retry_transient_io(|| fs::remove_dir(&path))
                .map_err(|source| io_error("remove transaction directory", &path, source))?;
        } else if metadata.is_file() || metadata.file_type().is_symlink() {
            retry_transient_io(|| fs::remove_file(&path))
                .map_err(|source| io_error("remove transaction file", &path, source))?;
        } else {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
    }
    debug_assert!(directory.starts_with(root));
    Ok(())
}

fn transaction_tree_is_empty(path: &Path) -> Result<bool, OutputWriterError> {
    let metadata = fs::symlink_metadata(path)
        .map_err(|source| io_error("inspect empty transaction tree", path, source))?;
    if metadata.file_type().is_symlink() || !metadata.is_dir() {
        return Ok(false);
    }
    let mut entries = fs::read_dir(path)
        .map_err(|source| io_error("read empty transaction tree", path, source))?;
    Ok(entries.next().is_none())
}

fn remove_empty_transaction_tree(path: &Path) -> Result<(), OutputWriterError> {
    retry_transient_io(|| fs::remove_dir(path))
        .map_err(|source| io_error("remove empty transaction tree", path, source))
}

fn previous_owned_files(target: &Path) -> Result<(BTreeSet<String>, bool), OutputWriterError> {
    if !path_lexists(target) {
        return Ok((BTreeSet::new(), false));
    }
    let metadata = fs::symlink_metadata(target)
        .map_err(|source| io_error("inspect output directory", target, source))?;
    if metadata.file_type().is_symlink() {
        return Err(OutputWriterError::Symlink(target.to_path_buf()));
    }
    if !metadata.is_dir() {
        return Err(OutputWriterError::UnexpectedFileType(target.to_path_buf()));
    }

    let manifest_path = target.join(OUTPUT_MANIFEST_FILE);
    let manifest = read_optional_manifest(&manifest_path)?;
    let pending = pending_manifest_paths(target)?;
    let is_manifestless = manifest.is_none() && pending.is_empty();
    let mut adopted_legacy_output = false;
    let mut owned = BTreeSet::new();
    if let Some(manifest) = manifest {
        owned.extend(manifest_owned_paths(&manifest_path, &manifest)?);
    }
    for path in pending {
        let manifest = read_required_manifest(&path)?;
        owned.extend(manifest_owned_paths(&path, &manifest)?);
    }
    if is_manifestless
        && let Some(legacy_owned) =
            legacy_csharp_owned_files(target, &target.join(LEGACY_CSHARP_MANIFEST))?
    {
        owned.extend(legacy_owned);
        adopted_legacy_output = true;
    }
    Ok((owned, adopted_legacy_output))
}

fn pending_manifest_paths(target: &Path) -> Result<Vec<PathBuf>, OutputWriterError> {
    let mut paths = Vec::new();
    for entry in
        fs::read_dir(target).map_err(|source| io_error("read output directory", target, source))?
    {
        let entry =
            entry.map_err(|source| io_error("read output directory entry", target, source))?;
        let Some(name) = entry.file_name().to_str().map(str::to_owned) else {
            continue;
        };
        if name.starts_with(PENDING_PREFIX) {
            let path = entry.path();
            let metadata = fs::symlink_metadata(&path)
                .map_err(|source| io_error("inspect recovery journal", &path, source))?;
            if metadata.file_type().is_symlink() {
                return Err(OutputWriterError::Symlink(path));
            }
            if !metadata.is_file() {
                return Err(OutputWriterError::UnexpectedFileType(path));
            }
            paths.push(path);
        }
    }
    paths.sort();
    Ok(paths)
}

fn read_optional_manifest(path: &Path) -> Result<Option<OwnershipManifest>, OutputWriterError> {
    match fs::read(path) {
        Ok(bytes) => parse_manifest(path, &bytes).map(Some),
        Err(error) if error.kind() == io::ErrorKind::NotFound => Ok(None),
        Err(source) => Err(io_error("read output manifest", path, source)),
    }
}

fn read_required_manifest(path: &Path) -> Result<OwnershipManifest, OutputWriterError> {
    let bytes =
        fs::read(path).map_err(|source| io_error("read recovery manifest", path, source))?;
    parse_manifest(path, &bytes)
}

fn parse_manifest(path: &Path, bytes: &[u8]) -> Result<OwnershipManifest, OutputWriterError> {
    if fs::symlink_metadata(path).is_ok_and(|metadata| metadata.file_type().is_symlink()) {
        return Err(OutputWriterError::Symlink(path.to_path_buf()));
    }
    let manifest: OwnershipManifest =
        serde_json::from_slice(bytes).map_err(|error| OutputWriterError::InvalidManifest {
            path: path.to_path_buf(),
            message: error.to_string(),
        })?;
    // Schema 1 predates the per-file inventory, so its ownership cannot be
    // recovered; schema 2 still reads, which is what keeps the first
    // regenerate after an upgrade from failing on an existing bridge.
    if !matches!(
        manifest.schema_version,
        FIRST_FILE_INVENTORY_VERSION..=MANIFEST_VERSION
    ) {
        return Err(OutputWriterError::InvalidManifest {
            path: path.to_path_buf(),
            message: format!("unsupported schema version {}", manifest.schema_version),
        });
    }
    Ok(manifest)
}

fn manifest_owned_paths(
    manifest_path: &Path,
    manifest: &OwnershipManifest,
) -> Result<BTreeSet<String>, OutputWriterError> {
    let raw_paths = manifest
        .files
        .iter()
        .map(|entry| entry.relative_path.as_str())
        .collect::<Vec<_>>();
    let mut validated = BTreeSet::new();
    for path in raw_paths {
        let portable = validate_manifest_path(manifest_path, path)?;
        if !validated.insert(portable) {
            return Err(invalid_manifest(
                manifest_path,
                format!("duplicate owned path `{path}`"),
            ));
        }
    }
    {
        if manifest.files.len() != validated.len() {
            return Err(invalid_manifest(
                manifest_path,
                "duplicate file inventory".to_string(),
            ));
        }
        for entry in &manifest.files {
            if !is_lower_hex_sha256(&entry.sha256) {
                return Err(invalid_manifest(
                    manifest_path,
                    format!("invalid SHA-256 for `{}`", entry.relative_path),
                ));
            }
        }
    }
    Ok(validated)
}

fn validate_manifest_path(manifest_path: &Path, path: &str) -> Result<String, OutputWriterError> {
    let portable = validate_relative_path(Path::new(path))
        .map_err(|error| invalid_manifest(manifest_path, error.to_string()))?;
    if portable != path || is_manifest_reserved_path(Path::new(path)) {
        return Err(invalid_manifest(
            manifest_path,
            format!("unsafe owned path `{path}`"),
        ));
    }
    Ok(portable)
}

fn is_manifest_reserved_path(path: &Path) -> bool {
    path.components().any(|component| {
        let Component::Normal(segment) = component else {
            return true;
        };
        let segment = segment.to_string_lossy().to_ascii_lowercase();
        segment == OUTPUT_MANIFEST_FILE
            || segment == OWNERSHIP_MARKER_FILE
            || segment == LEGACY_CSHARP_MANIFEST
            || segment == LEGACY_CSHARP_STAGING_MARKER
            || segment.starts_with(PENDING_PREFIX)
            || segment.starts_with(TEMP_PREFIX)
            || (segment == GITIGNORE_FILE && path != Path::new(GITIGNORE_FILE))
    })
}

fn invalid_manifest(path: &Path, message: String) -> OutputWriterError {
    OutputWriterError::InvalidManifest {
        path: path.to_path_buf(),
        message,
    }
}

fn collect_unknown_files(
    target: &Path,
    previous_owned: &BTreeSet<String>,
    next_owned: &BTreeSet<String>,
) -> Result<Vec<UnknownFile>, OutputWriterError> {
    if !path_lexists(target) {
        return Ok(Vec::new());
    }
    let next_lowercase = next_owned
        .iter()
        .map(|path| (path.to_lowercase(), path))
        .collect::<HashMap<_, _>>();
    let mut unknown = Vec::new();
    collect_unknown_files_in(
        target,
        target,
        previous_owned,
        &next_lowercase,
        &mut unknown,
    )?;
    unknown.sort_by(|left, right| left.relative_path.cmp(&right.relative_path));
    Ok(unknown)
}

fn collect_unknown_files_in(
    root: &Path,
    directory: &Path,
    previous_owned: &BTreeSet<String>,
    next_lowercase: &HashMap<String, &String>,
    unknown: &mut Vec<UnknownFile>,
) -> Result<(), OutputWriterError> {
    for entry in fs::read_dir(directory)
        .map_err(|source| io_error("read existing output directory", directory, source))?
    {
        let entry =
            entry.map_err(|source| io_error("read existing output entry", directory, source))?;
        let path = entry.path();
        let relative = path
            .strip_prefix(root)
            .expect("existing entry is below output root");
        if is_root_writer_infrastructure(relative) {
            continue;
        }
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect existing output entry", &path, source))?;
        if metadata.file_type().is_symlink() {
            let portable = validate_relative_path(relative)?;
            if previous_owned.contains(&portable)
                || next_lowercase.contains_key(&portable.to_lowercase())
            {
                continue;
            }
            return Err(OutputWriterError::Symlink(path));
        }
        if metadata.is_dir() {
            collect_unknown_files_in(root, &path, previous_owned, next_lowercase, unknown)?;
        } else if metadata.is_file() {
            let portable = validate_relative_path(relative)?;
            if previous_owned.contains(&portable)
                || next_lowercase.contains_key(&portable.to_lowercase())
            {
                continue;
            }
            unknown.push(UnknownFile {
                relative_path: portable,
                source: path,
            });
        } else {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
    }
    Ok(())
}

fn validate_preserved_paths(
    unknown: &[UnknownFile],
    next_owned: &BTreeSet<String>,
) -> Result<(), OutputWriterError> {
    let mut paths = next_owned.iter().map(String::as_str).collect::<Vec<_>>();
    let mut case_insensitive = next_owned
        .iter()
        .map(|path| path.to_lowercase())
        .collect::<HashSet<_>>();
    for file in unknown {
        let lowercase = file.relative_path.to_lowercase();
        if !case_insensitive.insert(lowercase) {
            return Err(OutputWriterError::UnownedPathCollision(PathBuf::from(
                &file.relative_path,
            )));
        }
        paths.push(&file.relative_path);
    }
    validate_no_file_directory_collisions(paths)
}

fn create_staging_tree(
    staging: &Path,
    unknown: &[UnknownFile],
    generated: &BTreeMap<String, Vec<u8>>,
) -> Result<(), OutputWriterError> {
    fs::create_dir(staging)
        .map_err(|source| io_error("create output staging directory", staging, source))?;
    if let Err(error) =
        write_internal_file(staging, OWNERSHIP_MARKER_FILE, OWNERSHIP_MARKER_CONTENT)
    {
        let _ = fs::remove_dir_all(staging);
        return Err(error);
    }

    let result = (|| {
        parallel_try_for_each(unknown, |_index, file| copy_unknown_file(staging, file))?;
        let generated = generated.iter().collect::<Vec<_>>();
        parallel_try_for_each(&generated, |index, (relative, contents)| {
            write_one_file(staging, relative, contents, index)
        })
    })();
    if result.is_err() {
        let _ = remove_owned_transaction_tree(staging);
    }
    result
}

fn copy_unknown_file(root: &Path, file: &UnknownFile) -> Result<(), OutputWriterError> {
    let metadata = fs::symlink_metadata(&file.source)
        .map_err(|source| io_error("inspect preserved output file", &file.source, source))?;
    if metadata.file_type().is_symlink() {
        return Err(OutputWriterError::Symlink(file.source.clone()));
    }
    if !metadata.is_file() {
        return Err(OutputWriterError::UnexpectedFileType(file.source.clone()));
    }
    let destination = root.join(&file.relative_path);
    let parent = destination
        .parent()
        .expect("validated preserved path has an output parent");
    ensure_safe_directories(root, parent)?;
    match fs::hard_link(&file.source, &destination) {
        Ok(()) => {}
        Err(_) => {
            fs::copy(&file.source, &destination)
                .map_err(|source| io_error("copy preserved output file", &destination, source))?;
            File::open(&destination)
                .and_then(|file| file.sync_all())
                .map_err(|source| io_error("sync preserved output file", &destination, source))?;
        }
    }
    sync_directory(parent)
}

fn manifest_for_generated(
    generated: &BTreeMap<String, Vec<u8>>,
    provenance: &OutputProvenance,
) -> OwnershipManifest {
    OwnershipManifest {
        schema_version: MANIFEST_VERSION,
        files: generated
            .iter()
            .map(|(relative_path, contents)| OwnedFile {
                relative_path: relative_path.clone(),
                sha256: sha256(contents),
            })
            .collect(),
        input_fingerprint: Some(provenance.input_fingerprint.clone()),
        toolchain_version: Some(provenance.toolchain_version.clone()),
        generator_name: Some(provenance.generator_name.clone()),
    }
}

fn manifest_bytes(manifest: &OwnershipManifest) -> Result<Vec<u8>, OutputWriterError> {
    let mut bytes = serde_json::to_vec_pretty(manifest)
        .map_err(|error| invalid_manifest(Path::new(OUTPUT_MANIFEST_FILE), error.to_string()))?;
    bytes.push(b'\n');
    Ok(bytes)
}

fn validate_staging_tree(
    staging: &Path,
    manifest: &OwnershipManifest,
    unknown: &[UnknownFile],
) -> Result<(), OutputWriterError> {
    require_owned_transaction_tree(staging)?;
    let installed = read_required_manifest(&staging.join(OUTPUT_MANIFEST_FILE))?;
    if &installed != manifest {
        return Err(invalid_manifest(
            &staging.join(OUTPUT_MANIFEST_FILE),
            "staged manifest differs from validated inventory".to_string(),
        ));
    }
    for entry in &manifest.files {
        let path = staging.join(&entry.relative_path);
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect staged generated file", &path, source))?;
        if metadata.file_type().is_symlink() || !metadata.is_file() {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
        let contents = fs::read(&path)
            .map_err(|source| io_error("read staged generated file", &path, source))?;
        if sha256(&contents) != entry.sha256 {
            return Err(invalid_manifest(
                &staging.join(OUTPUT_MANIFEST_FILE),
                format!("staged bytes differ for `{}`", entry.relative_path),
            ));
        }
    }

    let mut expected = manifest
        .files
        .iter()
        .map(|entry| entry.relative_path.clone())
        .chain(unknown.iter().map(|file| file.relative_path.clone()))
        .collect::<BTreeSet<_>>();
    expected.insert(OUTPUT_MANIFEST_FILE.to_string());
    expected.insert(OWNERSHIP_MARKER_FILE.to_string());
    let mut actual = BTreeSet::new();
    collect_tree_files(staging, staging, &mut actual)?;
    if actual != expected {
        return Err(invalid_manifest(
            &staging.join(OUTPUT_MANIFEST_FILE),
            "staged tree contains missing or unexpected files".to_string(),
        ));
    }
    Ok(())
}

fn collect_tree_files(
    root: &Path,
    directory: &Path,
    files: &mut BTreeSet<String>,
) -> Result<(), OutputWriterError> {
    for entry in fs::read_dir(directory)
        .map_err(|source| io_error("read generated tree", directory, source))?
    {
        let entry =
            entry.map_err(|source| io_error("read generated tree entry", directory, source))?;
        let path = entry.path();
        let metadata = fs::symlink_metadata(&path)
            .map_err(|source| io_error("inspect generated tree entry", &path, source))?;
        if metadata.file_type().is_symlink() {
            return Err(OutputWriterError::Symlink(path));
        }
        if metadata.is_dir() {
            collect_tree_files(root, &path, files)?;
        } else if metadata.is_file() {
            let relative = path
                .strip_prefix(root)
                .expect("generated tree entry is below its root");
            files.insert(validate_relative_path(relative)?);
        } else {
            return Err(OutputWriterError::UnexpectedFileType(path));
        }
    }
    Ok(())
}

fn install_staging_tree(
    paths: &TransactionPaths,
    rename: &mut impl FnMut(&Path, &Path) -> io::Result<()>,
) -> Result<(), OutputWriterError> {
    if path_lexists(&paths.target) {
        let marker = paths.target.join(OWNERSHIP_MARKER_FILE);
        if path_lexists(&marker) {
            if !fs::read(&marker).is_ok_and(|bytes| bytes == OWNERSHIP_MARKER_CONTENT) {
                return Err(OutputWriterError::UnownedTransactionPath(marker));
            }
        } else {
            write_internal_file(
                &paths.target,
                OWNERSHIP_MARKER_FILE,
                OWNERSHIP_MARKER_CONTENT,
            )?;
        }
        rename_with_retry(rename, &paths.target, &paths.backup)
            .map_err(|source| io_error("move prior output to backup", &paths.target, source))?;
        sync_directory(&paths.parent)?;
        if let Err(replacement) = rename_with_retry(rename, &paths.staging, &paths.target) {
            return match rename_with_retry(rename, &paths.backup, &paths.target) {
                Ok(()) => {
                    sync_directory(&paths.parent)?;
                    Err(io_error(
                        "replace generated output",
                        &paths.target,
                        replacement,
                    ))
                }
                Err(rollback) => Err(OutputWriterError::ReplacementRollbackFailed {
                    replacement,
                    rollback,
                    backup: paths.backup.clone(),
                }),
            };
        }
        sync_directory(&paths.parent)?;
        let _ = remove_owned_transaction_tree(&paths.backup);
    } else {
        rename_with_retry(rename, &paths.staging, &paths.target)
            .map_err(|source| io_error("install generated output", &paths.target, source))?;
    }
    sync_directory(&paths.parent)
}

fn rename_with_retry(
    rename: &mut impl FnMut(&Path, &Path) -> io::Result<()>,
    from: &Path,
    to: &Path,
) -> io::Result<()> {
    retry_transient_io(|| rename(from, to))
}

fn retry_transient_io(mut operation: impl FnMut() -> io::Result<()>) -> io::Result<()> {
    for delay in FILESYSTEM_RETRY_DELAYS {
        match operation() {
            Ok(()) => return Ok(()),
            Err(error) if is_transient_filesystem_error(&error) => wait_before_retry(delay),
            Err(error) => return Err(error),
        }
    }
    operation()
}

fn is_transient_filesystem_error(error: &io::Error) -> bool {
    let portable = matches!(
        error.kind(),
        io::ErrorKind::Interrupted
            | io::ErrorKind::PermissionDenied
            | io::ErrorKind::WouldBlock
            | io::ErrorKind::DirectoryNotEmpty
    );
    #[cfg(windows)]
    {
        // Windows may preserve these Win32 codes instead of mapping them to
        // the portable kinds above: access denied, sharing violation, lock
        // violation, and directory not empty.
        portable || matches!(error.raw_os_error(), Some(5 | 32 | 33 | 145))
    }
    #[cfg(not(windows))]
    {
        portable
    }
}

fn wait_before_retry(delay: Duration) {
    #[cfg(not(target_arch = "wasm32"))]
    std::thread::sleep(delay);
    #[cfg(target_arch = "wasm32")]
    let _ = delay;
}

fn write_internal_file(
    root: &Path,
    relative: &str,
    contents: &[u8],
) -> Result<(), OutputWriterError> {
    let path = root.join(relative);
    let mut file = OpenOptions::new()
        .create_new(true)
        .write(true)
        .open(&path)
        .map_err(|source| io_error("create output infrastructure file", &path, source))?;
    file.write_all(contents)
        .and_then(|()| file.sync_all())
        .map_err(|source| io_error("write output infrastructure file", &path, source))?;
    sync_directory(root)
}

fn parallel_try_for_each<T: Sync>(
    items: &[T],
    operation: impl Fn(usize, &T) -> Result<(), OutputWriterError> + Sync,
) -> Result<(), OutputWriterError> {
    if items.is_empty() {
        return Ok(());
    }
    let workers = std::thread::available_parallelism()
        .map_or(1, std::num::NonZeroUsize::get)
        .min(items.len());
    let next = AtomicUsize::new(0);
    let failed = AtomicBool::new(false);
    let first_error = Mutex::new(None);
    std::thread::scope(|scope| {
        for _ in 0..workers {
            scope.spawn(|| {
                while !failed.load(Ordering::Acquire) {
                    let index = next.fetch_add(1, Ordering::Relaxed);
                    let Some(item) = items.get(index) else {
                        break;
                    };
                    if let Err(error) = operation(index, item) {
                        failed.store(true, Ordering::Release);
                        let mut slot = first_error.lock().expect("output error mutex poisoned");
                        if slot.is_none() {
                            *slot = Some(error);
                        }
                        break;
                    }
                }
            });
        }
    });
    first_error
        .into_inner()
        .expect("output error mutex poisoned")
        .map_or(Ok(()), Err)
}

fn write_one_file(
    root: &Path,
    relative: &str,
    contents: &[u8],
    index: usize,
) -> Result<(), OutputWriterError> {
    let destination = root.join(relative);
    let parent = destination
        .parent()
        .expect("validated generated path has an output parent");
    ensure_safe_directories(root, parent)?;
    let temp = parent.join(format!("{TEMP_PREFIX}{}-{index}", std::process::id()));
    let mut file = OpenOptions::new()
        .create_new(true)
        .write(true)
        .open(&temp)
        .map_err(|source| io_error("create temporary generated file", &temp, source))?;
    let result = (|| {
        file.write_all(contents)
            .and_then(|()| file.sync_all())
            .map_err(|source| io_error("write temporary generated file", &temp, source))?;
        fs::rename(&temp, &destination)
            .map_err(|source| io_error("install staged generated file", &destination, source))?;
        sync_directory(parent)
    })();
    if result.is_err() {
        let _ = fs::remove_file(&temp);
    }
    result
}

fn ensure_safe_directories(root: &Path, directory: &Path) -> Result<(), OutputWriterError> {
    let relative = directory
        .strip_prefix(root)
        .map_err(|_| OutputWriterError::UnsafeOutputPath(directory.to_path_buf()))?;
    let mut current = root.to_path_buf();
    for component in relative.components() {
        let Component::Normal(segment) = component else {
            return Err(OutputWriterError::UnsafeOutputPath(directory.to_path_buf()));
        };
        current.push(segment);
        match fs::symlink_metadata(&current) {
            Ok(metadata) if metadata.file_type().is_symlink() => {
                return Err(OutputWriterError::Symlink(current));
            }
            Ok(metadata) if !metadata.is_dir() => {
                return Err(OutputWriterError::UnexpectedFileType(current));
            }
            Ok(_) => {}
            Err(error) if error.kind() == io::ErrorKind::NotFound => {
                match fs::create_dir(&current) {
                    Ok(()) => {}
                    Err(error) if error.kind() == io::ErrorKind::AlreadyExists => {}
                    Err(source) => {
                        return Err(io_error("create staged output directory", &current, source));
                    }
                }
                let metadata = fs::symlink_metadata(&current).map_err(|source| {
                    io_error("inspect staged output directory", &current, source)
                })?;
                if metadata.file_type().is_symlink() {
                    return Err(OutputWriterError::Symlink(current));
                }
                if !metadata.is_dir() {
                    return Err(OutputWriterError::UnexpectedFileType(current));
                }
            }
            Err(source) => {
                return Err(io_error(
                    "inspect staged output directory",
                    &current,
                    source,
                ));
            }
        }
    }
    Ok(())
}

fn path_lexists(path: &Path) -> bool {
    fs::symlink_metadata(path).is_ok()
}

fn is_lower_hex_sha256(value: &str) -> bool {
    value.len() == 64
        && value
            .bytes()
            .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
}

fn sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .fold(String::with_capacity(64), |mut encoded, byte| {
            write!(&mut encoded, "{byte:02x}").expect("writing to String cannot fail");
            encoded
        })
}

#[cfg(unix)]
fn sync_directory(path: &Path) -> Result<(), OutputWriterError> {
    File::open(path)
        .and_then(|directory| directory.sync_all())
        .map_err(|source| io_error("sync generated output directory", path, source))
}

#[cfg(not(unix))]
#[allow(clippy::unnecessary_wraps)]
fn sync_directory(_path: &Path) -> Result<(), OutputWriterError> {
    Ok(())
}

fn io_error(operation: &'static str, path: &Path, source: io::Error) -> OutputWriterError {
    OutputWriterError::Io {
        operation,
        path: path.to_path_buf(),
        source,
    }
}

