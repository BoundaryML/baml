/// Render every enum, class and candidate as one Rust module. `names` gives
/// each function's Rust identifier, callees included.
pub(crate) fn render_module<'db>(
    classes: &[&ClassInfo<'db>],
    enums: &[&EnumInfo<'db>],
    unions: &[&UnionInfo<'db>],
    interfaces: &[&IfaceInfo<'db>],
    candidates: &[Candidate<'db>],
    names: &FxHashMap<FnId<'db>, Ident>,
    table: &ClassTable<'db>,
) -> Result<String, Rejection> {
    let mut items = quote! {
        use std::rc::Rc;
        use bex_aot::{
            BigInt, Int63, Map, Panic, Str, Thrown, array, bigint, cell, float, int, json, map,
            string,
        };
        use bex_aot::handle::{Shared, shared};
        use bex_aot::render::ToBaml;
    };
    for info in enums {
        items.extend(render_enum(info));
    }
    for class in classes {
        items.extend(render_class(class, table));
    }
    for union in unions {
        items.extend(render_union(union, table));
    }
    for interface in interfaces {
        items.extend(render_iface(interface, table));
    }
    for candidate in candidates {
        items.extend(Printer::new(candidate, names, table).function()?);
    }
    render_rust_file(HEADER, items)
}

/// Parse the tokens back as a file and pretty-print them. A parse failure is
/// a bug in this emitter, reported rather than panicked on.
pub(crate) fn render_rust_file(header: &str, tokens: TokenStream) -> Result<String, Rejection> {
    let file: syn::File = syn::parse2(tokens).map_err(|error| {
        Rejection::invalid(format!(
            "generated tokens do not parse as a Rust file: {error}"
        ))
    })?;
    Ok(format!("{header}{}", prettyplease::unparse(&file)))
}

/// The struct for one class: fields in declaration order with serde derives
/// (through `bex_aot`'s re-export), and the `ToBaml` rendering
/// `Name { f: v, .. }`.
fn render_class<'db>(class: &ClassInfo<'db>, table: &ClassTable<'db>) -> TokenStream {
    let class_ident = |decl| table.ident(decl);
    let doc = format!(" BAML class `{}`.", class.link_name);
    let name = &class.ident;
    let fields = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let ty = field.ty.to_tokens(&class_ident);
        let rename = field.renamed().then(|| {
            let baml_name = &field.name;
            quote! { #[serde(rename = #baml_name)] }
        });
        quote! {
            #rename
            pub #ident: #ty,
        }
    });
    let display_name = &class.display_name;
    let link_name = &class.class_fqn;
    let expecting = format!("expected JSON object for class `{}`", class.json_name);
    let rendered = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let baml_name = &field.name;
        quote! { (#baml_name, &self.#ident as &dyn ToBaml) }
    });
    let readable = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let baml_name = &field.name;
        quote! { (#baml_name, bex_aot::Readable::readable(&self.#ident)) }
    });
    // Every class can be thrown (`throw C { .. }`) and caught by name, and
    // prints inside an uncaught throw as the engine does, so each one is an
    // `ErrorClass`; the trait costs nothing when the class is never thrown.
    quote! {
        #[doc = #doc]
        #[derive(Debug, bex_aot::serde::Serialize, bex_aot::serde::Deserialize)]
        #[serde(crate = "bex_aot::serde", expecting = #expecting)]
        pub struct #name {
            #(#fields)*
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, _nested: bool) {
                bex_aot::render::class(out, #display_name, &[#(#rendered),*]);
            }
        }

        impl bex_aot::ErrorClass for #name {
            const CLASS_FQN: &'static str = #link_name;

            fn readable_fields(&self) -> Vec<(&'static str, String)> {
                Vec::from([#(#readable),*])
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                bex_aot::readable::class(
                    <Self as bex_aot::ErrorClass>::CLASS_FQN,
                    &bex_aot::ErrorClass::readable_fields(self),
                )
            }
        }
    }
}

/// The Rust enum for a BAML enum: fieldless, one variant per BAML variant
/// in declaration order (so `as i64` is the VM's discriminant), `Copy`,
/// compared by variant, serialized as the variant's name (through
/// `bex_aot`'s serde re-export, renamed where the Rust identifier had to
/// change) and rendered by `to_string` as the bare name, nested or not.
fn render_enum(info: &EnumInfo<'_>) -> TokenStream {
    let doc = format!(" BAML enum `{}`.", info.link_name);
    let name = &info.ident;
    let variants = info.variants.iter().map(|variant| {
        let ident = &variant.ident;
        let rename = variant.renamed().then(|| {
            let baml_name = &variant.name;
            quote! { #[serde(rename = #baml_name)] }
        });
        quote! {
            #rename
            #ident,
        }
    });
    let names = info.variants.iter().map(|variant| &variant.name);
    let count = info.variants.len();
    quote! {
        #[doc = #doc]
        #[derive(
            Clone, Copy, PartialEq, Eq, Hash, Debug,
            bex_aot::serde::Serialize, bex_aot::serde::Deserialize
        )]
        #[serde(crate = "bex_aot::serde", expecting = "expected enum variant string")]
        pub enum #name {
            #(#variants)*
        }

        impl #name {
            /// The BAML variant names, by discriminant.
            pub const NAMES: [&'static str; #count] = [#(#names),*];
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, _nested: bool) {
                out.push_str(Self::NAMES[*self as usize]);
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                Self::NAMES[*self as usize].to_string()
            }
        }

        impl bex_aot::BamlEq for #name {
            fn baml_eq(&self, other: &Self) -> bool {
                self == other
            }
        }
    }
}

/// The Rust enum for a closed union: one variant per member in the type
/// system's order, holding the member's native value. `Copy` when every
/// member is. `to_string`, the readable rendering and JSON delegate to the
/// member held, as the VM renders the member value itself; JSON decoding
/// takes the first member the text decodes as, as the VM's typed decode
/// does (`bex_aot::json::deserialize_union`); `==` compares the members
/// when both sides hold the same variant and is false otherwise, which is
/// the VM's broad `==` across kinds, and exists only when every member
/// compares natively (classes compare structurally on the VM).
fn render_union<'db>(info: &UnionInfo<'db>, table: &ClassTable<'db>) -> TokenStream {
    let class_ident = |decl| table.ident(decl);
    let doc = format!(" BAML union `{}`.", info.described);
    let name = &info.ident;
    let variants = info
        .variants
        .iter()
        .zip(&info.members)
        .map(|(variant, member)| {
            let ty = member.to_tokens(&class_ident);
            quote! { #variant(#ty), }
        });
    let copy = info
        .members
        .iter()
        .all(NativeTy::is_copy)
        .then(|| quote! { Copy, });
    let variant_names = &info.variants;
    let decoders = info
        .variants
        .iter()
        .zip(&info.members)
        .map(|(variant, member)| {
            let ty = member.to_tokens(&class_ident);
            quote! {
                |value| <#ty as bex_aot::serde::Deserialize>::deserialize(value).map(Self::#variant)
            }
        });
    let comparable = info.members.iter().all(|member| {
        matches!(
            member,
            NativeTy::Int
                | NativeTy::Bool
                | NativeTy::Float
                | NativeTy::Bigint
                | NativeTy::Str
                | NativeTy::Null
                | NativeTy::Enum(_)
        )
    });
    let equals = comparable.then(|| {
        quote! {
            impl bex_aot::BamlEq for #name {
                fn baml_eq(&self, other: &Self) -> bool {
                    match (self, other) {
                        #((Self::#variant_names(a), Self::#variant_names(b)) => bex_aot::BamlEq::baml_eq(a, b),)*
                        _ => false,
                    }
                }
            }
        }
    });
    quote! {
        #[doc = #doc]
        #[derive(Clone, #copy Debug)]
        pub enum #name {
            #(#variants)*
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, nested: bool) {
                match self {
                    #(Self::#variant_names(value) => value.render(out, nested),)*
                }
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                match self {
                    #(Self::#variant_names(value) => bex_aot::Readable::readable(value),)*
                }
            }
        }

        impl bex_aot::serde::Serialize for #name {
            fn serialize<S: bex_aot::serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                match self {
                    #(Self::#variant_names(value) => bex_aot::serde::Serialize::serialize(value, serializer),)*
                }
            }
        }

        impl<'de> bex_aot::serde::Deserialize<'de> for #name {
            fn deserialize<D: bex_aot::serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                bex_aot::json::deserialize_union(deserializer, &[#(#decoders),*])
            }
        }

        #equals
    }
}

/// The Rust enum for an interface: one variant per implementor, holding
/// the implementor's value, shaped and rendered like a union's (`to_string`
/// and JSON render the implementor the value holds, as the VM renders the
/// concrete object). JSON decoding into an interface has no VM form and is
/// rejected at the call; the impl exists so a struct with such a field
/// derives, and errors if it is ever reached.
fn render_iface<'db>(info: &IfaceInfo<'db>, table: &ClassTable<'db>) -> TokenStream {
    let class_ident = |decl| table.ident(decl);
    let doc = format!(" BAML interface `{}`.", info.link_name);
    let name = &info.union.ident;
    let variants = info
        .union
        .variants
        .iter()
        .zip(&info.union.members)
        .map(|(variant, member)| {
            let ty = member.to_tokens(&class_ident);
            quote! { #variant(#ty), }
        });
    let copy = info
        .union
        .members
        .iter()
        .all(NativeTy::is_copy)
        .then(|| quote! { Copy, });
    let variant_names = &info.union.variants;
    let expecting = format!(
        "a value of the interface `{}` cannot be decoded from JSON",
        info.link_name
    );
    quote! {
        #[doc = #doc]
        #[derive(Clone, #copy Debug)]
        pub enum #name {
            #(#variants)*
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, nested: bool) {
                match self {
                    #(Self::#variant_names(value) => value.render(out, nested),)*
                }
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                match self {
                    #(Self::#variant_names(value) => bex_aot::Readable::readable(value),)*
                }
            }
        }

        impl bex_aot::serde::Serialize for #name {
            fn serialize<S: bex_aot::serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
                match self {
                    #(Self::#variant_names(value) => bex_aot::serde::Serialize::serialize(value, serializer),)*
                }
            }
        }

        impl<'de> bex_aot::serde::Deserialize<'de> for #name {
            fn deserialize<D: bex_aot::serde::Deserializer<'de>>(_deserializer: D) -> Result<Self, D::Error> {
                Err(<D::Error as bex_aot::serde::de::Error>::custom(#expecting))
            }
        }
    }
}

/// Where a throw or panic in the block being printed goes: the handler's
/// error local takes the value, then the jump leaves for the handler.
struct UnwindSite {
    error: Ident,
    jump: TokenStream,
}

struct Printer<'a, 'db> {
    candidate: &'a Candidate<'db>,
    names: &'a FxHashMap<FnId<'db>, Ident>,
    classes: &'a ClassTable<'db>,
    /// Blocks that head a loop, whose merge label (if any) needs its own name.
    loop_headers: FxHashSet<usize>,
    /// The unwind site of the block whose code is being printed, if it has a
    /// handler; `None` between blocks and in a block that unwinds out of the
    /// function.
    unwind: RefCell<Option<UnwindSite>>,
}

impl<'a, 'db> Printer<'a, 'db> {
    fn new(
        candidate: &'a Candidate<'db>,
        names: &'a FxHashMap<FnId<'db>, Ident>,
        classes: &'a ClassTable<'db>,
    ) -> Self {
        let mut loop_headers = FxHashSet::default();
        collect_loop_headers(&candidate.structured, &mut loop_headers);
        Self {
            candidate,
            names,
            classes,
            loop_headers,
            unwind: RefCell::new(None),
        }
    }

    fn ty(&self, ty: &NativeTy<'db>) -> TokenStream {
        ty.to_tokens(&|decl| self.classes.ident(decl))
    }

    /// The unwind site of `block`: the error local of its handler and the
    /// jump the structurer gave it.
    fn unwind_site(&self, block: BlockId) -> Result<Option<UnwindSite>, Rejection> {
        let body = self.candidate.body;
        let Some(handler) = body.block(block).unwind else {
            return Ok(None);
        };
        let landing = body
            .blocks
            .get(handler.0)
            .and_then(|handler| handler.landing)
            .ok_or_else(|| {
                Rejection::invalid(format!("{block} unwinds to {handler}, which lands nothing"))
            })?;
        let jump = self
            .candidate
            .unwind_jumps
            .get(block.0)
            .ok_or_else(|| Rejection::invalid(format!("{block} has no unwind jump")))?;
        if jump.is_empty() {
            return Err(Rejection::invalid(format!(
                "{block} unwinds to {handler} but the structurer gave it no jump"
            )));
        }
        let jump = self.stmts(jump)?;
        Ok(Some(UnwindSite {
            error: local_ident(landing.error_local),
            jump: quote! { #(#jump)* },
        }))
    }

    /// Print `f` with the unwind site of `block` in force.
    fn in_block<T>(
        &self,
        block: BlockId,
        f: impl FnOnce() -> Result<T, Rejection>,
    ) -> Result<T, Rejection> {
        let site = self.unwind_site(block)?;
        let previous = self.unwind.replace(site);
        let result = f();
        *self.unwind.borrow_mut() = previous;
        result
    }

    /// `expr`, a `Result`, unwrapped: `expr?` when the block has no handler,
    /// else a `match` that hands the error to the handler and leaves for it.
    fn fallible(&self, expr: &TokenStream) -> TokenStream {
        match &*self.unwind.borrow() {
            None => quote! { #expr? },
            Some(UnwindSite { error, jump }) => quote! {
                match #expr {
                    Ok(value) => value,
                    Err(error) => {
                        #error = Thrown::from(error);
                        #jump
                    }
                }
            },
        }
    }

    /// Raise `thrown` (an expression of type `Thrown`) from the block being
    /// printed: into its handler, or out of the function (`Err(..)` in tail
    /// position, else `return Err(..);`).
    fn raise(&self, thrown: &TokenStream, tail: bool) -> TokenStream {
        match (&*self.unwind.borrow(), tail) {
            (Some(UnwindSite { error, jump }), _) => quote! {{
                #error = #thrown;
                #jump
            }},
            (None, true) => quote! { Err(#thrown) },
            (None, false) => quote! { return Err(#thrown); },
        }
    }

    fn function(&self) -> Result<TokenStream, Rejection> {
        let candidate = self.candidate;
        let name = self
            .names
            .get(&candidate.id)
            .ok_or_else(|| Rejection::invalid("function has no Rust name"))?;
        let doc = match &candidate.id {
            FnId::Declared(_) => format!(" BAML function `{}`.", candidate.link_name),
            FnId::Lambda { .. } => format!(" BAML lambda `{}`.", candidate.link_name),
        };
        // A lambda's captures come first, each a borrowed cell: the closure
        // value that calls it holds the cells and lends them per call.
        let captures = candidate.captures.iter().enumerate().map(|(index, ty)| {
            let ident = capture_ident(index);
            let ty = self.ty(ty);
            quote! { #ident: &cell::Cell<#ty> }
        });
        let params = candidate
            .param_tys()
            .into_iter()
            .enumerate()
            .map(|(index, ty)| {
                let ident = local_ident(Local(index + 1));
                let ty = self.ty(ty);
                quote! { mut #ident: #ty }
            });
        // A captured parameter is celled on entry with the value the caller
        // passed, as the VM's frame preamble does: the parameter is shadowed
        // by its cell.
        let celled_params = (1..=candidate.arity())
            .filter(|index| candidate.body.local(Local(*index)).is_captured)
            .map(|index| {
                let ident = local_ident(Local(index));
                let ty = self.ty(&candidate.param_tys()[index - 1].clone());
                quote! { let mut #ident: cell::Cell<#ty> = cell::with(#ident); }
            });
        let ret = self.ty(candidate.return_ty());
        // Declared without initializers: rustc proves every read follows a
        // write, over the same paths the MIR has. Aliased temporaries are
        // read through their source and need no declaration. A captured
        // local holds its cell.
        let locals = candidate
            .kinds
            .iter()
            .enumerate()
            .filter(|(index, _)| !(1..=candidate.arity()).contains(index))
            .filter(|(index, _)| !candidate.aliases.contains_key(&Local(*index)))
            .filter_map(|(index, kind)| {
                let ident = local_ident(Local(index));
                let tokens = match kind {
                    LocalKind::Value(ty) if candidate.body.local(Local(index)).is_captured => {
                        let ty = self.ty(ty);
                        quote! { cell::Cell<#ty> }
                    }
                    LocalKind::Value(ty) => self.ty(ty),
                    LocalKind::Tag(TagSource::Thrown) => quote! { &'static str },
                    LocalKind::Tag(TagSource::Union(_))
                    | LocalKind::Type
                    | LocalKind::Never
                    | LocalKind::Context => return None,
                };
                Some(quote! { let mut #ident: #tokens; })
            });
        // A function on a call cycle counts its frame, so runaway recursion
        // throws `StackOverflow` where the VM would, instead of overflowing
        // the native stack.
        let guard = candidate
            .recursive
            .then(|| quote! { let _frame = bex_aot::depth::Guard::enter()?; });
        let body = self.tail_stmts(&candidate.structured)?;
        Ok(quote! {
            #[doc = #doc]
            pub fn #name(#(#captures,)* #(#params),*) -> Result<#ret, Thrown> {
                #guard
                #(#celled_params)*
                #(#locals)*
                #(#body)*
            }
        })
    }

    fn stmts(&self, stmts: &[Stmt]) -> Result<Vec<TokenStream>, Rejection> {
        stmts.iter().map(|stmt| self.stmt(stmt, false)).collect()
    }

    /// [`Self::stmts`] with the last statement in tail position: an exit there
    /// is the enclosing function's value rather than a `return`, through the
    /// arms of an `if` or `match`. A labeled block or loop is never a tail,
    /// since a `break` out of it has to land on code that follows.
    fn tail_stmts(&self, stmts: &[Stmt]) -> Result<Vec<TokenStream>, Rejection> {
        let Some((last, init)) = stmts.split_last() else {
            return Ok(Vec::new());
        };
        let mut out = self.stmts(init)?;
        out.push(self.stmt(last, true)?);
        Ok(out)
    }

    fn body(&self, stmts: &[Stmt], tail: bool) -> Result<Vec<TokenStream>, Rejection> {
        if tail {
            self.tail_stmts(stmts)
        } else {
            self.stmts(stmts)
        }
    }

    fn stmt(&self, stmt: &Stmt, tail: bool) -> Result<TokenStream, Rejection> {
        Ok(match stmt {
            Stmt::Leaf(block) => {
                let lines = self.leaf(BlockId(*block))?;
                quote! { #(#lines)* }
            }
            Stmt::Block { label, body } => {
                let label = self.block_label(*label);
                let body = self.stmts(body)?;
                quote! { #label: { #(#body)* } }
            }
            Stmt::Loop { label, body } => {
                let label = loop_label(*label);
                let body = self.stmts(body)?;
                quote! { #label: loop { #(#body)* } }
            }
            Stmt::If {
                block,
                then_branch,
                else_branch,
            } => {
                let then_branch = self.body(then_branch, tail)?;
                let else_branch = self.body(else_branch, tail)?;
                match self.terminator(BlockId(*block))? {
                    Terminator::Branch { condition, .. } => {
                        let condition = self.operand(condition, Some(&NativeTy::Bool))?;
                        quote! {
                            if #condition { #(#then_branch)* } else { #(#else_branch)* }
                        }
                    }
                    // A `catch` arm binding: the caught error narrowed to the
                    // arm's class, as the handle it was thrown as.
                    Terminator::NarrowBind {
                        destination,
                        source,
                        ..
                    } => {
                        if let Some(error) = self.candidate.narrow_sources.get(destination) {
                            let error = local_ident(*error);
                            let target = self.ty(&self.local_ty(*destination)?);
                            let destination = local_ident(*destination);
                            quote! {
                                if let Some(value) = bex_aot::thrown::downcast::<#target>(&#error) {
                                    #destination = value;
                                    #(#then_branch)*
                                } else {
                                    #(#else_branch)*
                                }
                            }
                        } else {
                            // A binding pattern on a union: the test decides
                            // the variant; the binding is the value itself,
                            // read narrowed afterwards.
                            let test = self.member_test(TestSite::Terminator(BlockId(*block)))?;
                            let source_ty = self.operand_ty(source)?;
                            let condition = self.member_test_tokens(source, &source_ty, test)?;
                            let bind = match source {
                                Operand::Copy(Place::Local(local))
                                | Operand::Move(Place::Local(local))
                                    if local == destination =>
                                {
                                    TokenStream::new()
                                }
                                _ => {
                                    let destination_ty = self.local_ty(*destination)?;
                                    let value = self.operand(source, Some(&destination_ty))?;
                                    let destination = local_ident(*destination);
                                    quote! { #destination = #value; }
                                }
                            };
                            quote! {
                                if #condition {
                                    #bind
                                    #(#then_branch)*
                                } else {
                                    #(#else_branch)*
                                }
                            }
                        }
                    }
                    // `then_branch` is the right-hand side, `else_branch` the
                    // join. On the short edge the result is the operand's
                    // value, which the test just decided.
                    Terminator::ShortCircuit {
                        operand,
                        kind,
                        destination,
                        ..
                    } => {
                        let operand_ty = self.operand_ty(operand)?;
                        let destination_ty = self.place_ty(destination)?;
                        let operand = match kind {
                            ShortCircuitKind::Coalesce => self.operand(operand, None)?,
                            _ => self.operand(operand, Some(&NativeTy::Bool))?,
                        };
                        let destination = self.local_place(destination)?;
                        match kind {
                            ShortCircuitKind::And => quote! {
                                if #operand {
                                    #(#then_branch)*
                                } else {
                                    #destination = false;
                                    #(#else_branch)*
                                }
                            },
                            ShortCircuitKind::Or => quote! {
                                if #operand {
                                    #destination = true;
                                    #(#else_branch)*
                                } else {
                                    #(#then_branch)*
                                }
                            },
                            // `a ?? b`: a non-null `a` is the result; `b`
                            // is evaluated into the result otherwise.
                            ShortCircuitKind::Coalesce => {
                                let NativeTy::Option(inner) = operand_ty else {
                                    return Err(Rejection::invalid("`??` on a non-nullable"));
                                };
                                let result_ty = destination_ty;
                                let store = coercion(&inner, &result_ty).ok_or_else(|| {
                                    Rejection::invalid("`??` result does not fit its destination")
                                })?;
                                let value =
                                    self.coerce(quote! { value }, &inner, &result_ty, store)?;
                                quote! {
                                    if let Some(value) = #operand {
                                        #destination = #value;
                                        #(#else_branch)*
                                    } else {
                                        #(#then_branch)*
                                    }
                                }
                            }
                        }
                    }
                    _ => return Err(Rejection::invalid("two-way branch without a branch")),
                }
            }
            Stmt::Switch {
                block,
                arms,
                otherwise,
            } => {
                let Terminator::Switch {
                    discriminant,
                    arms: keys,
                    ..
                } = self.terminator(BlockId(*block))?
                else {
                    return Err(Rejection::invalid("multi-way branch without a switch"));
                };
                // A multi-arm `catch` switches on the caught error's class
                // tag, its fully qualified name matched as a string; a
                // multi-arm `match` on types switches on a union's tag,
                // which is a `match` on the union value's variants.
                let tag = match discriminant {
                    Operand::Copy(Place::Local(local)) | Operand::Move(Place::Local(local)) => {
                        match self.kind(*local)? {
                            LocalKind::Tag(source) => Some((*local, *source)),
                            _ => None,
                        }
                    }
                    _ => None,
                };
                let union = match tag {
                    Some((_, TagSource::Union(source))) => {
                        let ty = self.local_ty(source)?;
                        if ty.union_members().is_none() {
                            return Err(Rejection::invalid("type tag of a non-union"));
                        }
                        let info = self.classes.variants_of(&ty)?;
                        Some((source, info, matches!(ty, NativeTy::Option(_))))
                    }
                    _ => None,
                };
                let discriminant = match (tag, &union) {
                    (Some((local, TagSource::Thrown)), _) => {
                        let tag = local_ident(local);
                        quote! { #tag }
                    }
                    (_, Some((source, _, _))) => {
                        let value = self.place(&Place::Local(*source))?;
                        quote! { &#value }
                    }
                    _ => {
                        let value = self.operand(discriminant, Some(&NativeTy::Int))?;
                        quote! { #value.get() }
                    }
                };
                let mut seen: FxHashSet<String> = FxHashSet::default();
                let mut match_arms = Vec::with_capacity(arms.len());
                for (indices, body) in arms {
                    let mut patterns = Vec::new();
                    for index in indices {
                        let Some((key, _)) = keys.get(*index) else {
                            return Err(Rejection::invalid("switch arm index is out of range"));
                        };
                        // A repeated key can never fire: the VM takes the arm
                        // where it first appears, which may be one folded into
                        // `_`, so the key is emitted at its first index only.
                        let first = keys.iter().position(|(k, _)| k == key);
                        if first != Some(*index) {
                            continue;
                        }
                        match (key, tag.map(|(_, source)| source)) {
                            (SwitchKey::Int(key), None) => {
                                if seen.insert(key.to_string()) {
                                    patterns.push(
                                        proc_macro2::Literal::i64_suffixed(*key)
                                            .into_token_stream(),
                                    );
                                }
                            }
                            (SwitchKey::Class(class), Some(TagSource::Thrown)) => {
                                let fqn = self.classes.class_fqn(*class);
                                if seen.insert(fqn.clone()) {
                                    patterns.push(quote! { #fqn });
                                }
                            }
                            (SwitchKey::Class(_), None) => {
                                return Err(Rejection::unsupported("switch on a class tag"));
                            }
                            (SwitchKey::Int(_), Some(TagSource::Thrown)) => {
                                return Err(Rejection::unsupported(
                                    "`catch` arm on a primitive type",
                                ));
                            }
                            (_, Some(TagSource::Union(_))) => {
                                let (_, info, nullable) =
                                    union.as_ref().expect("a union tag names its union");
                                let test =
                                    self.member_test(TestSite::SwitchArm(BlockId(*block), *index))?;
                                for pattern in variant_patterns(info, *nullable, test)? {
                                    if seen.insert(pattern.to_string()) {
                                        patterns.push(pattern);
                                    }
                                }
                            }
                        }
                    }
                    if patterns.is_empty() {
                        continue;
                    }
                    let body = self.body(body, tail)?;
                    match_arms.push(quote! { #(#patterns)|* => { #(#body)* } });
                }
                let otherwise = self.body(otherwise, tail)?;
                quote! {
                    match #discriminant {
                        #(#match_arms)*
                        _ => { #(#otherwise)* }
                    }
                }
            }
            Stmt::Break(label) => {
                let label = self.block_label(*label);
                quote! { break #label; }
            }
            Stmt::BreakLoop(label) => {
                let label = loop_label(*label);
                quote! { break #label; }
            }
            Stmt::Continue(label) => {
                let label = loop_label(*label);
                quote! { continue #label; }
            }
            Stmt::Exit(block) => {
                let block = BlockId(*block);
                match (self.terminator(block)?, tail) {
                    (Terminator::Return, true) => quote! { Ok(_0) },
                    (Terminator::Return, false) => quote! { return Ok(_0); },
                    (Terminator::Unreachable, _) => self.in_block(block, || {
                        Ok(self.raise(&quote! { Thrown::from(Panic::Unreachable) }, tail))
                    })?,
                    // `throw v`: a class instance becomes a thrown object; a
                    // caught error thrown on goes as it is. `rethrow` carries
                    // the caught error; its context has no native form.
                    (Terminator::Throw { value }, _) => self.in_block(block, || {
                        let ty = self.operand_ty(value)?;
                        let value = self.operand(value, None)?;
                        let thrown = match ty {
                            NativeTy::Thrown => value,
                            _ => quote! { Thrown::error(#value) },
                        };
                        Ok(self.raise(&thrown, tail))
                    })?,
                    (Terminator::Rethrow { value, .. }, _) => self.in_block(block, || {
                        let value = self.operand(value, None)?;
                        Ok(self.raise(&value, tail))
                    })?,
                    _ => return Err(Rejection::invalid("exit without a return")),
                }
            }
        })
    }

    /// A block's statements, then what its terminator computes, with the
    /// block's unwind site in force.
    fn leaf(&self, block: BlockId) -> Result<Vec<TokenStream>, Rejection> {
        let body = self.candidate.body;
        if block.0 >= body.blocks.len() {
            return Err(Rejection::invalid(format!("{block} does not exist")));
        }
        self.in_block(block, || self.leaf_lines(block))
    }

    fn leaf_lines(&self, block: BlockId) -> Result<Vec<TokenStream>, Rejection> {
        let body = self.candidate.body;
        let mut lines = Vec::new();
        let stores = self
            .candidate
            .stores
            .get(block.0)
            .ok_or_else(|| Rejection::invalid(format!("{block} was not analyzed")))?;
        let values = self
            .candidate
            .values
            .get(block.0)
            .ok_or_else(|| Rejection::invalid(format!("{block} was not analyzed")))?;
        for (index, ((statement, store), value)) in body
            .block(block)
            .statements
            .iter()
            .zip(stores)
            .zip(values)
            .enumerate()
        {
            if let Some(line) =
                self.statement(block, index, &statement.kind, *store, value.as_ref())?
            {
                lines.push(line);
            }
        }
        match self.terminator(block)? {
            Terminator::Call {
                args,
                ntypeargs,
                destination,
                ..
            } => {
                let call = self
                    .candidate
                    .call(block)
                    .ok_or_else(|| Rejection::invalid(format!("{block} call was not analyzed")))?;
                lines.push(self.call(block, call, &args[*ntypeargs..], destination)?);
            }
            Terminator::VirtualCall {
                args,
                ntypeargs,
                destination,
                ..
            } => {
                let call = self
                    .candidate
                    .call(block)
                    .ok_or_else(|| Rejection::invalid(format!("{block} call was not analyzed")))?;
                lines.push(self.call(block, call, &args[*ntypeargs..], destination)?);
            }
            // The guard in front of a wildcard `catch` arm: a panic is not
            // for the wildcard and goes on to the next handler.
            Terminator::ThrowIfPanic { value, .. } => {
                let thrown = self.operand_borrowed(value)?;
                let raise = self.raise(&quote! { #thrown.clone() }, false);
                lines.push(quote! {
                    if bex_aot::thrown::is_panic(&#thrown) { #raise }
                });
            }
            _ => {}
        }
        Ok(lines)
    }

    fn call(
        &self,
        block: BlockId,
        call: &CallKind<'db>,
        args: &[Operand<'db>],
        destination: &Place,
    ) -> Result<TokenStream, Rejection> {
        let arg = |index: usize| -> Result<&Operand<'db>, Rejection> {
            args.get(index)
                .ok_or_else(|| Rejection::invalid("call has fewer arguments than analyzed"))
        };
        // Statements run before the store, then the stored value.
        let (prelude, value, result) = match call {
            CallKind::Panic(message) => {
                return Ok(self.raise(
                    &quote! { Thrown::from(Panic::UserPanic { message: String::from(#message) }) },
                    false,
                ));
            }
            CallKind::Indirect { params, result } => {
                let Terminator::Call { callee, .. } = self.terminator(block)? else {
                    return Err(Rejection::invalid("indirect call without a call"));
                };
                let callee = self.operand_borrowed(callee)?;
                let args = args
                    .iter()
                    .zip(params)
                    .map(|(arg, param)| self.operand(arg, Some(param)))
                    .collect::<Result<Vec<_>, _>>()?;
                (
                    TokenStream::new(),
                    self.fallible(&quote! { (#callee)(#(#args),*) }),
                    result,
                )
            }
            CallKind::Direct(target) => {
                let value = self.direct_call(target, args, None)?;
                (TokenStream::new(), value, &target.result)
            }
            // The receiver, read as the interface, matched over its
            // implementors: each arm the static call for that implementor
            // with the variant's value as the receiver, its result lifted
            // into the method's declared result.
            CallKind::Virtual {
                receiver,
                receiver_ty,
                arms,
                result,
            } => {
                let receiver_operand = arg(*receiver)?;
                // The receiver's place, or, when the checker narrowed it
                // (`x?.m()` after a null test), the value read as the
                // interface.
                let (prelude, receiver_expr) = if self.operand_ty(receiver_operand)? == *receiver_ty
                {
                    (TokenStream::new(), self.operand_borrowed(receiver_operand)?)
                } else {
                    let value = self.operand(receiver_operand, Some(receiver_ty))?;
                    (quote! { let __receiver = #value; }, quote! { __receiver })
                };
                let info = self.classes.variants_of(receiver_ty)?;
                let enum_name = info.ident.clone();
                if arms.len() != info.variants.len() {
                    return Err(Rejection::invalid(
                        "virtual call arms do not match the implementors",
                    ));
                }
                let mut match_arms = Vec::with_capacity(arms.len());
                for ((variant, member), target) in info.variants.iter().zip(&info.members).zip(arms)
                {
                    let call = self.direct_call(
                        target,
                        args,
                        Some((*receiver, member, receiver_ty, &receiver_expr)),
                    )?;
                    let store = coercion(&target.result, result).ok_or_else(|| {
                        Rejection::invalid("virtual call arm result does not fit the method's")
                    })?;
                    let lifted = self.coerce(call, &target.result, result, store)?;
                    match_arms.push(quote! { #enum_name::#variant(__value) => { #lifted } });
                }
                (
                    TokenStream::new(),
                    quote! {{
                        #prelude
                        match &#receiver_expr {
                            #(#match_arms)*
                        }
                    }},
                    result,
                )
            }
            CallKind::Builtin { builtin, result } => {
                let (prelude, value) = match builtin {
                    Builtin::ArrayPush => {
                        let array = self.operand_ref(arg(0)?)?;
                        let element_ty = match self.operand_ty(arg(0)?)? {
                            NativeTy::Array(element) => *element,
                            _ => return Err(Rejection::invalid("`push` on a non-array")),
                        };
                        let value = self.operand(arg(1)?, Some(&element_ty))?;
                        (
                            quote! { array::push(#array, #value); },
                            quote! { array::len(#array) },
                        )
                    }
                    Builtin::JsonDeserialize(target) => {
                        let target = self.ty(target);
                        let text = self.operand_ref_as(arg(0)?, &NativeTy::Str)?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { json::deserialize::<#target>(#text) }),
                        )
                    }
                    Builtin::JsonToString => {
                        let value = self.operand_ref(arg(0)?)?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { json::to_string(#value) }),
                        )
                    }
                    Builtin::ToStringDefault => {
                        let value = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { ToBaml::to_baml(#value) })
                    }
                    Builtin::StringLength => {
                        let value = self.operand_ref_as(arg(0)?, &NativeTy::Str)?;
                        (TokenStream::new(), quote! { string::length(#value) })
                    }
                    Builtin::StringIsAscii => {
                        let value = self.operand_ref_as(arg(0)?, &NativeTy::Str)?;
                        (TokenStream::new(), quote! { string::is_ascii(#value) })
                    }
                    Builtin::FloatFloor => {
                        let value = self.operand(arg(0)?, Some(&NativeTy::Float))?;
                        (TokenStream::new(), quote! { float::floor(#value) })
                    }
                    Builtin::FloatItrunc => {
                        let value = self.operand(arg(0)?, Some(&NativeTy::Float))?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { float::itrunc(#value) }),
                        )
                    }
                    Builtin::IsNull { operand } => {
                        let value = self.operand_borrowed(arg(*operand)?)?;
                        (TokenStream::new(), quote! { #value.is_none() })
                    }
                    Builtin::EnumEq => {
                        let left = self.operand(arg(0)?, None)?;
                        let right = self.operand(arg(1)?, None)?;
                        (TokenStream::new(), quote! { #left == #right })
                    }
                    Builtin::Equals(common) => {
                        let left = self.operand(arg(0)?, Some(common))?;
                        let right = self.operand(arg(1)?, Some(common))?;
                        (
                            TokenStream::new(),
                            quote! { bex_aot::eq::equals(&#left, &#right) },
                        )
                    }
                    Builtin::Iter => {
                        let array = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { array::iter(#array) })
                    }
                    Builtin::Next => {
                        let (Operand::Copy(Place::Local(iterator))
                        | Operand::Move(Place::Local(iterator))) = arg(0)?
                        else {
                            return Err(Rejection::invalid("`next` receiver is not a local"));
                        };
                        let iterator = local_ident(*iterator);
                        (TokenStream::new(), quote! { array::next(&mut #iterator) })
                    }
                    Builtin::Sort(kind) => {
                        let array = self.operand_ref(arg(0)?)?;
                        let sorted = self.operand(arg(0)?, Some(result))?;
                        let sort = match kind {
                            SortKind::Int => quote! { array::sort_int },
                            SortKind::Float => quote! { array::sort_float },
                            SortKind::Str => quote! { array::sort_str },
                        };
                        (quote! { #sort(#array); }, sorted)
                    }
                    Builtin::Bigint(op) => {
                        let first_ty = match op {
                            BigintOp::Parse => NativeTy::Str,
                            _ => NativeTy::Bigint,
                        };
                        let first = self.operand_ref_as(arg(0)?, &first_ty)?;
                        let call = match op {
                            BigintOp::Abs => quote! { bigint::abs(#first) },
                            BigintOp::Isqrt => self.fallible(&quote! { bigint::isqrt(#first) }),
                            BigintOp::ToInt => self.fallible(&quote! { bigint::to_int(#first) }),
                            BigintOp::Parse => self.fallible(&quote! { bigint::parse(#first) }),
                            BigintOp::Pow => {
                                let second = self.operand_ref_as(arg(1)?, &NativeTy::Bigint)?;
                                self.fallible(&quote! { bigint::pow(#first, #second) })
                            }
                            BigintOp::Ilog => {
                                let second = self.operand_ref_as(arg(1)?, &NativeTy::Bigint)?;
                                self.fallible(&quote! { bigint::ilog(#first, #second) })
                            }
                        };
                        (TokenStream::new(), call)
                    }
                    Builtin::Map(op) => {
                        let map = self.operand_ref(arg(0)?)?;
                        let (key_ty, value_ty) = match self.operand_ty(arg(0)?)? {
                            NativeTy::Map(key, value) => (*key, *value),
                            _ => return Err(Rejection::invalid("map operation on a non-map")),
                        };
                        // Keys are borrowed by the reads and owned by the
                        // inserts, the values always owned.
                        let key_ref = || self.operand_ref_as(arg(1)?, &key_ty);
                        let key = || self.operand(arg(1)?, Some(&key_ty));
                        let value = || self.operand(arg(2)?, Some(&value_ty));
                        let call = match op {
                            MapOp::Length => quote! { map::len(#map) },
                            MapOp::Has => {
                                let key = key_ref()?;
                                quote! { map::has(#map, #key) }
                            }
                            MapOp::Get => {
                                let key = key_ref()?;
                                quote! { map::get(#map, #key) }
                            }
                            MapOp::Index => {
                                let key = key_ref()?;
                                self.fallible(&quote! { map::index(#map, #key) })
                            }
                            MapOp::Set => {
                                let key = key()?;
                                let value = value()?;
                                quote! { map::set(#map, #key, #value) }
                            }
                            MapOp::Delete => {
                                let key = key_ref()?;
                                quote! { map::delete(#map, #key) }
                            }
                            MapOp::Keys => quote! { map::keys(#map) },
                            MapOp::Values => quote! { map::values(#map) },
                            MapOp::GetOrInsert => {
                                let key = key()?;
                                let value = value()?;
                                quote! { map::get_or_insert(#map, #key, #value) }
                            }
                            MapOp::Clear => quote! { map::clear(#map) },
                        };
                        (TokenStream::new(), call)
                    }
                    Builtin::Cmp(kind) => {
                        let NativeTy::Enum(ordering) = result else {
                            return Err(Rejection::invalid(
                                "`cmp` result is not the ordering enum",
                            ));
                        };
                        let (less, equal, greater) = self.ordering_variants(*ordering)?;
                        let ordering = self.ty(result);
                        let compared = self.primitive_cmp(*kind, arg(0)?, arg(1)?)?;
                        (
                            TokenStream::new(),
                            quote! {
                                match #compared {
                                    std::cmp::Ordering::Less => #ordering::#less,
                                    std::cmp::Ordering::Equal => #ordering::#equal,
                                    std::cmp::Ordering::Greater => #ordering::#greater,
                                }
                            },
                        )
                    }
                    Builtin::CompareOp { op, kind } => {
                        let compared = self.primitive_cmp(*kind, arg(0)?, arg(1)?)?;
                        let relation = match op {
                            CompareOp::Lt => quote! { is_lt },
                            CompareOp::Le => quote! { is_le },
                            CompareOp::Gt => quote! { is_gt },
                            CompareOp::Ge => quote! { is_ge },
                        };
                        (TokenStream::new(), quote! { #compared.#relation() })
                    }
                    // The default body's test on the class's own `cmp`.
                    Builtin::CompareVia { op, cmp } => {
                        let NativeTy::Enum(ordering) = &cmp.result else {
                            return Err(Rejection::invalid(
                                "`cmp` result is not the ordering enum",
                            ));
                        };
                        let (less, _, greater) = self.ordering_variants(*ordering)?;
                        let ordering = self.ty(&cmp.result);
                        let compared = self.direct_call(cmp, args, None)?;
                        let value = match op {
                            CompareOp::Lt => quote! { matches!(#compared, #ordering::#less) },
                            CompareOp::Le => quote! { !matches!(#compared, #ordering::#greater) },
                            CompareOp::Gt => quote! { matches!(#compared, #ordering::#greater) },
                            CompareOp::Ge => quote! { !matches!(#compared, #ordering::#less) },
                        };
                        (TokenStream::new(), value)
                    }
                    Builtin::ArrayCallback { op, wanted } => {
                        self.array_callback(*op, wanted, arg(0)?, arg(1)?, args.get(2), result)?
                    }
                };
                (prelude, value, result)
            }
        };
        let target = self.local_place(destination)?;
        let target_ty = self.place_ty(destination)?;
        let value = match coercion(result, &target_ty) {
            // The call's effects are kept.
            Some(Coercion::Null) => quote! {{ #value; None }},
            Some(store) => self.coerce(value, result, &target_ty, store)?,
            None => value,
        };
        Ok(quote! {
            #prelude
            #target = #value;
        })
    }

    /// A direct call of `target` with `args` (the terminator's value
    /// operands), as an expression yielding the callee's result. Inside a
    /// virtual call's arm, `receiver` names the receiver argument's index,
    /// the implementor the arm is for (whose value is `__value`), the
    /// interface type (whose value is the given expression) and that
    /// expression: the receiver parameter takes whichever of the two it is
    /// typed as.
    fn direct_call(
        &self,
        target: &DirectCall<'db>,
        args: &[Operand<'db>],
        receiver: Option<(usize, &NativeTy<'db>, &NativeTy<'db>, &TokenStream)>,
    ) -> Result<TokenStream, Rejection> {
        let DirectCall {
            callee,
            args: params,
            result: _,
            substituted,
        } = target;
        let callee = self
            .names
            .get(&FnId::Declared(callee.clone()))
            .ok_or_else(|| Rejection::invalid("callee has no Rust name"))?;
        if substituted.len() != params.len() || args.len() > params.len() {
            return Err(Rejection::invalid("call has fewer arguments than analyzed"));
        }
        // An interface method call passes what the interface declares; an
        // implementation's further parameters take their defaults.
        let omitted = Operand::Constant(Constant::OmittedArg);
        let args = (0..params.len())
            .map(|index| args.get(index).unwrap_or(&omitted))
            .zip(params)
            .zip(substituted)
            .enumerate()
            .map(|(index, ((arg, param), default))| {
                if let Some((receiver_index, member, iface_ty, iface_value)) = receiver
                    && index == receiver_index
                {
                    // The implementor's value, or, for the interface's own
                    // default body, the interface value as it is.
                    return if param == iface_ty {
                        Ok(quote! { #iface_value.clone() })
                    } else {
                        let store = coercion(member, param).ok_or_else(|| {
                            Rejection::invalid("virtual call receiver does not fit its arm")
                        })?;
                        let value = if member.is_copy() {
                            quote! { *__value }
                        } else {
                            quote! { __value.clone() }
                        };
                        self.coerce(value, member, param, store)
                    };
                }
                // An omitted argument is the callee's constant default.
                let substitute = default.clone().map(Operand::Constant);
                self.operand(substitute.as_ref().unwrap_or(arg), Some(param))
            })
            .collect::<Result<Vec<_>, _>>()?;
        Ok(self.fallible(&quote! { #callee(#(#args),*) }))
    }

    /// Two primitives compared by the language's order, as a
    /// `std::cmp::Ordering` expression.
    fn primitive_cmp(
        &self,
        kind: CmpKind,
        left: &Operand<'db>,
        right: &Operand<'db>,
    ) -> Result<TokenStream, Rejection> {
        Ok(match kind {
            CmpKind::Int | CmpKind::Bool => {
                let ty = match kind {
                    CmpKind::Int => NativeTy::Int,
                    _ => NativeTy::Bool,
                };
                let left = self.operand(left, Some(&ty))?;
                let right = self.operand(right, Some(&ty))?;
                quote! { Ord::cmp(&#left, &#right) }
            }
            CmpKind::Float => {
                let left = self.operand(left, Some(&NativeTy::Float))?;
                let right = self.operand(right, Some(&NativeTy::Float))?;
                quote! { float::cmp(#left, #right) }
            }
            CmpKind::Str => {
                let left = self.operand_ref_as(left, &NativeTy::Str)?;
                let right = self.operand_ref_as(right, &NativeTy::Str)?;
                quote! { string::cmp(#left, #right) }
            }
            CmpKind::Bigint => {
                let left = self.operand_ref_as(left, &NativeTy::Bigint)?;
                let right = self.operand_ref_as(right, &NativeTy::Bigint)?;
                quote! { bigint::cmp(#left, #right) }
            }
        })
    }

    /// The `Less`, `Equal` and `Greater` variants of `baml.ops.Ordering`,
    /// by name as the VM reads them.
    fn ordering_variants(
        &self,
        ordering: baml_compiler2_hir_ty::extern_loc::EnumRef<'db>,
    ) -> Result<(Ident, Ident, Ident), Rejection> {
        let info = self.classes.enum_info(ordering)?;
        let variant = |name: &str| {
            info.variants
                .iter()
                .find(|variant| variant.name == name)
                .map(|variant| variant.ident.clone())
                .ok_or_else(|| {
                    Rejection::invalid(format!("`baml.ops.Ordering` has no variant `{name}`"))
                })
        };
        Ok((variant("Less")?, variant("Equal")?, variant("Greater")?))
    }

    /// A `baml.Array` method calling back into `callback`: the runtime
    /// function over the receiver and the callback adapted to the function
    /// type `wanted`, as a prelude (for the in-place sorts) and the value.
    fn array_callback(
        &self,
        op: ArrayCallback,
        wanted: &NativeTy<'db>,
        receiver: &Operand<'db>,
        callback: &Operand<'db>,
        extra: Option<&Operand<'db>>,
        result: &NativeTy<'db>,
    ) -> Result<(TokenStream, TokenStream), Rejection> {
        let array = self.operand_ref(receiver)?;
        let NativeTy::Fn(wanted_params, wanted_ret) = wanted else {
            return Err(Rejection::invalid("array callback without a function type"));
        };
        let callable = self.adapt_callback(op, callback, wanted_params, wanted_ret)?;
        let runtime = format_ident!("{}", op.runtime_name());
        Ok(match op {
            ArrayCallback::SortBy => {
                let NativeTy::Enum(ordering) = &**wanted_ret else {
                    return Err(Rejection::invalid(
                        "`sort_by` comparator without an ordering",
                    ));
                };
                let (_, _, greater) = self.ordering_variants(*ordering)?;
                let ordering = self.ty(wanted_ret);
                let sorted = self.operand(receiver, Some(result))?;
                let sort = self.fallible(&quote! {
                    array::sort_by(#array, &|left, right| {
                        let ordering = __callback(left, right)?;
                        Ok(matches!(ordering, #ordering::#greater))
                    })
                });
                (
                    quote! {{
                        let __callback = #callable;
                        #sort;
                    }},
                    sorted,
                )
            }
            ArrayCallback::SortByKey(kind) => {
                let compare = match kind {
                    CmpKind::Int | CmpKind::Bool => quote! { &|left, right| Ord::cmp(left, right) },
                    CmpKind::Float => quote! { &|left, right| float::cmp(*left, *right) },
                    CmpKind::Str => quote! { &|left, right| string::cmp(left, right) },
                    CmpKind::Bigint => quote! { &|left, right| bigint::cmp(left, right) },
                };
                let sorted = self.operand(receiver, Some(result))?;
                let sort = self.fallible(&quote! {
                    array::sort_by_key(#array, __callback, #compare)
                });
                (
                    quote! {{
                        let __callback = #callable;
                        #sort;
                    }},
                    sorted,
                )
            }
            ArrayCallback::Reduce => {
                let accumulator = wanted_params
                    .first()
                    .ok_or_else(|| Rejection::invalid("`reduce` callback without parameters"))?;
                let initial =
                    extra.ok_or_else(|| Rejection::invalid("`reduce` without an initial value"))?;
                let initial = self.operand(initial, Some(accumulator))?;
                let call = self.fallible(&quote! {
                    array::reduce(#array, __callback, #initial)
                });
                (
                    TokenStream::new(),
                    quote! {{
                        let __callback = #callable;
                        #call
                    }},
                )
            }
            _ => {
                let call = self.fallible(&quote! { array::#runtime(#array, __callback) });
                (
                    TokenStream::new(),
                    quote! {{
                        let __callback = #callable;
                        #call
                    }},
                )
            }
        })
    }

    /// `callback` as a `&dyn Fn` of the type the runtime calls: the value
    /// itself when its type is that one, else a closure that coerces each
    /// argument into the callback's parameter and its result into what the
    /// runtime reads (`filter_map` reads an `Option` the callback may not
    /// produce; `for_each` reads nothing).
    fn adapt_callback(
        &self,
        op: ArrayCallback,
        callback: &Operand<'db>,
        wanted_params: &[NativeTy<'db>],
        wanted_ret: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let actual = self.operand_ty(callback)?;
        let NativeTy::Fn(actual_params, actual_ret) = &actual else {
            return Err(Rejection::invalid("array callback is not a function value"));
        };
        // A declared function is borrowed as the function item it is; a
        // function value is borrowed through its pointer.
        let function = match function_constant(callback) {
            Some(instance) => {
                let name = self
                    .names
                    .get(&FnId::Declared(instance))
                    .ok_or_else(|| Rejection::invalid("callee has no Rust name"))?;
                quote! { &#name }
            }
            _ => {
                let value = self.operand_borrowed(callback)?;
                quote! { &*#value }
            }
        };
        let ret_as_is = match op {
            ArrayCallback::ForEach => **actual_ret == NativeTy::Null,
            _ => **actual_ret == *wanted_ret,
        };
        if actual_params == wanted_params && ret_as_is {
            return Ok(function);
        }
        let names: Vec<Ident> = (0..wanted_params.len())
            .map(|index| format_ident!("__arg{index}"))
            .collect();
        let params = names.iter().zip(wanted_params).map(|(name, ty)| {
            let ty = self.ty(ty);
            quote! { #name: #ty }
        });
        let args = names
            .iter()
            .zip(wanted_params)
            .zip(actual_params)
            .map(|((name, wanted), actual)| {
                let store = coercion(wanted, actual)
                    .ok_or_else(|| Rejection::invalid("array callback parameter does not fit"))?;
                self.coerce(quote! { #name }, wanted, actual, store)
            })
            .collect::<Result<Vec<_>, _>>()?;
        let ret = self.ty(wanted_ret);
        let body = match op {
            ArrayCallback::ForEach => quote! {{
                __function(#(#args),*)?;
                Ok(())
            }},
            ArrayCallback::FilterMap => {
                let NativeTy::Option(inner) = wanted_ret else {
                    return Err(Rejection::invalid("`filter_map` reads a non-option"));
                };
                match &**actual_ret {
                    NativeTy::Option(produced) => {
                        let store = coercion(produced, inner).ok_or_else(|| {
                            Rejection::invalid("`filter_map` result does not fit")
                        })?;
                        let value = self.coerce(quote! { value }, produced, inner, store)?;
                        quote! {{
                            Ok(__function(#(#args),*)?.map(|value| #value))
                        }}
                    }
                    produced => {
                        let store = coercion(produced, inner).ok_or_else(|| {
                            Rejection::invalid("`filter_map` result does not fit")
                        })?;
                        let value = self.coerce(quote! { value }, produced, inner, store)?;
                        quote! {{
                            let value = __function(#(#args),*)?;
                            Ok(Some(#value))
                        }}
                    }
                }
            }
            _ => {
                let store = coercion(actual_ret, wanted_ret)
                    .ok_or_else(|| Rejection::invalid("array callback result does not fit"))?;
                let value = self.coerce(quote! { value }, actual_ret, wanted_ret, store)?;
                quote! {{
                    let value = __function(#(#args),*)?;
                    Ok(#value)
                }}
            }
        };
        Ok(quote! {{
            let __function = #function;
            &move |#(#params),*| -> Result<#ret, Thrown> #body
        }})
    }

    /// The `&cell::Cell<T>` a cell id names: a captured local's cell
    /// borrowed, or a capture, which is a borrowed cell already.
    fn cell_ref(&self, cell: CellId) -> Result<TokenStream, Rejection> {
        match cell {
            CellId::Local(local) => {
                if !self.candidate.body.local(local).is_captured {
                    return Err(Rejection::invalid(format!(
                        "deref of {local}, which no closure captures"
                    )));
                }
                let ident = local_ident(local);
                Ok(quote! { &#ident })
            }
            CellId::Capture(index) => {
                if index >= self.candidate.captures.len() {
                    return Err(Rejection::invalid(format!(
                        "capture[{index}] is not a capture of this lambda"
                    )));
                }
                let ident = capture_ident(index);
                Ok(quote! { #ident })
            }
        }
    }

    /// `expr`, a value of type `actual`, as a value of type `expected`
    /// through `store` (see [`crate::types::coercion`]). A narrowing
    /// coercion matches the variant the checker proved the value holds and
    /// raises `Unreachable` from the others.
    fn coerce(
        &self,
        expr: TokenStream,
        actual: &NativeTy<'db>,
        expected: &NativeTy<'db>,
        store: Coercion,
    ) -> Result<TokenStream, Rejection> {
        let unreachable = self.raise(&quote! { Thrown::from(Panic::Unreachable) }, false);
        let inner = |ty: &NativeTy<'db>| -> NativeTy<'db> {
            match ty {
                NativeTy::Option(inner) => (**inner).clone(),
                other => other.clone(),
            }
        };
        let union = |ty: &NativeTy<'db>| -> Result<&UnionInfo<'db>, Rejection> {
            self.classes.variants_of(ty)
        };
        // `U::v(expr)` for the variant of `target` holding `member`: the
        // member's own, or, through an interface variant, that interface's
        // variant for the member (`Union::Named(Iface::Dog(expr))`).
        let inject = |expr: TokenStream, member: &NativeTy<'db>, target: &NativeTy<'db>| {
            let info = union(target)?;
            let name = &info.ident;
            if let Some(variant) = info.variant_of(member) {
                return Ok::<_, Rejection>(quote! { #name::#variant(#expr) });
            }
            let via = info
                .members
                .iter()
                .zip(&info.variants)
                .find(|(candidate, _)| {
                    matches!(candidate, NativeTy::Interface(instance) if instance.implementors.contains(member))
                })
                .ok_or_else(|| {
                    Rejection::invalid(format!(
                        "`{}` is not a member of `{}`",
                        self.describe(member),
                        info.described
                    ))
                })?;
            let (iface_ty, variant) = via;
            let inner = union(iface_ty)?;
            let inner_name = &inner.ident;
            let inner_variant = inner
                .variant_of(member)
                .ok_or_else(|| Rejection::invalid("implementor without a variant"))?;
            Ok(quote! { #name::#variant(#inner_name::#inner_variant(#expr)) })
        };
        // The pattern of `target`'s variant holding `member`, binding the
        // value as `value`; nested through an interface variant.
        let narrow_pattern = |member: &NativeTy<'db>, target: &NativeTy<'db>| {
            let info = union(target)?;
            let name = &info.ident;
            if let Some(variant) = info.variant_of(member) {
                return Ok::<_, Rejection>(quote! { #name::#variant(value) });
            }
            let via = info
                .members
                .iter()
                .zip(&info.variants)
                .find(|(candidate, _)| {
                    matches!(candidate, NativeTy::Interface(instance) if instance.implementors.contains(member))
                })
                .ok_or_else(|| Rejection::invalid("narrowed to a type that is not a member"))?;
            let (iface_ty, variant) = via;
            let inner = union(iface_ty)?;
            let inner_name = &inner.ident;
            let inner_variant = inner
                .variant_of(member)
                .ok_or_else(|| Rejection::invalid("implementor without a variant"))?;
            Ok(quote! { #name::#variant(#inner_name::#inner_variant(value)) })
        };
        // Re-tag every variant of `from` that `to` has; the others raise.
        let retag = |expr: TokenStream, from: &NativeTy<'db>, to: &NativeTy<'db>| {
            let from_info = union(from)?;
            let to_info = union(to)?;
            let from_name = &from_info.ident;
            let to_name = &to_info.ident;
            let mut arms = Vec::new();
            for (variant, member) in from_info.variants.iter().zip(&from_info.members) {
                if let Some(target) = to_info.variant_of(member) {
                    arms.push(quote! { #from_name::#variant(value) => #to_name::#target(value), });
                }
            }
            let fallback =
                (arms.len() < from_info.variants.len()).then(|| quote! { _ => { #unreachable } });
            Ok::<_, Rejection>(quote! { match #expr { #(#arms)* #fallback } })
        };
        Ok(match store {
            Coercion::Identity => expr,
            Coercion::Wrap => quote! { Some(#expr) },
            Coercion::Null => quote! { None },
            Coercion::Unwrap => quote! { #expr.expect("non-null by the checker's narrowing") },
            Coercion::Inject => inject(expr, actual, expected)?,
            Coercion::InjectSome => {
                let injected = inject(expr, actual, &inner(expected))?;
                quote! { Some(#injected) }
            }
            Coercion::Widen => retag(expr, actual, expected)?,
            Coercion::WidenSome => {
                let widened = retag(expr, actual, &inner(expected))?;
                quote! { Some(#widened) }
            }
            Coercion::MapInject => {
                let member = inner(actual);
                let target = inner(expected);
                let injected = inject(quote! { value }, &member, &target)?;
                quote! { #expr.map(|value| #injected) }
            }
            Coercion::MapWiden => {
                let widened = retag(quote! { value }, &inner(actual), &inner(expected))?;
                quote! { #expr.map(|value| #widened) }
            }
            Coercion::Narrow => {
                let pattern = narrow_pattern(expected, actual)?;
                quote! {
                    match #expr {
                        #pattern => value,
                        _ => { #unreachable }
                    }
                }
            }
            Coercion::NarrowUnion => retag(expr, actual, expected)?,
            Coercion::UnwrapNarrow => {
                let pattern = narrow_pattern(expected, &inner(actual))?;
                quote! {
                    match #expr {
                        Some(#pattern) => value,
                        _ => { #unreachable }
                    }
                }
            }
            Coercion::UnwrapWiden => {
                let widened = retag(quote! { value }, &inner(actual), expected)?;
                quote! {
                    match #expr {
                        Some(value) => #widened,
                        None => { #unreachable }
                    }
                }
            }
        })
    }

    /// The decision recorded for the type test at `site`.
    fn member_test(&self, site: TestSite) -> Result<&MemberTest, Rejection> {
        self.candidate
            .member_tests
            .get(&site)
            .ok_or_else(|| Rejection::invalid(format!("type test at {site:?} was not analyzed")))
    }

    /// `test` on `operand`, a union or nullable value of type `ty`, as a
    /// `bool` expression: a `matches!` over the variants it selects. On a
    /// value of one closed type the test is a constant.
    fn member_test_tokens(
        &self,
        operand: &Operand<'db>,
        ty: &NativeTy<'db>,
        test: &MemberTest,
    ) -> Result<TokenStream, Rejection> {
        let value = self.operand_borrowed(operand)?;
        let nullable = matches!(ty, NativeTy::Option(_));
        if !nullable && ty.union_members().is_none() {
            return Ok(match test {
                MemberTest::Variants(variants) => {
                    let holds = !variants.is_empty();
                    quote! { #holds }
                }
                MemberTest::Null => quote! { false },
                MemberTest::EnumVariant { index, .. } => {
                    let NativeTy::Enum(enum_ref) = ty else {
                        return Err(Rejection::invalid("variant test on a non-enum"));
                    };
                    let info = self.classes.enum_info(*enum_ref)?;
                    let name = &info.ident;
                    let variant = &info
                        .variants
                        .get(*index)
                        .ok_or_else(|| Rejection::invalid("enum variant index out of range"))?
                        .ident;
                    quote! { #value == #name::#variant }
                }
                MemberTest::Literal { .. } => {
                    return Err(Rejection::unsupported("type test against a literal"));
                }
            });
        }
        let info = match ty.union_members() {
            Some(_) => Some(self.classes.variants_of(ty)?),
            None => None,
        };
        // The pattern for one variant, binding its value as `value` when
        // asked; on a nullable non-union the value itself.
        let variant_pattern = |variant: usize, bind: bool| -> TokenStream {
            let payload = if bind {
                quote! { value }
            } else {
                quote! { _ }
            };
            let pattern = match info {
                Some(info) => {
                    let name = &info.ident;
                    let variant = &info.variants[variant];
                    quote! { #name::#variant(#payload) }
                }
                None => payload,
            };
            if nullable {
                quote! { Some(#pattern) }
            } else {
                pattern
            }
        };
        Ok(match test {
            MemberTest::Null => quote! { #value.is_none() },
            MemberTest::Variants(variants) if variants.is_empty() => quote! { false },
            MemberTest::Variants(variants) => {
                let patterns = variants
                    .iter()
                    .map(|variant| variant_pattern(*variant, false));
                quote! { matches!(&#value, #(#patterns)|*) }
            }
            MemberTest::Literal { variant, literal } => {
                let pattern = variant_pattern(*variant, true);
                let guard = match literal {
                    Literal::Int(expected) => {
                        let expected = int_literal(*expected)?;
                        quote! { *value == #expected }
                    }
                    Literal::Bool(expected) => quote! { *value == #expected },
                    Literal::String(text) => {
                        quote! { string::eq(value, &string::from_literal(#text)) }
                    }
                    Literal::Float(_) | Literal::Bigint(_) => {
                        return Err(Rejection::unsupported(
                            "type test against a float or bigint literal",
                        ));
                    }
                };
                quote! { matches!(&#value, #pattern if #guard) }
            }
            MemberTest::EnumVariant { variant, index } => {
                let pattern = variant_pattern(*variant, true);
                let member = match info {
                    Some(info) => &info.members[*variant],
                    None => ty.union_members().map_or(ty, |_| ty),
                };
                let NativeTy::Enum(enum_ref) = (match member {
                    NativeTy::Option(inner) => &**inner,
                    other => other,
                }) else {
                    return Err(Rejection::invalid("variant test on a non-enum member"));
                };
                let enum_info = self.classes.enum_info(*enum_ref)?;
                let enum_name = &enum_info.ident;
                let variant_ident = &enum_info
                    .variants
                    .get(*index)
                    .ok_or_else(|| Rejection::invalid("enum variant index out of range"))?
                    .ident;
                quote! { matches!(&#value, #pattern if *value == #enum_name::#variant_ident) }
            }
        })
    }

    /// One statement, the `index`th of `block`; `store` is how the analyzer
    /// found its value fits its destination and `value_ty` the value's own
    /// type.
    fn statement(
        &self,
        block: BlockId,
        index: usize,
        kind: &StatementKind<'db>,
        store: Option<Coercion>,
        value_ty: Option<&NativeTy<'db>>,
    ) -> Result<Option<TokenStream>, Rejection> {
        match kind {
            StatementKind::Assign { destination, value } => {
                if let Place::Local(local) = destination {
                    if matches!(self.kind(*local)?, LocalKind::Type) {
                        // A `load_type` feeding a generic call: no code, the
                        // call site is monomorphized.
                        return Ok(None);
                    }
                    if let LocalKind::Tag(source) = self.kind(*local)? {
                        let Rvalue::TypeTag(place) = value else {
                            return Err(Rejection::invalid("type tag from a non-tag value"));
                        };
                        return Ok(match source {
                            // `_t = type_tag(_e)`: the caught error's class name.
                            TagSource::Thrown => {
                                let thrown = self.place(place)?;
                                let ident = local_ident(*local);
                                Some(quote! { #ident = bex_aot::thrown::class_fqn(&#thrown); })
                            }
                            // The switch matches on the union itself.
                            TagSource::Union(_) => None,
                        });
                    }
                    if self.candidate.aliases.contains_key(local) {
                        // Reads of the alias go through its source.
                        return Ok(None);
                    }
                    if let Some(source) = self.candidate.narrow_sources.get(local)
                        && let Rvalue::Use(
                            Operand::Copy(Place::Local(from)) | Operand::Move(Place::Local(from)),
                        ) = value
                        && from == source
                    {
                        // The seed of a `narrow_bind` temporary: the
                        // `narrow_bind` downcasts the error local itself.
                        return Ok(None);
                    }
                }
                let target_ty = self.place_ty(destination)?;
                if is_dead_null_write(value)
                    && !matches!(target_ty, NativeTy::Null | NativeTy::Option(_))
                {
                    return Ok(Some(
                        self.raise(&quote! { Thrown::from(Panic::Unreachable) }, false),
                    ));
                }
                let (value, actual) = self.rvalue(
                    value,
                    &target_ty,
                    value_ty,
                    TestSite::Statement(block, index),
                )?;
                let value = match store {
                    // The unit has no effects to keep.
                    Some(Coercion::Null) => quote! { None },
                    Some(store) => self.coerce(value, &actual, &target_ty, store)?,
                    None => value,
                };
                Ok(Some(match destination {
                    Place::Local(local) => {
                        let ident = local_ident(*local);
                        quote! { #ident = #value; }
                    }
                    // The value is computed first so a `borrow()` its
                    // operands took on the same cell is released before the
                    // `borrow_mut()` of the store.
                    Place::Field { base, field } => {
                        let class = base_ty(self, base)?;
                        let field = self.field_ident(&class, *field)?;
                        let base = self.place(base)?;
                        quote! {{
                            let value = #value;
                            #base.borrow_mut().#field = value;
                        }}
                    }
                    Place::Index { base, index, kind } => {
                        if *kind == IndexKind::Map {
                            return Err(Rejection::unsupported("map index"));
                        }
                        let base = self.place(base)?;
                        let index = local_ident(*index);
                        let set = self.fallible(&quote! { array::set(&#base, #index, value) });
                        quote! {{
                            let value = #value;
                            #set;
                        }}
                    }
                    Place::Deref(cell) => {
                        let cell = self.cell_ref(*cell)?;
                        quote! {{
                            let value = #value;
                            cell::set(#cell, value);
                        }}
                    }
                    Place::Capture(index) => {
                        return Err(Rejection::invalid(format!(
                            "store into the cell pointer capture[{index}]"
                        )));
                    }
                }))
            }
            // Dropping a handle or a scalar early changes nothing observable;
            // the Rust value is dropped at scope end.
            StatementKind::Drop(_) | StatementKind::Nop | StatementKind::Intrinsic { .. } => {
                Ok(None)
            }
            // A new cell for a captured local: empty, or holding the value of
            // the cell it replaces (a loop's per-iteration binding).
            StatementKind::FreshCell { local, carry_value } => {
                let cell = self.cell_ref(CellId::Local(*local))?;
                let ident = local_ident(*local);
                Ok(Some(if *carry_value {
                    quote! { #ident = cell::carry(#cell); }
                } else {
                    quote! { #ident = cell::fresh(); }
                }))
            }
            // The field by name of the receiver's class, or of each
            // implementor's; the value is computed first, as for any field
            // store.
            StatementKind::VirtualFieldStore {
                receiver,
                field,
                value,
                ..
            } => {
                let receiver_ty = self.operand_ty(receiver)?;
                let links = self.field_links(block, index)?;
                let field_ty = self.virtual_field_ty(&receiver_ty, links)?;
                let value = self.operand(value, Some(&field_ty))?;
                let store = self.virtual_field_access(
                    &receiver_ty,
                    receiver,
                    field,
                    links,
                    |class_value, field_ident| {
                        quote! { #class_value.borrow_mut().#field_ident = value; }
                    },
                )?;
                Ok(Some(quote! {{
                    let value = #value;
                    #store
                }}))
            }
        }
    }

    /// The value of `value` as its own type, and that type; the caller
    /// applies the store's coercion. `target` types a bare `null` and says
    /// what a union operand the checker narrowed is read as; `site` is
    /// where the analyzer recorded a type test's decision.
    fn rvalue(
        &self,
        value: &Rvalue<'db>,
        target: &NativeTy<'db>,
        value_ty: Option<&NativeTy<'db>>,
        site: TestSite,
    ) -> Result<(TokenStream, NativeTy<'db>), Rejection> {
        // An array or map literal builds the type the analyzer found, which
        // a union destination does not spell.
        let literal_ty = value_ty.unwrap_or(target);
        Ok(match value {
            Rvalue::Use(operand) => {
                let ty = self.operand_ty_with(operand, Some(target))?;
                (self.operand_value(operand, Some(target))?, ty)
            }
            Rvalue::BinaryOp { op, left, right } => {
                if is_omitted(left) || is_omitted(right) {
                    // The callee prologue's `param == <omitted>` test: every
                    // call passes the constant default, so it never holds.
                    let value = match op {
                        BinOp::Eq => quote! { false },
                        BinOp::Ne => quote! { true },
                        _ => {
                            return Err(Rejection::invalid(format!(
                                "`{op}` against an omitted argument"
                            )));
                        }
                    };
                    return Ok((value, NativeTy::Bool));
                }
                let left_ty = self.operand_ty(left)?;
                let right_ty = self.operand_ty_with(right, Some(&left_ty))?;
                let left_ty = match (&left_ty, &right_ty) {
                    (NativeTy::Null, NativeTy::Option(_)) => right_ty.clone(),
                    _ => left_ty,
                };
                let with_null = matches!(left, Operand::Constant(Constant::Null))
                    || matches!(right, Operand::Constant(Constant::Null));
                let (left_ty, right_ty) =
                    binop_operand_tys(*op, left_ty, right_ty, Some(target), with_null);
                let ty = binop_ty(*op, &left_ty, &right_ty, with_null).ok_or_else(|| {
                    Rejection::unsupported(format!(
                        "`{op}` on `{}` and `{}`",
                        self.describe(&left_ty),
                        self.describe(&right_ty)
                    ))
                })?;
                (self.binary_op(*op, left, right, &left_ty, &right_ty)?, ty)
            }
            Rvalue::UnaryOp { op, operand } => {
                let ty = unary_operand_ty(self.operand_ty(operand)?, Some(target));
                if matches!((op, &ty), (UnaryOp::Neg, NativeTy::Bigint)) {
                    let operand = self.operand_ref_as(operand, &ty)?;
                    return Ok((quote! { bigint::neg(#operand) }, NativeTy::Bigint));
                }
                let operand = self.operand(operand, Some(&ty))?;
                match (op, ty) {
                    (UnaryOp::Not, _) => (quote! { !#operand }, NativeTy::Bool),
                    (UnaryOp::Neg, NativeTy::Float) => (quote! { -#operand }, NativeTy::Float),
                    (UnaryOp::Neg, _) => {
                        (self.fallible(&quote! { int::neg(#operand) }), NativeTy::Int)
                    }
                    (UnaryOp::Truthy, NativeTy::Int) => {
                        (quote! { #operand != int::ZERO }, NativeTy::Bool)
                    }
                    (UnaryOp::Truthy, _) => (operand, NativeTy::Bool),
                }
            }
            Rvalue::Array(_, elements) => {
                let NativeTy::Array(element_ty) = literal_ty else {
                    return Err(Rejection::invalid("array literal stored in a non-array"));
                };
                let element_tokens = self.ty(element_ty);
                let elements = elements
                    .iter()
                    .map(|element| self.operand(element, Some(element_ty)))
                    .collect::<Result<Vec<_>, _>>()?;
                let value = if elements.is_empty() {
                    quote! { array::new::<#element_tokens>(Vec::new()) }
                } else {
                    quote! { array::new::<#element_tokens>(Vec::from([#(#elements),*])) }
                };
                (value, literal_ty.clone())
            }
            Rvalue::Len(place) => {
                let is_map = matches!(self.place_ty(place)?, NativeTy::Map(..));
                let place = self.place(place)?;
                let value = if is_map {
                    quote! { map::len(&#place) }
                } else {
                    quote! { array::len(&#place) }
                };
                (value, NativeTy::Int)
            }
            Rvalue::Map(_, _, entries) => {
                let NativeTy::Map(key_ty, value_ty) = literal_ty else {
                    return Err(Rejection::invalid("map literal stored in a non-map"));
                };
                let key_tokens = self.ty(key_ty);
                let value_tokens = self.ty(value_ty);
                let entries = entries
                    .iter()
                    .map(|(key, value)| {
                        let key = self.operand(key, Some(key_ty))?;
                        let value = self.operand(value, Some(value_ty))?;
                        Ok(quote! { (#key, #value) })
                    })
                    .collect::<Result<Vec<_>, Rejection>>()?;
                let value = if entries.is_empty() {
                    quote! { map::new::<#key_tokens, #value_tokens>(Vec::new()) }
                } else {
                    quote! { map::new::<#key_tokens, #value_tokens>(Vec::from([#(#entries),*])) }
                };
                (value, literal_ty.clone())
            }
            // Variants are declared in discriminant order.
            Rvalue::Discriminant(place) => {
                let place = self.place(place)?;
                (quote! { int::lit(#place as i64) }, NativeTy::Int)
            }
            // The instance the analyzer found (its arguments realized).
            Rvalue::Aggregate {
                kind: AggregateKind::Class { .. },
                fields,
            } => {
                let NativeTy::Class(class) = literal_ty else {
                    return Err(Rejection::invalid("class literal stored in a non-class"));
                };
                let info = self.classes.info(class)?;
                let name = &info.ident;
                let fields = fields
                    .iter()
                    .zip(&info.fields)
                    .map(|(operand, field)| {
                        let ident = &field.ident;
                        let value = self.operand(operand, Some(&field.ty))?;
                        Ok(quote! { #ident: #value })
                    })
                    .collect::<Result<Vec<_>, Rejection>>()?;
                (
                    quote! { shared(#name { #(#fields),* }) },
                    NativeTy::Class(class.clone()),
                )
            }
            Rvalue::IsType { operand, test } => {
                (self.is_type(operand, test, site)?, NativeTy::Bool)
            }
            Rvalue::IsTypeTag { operand, .. } => {
                let ty = self.operand_ty(operand)?;
                let test = self.member_test(site)?;
                (self.member_test_tokens(operand, &ty, test)?, NativeTy::Bool)
            }
            // A closure value: the cells it captures, cloned into a Rust
            // closure that lends them to the lambda's function on every
            // call.
            Rvalue::MakeClosure {
                lambda_idx,
                captures,
                ..
            } => {
                let site = self.candidate.closures.get(lambda_idx).ok_or_else(|| {
                    Rejection::invalid(format!("lambda {lambda_idx} was not analyzed"))
                })?;
                let name = self
                    .names
                    .get(&site.id)
                    .ok_or_else(|| Rejection::invalid("lambda has no Rust name"))?;
                let cells: Vec<Ident> = (0..captures.len())
                    .map(|index| format_ident!("__cell{index}"))
                    .collect();
                let clones = cells
                    .iter()
                    .zip(captures)
                    .map(|(cell, capture)| {
                        let source = match capture {
                            Operand::Copy(Place::Local(local))
                            | Operand::Move(Place::Local(local)) => {
                                self.cell_ref(CellId::Local(*local))?
                            }
                            Operand::Copy(Place::Capture(index))
                            | Operand::Move(Place::Capture(index)) => {
                                self.cell_ref(CellId::Capture(*index))?
                            }
                            other => {
                                return Err(Rejection::invalid(format!(
                                    "closure capture `{other:?}` is not a cell pointer"
                                )));
                            }
                        };
                        Ok(quote! { let #cell = cell::Cell::clone(#source); })
                    })
                    .collect::<Result<Vec<_>, Rejection>>()?;
                let args: Vec<Ident> = (0..site.params.len())
                    .map(|index| format_ident!("__arg{index}"))
                    .collect();
                let params = args.iter().zip(&site.params).map(|(arg, ty)| {
                    let ty = self.ty(ty);
                    quote! { #arg: #ty }
                });
                let ty = NativeTy::Fn(site.params.clone(), Box::new(site.ret.clone()));
                let fn_ty = self.ty(&ty);
                (
                    quote! {{
                        #(#clones)*
                        let __closure: #fn_ty = Rc::new(move |#(#params),*| {
                            #name(#(&#cells,)* #(#args),*)
                        });
                        __closure
                    }},
                    ty,
                )
            }
            // An interface field read: the field by name of the receiver's
            // class, or of each implementor's.
            Rvalue::VirtualFieldAccess {
                receiver, field, ..
            } => {
                let TestSite::Statement(block, index) = site else {
                    return Err(Rejection::invalid(
                        "interface field read outside a statement",
                    ));
                };
                let receiver_ty = self.operand_ty(receiver)?;
                let links = self.field_links(block, index)?;
                let field_ty = self.virtual_field_ty(&receiver_ty, links)?;
                let clone = if field_ty.is_copy() {
                    TokenStream::new()
                } else {
                    quote! { .clone() }
                };
                let read = self.virtual_field_access(
                    &receiver_ty,
                    receiver,
                    field,
                    links,
                    |class_value, field_ident| {
                        quote! { #class_value.borrow().#field_ident #clone }
                    },
                )?;
                (read, field_ty)
            }
            // A generic function value whose type arguments mention the
            // frame: the instance the analyzer recorded for this statement.
            Rvalue::MakeGenericFunction {
                func,
                type_arg_templates,
            } => {
                let instance = match func {
                    DeclRef::Source(loc) => self
                        .candidate
                        .generic_values
                        .get(&(*loc, type_arg_templates.clone())),
                    DeclRef::External(_) => None,
                }
                .ok_or_else(|| Rejection::invalid("generic function value was not analyzed"))?;
                let ty = self
                    .candidate
                    .function_values
                    .get(instance)
                    .cloned()
                    .ok_or_else(|| Rejection::invalid("function value was not analyzed"))?;
                (self.function_value(instance, &ty)?, ty)
            }
            other => return Err(Rejection::unsupported(format!("rvalue {other:?}"))),
        })
    }

    /// The struct fields the interface field at statement `index` of
    /// `block` reaches, one per class the receiver may hold.
    fn field_links(&self, block: BlockId, index: usize) -> Result<&'a [Ident], Rejection> {
        self.candidate
            .field_links
            .get(&(block, index))
            .map(Vec::as_slice)
            .ok_or_else(|| Rejection::invalid("interface field access was not analyzed"))
    }

    /// The type of the interface field linked as `links` on a receiver of
    /// `receiver_ty`: its type in the receiver's class, or in the first
    /// class the receiver may hold (the analyzer checked they agree).
    fn virtual_field_ty(
        &self,
        receiver_ty: &NativeTy<'db>,
        links: &[Ident],
    ) -> Result<NativeTy<'db>, Rejection> {
        let class = match receiver_ty {
            NativeTy::Class(class) => class.clone(),
            NativeTy::Option(inner) => return self.virtual_field_ty(inner, links),
            other => match other.union_members().and_then(<[NativeTy<'db>]>::first) {
                Some(NativeTy::Class(class)) => class.clone(),
                _ => {
                    return Err(Rejection::invalid(format!(
                        "interface field on a `{}`",
                        self.describe(other)
                    )));
                }
            },
        };
        let linked = links
            .first()
            .ok_or_else(|| Rejection::invalid("interface field without a link"))?;
        let info = self.classes.info(&class)?;
        info.fields
            .iter()
            .find(|candidate| candidate.ident == *linked)
            .map(|candidate| candidate.ty.clone())
            .ok_or_else(|| Rejection::invalid(format!("no field `{linked}`")))
    }

    /// `access(class_value, field)` on the receiver's class value and the
    /// struct field linked to the interface field there: directly for a
    /// class receiver, in a `match` arm per variant for an interface or
    /// union one (the receiver read as that enum).
    fn virtual_field_access(
        &self,
        receiver_ty: &NativeTy<'db>,
        receiver: &Operand<'db>,
        field: &baml_type::Name,
        links: &[Ident],
        access: impl Fn(&TokenStream, &Ident) -> TokenStream,
    ) -> Result<TokenStream, Rejection> {
        let iface_ty = match receiver_ty {
            NativeTy::Option(inner) => (**inner).clone(),
            other => other.clone(),
        };
        if iface_ty.union_members().is_none() {
            let value = self.operand_borrowed(receiver)?;
            let linked = links
                .first()
                .ok_or_else(|| Rejection::invalid("interface field without a link"))?;
            return Ok(access(&value, linked));
        }
        let info = self.classes.variants_of(&iface_ty)?;
        if info.variants.len() != links.len() {
            return Err(Rejection::invalid(format!(
                "interface field `{field}` links do not match the receiver's variants"
            )));
        }
        let enum_name = &info.ident;
        let (prelude, receiver_expr) = if self.operand_ty(receiver)? == iface_ty {
            (TokenStream::new(), self.operand_borrowed(receiver)?)
        } else {
            let value = self.operand(receiver, Some(&iface_ty))?;
            (quote! { let __receiver = #value; }, quote! { __receiver })
        };
        let arms = info.variants.iter().zip(links).map(|(variant, linked)| {
            let body = access(&quote! { __value }, linked);
            quote! { #enum_name::#variant(__value) => { #body } }
        });
        Ok(quote! {{
            #prelude
            match &#receiver_expr {
                #(#arms)*
            }
        }})
    }

    /// The function item of `instance` behind a counted pointer, as a
    /// value of the function type `ty`.
    fn function_value(
        &self,
        instance: &Instance<'db>,
        ty: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let name = self
            .names
            .get(&FnId::Declared(instance.clone()))
            .ok_or_else(|| Rejection::invalid("callee has no Rust name"))?;
        let fn_ty = self.ty(ty);
        Ok(quote! {{
            let __function: #fn_ty = Rc::new(#name);
            __function
        }})
    }

    /// `is_type(operand, test)`.
    fn is_type(
        &self,
        operand: &Operand<'db>,
        test: &TypeTest<'db>,
        site: TestSite,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty(operand)?;
        Ok(match (test, &ty) {
            // A `catch` arm's class test, by the class's name.
            (TypeTest::Class { class, .. }, NativeTy::Thrown) => {
                let value = self.operand_borrowed(operand)?;
                let fqn = self.classes.class_fqn(*class);
                quote! { bex_aot::thrown::is_class(&#value, #fqn) }
            }
            // Membership in a literal type is exact equality with the
            // value, which for these primitives is `==`.
            (
                TypeTest::Template(TyTemplate::Literal(literal, _)),
                NativeTy::Int | NativeTy::Bool | NativeTy::Str,
            ) => match literal {
                Literal::Int(value_lit) => {
                    let value = self.operand(operand, None)?;
                    let expected = int_literal(*value_lit)?;
                    quote! { #value == #expected }
                }
                Literal::Bool(true) => self.operand(operand, None)?,
                Literal::Bool(false) => {
                    let value = self.operand(operand, None)?;
                    quote! { !#value }
                }
                Literal::String(text) => {
                    let value = self.operand_ref(operand)?;
                    quote! { string::eq(#value, &string::from_literal(#text)) }
                }
                _ => return Err(Rejection::unsupported("type test other than a literal")),
            },
            // The for-in `Done` test on the result of `next`.
            (TypeTest::Class { class, .. }, NativeTy::Option(_))
                if !self.candidate.member_tests.contains_key(&site) =>
            {
                let _ = class;
                let value = self.operand_borrowed(operand)?;
                quote! { #value.is_none() }
            }
            (_, NativeTy::ArrayIter(_) | NativeTy::Thrown) => {
                return Err(Rejection::unsupported(format!(
                    "type test on a `{}`",
                    self.describe(&ty)
                )));
            }
            _ => {
                let test = self.member_test(site)?;
                self.member_test_tokens(operand, &ty, test)?
            }
        })
    }

    fn binary_op(
        &self,
        op: BinOp,
        left: &Operand<'db>,
        right: &Operand<'db>,
        left_ty: &NativeTy<'db>,
        right_ty: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let unsupported = || {
            Rejection::unsupported(format!(
                "`{op}` on `{}` and `{}`",
                self.describe(left_ty),
                self.describe(right_ty)
            ))
        };
        if matches!(left_ty, NativeTy::Bigint) || matches!(right_ty, NativeTy::Bigint) {
            return self.bigint_op(op, left, right, left_ty, right_ty);
        }
        // `==` with a union or nullable operand (other than against `null`):
        // both sides lifted into the wider type and compared as the VM's
        // comparison opcode compares values, false across kinds.
        let with_null = matches!(left, Operand::Constant(Constant::Null))
            || matches!(right, Operand::Constant(Constant::Null));
        if matches!(op, BinOp::Eq | BinOp::Ne)
            && !with_null
            && (matches!(left_ty, NativeTy::Union(_) | NativeTy::Option(_))
                || matches!(right_ty, NativeTy::Union(_) | NativeTy::Option(_)))
        {
            let common = equality_common(left_ty, right_ty).ok_or_else(unsupported)?;
            let l = self.operand(left, Some(&common))?;
            let r = self.operand(right, Some(&common))?;
            return Ok(match op {
                BinOp::Eq => quote! { bex_aot::eq::equals(&#l, &#r) },
                _ => quote! { !bex_aot::eq::equals(&#l, &#r) },
            });
        }
        // The operand types are the narrowed ones (`binop_operand_tys`), so
        // each operand is read as its type.
        Ok(match left_ty {
            NativeTy::Int => {
                let l = self.operand(left, Some(left_ty))?;
                let r = self.operand(right, Some(right_ty))?;
                match op {
                    BinOp::Add => self.fallible(&quote! { int::add(#l, #r) }),
                    BinOp::Sub => self.fallible(&quote! { int::sub(#l, #r) }),
                    BinOp::Mul => self.fallible(&quote! { int::mul(#l, #r) }),
                    BinOp::Div => self.fallible(&quote! { int::div(#l, #r) }),
                    BinOp::Mod => self.fallible(&quote! { int::rem(#l, #r) }),
                    BinOp::Shl => self.fallible(&quote! { int::shl(#l, #r) }),
                    BinOp::Shr => self.fallible(&quote! { int::shr(#l, #r) }),
                    BinOp::BitAnd => quote! { int::bit_and(#l, #r) },
                    BinOp::BitOr => quote! { int::bit_or(#l, #r) },
                    BinOp::BitXor => quote! { int::bit_xor(#l, #r) },
                    // Operands are locals or literal blocks, so no operator
                    // needs parentheses around them.
                    BinOp::Eq => quote! { #l == #r },
                    BinOp::Ne => quote! { #l != #r },
                    BinOp::Lt => quote! { #l < #r },
                    BinOp::Le => quote! { #l <= #r },
                    BinOp::Gt => quote! { #l > #r },
                    BinOp::Ge => quote! { #l >= #r },
                }
            }
            NativeTy::Float => {
                let l = self.operand(left, Some(left_ty))?;
                let r = self.operand(right, Some(right_ty))?;
                match op {
                    BinOp::Add => quote! { #l + #r },
                    BinOp::Sub => quote! { #l - #r },
                    BinOp::Mul => quote! { #l * #r },
                    BinOp::Div => quote! { #l / #r },
                    BinOp::Mod => quote! { #l % #r },
                    BinOp::Eq => quote! { float::eq(#l, #r) },
                    BinOp::Ne => quote! { !float::eq(#l, #r) },
                    BinOp::Lt => quote! { float::lt(#l, #r) },
                    BinOp::Le => quote! { float::le(#l, #r) },
                    BinOp::Gt => quote! { float::gt(#l, #r) },
                    BinOp::Ge => quote! { float::ge(#l, #r) },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Str => {
                let l = self.operand_ref_as(left, left_ty)?;
                let r = self.operand_ref_as(right, right_ty)?;
                match op {
                    BinOp::Add => quote! { string::concat(#l, #r) },
                    BinOp::Eq => quote! { string::eq(#l, #r) },
                    BinOp::Ne => quote! { !string::eq(#l, #r) },
                    BinOp::Lt => quote! { string::cmp(#l, #r).is_lt() },
                    BinOp::Le => quote! { string::cmp(#l, #r).is_le() },
                    BinOp::Gt => quote! { string::cmp(#l, #r).is_gt() },
                    BinOp::Ge => quote! { string::cmp(#l, #r).is_ge() },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Bool | NativeTy::Enum(_) => {
                let l = self.operand(left, Some(left_ty))?;
                let r = self.operand(right, Some(right_ty))?;
                match op {
                    BinOp::Eq => quote! { #l == #r },
                    BinOp::Ne => quote! { #l != #r },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Null => match op {
                BinOp::Eq => quote! { true },
                BinOp::Ne => quote! { false },
                _ => return Err(unsupported()),
            },
            NativeTy::Option(_) => {
                // One side is the `null` constant: admission checked that.
                let value = if matches!(left, Operand::Constant(Constant::Null)) {
                    right
                } else {
                    left
                };
                let value = self.operand_borrowed(value)?;
                match op {
                    BinOp::Eq => quote! { #value.is_none() },
                    BinOp::Ne => quote! { #value.is_some() },
                    _ => return Err(unsupported()),
                }
            }
            // Handled above: a `bigint` on either side takes the bigint path.
            // A union operand is one the checker did not narrow.
            NativeTy::Bigint
            | NativeTy::Array(_)
            | NativeTy::Map(..)
            | NativeTy::Class(_)
            | NativeTy::Union(_)
            | NativeTy::Interface(_)
            | NativeTy::Fn(..)
            | NativeTy::ArrayIter(_)
            | NativeTy::Thrown => {
                return Err(unsupported());
            }
        })
    }

    /// A binary operation with a `bigint` on at least one side: the `int`
    /// side, if any, is widened first, and every operand is passed by
    /// reference (a `BigInt` is a counted pointer; the operation allocates
    /// its result).
    fn bigint_op(
        &self,
        op: BinOp,
        left: &Operand<'db>,
        right: &Operand<'db>,
        left_ty: &NativeTy<'db>,
        right_ty: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let side = |operand: &Operand<'db>, ty: &NativeTy<'db>| -> Result<TokenStream, Rejection> {
            match ty {
                NativeTy::Bigint => self.operand_ref_as(operand, ty),
                NativeTy::Int => {
                    let value = self.operand(operand, Some(ty))?;
                    Ok(quote! { &bigint::from_int(#value) })
                }
                other => Err(Rejection::unsupported(format!(
                    "`{op}` on `{}` and `{}`",
                    self.describe(left_ty),
                    self.describe(other)
                ))),
            }
        };
        let l = side(left, left_ty)?;
        let r = side(right, right_ty)?;
        Ok(match op {
            BinOp::Add => quote! { bigint::add(#l, #r) },
            BinOp::Sub => quote! { bigint::sub(#l, #r) },
            BinOp::Mul => self.fallible(&quote! { bigint::mul(#l, #r) }),
            BinOp::Div => self.fallible(&quote! { bigint::div(#l, #r) }),
            BinOp::Mod => self.fallible(&quote! { bigint::rem(#l, #r) }),
            BinOp::Shl => self.fallible(&quote! { bigint::shl(#l, #r) }),
            BinOp::Shr => self.fallible(&quote! { bigint::shr(#l, #r) }),
            BinOp::BitAnd => quote! { bigint::bit_and(#l, #r) },
            BinOp::BitOr => quote! { bigint::bit_or(#l, #r) },
            BinOp::BitXor => quote! { bigint::bit_xor(#l, #r) },
            BinOp::Eq => quote! { bigint::eq(#l, #r) },
            BinOp::Ne => quote! { !bigint::eq(#l, #r) },
            BinOp::Lt => quote! { bigint::cmp(#l, #r).is_lt() },
            BinOp::Le => quote! { bigint::cmp(#l, #r).is_le() },
            BinOp::Gt => quote! { bigint::cmp(#l, #r).is_gt() },
            BinOp::Ge => quote! { bigint::cmp(#l, #r).is_ge() },
        })
    }

    /// [`Self::operand_value`], coerced to `expected` when given: a `T`
    /// passed where `T | null` is expected is wrapped in `Some`, a member
    /// passed to a union is lifted into its variant, a union the checker
    /// narrowed is read as the member. A call argument, an aggregate field
    /// or an array element coerces by its operand type alone.
    fn operand(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty_with(operand, expected)?;
        let expr = self.operand_value(operand, expected)?;
        match expected.and_then(|expected| coercion(&ty, expected).map(|store| (expected, store))) {
            Some((expected, store)) => self.coerce(expr, &ty, expected, store),
            None => Ok(expr),
        }
    }

    /// A `&T` for `operand` read as `expected`: the place itself when it has
    /// that type, else a borrow of the coerced value.
    fn operand_ref_as(
        &self,
        operand: &Operand<'db>,
        expected: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty_with(operand, Some(expected))?;
        if ty == *expected {
            self.operand_ref(operand)
        } else {
            let value = self.operand(operand, Some(expected))?;
            Ok(quote! { &#value })
        }
    }

    /// An owned value for `operand` as its own type: a copy of a scalar, a
    /// clone of a handle or string, or a literal. `expected` only decides
    /// whether a `null` constant is the `None` of an `Option` or the unit.
    fn operand_value(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty_with(operand, expected)?;
        Ok(match operand {
            Operand::Copy(place) | Operand::Move(place) => {
                let expr = self.place(place)?;
                // An element read and a cell read are owned already.
                if ty.is_copy() || matches!(place, Place::Index { .. } | Place::Deref(_)) {
                    expr
                } else {
                    quote! { #expr.clone() }
                }
            }
            Operand::Constant(constant) => match constant {
                Constant::Int(value) => int_literal(*value)?,
                Constant::Bool(value) => quote! { #value },
                Constant::Float(value) => float_literal(*value),
                Constant::String(value) => quote! { string::from_literal(#value) },
                Constant::Bigint(value) => bigint_literal(value),
                Constant::Null => match expected {
                    Some(NativeTy::Option(_)) => quote! { None },
                    _ => quote! { () },
                },
                Constant::EnumVariant { enum_ref, index } => {
                    let info = self.classes.enum_info(*enum_ref)?;
                    let variant = usize::try_from(*index)
                        .ok()
                        .and_then(|index| info.variants.get(index))
                        .ok_or_else(|| {
                            Rejection::invalid(format!(
                                "enum `{}` has no variant {index}",
                                info.link_name
                            ))
                        })?;
                    let name = &info.ident;
                    let variant = &variant.ident;
                    quote! { #name::#variant }
                }
                // A declared function as a value (at its type arguments, for
                // a generic one): its function item behind a counted pointer.
                Constant::Function(DeclRef::Source(_)) | Constant::GenericFunction { .. } => {
                    let instance = function_constant(operand)
                        .ok_or_else(|| Rejection::unsupported("stdlib function used as a value"))?;
                    self.function_value(&instance, &ty)?
                }
                other => return Err(Rejection::unsupported(format!("constant {other:?}"))),
            },
        })
    }

    /// `operand` as an expression that can be borrowed without cloning: the
    /// place itself, or a literal.
    fn operand_borrowed(&self, operand: &Operand<'db>) -> Result<TokenStream, Rejection> {
        match operand {
            Operand::Copy(place) | Operand::Move(place) => self.place(place),
            Operand::Constant(_) => self.operand(operand, None),
        }
    }

    /// A `&T` for `operand`.
    fn operand_ref(&self, operand: &Operand<'db>) -> Result<TokenStream, Rejection> {
        let value = self.operand_borrowed(operand)?;
        Ok(quote! { &#value })
    }

    fn operand_ty(&self, operand: &Operand<'db>) -> Result<NativeTy<'db>, Rejection> {
        self.operand_ty_with(operand, None)
    }

    fn operand_ty_with(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<NativeTy<'db>, Rejection> {
        match operand {
            Operand::Copy(place) | Operand::Move(place) => self.place_ty(place),
            Operand::Constant(Constant::Int(_)) => Ok(NativeTy::Int),
            Operand::Constant(Constant::Bool(_)) => Ok(NativeTy::Bool),
            Operand::Constant(Constant::Float(_)) => Ok(NativeTy::Float),
            Operand::Constant(Constant::String(_)) => Ok(NativeTy::Str),
            Operand::Constant(Constant::Bigint(_)) => Ok(NativeTy::Bigint),
            Operand::Constant(Constant::Null) => Ok(match expected {
                Some(option @ NativeTy::Option(_)) => option.clone(),
                _ => NativeTy::Null,
            }),
            Operand::Constant(Constant::EnumVariant { enum_ref, .. }) => {
                Ok(NativeTy::Enum(*enum_ref))
            }
            Operand::Constant(
                Constant::Function(DeclRef::Source(_)) | Constant::GenericFunction { .. },
            ) => {
                let instance = function_constant(operand)
                    .ok_or_else(|| Rejection::unsupported("stdlib function used as a value"))?;
                self.candidate
                    .function_values
                    .get(&instance)
                    .cloned()
                    .ok_or_else(|| Rejection::invalid("function value was not analyzed"))
            }
            other @ Operand::Constant(_) => {
                Err(Rejection::unsupported(format!("operand {other:?}")))
            }
        }
    }

    fn kind(&self, local: Local) -> Result<&LocalKind<'db>, Rejection> {
        self.candidate
            .kinds
            .get(local.0)
            .ok_or_else(|| Rejection::invalid(format!("{local} is not declared")))
    }

    fn local_ty(&self, local: Local) -> Result<NativeTy<'db>, Rejection> {
        match self.kind(local)? {
            LocalKind::Value(ty) => Ok(ty.clone()),
            LocalKind::Never => Err(Rejection::unsupported("read of a `never` local")),
            LocalKind::Type => Err(Rejection::unsupported("type value used as a value")),
            LocalKind::Context => Err(Rejection::unsupported(
                "read of a caught error's `baml.errors.Context` (`catch (e, ctx)`)",
            )),
            LocalKind::Tag(_) => Err(Rejection::unsupported("type tag used as a value")),
        }
    }

    fn place_ty(&self, place: &Place) -> Result<NativeTy<'db>, Rejection> {
        match place {
            Place::Local(local) => self.local_ty(*local),
            Place::Field { base, field } => {
                let class = base_ty(self, base)?;
                let info = self.classes.info(&class)?;
                info.fields
                    .get(*field)
                    .map(|f| f.ty.clone())
                    .ok_or_else(|| Rejection::invalid(format!("no field slot {field}")))
            }
            Place::Index { base, kind, .. } => {
                if *kind == IndexKind::Map {
                    return Err(Rejection::unsupported("map index"));
                }
                match self.place_ty(base)? {
                    NativeTy::Array(element) => Ok(*element),
                    _ => Err(Rejection::invalid("index into a non-array")),
                }
            }
            Place::Deref(CellId::Local(local)) => self.local_ty(*local),
            Place::Deref(CellId::Capture(index)) => {
                self.candidate.captures.get(*index).cloned().ok_or_else(|| {
                    Rejection::invalid(format!("capture[{index}] is not a capture of this lambda"))
                })
            }
            Place::Capture(index) => Err(Rejection::invalid(format!(
                "cell pointer capture[{index}] read as a value"
            ))),
        }
    }

    /// The expression reading `place`, without cloning: a local (or, for an
    /// alias, its source place), a field through `borrow()`, or an indexed
    /// element (owned, via `array::get`).
    fn place(&self, place: &Place) -> Result<TokenStream, Rejection> {
        match place {
            Place::Local(local) => {
                self.local_ty(*local)?;
                if let Some(source) = self.candidate.aliases.get(local) {
                    return self.place(source);
                }
                let ident = local_ident(*local);
                Ok(quote! { #ident })
            }
            Place::Field { base, field } => {
                let class = base_ty(self, base)?;
                let field = self.field_ident(&class, *field)?;
                let base = self.place(base)?;
                Ok(quote! { #base.borrow().#field })
            }
            Place::Index { base, index, kind } => {
                if *kind == IndexKind::Map {
                    return Err(Rejection::unsupported("map index"));
                }
                let base = self.place(base)?;
                let index = local_ident(*index);
                Ok(self.fallible(&quote! { array::get(&#base, #index) }))
            }
            // The value in a cell, copied out; reading a cell no store has
            // reached is a panic, not a Rust one.
            Place::Deref(cell) => {
                let cell = self.cell_ref(*cell)?;
                Ok(self.fallible(&quote! { cell::get(#cell) }))
            }
            Place::Capture(index) => Err(Rejection::invalid(format!(
                "cell pointer capture[{index}] read as a value"
            ))),
        }
    }

    /// A place that must be a plain local: a call or short-circuit
    /// destination.
    fn local_place(&self, place: &Place) -> Result<TokenStream, Rejection> {
        match place {
            Place::Local(local) => {
                self.kind(*local)?;
                let ident = local_ident(*local);
                Ok(quote! { #ident })
            }
            other => Err(Rejection::unsupported(format!(
                "call destination `{other}`"
            ))),
        }
    }

    fn field_ident(&self, class: &ClassInst<'db>, field: usize) -> Result<Ident, Rejection> {
        let info = self.classes.info(class)?;
        info.fields
            .get(field)
            .map(|f| f.ident.clone())
            .ok_or_else(|| Rejection::invalid(format!("no field slot {field}")))
    }

    fn describe(&self, ty: &NativeTy<'db>) -> String {
        ty.describe(&|decl| self.classes.link_name(decl))
    }

    fn terminator(&self, block: BlockId) -> Result<&'a Terminator<'db>, Rejection> {
        self.candidate
            .body
            .blocks
            .get(block.0)
            .and_then(|block| block.terminator.as_ref())
            .ok_or_else(|| Rejection::invalid(format!("{block} has no terminator")))
    }

    /// The label of the merge block that leads into `block`. A block that
    /// also heads a loop keeps `'bbN` for the loop.
    fn block_label(&self, block: usize) -> Lifetime {
        if self.loop_headers.contains(&block) {
            Lifetime::new(&format!("'bb{block}_join"), Span::call_site())
        } else {
            Lifetime::new(&format!("'bb{block}"), Span::call_site())
        }
    }
}

/// The class instance a field place's base holds.
fn base_ty<'db>(printer: &Printer<'_, 'db>, base: &Place) -> Result<ClassInst<'db>, Rejection> {
    match printer.place_ty(base)? {
        NativeTy::Class(class) => Ok(class),
        other => Err(Rejection::invalid(format!(
            "field access on a `{}`",
            printer.describe(&other)
        ))),
    }
}

/// The `match` patterns of one arm of a switch on a union's type tag: the
/// variants the arm's key selects, `None` for the `null` key of a nullable.
fn variant_patterns(
    info: &UnionInfo<'_>,
    nullable: bool,
    test: &MemberTest,
) -> Result<Vec<TokenStream>, Rejection> {
    let name = &info.ident;
    let wrap = |pattern: TokenStream| {
        if nullable {
            quote! { Some(#pattern) }
        } else {
            pattern
        }
    };
    Ok(match test {
        MemberTest::Null => vec![quote! { None }],
        MemberTest::Variants(variants) => variants
            .iter()
            .map(|variant| {
                let variant = &info.variants[*variant];
                wrap(quote! { #name::#variant(_) })
            })
            .collect(),
        MemberTest::Literal { .. } | MemberTest::EnumVariant { .. } => {
            return Err(Rejection::invalid(
                "a switch arm on a union's type tag names a literal",
            ));
        }
    })
}

fn loop_label(block: usize) -> Lifetime {
    Lifetime::new(&format!("'bb{block}"), Span::call_site())
}

fn collect_loop_headers(stmts: &[Stmt], out: &mut FxHashSet<usize>) {
    for stmt in stmts {
        match stmt {
            Stmt::Loop { label, body } => {
                out.insert(*label);
                collect_loop_headers(body, out);
            }
            Stmt::Block { body, .. } => collect_loop_headers(body, out),
            Stmt::If {
                then_branch,
                else_branch,
                ..
            } => {
                collect_loop_headers(then_branch, out);
                collect_loop_headers(else_branch, out);
            }
            Stmt::Switch {
                arms, otherwise, ..
            } => {
                for (_, body) in arms {
                    collect_loop_headers(body, out);
                }
                collect_loop_headers(otherwise, out);
            }
            Stmt::Leaf(_)
            | Stmt::Break(_)
            | Stmt::BreakLoop(_)
            | Stmt::Continue(_)
            | Stmt::Exit(_) => {}
        }
    }
}

/// The instance a source-function constant names: a declared function at
/// no type arguments, or a generic one at the arguments baked into the
/// constant. `None` for a stdlib function.
fn function_constant<'db>(operand: &Operand<'db>) -> Option<Instance<'db>> {
    match operand {
        Operand::Constant(Constant::Function(DeclRef::Source(loc))) => Some(Instance::plain(*loc)),
        Operand::Constant(Constant::GenericFunction {
            func: DeclRef::Source(loc),
            type_args,
        }) => Some(Instance {
            loc: *loc,
            type_args: type_args.clone(),
        }),
        _ => None,
    }
}

fn local_ident(local: Local) -> Ident {
    format_ident!("_{}", local.0)
}

/// The parameter holding a lambda's `index`th capture.
fn capture_ident(index: usize) -> Ident {
    format_ident!("_c{index}")
}

/// An `int` literal, range-checked here; `int::lit` is a `const fn` the
/// optimizer folds to the constant.
fn int_literal(value: i64) -> Result<TokenStream, Rejection> {
    if baml_type::Int63::new(value).is_none() {
        return Err(Rejection::unsupported(format!(
            "int literal {value} is outside the int range"
        )));
    }
    let literal = proc_macro2::Literal::i64_unsuffixed(value);
    Ok(quote! { int::lit(#literal) })
}

/// A `bigint` literal: from an `i64` when it fits, else parsed from its
/// decimal digits.
fn bigint_literal(value: &num_bigint::BigInt) -> TokenStream {
    match i64::try_from(value) {
        Ok(small) => {
            let literal = proc_macro2::Literal::i64_unsuffixed(small);
            quote! { bigint::from_i64(#literal) }
        }
        Err(_) => {
            let digits = value.to_string();
            quote! { bigint::lit(#digits) }
        }
    }
}

/// A `float` literal that round-trips: `{:?}` of the value with an `f64`
/// suffix, or the `f64` constants for the non-finite values.
fn float_literal(value: f64) -> TokenStream {
    if value.is_nan() {
        quote! { f64::NAN }
    } else if value == f64::INFINITY {
        quote! { f64::INFINITY }
    } else if value == f64::NEG_INFINITY {
        quote! { f64::NEG_INFINITY }
    } else {
        let text = format!("{value:?}_f64");
        let literal: proc_macro2::Literal = text
            .trim_start_matches('-')
            .parse()
            .expect("a finite f64 debug rendering is a Rust float literal");
        if value.is_sign_negative() {
            quote! { (-#literal) }
        } else {
            quote! { #literal }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bigint_literals_prefer_i64() {
        assert_eq!(
            bigint_literal(&num_bigint::BigInt::from(-5)).to_string(),
            "bigint :: from_i64 (- 5)"
        );
        let wide: num_bigint::BigInt = "123456789012345678901234567890".parse().unwrap();
        assert_eq!(
            bigint_literal(&wide).to_string(),
            "bigint :: lit (\"123456789012345678901234567890\")"
        );
    }

    #[test]
    fn float_literals_round_trip() {
        assert_eq!(float_literal(1.0).to_string(), "1.0_f64");
        assert_eq!(float_literal(-2.5).to_string(), "(- 2.5_f64)");
        assert_eq!(float_literal(1e300).to_string(), "1e300_f64");
        assert_eq!(float_literal(f64::NAN).to_string(), "f64 :: NAN");
        assert_eq!(
            float_literal(f64::NEG_INFINITY).to_string(),
            "f64 :: NEG_INFINITY"
        );
        assert_eq!(float_literal(-0.0).to_string(), "(- 0.0_f64)");
    }
}
