/// Render every enum, class and candidate as one Rust module. `names` gives
/// each function's Rust identifier, callees included.
pub(crate) fn render_module<'db>(
    classes: &[&ClassInfo<'db>],
    enums: &[&EnumInfo<'db>],
    candidates: &[Candidate<'db>],
    names: &FxHashMap<FunctionLoc<'db>, Ident>,
    table: &ClassTable<'db>,
) -> Result<String, Rejection> {
    let mut items = quote! {
        use bex_aot::{
            BigInt, Int63, Map, Panic, Str, Thrown, array, bigint, float, int, json, map, string,
        };
        use bex_aot::handle::{Shared, shared};
        use bex_aot::render::ToBaml;
    };
    for info in enums {
        items.extend(render_enum(info));
    }
    for class in classes {
        items.extend(render_class(class, table));
    }
    for candidate in candidates {
        items.extend(Printer::new(candidate, names, table).function()?);
    }
    render_rust_file(HEADER, items)
}

/// Parse the tokens back as a file and pretty-print them. A parse failure is
/// a bug in this emitter, reported rather than panicked on.
pub(crate) fn render_rust_file(header: &str, tokens: TokenStream) -> Result<String, Rejection> {
    let file: syn::File = syn::parse2(tokens).map_err(|error| {
        Rejection::invalid(format!(
            "generated tokens do not parse as a Rust file: {error}"
        ))
    })?;
    Ok(format!("{header}{}", prettyplease::unparse(&file)))
}

/// The struct for one class: fields in declaration order with serde derives
/// (through `bex_aot`'s re-export), and the `ToBaml` rendering
/// `Name { f: v, .. }`.
fn render_class<'db>(class: &ClassInfo<'db>, table: &ClassTable<'db>) -> TokenStream {
    let class_ident = |decl| table.ident(decl);
    let doc = format!(" BAML class `{}`.", class.link_name);
    let name = &class.ident;
    let fields = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let ty = field.ty.to_tokens(&class_ident);
        let rename = field.renamed().then(|| {
            let baml_name = &field.name;
            quote! { #[serde(rename = #baml_name)] }
        });
        quote! {
            #rename
            pub #ident: #ty,
        }
    });
    let display_name = &class.display_name;
    let link_name = &class.link_name;
    let expecting = format!("expected JSON object for class `{}`", class.json_name);
    let rendered = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let baml_name = &field.name;
        quote! { (#baml_name, &self.#ident as &dyn ToBaml) }
    });
    let readable = class.fields.iter().map(|field| {
        let ident = &field.ident;
        let baml_name = &field.name;
        quote! { (#baml_name, bex_aot::Readable::readable(&self.#ident)) }
    });
    // Every class can be thrown (`throw C { .. }`) and caught by name, and
    // prints inside an uncaught throw as the engine does, so each one is an
    // `ErrorClass`; the trait costs nothing when the class is never thrown.
    quote! {
        #[doc = #doc]
        #[derive(Debug, bex_aot::serde::Serialize, bex_aot::serde::Deserialize)]
        #[serde(crate = "bex_aot::serde", expecting = #expecting)]
        pub struct #name {
            #(#fields)*
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, _nested: bool) {
                bex_aot::render::class(out, #display_name, &[#(#rendered),*]);
            }
        }

        impl bex_aot::ErrorClass for #name {
            const CLASS_FQN: &'static str = #link_name;

            fn readable_fields(&self) -> Vec<(&'static str, String)> {
                Vec::from([#(#readable),*])
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                bex_aot::readable::class(
                    <Self as bex_aot::ErrorClass>::CLASS_FQN,
                    &bex_aot::ErrorClass::readable_fields(self),
                )
            }
        }
    }
}

/// The Rust enum for a BAML enum: fieldless, one variant per BAML variant
/// in declaration order (so `as i64` is the VM's discriminant), `Copy`,
/// compared by variant, serialized as the variant's name (through
/// `bex_aot`'s serde re-export, renamed where the Rust identifier had to
/// change) and rendered by `to_string` as the bare name, nested or not.
fn render_enum(info: &EnumInfo<'_>) -> TokenStream {
    let doc = format!(" BAML enum `{}`.", info.link_name);
    let name = &info.ident;
    let variants = info.variants.iter().map(|variant| {
        let ident = &variant.ident;
        let rename = variant.renamed().then(|| {
            let baml_name = &variant.name;
            quote! { #[serde(rename = #baml_name)] }
        });
        quote! {
            #rename
            #ident,
        }
    });
    let names = info.variants.iter().map(|variant| &variant.name);
    let count = info.variants.len();
    quote! {
        #[doc = #doc]
        #[derive(
            Clone, Copy, PartialEq, Eq, Hash, Debug,
            bex_aot::serde::Serialize, bex_aot::serde::Deserialize
        )]
        #[serde(crate = "bex_aot::serde", expecting = "expected enum variant string")]
        pub enum #name {
            #(#variants)*
        }

        impl #name {
            /// The BAML variant names, by discriminant.
            pub const NAMES: [&'static str; #count] = [#(#names),*];
        }

        impl ToBaml for #name {
            fn render(&self, out: &mut String, _nested: bool) {
                out.push_str(Self::NAMES[*self as usize]);
            }
        }

        impl bex_aot::Readable for #name {
            fn readable(&self) -> String {
                Self::NAMES[*self as usize].to_string()
            }
        }
    }
}

/// Where a throw or panic in the block being printed goes: the handler's
/// error local takes the value, then the jump leaves for the handler.
struct UnwindSite {
    error: Ident,
    jump: TokenStream,
}

struct Printer<'a, 'db> {
    candidate: &'a Candidate<'db>,
    names: &'a FxHashMap<FunctionLoc<'db>, Ident>,
    classes: &'a ClassTable<'db>,
    /// Blocks that head a loop, whose merge label (if any) needs its own name.
    loop_headers: FxHashSet<usize>,
    /// The unwind site of the block whose code is being printed, if it has a
    /// handler; `None` between blocks and in a block that unwinds out of the
    /// function.
    unwind: RefCell<Option<UnwindSite>>,
}

impl<'a, 'db> Printer<'a, 'db> {
    fn new(
        candidate: &'a Candidate<'db>,
        names: &'a FxHashMap<FunctionLoc<'db>, Ident>,
        classes: &'a ClassTable<'db>,
    ) -> Self {
        let mut loop_headers = FxHashSet::default();
        collect_loop_headers(&candidate.structured, &mut loop_headers);
        Self {
            candidate,
            names,
            classes,
            loop_headers,
            unwind: RefCell::new(None),
        }
    }

    fn ty(&self, ty: &NativeTy<'db>) -> TokenStream {
        ty.to_tokens(&|decl| self.classes.ident(decl))
    }

    /// The unwind site of `block`: the error local of its handler and the
    /// jump the structurer gave it.
    fn unwind_site(&self, block: BlockId) -> Result<Option<UnwindSite>, Rejection> {
        let body = self.candidate.body;
        let Some(handler) = body.block(block).unwind else {
            return Ok(None);
        };
        let landing = body
            .blocks
            .get(handler.0)
            .and_then(|handler| handler.landing)
            .ok_or_else(|| {
                Rejection::invalid(format!("{block} unwinds to {handler}, which lands nothing"))
            })?;
        let jump = self
            .candidate
            .unwind_jumps
            .get(block.0)
            .ok_or_else(|| Rejection::invalid(format!("{block} has no unwind jump")))?;
        if jump.is_empty() {
            return Err(Rejection::invalid(format!(
                "{block} unwinds to {handler} but the structurer gave it no jump"
            )));
        }
        let jump = self.stmts(jump)?;
        Ok(Some(UnwindSite {
            error: local_ident(landing.error_local),
            jump: quote! { #(#jump)* },
        }))
    }

    /// Print `f` with the unwind site of `block` in force.
    fn in_block<T>(
        &self,
        block: BlockId,
        f: impl FnOnce() -> Result<T, Rejection>,
    ) -> Result<T, Rejection> {
        let site = self.unwind_site(block)?;
        let previous = self.unwind.replace(site);
        let result = f();
        *self.unwind.borrow_mut() = previous;
        result
    }

    /// `expr`, a `Result`, unwrapped: `expr?` when the block has no handler,
    /// else a `match` that hands the error to the handler and leaves for it.
    fn fallible(&self, expr: &TokenStream) -> TokenStream {
        match &*self.unwind.borrow() {
            None => quote! { #expr? },
            Some(UnwindSite { error, jump }) => quote! {
                match #expr {
                    Ok(value) => value,
                    Err(error) => {
                        #error = Thrown::from(error);
                        #jump
                    }
                }
            },
        }
    }

    /// Raise `thrown` (an expression of type `Thrown`) from the block being
    /// printed: into its handler, or out of the function (`Err(..)` in tail
    /// position, else `return Err(..);`).
    fn raise(&self, thrown: &TokenStream, tail: bool) -> TokenStream {
        match (&*self.unwind.borrow(), tail) {
            (Some(UnwindSite { error, jump }), _) => quote! {{
                #error = #thrown;
                #jump
            }},
            (None, true) => quote! { Err(#thrown) },
            (None, false) => quote! { return Err(#thrown); },
        }
    }

    fn function(&self) -> Result<TokenStream, Rejection> {
        let candidate = self.candidate;
        let name = self
            .names
            .get(&candidate.loc)
            .ok_or_else(|| Rejection::invalid("function has no Rust name"))?;
        let doc = format!(" BAML function `{}`.", candidate.link_name);
        let params = candidate
            .param_tys()
            .into_iter()
            .enumerate()
            .map(|(index, ty)| {
                let ident = local_ident(Local(index + 1));
                let ty = self.ty(ty);
                quote! { mut #ident: #ty }
            });
        let ret = self.ty(candidate.return_ty());
        // Declared without initializers: rustc proves every read follows a
        // write, over the same paths the MIR has. Aliased temporaries are
        // read through their source and need no declaration.
        let locals = candidate
            .kinds
            .iter()
            .enumerate()
            .filter(|(index, _)| !(1..=candidate.arity()).contains(index))
            .filter(|(index, _)| !candidate.aliases.contains_key(&Local(*index)))
            .filter_map(|(index, kind)| {
                let ident = local_ident(Local(index));
                let tokens = match kind {
                    LocalKind::Value(ty) => self.ty(ty),
                    LocalKind::Tag => quote! { &'static str },
                    LocalKind::Type | LocalKind::Never | LocalKind::Context => return None,
                };
                Some(quote! { let mut #ident: #tokens; })
            });
        // A function on a call cycle counts its frame, so runaway recursion
        // throws `StackOverflow` where the VM would, instead of overflowing
        // the native stack.
        let guard = candidate
            .recursive
            .then(|| quote! { let _frame = bex_aot::depth::Guard::enter()?; });
        let body = self.tail_stmts(&candidate.structured)?;
        Ok(quote! {
            #[doc = #doc]
            pub fn #name(#(#params),*) -> Result<#ret, Thrown> {
                #guard
                #(#locals)*
                #(#body)*
            }
        })
    }

    fn stmts(&self, stmts: &[Stmt]) -> Result<Vec<TokenStream>, Rejection> {
        stmts.iter().map(|stmt| self.stmt(stmt, false)).collect()
    }

    /// [`Self::stmts`] with the last statement in tail position: an exit there
    /// is the enclosing function's value rather than a `return`, through the
    /// arms of an `if` or `match`. A labeled block or loop is never a tail,
    /// since a `break` out of it has to land on code that follows.
    fn tail_stmts(&self, stmts: &[Stmt]) -> Result<Vec<TokenStream>, Rejection> {
        let Some((last, init)) = stmts.split_last() else {
            return Ok(Vec::new());
        };
        let mut out = self.stmts(init)?;
        out.push(self.stmt(last, true)?);
        Ok(out)
    }

    fn body(&self, stmts: &[Stmt], tail: bool) -> Result<Vec<TokenStream>, Rejection> {
        if tail {
            self.tail_stmts(stmts)
        } else {
            self.stmts(stmts)
        }
    }

    fn stmt(&self, stmt: &Stmt, tail: bool) -> Result<TokenStream, Rejection> {
        Ok(match stmt {
            Stmt::Leaf(block) => {
                let lines = self.leaf(BlockId(*block))?;
                quote! { #(#lines)* }
            }
            Stmt::Block { label, body } => {
                let label = self.block_label(*label);
                let body = self.stmts(body)?;
                quote! { #label: { #(#body)* } }
            }
            Stmt::Loop { label, body } => {
                let label = loop_label(*label);
                let body = self.stmts(body)?;
                quote! { #label: loop { #(#body)* } }
            }
            Stmt::If {
                block,
                then_branch,
                else_branch,
            } => {
                let then_branch = self.body(then_branch, tail)?;
                let else_branch = self.body(else_branch, tail)?;
                match self.terminator(BlockId(*block))? {
                    Terminator::Branch { condition, .. } => {
                        let condition = self.operand(condition, None)?;
                        quote! {
                            if #condition { #(#then_branch)* } else { #(#else_branch)* }
                        }
                    }
                    // A `catch` arm binding: the caught error narrowed to the
                    // arm's class, as the handle it was thrown as.
                    Terminator::NarrowBind { destination, .. } => {
                        let source = self
                            .candidate
                            .narrow_sources
                            .get(destination)
                            .ok_or_else(|| {
                                Rejection::invalid(format!(
                                    "{destination} is narrowed but was never seeded with a caught error"
                                ))
                            })?;
                        let source = local_ident(*source);
                        let target = self.ty(&self.local_ty(*destination)?);
                        let destination = local_ident(*destination);
                        quote! {
                            if let Some(value) = bex_aot::thrown::downcast::<#target>(&#source) {
                                #destination = value;
                                #(#then_branch)*
                            } else {
                                #(#else_branch)*
                            }
                        }
                    }
                    // `then_branch` is the right-hand side, `else_branch` the
                    // join. On the short edge the result is the operand's
                    // value, which the test just decided.
                    Terminator::ShortCircuit {
                        operand,
                        kind,
                        destination,
                        ..
                    } => {
                        let operand = self.operand(operand, None)?;
                        let destination = self.local_place(destination)?;
                        match kind {
                            ShortCircuitKind::And => quote! {
                                if #operand {
                                    #(#then_branch)*
                                } else {
                                    #destination = false;
                                    #(#else_branch)*
                                }
                            },
                            ShortCircuitKind::Or => quote! {
                                if #operand {
                                    #destination = true;
                                    #(#else_branch)*
                                } else {
                                    #(#then_branch)*
                                }
                            },
                            ShortCircuitKind::Coalesce => {
                                return Err(Rejection::unsupported("`??`"));
                            }
                        }
                    }
                    _ => return Err(Rejection::invalid("two-way branch without a branch")),
                }
            }
            Stmt::Switch {
                block,
                arms,
                otherwise,
            } => {
                let Terminator::Switch {
                    discriminant,
                    arms: keys,
                    ..
                } = self.terminator(BlockId(*block))?
                else {
                    return Err(Rejection::invalid("multi-way branch without a switch"));
                };
                // A multi-arm `catch` switches on the caught error's class
                // tag: its fully qualified name, matched as a string.
                let tag = match discriminant {
                    Operand::Copy(Place::Local(local)) | Operand::Move(Place::Local(local))
                        if matches!(self.kind(*local)?, LocalKind::Tag) =>
                    {
                        Some(local_ident(*local))
                    }
                    _ => None,
                };
                let on_tag = tag.is_some();
                let discriminant = match tag {
                    Some(tag) => quote! { #tag },
                    None => {
                        let value = self.operand(discriminant, None)?;
                        quote! { #value.get() }
                    }
                };
                let mut seen: FxHashSet<String> = FxHashSet::default();
                let mut match_arms = Vec::with_capacity(arms.len());
                for (indices, body) in arms {
                    let mut patterns = Vec::new();
                    for index in indices {
                        let Some((key, _)) = keys.get(*index) else {
                            return Err(Rejection::invalid("switch arm index is out of range"));
                        };
                        // A repeated key can never fire: the VM takes the arm
                        // where it first appears, which may be one folded into
                        // `_`, so the key is emitted at its first index only.
                        let first = keys.iter().position(|(k, _)| k == key);
                        if first != Some(*index) {
                            continue;
                        }
                        match (key, on_tag) {
                            (SwitchKey::Int(key), false) => {
                                if seen.insert(key.to_string()) {
                                    patterns.push(
                                        proc_macro2::Literal::i64_suffixed(*key)
                                            .into_token_stream(),
                                    );
                                }
                            }
                            (SwitchKey::Class(class), true) => {
                                let fqn = self.classes.link_name(TypeDecl::Class(*class));
                                if seen.insert(fqn.clone()) {
                                    patterns.push(quote! { #fqn });
                                }
                            }
                            (SwitchKey::Class(_), false) => {
                                return Err(Rejection::unsupported("switch on a class tag"));
                            }
                            (SwitchKey::Int(_), true) => {
                                return Err(Rejection::unsupported(
                                    "`catch` arm on a primitive type",
                                ));
                            }
                        }
                    }
                    if patterns.is_empty() {
                        continue;
                    }
                    let body = self.body(body, tail)?;
                    match_arms.push(quote! { #(#patterns)|* => { #(#body)* } });
                }
                let otherwise = self.body(otherwise, tail)?;
                quote! {
                    match #discriminant {
                        #(#match_arms)*
                        _ => { #(#otherwise)* }
                    }
                }
            }
            Stmt::Break(label) => {
                let label = self.block_label(*label);
                quote! { break #label; }
            }
            Stmt::BreakLoop(label) => {
                let label = loop_label(*label);
                quote! { break #label; }
            }
            Stmt::Continue(label) => {
                let label = loop_label(*label);
                quote! { continue #label; }
            }
            Stmt::Exit(block) => {
                let block = BlockId(*block);
                match (self.terminator(block)?, tail) {
                    (Terminator::Return, true) => quote! { Ok(_0) },
                    (Terminator::Return, false) => quote! { return Ok(_0); },
                    (Terminator::Unreachable, _) => self.in_block(block, || {
                        Ok(self.raise(&quote! { Thrown::from(Panic::Unreachable) }, tail))
                    })?,
                    // `throw v`: a class instance becomes a thrown object; a
                    // caught error thrown on goes as it is. `rethrow` carries
                    // the caught error; its context has no native form.
                    (Terminator::Throw { value }, _) => self.in_block(block, || {
                        let ty = self.operand_ty(value)?;
                        let value = self.operand(value, None)?;
                        let thrown = match ty {
                            NativeTy::Thrown => value,
                            _ => quote! { Thrown::error(#value) },
                        };
                        Ok(self.raise(&thrown, tail))
                    })?,
                    (Terminator::Rethrow { value, .. }, _) => self.in_block(block, || {
                        let value = self.operand(value, None)?;
                        Ok(self.raise(&value, tail))
                    })?,
                    _ => return Err(Rejection::invalid("exit without a return")),
                }
            }
        })
    }

    /// A block's statements, then what its terminator computes, with the
    /// block's unwind site in force.
    fn leaf(&self, block: BlockId) -> Result<Vec<TokenStream>, Rejection> {
        let body = self.candidate.body;
        if block.0 >= body.blocks.len() {
            return Err(Rejection::invalid(format!("{block} does not exist")));
        }
        self.in_block(block, || self.leaf_lines(block))
    }

    fn leaf_lines(&self, block: BlockId) -> Result<Vec<TokenStream>, Rejection> {
        let body = self.candidate.body;
        let mut lines = Vec::new();
        let stores = self
            .candidate
            .stores
            .get(block.0)
            .ok_or_else(|| Rejection::invalid(format!("{block} was not analyzed")))?;
        for (statement, store) in body.block(block).statements.iter().zip(stores) {
            if let Some(line) = self.statement(&statement.kind, *store)? {
                lines.push(line);
            }
        }
        match self.terminator(block)? {
            Terminator::Call {
                args,
                ntypeargs,
                destination,
                ..
            } => {
                let call = self
                    .candidate
                    .call(block)
                    .ok_or_else(|| Rejection::invalid(format!("{block} call was not analyzed")))?;
                lines.push(self.call(call, &args[*ntypeargs..], destination)?);
            }
            Terminator::VirtualCall {
                args, destination, ..
            } => {
                let call = self
                    .candidate
                    .call(block)
                    .ok_or_else(|| Rejection::invalid(format!("{block} call was not analyzed")))?;
                lines.push(self.call(call, args, destination)?);
            }
            // The guard in front of a wildcard `catch` arm: a panic is not
            // for the wildcard and goes on to the next handler.
            Terminator::ThrowIfPanic { value, .. } => {
                let thrown = self.operand_borrowed(value)?;
                let raise = self.raise(&quote! { #thrown.clone() }, false);
                lines.push(quote! {
                    if bex_aot::thrown::is_panic(&#thrown) { #raise }
                });
            }
            _ => {}
        }
        Ok(lines)
    }

    fn call(
        &self,
        call: &CallKind<'db>,
        args: &[Operand<'db>],
        destination: &Place,
    ) -> Result<TokenStream, Rejection> {
        let arg = |index: usize| -> Result<&Operand<'db>, Rejection> {
            args.get(index)
                .ok_or_else(|| Rejection::invalid("call has fewer arguments than analyzed"))
        };
        // Statements run before the store, then the stored value.
        let (prelude, value, result) = match call {
            CallKind::Panic(message) => {
                return Ok(self.raise(
                    &quote! { Thrown::from(Panic::UserPanic { message: String::from(#message) }) },
                    false,
                ));
            }
            CallKind::Direct {
                callee,
                args: params,
                result,
                substituted,
            } => {
                let callee = self
                    .names
                    .get(callee)
                    .ok_or_else(|| Rejection::invalid("callee has no Rust name"))?;
                if substituted.len() != args.len() {
                    return Err(Rejection::invalid("call has fewer arguments than analyzed"));
                }
                let args = args
                    .iter()
                    .zip(params)
                    .zip(substituted)
                    .map(|((arg, param), default)| {
                        // An omitted argument is the callee's constant default.
                        let substitute = default.clone().map(Operand::Constant);
                        self.operand(substitute.as_ref().unwrap_or(arg), Some(param))
                    })
                    .collect::<Result<Vec<_>, _>>()?;
                (
                    TokenStream::new(),
                    self.fallible(&quote! { #callee(#(#args),*) }),
                    result,
                )
            }
            CallKind::Builtin { builtin, result } => {
                let (prelude, value) = match builtin {
                    Builtin::ArrayPush => {
                        let array = self.operand_ref(arg(0)?)?;
                        let element_ty = match self.operand_ty(arg(0)?)? {
                            NativeTy::Array(element) => *element,
                            _ => return Err(Rejection::invalid("`push` on a non-array")),
                        };
                        let value = self.operand(arg(1)?, Some(&element_ty))?;
                        (
                            quote! { array::push(#array, #value); },
                            quote! { array::len(#array) },
                        )
                    }
                    Builtin::JsonDeserialize(target) => {
                        let target = self.ty(target);
                        let text = self.operand_ref(arg(0)?)?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { json::deserialize::<#target>(#text) }),
                        )
                    }
                    Builtin::JsonToString => {
                        let value = self.operand_ref(arg(0)?)?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { json::to_string(#value) }),
                        )
                    }
                    Builtin::ToStringDefault => {
                        let value = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { ToBaml::to_baml(#value) })
                    }
                    Builtin::StringLength => {
                        let value = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { string::length(#value) })
                    }
                    Builtin::StringIsAscii => {
                        let value = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { string::is_ascii(#value) })
                    }
                    Builtin::FloatFloor => {
                        let value = self.operand(arg(0)?, None)?;
                        (TokenStream::new(), quote! { float::floor(#value) })
                    }
                    Builtin::FloatItrunc => {
                        let value = self.operand(arg(0)?, None)?;
                        (
                            TokenStream::new(),
                            self.fallible(&quote! { float::itrunc(#value) }),
                        )
                    }
                    Builtin::IsNull { operand } => {
                        let value = self.operand_borrowed(arg(*operand)?)?;
                        (TokenStream::new(), quote! { #value.is_none() })
                    }
                    Builtin::EnumEq => {
                        let left = self.operand(arg(0)?, None)?;
                        let right = self.operand(arg(1)?, None)?;
                        (TokenStream::new(), quote! { #left == #right })
                    }
                    Builtin::Equals(common) => {
                        let left = self.operand(arg(0)?, Some(common))?;
                        let right = self.operand(arg(1)?, Some(common))?;
                        (
                            TokenStream::new(),
                            quote! { bex_aot::eq::equals(&#left, &#right) },
                        )
                    }
                    Builtin::Iter => {
                        let array = self.operand_ref(arg(0)?)?;
                        (TokenStream::new(), quote! { array::iter(#array) })
                    }
                    Builtin::Next => {
                        let (Operand::Copy(Place::Local(iterator))
                        | Operand::Move(Place::Local(iterator))) = arg(0)?
                        else {
                            return Err(Rejection::invalid("`next` receiver is not a local"));
                        };
                        let iterator = local_ident(*iterator);
                        (TokenStream::new(), quote! { array::next(&mut #iterator) })
                    }
                    Builtin::Sort(kind) => {
                        let array = self.operand_ref(arg(0)?)?;
                        let sorted = self.operand(arg(0)?, Some(result))?;
                        let sort = match kind {
                            SortKind::Int => quote! { array::sort_int },
                            SortKind::Float => quote! { array::sort_float },
                            SortKind::Str => quote! { array::sort_str },
                        };
                        (quote! { #sort(#array); }, sorted)
                    }
                    Builtin::Bigint(op) => {
                        let first = self.operand_ref(arg(0)?)?;
                        let call = match op {
                            BigintOp::Abs => quote! { bigint::abs(#first) },
                            BigintOp::Isqrt => self.fallible(&quote! { bigint::isqrt(#first) }),
                            BigintOp::ToInt => self.fallible(&quote! { bigint::to_int(#first) }),
                            BigintOp::Parse => self.fallible(&quote! { bigint::parse(#first) }),
                            BigintOp::Pow => {
                                let second = self.operand_ref(arg(1)?)?;
                                self.fallible(&quote! { bigint::pow(#first, #second) })
                            }
                            BigintOp::Ilog => {
                                let second = self.operand_ref(arg(1)?)?;
                                self.fallible(&quote! { bigint::ilog(#first, #second) })
                            }
                        };
                        (TokenStream::new(), call)
                    }
                    Builtin::Map(op) => {
                        let map = self.operand_ref(arg(0)?)?;
                        let (key_ty, value_ty) = match self.operand_ty(arg(0)?)? {
                            NativeTy::Map(key, value) => (*key, *value),
                            _ => return Err(Rejection::invalid("map operation on a non-map")),
                        };
                        // Keys are borrowed by the reads and owned by the
                        // inserts, the values always owned.
                        let key_ref = || self.operand_ref(arg(1)?);
                        let key = || self.operand(arg(1)?, Some(&key_ty));
                        let value = || self.operand(arg(2)?, Some(&value_ty));
                        let call = match op {
                            MapOp::Length => quote! { map::len(#map) },
                            MapOp::Has => {
                                let key = key_ref()?;
                                quote! { map::has(#map, #key) }
                            }
                            MapOp::Get => {
                                let key = key_ref()?;
                                quote! { map::get(#map, #key) }
                            }
                            MapOp::Index => {
                                let key = key_ref()?;
                                self.fallible(&quote! { map::index(#map, #key) })
                            }
                            MapOp::Set => {
                                let key = key()?;
                                let value = value()?;
                                quote! { map::set(#map, #key, #value) }
                            }
                            MapOp::Delete => {
                                let key = key_ref()?;
                                quote! { map::delete(#map, #key) }
                            }
                            MapOp::Keys => quote! { map::keys(#map) },
                            MapOp::Values => quote! { map::values(#map) },
                            MapOp::GetOrInsert => {
                                let key = key()?;
                                let value = value()?;
                                quote! { map::get_or_insert(#map, #key, #value) }
                            }
                            MapOp::Clear => quote! { map::clear(#map) },
                        };
                        (TokenStream::new(), call)
                    }
                };
                (prelude, value, result)
            }
        };
        let target = self.local_place(destination)?;
        let target_ty = self.place_ty(destination)?;
        let value = match coercion(result, &target_ty) {
            Some(Coercion::Wrap) => quote! { Some(#value) },
            Some(Coercion::Null) => quote! {{ #value; None }},
            _ => value,
        };
        Ok(quote! {
            #prelude
            #target = #value;
        })
    }

    /// One statement; `store` is how the analyzer found its value fits its
    /// destination.
    fn statement(
        &self,
        kind: &StatementKind<'db>,
        store: Option<Coercion>,
    ) -> Result<Option<TokenStream>, Rejection> {
        match kind {
            StatementKind::Assign { destination, value } => {
                if let Place::Local(local) = destination {
                    if matches!(self.kind(*local)?, LocalKind::Type) {
                        // A `load_type` feeding a generic call: no code, the
                        // call site is monomorphized.
                        return Ok(None);
                    }
                    if matches!(self.kind(*local)?, LocalKind::Tag) {
                        // `_t = type_tag(_e)`: the caught error's class name.
                        let Rvalue::TypeTag(place) = value else {
                            return Err(Rejection::invalid("class tag from a non-tag value"));
                        };
                        let thrown = self.place(place)?;
                        let ident = local_ident(*local);
                        return Ok(Some(
                            quote! { #ident = bex_aot::thrown::class_fqn(&#thrown); },
                        ));
                    }
                    if self.candidate.aliases.contains_key(local) {
                        // Reads of the alias go through its source.
                        return Ok(None);
                    }
                    if let Some(source) = self.candidate.narrow_sources.get(local)
                        && let Rvalue::Use(
                            Operand::Copy(Place::Local(from)) | Operand::Move(Place::Local(from)),
                        ) = value
                        && from == source
                    {
                        // The seed of a `narrow_bind` temporary: the
                        // `narrow_bind` downcasts the error local itself.
                        return Ok(None);
                    }
                }
                let target_ty = self.place_ty(destination)?;
                if is_dead_null_write(value)
                    && !matches!(target_ty, NativeTy::Null | NativeTy::Option(_))
                {
                    return Ok(Some(
                        self.raise(&quote! { Thrown::from(Panic::Unreachable) }, false),
                    ));
                }
                let value = self.rvalue(value, &target_ty)?;
                let value = match store {
                    Some(Coercion::Wrap) => quote! { Some(#value) },
                    // The unit has no effects to keep.
                    Some(Coercion::Null) => quote! { None },
                    _ => value,
                };
                Ok(Some(match destination {
                    Place::Local(local) => {
                        let ident = local_ident(*local);
                        quote! { #ident = #value; }
                    }
                    // The value is computed first so a `borrow()` its
                    // operands took on the same cell is released before the
                    // `borrow_mut()` of the store.
                    Place::Field { base, field } => {
                        let class = base_ty(self, base)?;
                        let field = self.field_ident(class, *field)?;
                        let base = self.place(base)?;
                        quote! {{
                            let value = #value;
                            #base.borrow_mut().#field = value;
                        }}
                    }
                    Place::Index { base, index, kind } => {
                        if *kind == IndexKind::Map {
                            return Err(Rejection::unsupported("map index"));
                        }
                        let base = self.place(base)?;
                        let index = local_ident(*index);
                        let set = self.fallible(&quote! { array::set(&#base, #index, value) });
                        quote! {{
                            let value = #value;
                            #set;
                        }}
                    }
                    Place::Capture(_) | Place::Deref(_) => {
                        return Err(Rejection::unsupported("captured local"));
                    }
                }))
            }
            // Dropping a handle or a scalar early changes nothing observable;
            // the Rust value is dropped at scope end.
            StatementKind::Drop(_) | StatementKind::Nop | StatementKind::Intrinsic { .. } => {
                Ok(None)
            }
            other => Err(Rejection::unsupported(format!("statement {other:?}"))),
        }
    }

    /// The value of `value` as its own type; the caller applies the store's
    /// coercion. `target` types a bare `null` and the for-in unwrap.
    fn rvalue(
        &self,
        value: &Rvalue<'db>,
        target: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        Ok(match value {
            Rvalue::Use(operand) => {
                let ty = self.operand_ty_with(operand, Some(target))?;
                if coercion(&ty, target) == Some(Coercion::Unwrap) {
                    // A `T | null` the checker proved is a `T` here: the
                    // for-in element after the `Done` test, or a value after
                    // a null test. A `Copy` option is read in place; a handle
                    // is cloned.
                    let option = self.operand_borrowed(operand)?;
                    let option = if ty.is_copy() {
                        option
                    } else {
                        quote! { #option.clone() }
                    };
                    return Ok(quote! {
                        #option.expect("non-null by the checker's narrowing")
                    });
                }
                self.operand_value(operand, Some(target))?
            }
            Rvalue::BinaryOp { op, left, right } => {
                if is_omitted(left) || is_omitted(right) {
                    // The callee prologue's `param == <omitted>` test: every
                    // call passes the constant default, so it never holds.
                    return Ok(match op {
                        BinOp::Eq => quote! { false },
                        BinOp::Ne => quote! { true },
                        _ => {
                            return Err(Rejection::invalid(format!(
                                "`{op}` against an omitted argument"
                            )));
                        }
                    });
                }
                let left_ty = self.operand_ty(left)?;
                let right_ty = self.operand_ty_with(right, Some(&left_ty))?;
                let left_ty = match (&left_ty, &right_ty) {
                    (NativeTy::Null, NativeTy::Option(_)) => right_ty.clone(),
                    _ => left_ty,
                };
                self.binary_op(*op, left, right, &left_ty, &right_ty)?
            }
            Rvalue::UnaryOp { op, operand } => {
                let ty = self.operand_ty(operand)?;
                if matches!((op, &ty), (UnaryOp::Neg, NativeTy::Bigint)) {
                    let operand = self.operand_ref(operand)?;
                    return Ok(quote! { bigint::neg(#operand) });
                }
                let operand = self.operand(operand, None)?;
                match (op, ty) {
                    (UnaryOp::Not, _) => quote! { !#operand },
                    (UnaryOp::Neg, NativeTy::Float) => quote! { -#operand },
                    (UnaryOp::Neg, _) => self.fallible(&quote! { int::neg(#operand) }),
                    (UnaryOp::Truthy, NativeTy::Int) => quote! { #operand != int::ZERO },
                    (UnaryOp::Truthy, _) => operand,
                }
            }
            Rvalue::Array(_, elements) => {
                let NativeTy::Array(element_ty) = target else {
                    return Err(Rejection::invalid("array literal stored in a non-array"));
                };
                let element_tokens = self.ty(element_ty);
                let elements = elements
                    .iter()
                    .map(|element| self.operand(element, Some(element_ty)))
                    .collect::<Result<Vec<_>, _>>()?;
                if elements.is_empty() {
                    quote! { array::new::<#element_tokens>(Vec::new()) }
                } else {
                    quote! { array::new::<#element_tokens>(Vec::from([#(#elements),*])) }
                }
            }
            Rvalue::Len(place) => {
                let is_map = matches!(self.place_ty(place)?, NativeTy::Map(..));
                let place = self.place(place)?;
                if is_map {
                    quote! { map::len(&#place) }
                } else {
                    quote! { array::len(&#place) }
                }
            }
            Rvalue::Map(_, _, entries) => {
                let NativeTy::Map(key_ty, value_ty) = target else {
                    return Err(Rejection::invalid("map literal stored in a non-map"));
                };
                let key_tokens = self.ty(key_ty);
                let value_tokens = self.ty(value_ty);
                let entries = entries
                    .iter()
                    .map(|(key, value)| {
                        let key = self.operand(key, Some(key_ty))?;
                        let value = self.operand(value, Some(value_ty))?;
                        Ok(quote! { (#key, #value) })
                    })
                    .collect::<Result<Vec<_>, Rejection>>()?;
                if entries.is_empty() {
                    quote! { map::new::<#key_tokens, #value_tokens>(Vec::new()) }
                } else {
                    quote! { map::new::<#key_tokens, #value_tokens>(Vec::from([#(#entries),*])) }
                }
            }
            // Variants are declared in discriminant order.
            Rvalue::Discriminant(place) => {
                let place = self.place(place)?;
                quote! { int::lit(#place as i64) }
            }
            Rvalue::Aggregate {
                kind: AggregateKind::Class { class, .. },
                fields,
            } => {
                let info = self.classes.info(*class)?;
                let name = &info.ident;
                let fields = fields
                    .iter()
                    .zip(&info.fields)
                    .map(|(operand, field)| {
                        let ident = &field.ident;
                        let value = self.operand(operand, Some(&field.ty))?;
                        Ok(quote! { #ident: #value })
                    })
                    .collect::<Result<Vec<_>, Rejection>>()?;
                quote! { shared(#name { #(#fields),* }) }
            }
            Rvalue::IsType {
                operand,
                test: TypeTest::Template(TyTemplate::Literal(literal, _)),
            } => {
                // Membership in a literal type is exact equality with the
                // value, which for these primitives is `==`.
                match literal {
                    Literal::Int(value_lit) => {
                        let value = self.operand(operand, None)?;
                        let expected = int_literal(*value_lit)?;
                        quote! { #value == #expected }
                    }
                    Literal::Bool(true) => self.operand(operand, None)?,
                    Literal::Bool(false) => {
                        let value = self.operand(operand, None)?;
                        quote! { !#value }
                    }
                    Literal::String(text) => {
                        let value = self.operand_ref(operand)?;
                        quote! { string::eq(#value, &string::from_literal(#text)) }
                    }
                    _ => return Err(Rejection::unsupported("type test other than a literal")),
                }
            }
            Rvalue::IsType {
                operand,
                test: TypeTest::Class { class, .. },
            } => {
                let value = self.operand_borrowed(operand)?;
                if self.operand_ty(operand)? == NativeTy::Thrown {
                    // A `catch` arm's class test, by the class's name.
                    let fqn = self.classes.link_name(TypeDecl::Class(*class));
                    quote! { bex_aot::thrown::is_class(&#value, #fqn) }
                } else {
                    // Admission only accepts the `baml.iter.Done` test on an
                    // `Option` otherwise.
                    quote! { #value.is_none() }
                }
            }
            other => return Err(Rejection::unsupported(format!("rvalue {other:?}"))),
        })
    }

    fn binary_op(
        &self,
        op: BinOp,
        left: &Operand<'db>,
        right: &Operand<'db>,
        left_ty: &NativeTy<'db>,
        right_ty: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let unsupported = || {
            Rejection::unsupported(format!(
                "`{op}` on `{}` and `{}`",
                self.describe(left_ty),
                self.describe(right_ty)
            ))
        };
        if matches!(left_ty, NativeTy::Bigint) || matches!(right_ty, NativeTy::Bigint) {
            return self.bigint_op(op, left, right, left_ty, right_ty);
        }
        Ok(match left_ty {
            NativeTy::Int => {
                let l = self.operand(left, None)?;
                let r = self.operand(right, None)?;
                match op {
                    BinOp::Add => self.fallible(&quote! { int::add(#l, #r) }),
                    BinOp::Sub => self.fallible(&quote! { int::sub(#l, #r) }),
                    BinOp::Mul => self.fallible(&quote! { int::mul(#l, #r) }),
                    BinOp::Div => self.fallible(&quote! { int::div(#l, #r) }),
                    BinOp::Mod => self.fallible(&quote! { int::rem(#l, #r) }),
                    BinOp::Shl => self.fallible(&quote! { int::shl(#l, #r) }),
                    BinOp::Shr => self.fallible(&quote! { int::shr(#l, #r) }),
                    BinOp::BitAnd => quote! { int::bit_and(#l, #r) },
                    BinOp::BitOr => quote! { int::bit_or(#l, #r) },
                    BinOp::BitXor => quote! { int::bit_xor(#l, #r) },
                    // Operands are locals or literal blocks, so no operator
                    // needs parentheses around them.
                    BinOp::Eq => quote! { #l == #r },
                    BinOp::Ne => quote! { #l != #r },
                    BinOp::Lt => quote! { #l < #r },
                    BinOp::Le => quote! { #l <= #r },
                    BinOp::Gt => quote! { #l > #r },
                    BinOp::Ge => quote! { #l >= #r },
                }
            }
            NativeTy::Float => {
                let l = self.operand(left, None)?;
                let r = self.operand(right, None)?;
                match op {
                    BinOp::Add => quote! { #l + #r },
                    BinOp::Sub => quote! { #l - #r },
                    BinOp::Mul => quote! { #l * #r },
                    BinOp::Div => quote! { #l / #r },
                    BinOp::Mod => quote! { #l % #r },
                    BinOp::Eq => quote! { float::eq(#l, #r) },
                    BinOp::Ne => quote! { !float::eq(#l, #r) },
                    BinOp::Lt => quote! { float::lt(#l, #r) },
                    BinOp::Le => quote! { float::le(#l, #r) },
                    BinOp::Gt => quote! { float::gt(#l, #r) },
                    BinOp::Ge => quote! { float::ge(#l, #r) },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Str => {
                let l = self.operand_ref(left)?;
                let r = self.operand_ref(right)?;
                match op {
                    BinOp::Add => quote! { string::concat(#l, #r) },
                    BinOp::Eq => quote! { string::eq(#l, #r) },
                    BinOp::Ne => quote! { !string::eq(#l, #r) },
                    BinOp::Lt => quote! { string::cmp(#l, #r).is_lt() },
                    BinOp::Le => quote! { string::cmp(#l, #r).is_le() },
                    BinOp::Gt => quote! { string::cmp(#l, #r).is_gt() },
                    BinOp::Ge => quote! { string::cmp(#l, #r).is_ge() },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Bool | NativeTy::Enum(_) => {
                let l = self.operand(left, None)?;
                let r = self.operand(right, None)?;
                match op {
                    BinOp::Eq => quote! { #l == #r },
                    BinOp::Ne => quote! { #l != #r },
                    _ => return Err(unsupported()),
                }
            }
            NativeTy::Null => match op {
                BinOp::Eq => quote! { true },
                BinOp::Ne => quote! { false },
                _ => return Err(unsupported()),
            },
            NativeTy::Option(_) => {
                // One side is the `null` constant: admission checked that.
                let value = if matches!(left, Operand::Constant(Constant::Null)) {
                    right
                } else {
                    left
                };
                let value = self.operand_borrowed(value)?;
                match op {
                    BinOp::Eq => quote! { #value.is_none() },
                    BinOp::Ne => quote! { #value.is_some() },
                    _ => return Err(unsupported()),
                }
            }
            // Handled above: a `bigint` on either side takes the bigint path.
            NativeTy::Bigint
            | NativeTy::Array(_)
            | NativeTy::Map(..)
            | NativeTy::Class(_)
            | NativeTy::ArrayIter(_)
            | NativeTy::Thrown => {
                return Err(unsupported());
            }
        })
    }

    /// A binary operation with a `bigint` on at least one side: the `int`
    /// side, if any, is widened first, and every operand is passed by
    /// reference (a `BigInt` is a counted pointer; the operation allocates
    /// its result).
    fn bigint_op(
        &self,
        op: BinOp,
        left: &Operand<'db>,
        right: &Operand<'db>,
        left_ty: &NativeTy<'db>,
        right_ty: &NativeTy<'db>,
    ) -> Result<TokenStream, Rejection> {
        let side = |operand: &Operand<'db>, ty: &NativeTy<'db>| -> Result<TokenStream, Rejection> {
            match ty {
                NativeTy::Bigint => self.operand_ref(operand),
                NativeTy::Int => {
                    let value = self.operand(operand, None)?;
                    Ok(quote! { &bigint::from_int(#value) })
                }
                other => Err(Rejection::unsupported(format!(
                    "`{op}` on `{}` and `{}`",
                    self.describe(left_ty),
                    self.describe(other)
                ))),
            }
        };
        let l = side(left, left_ty)?;
        let r = side(right, right_ty)?;
        Ok(match op {
            BinOp::Add => quote! { bigint::add(#l, #r) },
            BinOp::Sub => quote! { bigint::sub(#l, #r) },
            BinOp::Mul => self.fallible(&quote! { bigint::mul(#l, #r) }),
            BinOp::Div => self.fallible(&quote! { bigint::div(#l, #r) }),
            BinOp::Mod => self.fallible(&quote! { bigint::rem(#l, #r) }),
            BinOp::Shl => self.fallible(&quote! { bigint::shl(#l, #r) }),
            BinOp::Shr => self.fallible(&quote! { bigint::shr(#l, #r) }),
            BinOp::BitAnd => quote! { bigint::bit_and(#l, #r) },
            BinOp::BitOr => quote! { bigint::bit_or(#l, #r) },
            BinOp::BitXor => quote! { bigint::bit_xor(#l, #r) },
            BinOp::Eq => quote! { bigint::eq(#l, #r) },
            BinOp::Ne => quote! { !bigint::eq(#l, #r) },
            BinOp::Lt => quote! { bigint::cmp(#l, #r).is_lt() },
            BinOp::Le => quote! { bigint::cmp(#l, #r).is_le() },
            BinOp::Gt => quote! { bigint::cmp(#l, #r).is_gt() },
            BinOp::Ge => quote! { bigint::cmp(#l, #r).is_ge() },
        })
    }

    /// [`Self::operand_value`], then wrapped in `Some` when a `T` is passed
    /// where `expected` is `T | null`: a call argument, an aggregate field or
    /// an array element coerces by its operand type alone.
    fn operand(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty_with(operand, expected)?;
        let expr = self.operand_value(operand, expected)?;
        Ok(
            match expected.and_then(|expected| coercion(&ty, expected)) {
                Some(Coercion::Wrap) => quote! { Some(#expr) },
                Some(Coercion::Null) => quote! { None },
                _ => expr,
            },
        )
    }

    /// An owned value for `operand` as its own type: a copy of a scalar, a
    /// clone of a handle or string, or a literal. `expected` only decides
    /// whether a `null` constant is the `None` of an `Option` or the unit.
    fn operand_value(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<TokenStream, Rejection> {
        let ty = self.operand_ty_with(operand, expected)?;
        Ok(match operand {
            Operand::Copy(place) | Operand::Move(place) => {
                let expr = self.place(place)?;
                if ty.is_copy() || matches!(place, Place::Index { .. }) {
                    expr
                } else {
                    quote! { #expr.clone() }
                }
            }
            Operand::Constant(constant) => match constant {
                Constant::Int(value) => int_literal(*value)?,
                Constant::Bool(value) => quote! { #value },
                Constant::Float(value) => float_literal(*value),
                Constant::String(value) => quote! { string::from_literal(#value) },
                Constant::Bigint(value) => bigint_literal(value),
                Constant::Null => match expected {
                    Some(NativeTy::Option(_)) => quote! { None },
                    _ => quote! { () },
                },
                Constant::EnumVariant { enum_ref, index } => {
                    let info = self.classes.enum_info(*enum_ref)?;
                    let variant = usize::try_from(*index)
                        .ok()
                        .and_then(|index| info.variants.get(index))
                        .ok_or_else(|| {
                            Rejection::invalid(format!(
                                "enum `{}` has no variant {index}",
                                info.link_name
                            ))
                        })?;
                    let name = &info.ident;
                    let variant = &variant.ident;
                    quote! { #name::#variant }
                }
                other => return Err(Rejection::unsupported(format!("constant {other:?}"))),
            },
        })
    }

    /// `operand` as an expression that can be borrowed without cloning: the
    /// place itself, or a literal.
    fn operand_borrowed(&self, operand: &Operand<'db>) -> Result<TokenStream, Rejection> {
        match operand {
            Operand::Copy(place) | Operand::Move(place) => self.place(place),
            Operand::Constant(_) => self.operand(operand, None),
        }
    }

    /// A `&T` for `operand`.
    fn operand_ref(&self, operand: &Operand<'db>) -> Result<TokenStream, Rejection> {
        let value = self.operand_borrowed(operand)?;
        Ok(quote! { &#value })
    }

    fn operand_ty(&self, operand: &Operand<'db>) -> Result<NativeTy<'db>, Rejection> {
        self.operand_ty_with(operand, None)
    }

    fn operand_ty_with(
        &self,
        operand: &Operand<'db>,
        expected: Option<&NativeTy<'db>>,
    ) -> Result<NativeTy<'db>, Rejection> {
        match operand {
            Operand::Copy(place) | Operand::Move(place) => self.place_ty(place),
            Operand::Constant(Constant::Int(_)) => Ok(NativeTy::Int),
            Operand::Constant(Constant::Bool(_)) => Ok(NativeTy::Bool),
            Operand::Constant(Constant::Float(_)) => Ok(NativeTy::Float),
            Operand::Constant(Constant::String(_)) => Ok(NativeTy::Str),
            Operand::Constant(Constant::Bigint(_)) => Ok(NativeTy::Bigint),
            Operand::Constant(Constant::Null) => Ok(match expected {
                Some(option @ NativeTy::Option(_)) => option.clone(),
                _ => NativeTy::Null,
            }),
            Operand::Constant(Constant::EnumVariant { enum_ref, .. }) => {
                Ok(NativeTy::Enum(*enum_ref))
            }
            other @ Operand::Constant(_) => {
                Err(Rejection::unsupported(format!("operand {other:?}")))
            }
        }
    }

    fn kind(&self, local: Local) -> Result<&LocalKind<'db>, Rejection> {
        self.candidate
            .kinds
            .get(local.0)
            .ok_or_else(|| Rejection::invalid(format!("{local} is not declared")))
    }

    fn local_ty(&self, local: Local) -> Result<NativeTy<'db>, Rejection> {
        match self.kind(local)? {
            LocalKind::Value(ty) => Ok(ty.clone()),
            LocalKind::Never => Err(Rejection::unsupported("read of a `never` local")),
            LocalKind::Type => Err(Rejection::unsupported("type value used as a value")),
            LocalKind::Context => Err(Rejection::unsupported(
                "read of a caught error's `baml.errors.Context` (`catch (e, ctx)`)",
            )),
            LocalKind::Tag => Err(Rejection::unsupported("class tag used as a value")),
        }
    }

    fn place_ty(&self, place: &Place) -> Result<NativeTy<'db>, Rejection> {
        match place {
            Place::Local(local) => self.local_ty(*local),
            Place::Field { base, field } => {
                let class = base_ty(self, base)?;
                let info = self.classes.info(class)?;
                info.fields
                    .get(*field)
                    .map(|f| f.ty.clone())
                    .ok_or_else(|| Rejection::invalid(format!("no field slot {field}")))
            }
            Place::Index { base, kind, .. } => {
                if *kind == IndexKind::Map {
                    return Err(Rejection::unsupported("map index"));
                }
                match self.place_ty(base)? {
                    NativeTy::Array(element) => Ok(*element),
                    _ => Err(Rejection::invalid("index into a non-array")),
                }
            }
            Place::Capture(_) | Place::Deref(_) => Err(Rejection::unsupported("captured local")),
        }
    }

    /// The expression reading `place`, without cloning: a local (or, for an
    /// alias, its source place), a field through `borrow()`, or an indexed
    /// element (owned, via `array::get`).
    fn place(&self, place: &Place) -> Result<TokenStream, Rejection> {
        match place {
            Place::Local(local) => {
                self.local_ty(*local)?;
                if let Some(source) = self.candidate.aliases.get(local) {
                    return self.place(source);
                }
                let ident = local_ident(*local);
                Ok(quote! { #ident })
            }
            Place::Field { base, field } => {
                let class = base_ty(self, base)?;
                let field = self.field_ident(class, *field)?;
                let base = self.place(base)?;
                Ok(quote! { #base.borrow().#field })
            }
            Place::Index { base, index, kind } => {
                if *kind == IndexKind::Map {
                    return Err(Rejection::unsupported("map index"));
                }
                let base = self.place(base)?;
                let index = local_ident(*index);
                Ok(self.fallible(&quote! { array::get(&#base, #index) }))
            }
            Place::Capture(_) | Place::Deref(_) => Err(Rejection::unsupported("captured local")),
        }
    }

    /// A place that must be a plain local: a call or short-circuit
    /// destination.
    fn local_place(&self, place: &Place) -> Result<TokenStream, Rejection> {
        match place {
            Place::Local(local) => {
                self.kind(*local)?;
                let ident = local_ident(*local);
                Ok(quote! { #ident })
            }
            other => Err(Rejection::unsupported(format!(
                "call destination `{other}`"
            ))),
        }
    }

    fn field_ident(
        &self,
        class: baml_compiler2_hir_ty::extern_loc::ClassRef<'db>,
        field: usize,
    ) -> Result<Ident, Rejection> {
        let info = self.classes.info(class)?;
        info.fields
            .get(field)
            .map(|f| f.ident.clone())
            .ok_or_else(|| Rejection::invalid(format!("no field slot {field}")))
    }

    fn describe(&self, ty: &NativeTy<'db>) -> String {
        ty.describe(&|decl| self.classes.link_name(decl))
    }

    fn terminator(&self, block: BlockId) -> Result<&'a Terminator<'db>, Rejection> {
        self.candidate
            .body
            .blocks
            .get(block.0)
            .and_then(|block| block.terminator.as_ref())
            .ok_or_else(|| Rejection::invalid(format!("{block} has no terminator")))
    }

    /// The label of the merge block that leads into `block`. A block that
    /// also heads a loop keeps `'bbN` for the loop.
    fn block_label(&self, block: usize) -> Lifetime {
        if self.loop_headers.contains(&block) {
            Lifetime::new(&format!("'bb{block}_join"), Span::call_site())
        } else {
            Lifetime::new(&format!("'bb{block}"), Span::call_site())
        }
    }
}

/// The class a field place's base holds.
fn base_ty<'db>(
    printer: &Printer<'_, 'db>,
    base: &Place,
) -> Result<baml_compiler2_hir_ty::extern_loc::ClassRef<'db>, Rejection> {
    match printer.place_ty(base)? {
        NativeTy::Class(class) => Ok(class),
        other => Err(Rejection::invalid(format!(
            "field access on a `{}`",
            printer.describe(&other)
        ))),
    }
}

fn loop_label(block: usize) -> Lifetime {
    Lifetime::new(&format!("'bb{block}"), Span::call_site())
}

fn collect_loop_headers(stmts: &[Stmt], out: &mut FxHashSet<usize>) {
    for stmt in stmts {
        match stmt {
            Stmt::Loop { label, body } => {
                out.insert(*label);
                collect_loop_headers(body, out);
            }
            Stmt::Block { body, .. } => collect_loop_headers(body, out),
            Stmt::If {
                then_branch,
                else_branch,
                ..
            } => {
                collect_loop_headers(then_branch, out);
                collect_loop_headers(else_branch, out);
            }
            Stmt::Switch {
                arms, otherwise, ..
            } => {
                for (_, body) in arms {
                    collect_loop_headers(body, out);
                }
                collect_loop_headers(otherwise, out);
            }
            Stmt::Leaf(_)
            | Stmt::Break(_)
            | Stmt::BreakLoop(_)
            | Stmt::Continue(_)
            | Stmt::Exit(_) => {}
        }
    }
}

fn local_ident(local: Local) -> Ident {
    format_ident!("_{}", local.0)
}

/// An `int` literal, range-checked here; `int::lit` is a `const fn` the
/// optimizer folds to the constant.
fn int_literal(value: i64) -> Result<TokenStream, Rejection> {
    if baml_type::Int63::new(value).is_none() {
        return Err(Rejection::unsupported(format!(
            "int literal {value} is outside the int range"
        )));
    }
    let literal = proc_macro2::Literal::i64_unsuffixed(value);
    Ok(quote! { int::lit(#literal) })
}

/// A `bigint` literal: from an `i64` when it fits, else parsed from its
/// decimal digits.
fn bigint_literal(value: &num_bigint::BigInt) -> TokenStream {
    match i64::try_from(value) {
        Ok(small) => {
            let literal = proc_macro2::Literal::i64_unsuffixed(small);
            quote! { bigint::from_i64(#literal) }
        }
        Err(_) => {
            let digits = value.to_string();
            quote! { bigint::lit(#digits) }
        }
    }
}

/// A `float` literal that round-trips: `{:?}` of the value with an `f64`
/// suffix, or the `f64` constants for the non-finite values.
fn float_literal(value: f64) -> TokenStream {
    if value.is_nan() {
        quote! { f64::NAN }
    } else if value == f64::INFINITY {
        quote! { f64::INFINITY }
    } else if value == f64::NEG_INFINITY {
        quote! { f64::NEG_INFINITY }
    } else {
        let text = format!("{value:?}_f64");
        let literal: proc_macro2::Literal = text
            .trim_start_matches('-')
            .parse()
            .expect("a finite f64 debug rendering is a Rust float literal");
        if value.is_sign_negative() {
            quote! { (-#literal) }
        } else {
            quote! { #literal }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bigint_literals_prefer_i64() {
        assert_eq!(
            bigint_literal(&num_bigint::BigInt::from(-5)).to_string(),
            "bigint :: from_i64 (- 5)"
        );
        let wide: num_bigint::BigInt = "123456789012345678901234567890".parse().unwrap();
        assert_eq!(
            bigint_literal(&wide).to_string(),
            "bigint :: lit (\"123456789012345678901234567890\")"
        );
    }

    #[test]
    fn float_literals_round_trip() {
        assert_eq!(float_literal(1.0).to_string(), "1.0_f64");
        assert_eq!(float_literal(-2.5).to_string(), "(- 2.5_f64)");
        assert_eq!(float_literal(1e300).to_string(), "1e300_f64");
        assert_eq!(float_literal(f64::NAN).to_string(), "f64 :: NAN");
        assert_eq!(
            float_literal(f64::NEG_INFINITY).to_string(),
            "f64 :: NEG_INFINITY"
        );
        assert_eq!(float_literal(-0.0).to_string(), "(- 0.0_f64)");
    }
}
