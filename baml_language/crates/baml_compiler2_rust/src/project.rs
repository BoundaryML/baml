//! A standalone Cargo project around a [`NativeModule`]: the generated
//! library, a host binary that parses the entry function's arguments, and
//! the MIR the code was generated from.

use std::{fmt::Write as _, path::Path};

use proc_macro2::TokenStream;
use quote::{format_ident, quote};

use crate::{NativeModule, Scalar, print::render_rust_file};

/// How [`write_project`] lays out the generated crate.
#[derive(Debug, Clone)]
pub struct ProjectOptions<'a> {
    /// The generated package's name; also its binary's name.
    pub crate_name: &'a str,
    /// Where the `bex_lang` runtime crate lives; written as a path dependency.
    pub runtime_path: &'a Path,
    /// Whether to pin the release profile to `opt-level = 3`, fat LTO and one
    /// codegen unit. Off, the project builds with Cargo's defaults.
    pub release_profile: bool,
}

/// Write `module` as a Cargo project under `out_dir`:
///
/// - `Cargo.toml`: its own workspace, depending on `bex_lang` by path;
/// - `src/lib.rs`: the generated module;
/// - `src/main.rs`: a host shim that parses `--<param> <value>` flags for the
///   entry function, prints its result, and exits with the panic's exit code
///   on an uncaught throw;
/// - `mir.txt`: the MIR the module was generated from.
pub fn write_project(
    module: &NativeModule<'_>,
    out_dir: &Path,
    options: &ProjectOptions<'_>,
) -> std::io::Result<()> {
    let src = out_dir.join("src");
    std::fs::create_dir_all(&src)?;
    std::fs::write(out_dir.join("Cargo.toml"), manifest(options))?;
    std::fs::write(src.join("lib.rs"), &module.rust_source)?;
    std::fs::write(src.join("main.rs"), host_shim(module, options)?)?;
    std::fs::write(out_dir.join("mir.txt"), &module.mir_dump)?;
    Ok(())
}

fn manifest(options: &ProjectOptions<'_>) -> String {
    let mut text = format!(
        "[package]\nname = {name}\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n\
         [workspace]\n\n\
         [dependencies]\nbex_lang = {{ path = {runtime} }}\n",
        name = toml_string(options.crate_name),
        runtime = toml_string(&options.runtime_path.to_string_lossy()),
    );
    if options.release_profile {
        text.push_str("\n[profile.release]\nopt-level = 3\nlto = \"fat\"\ncodegen-units = 1\n");
    }
    text
}

/// A TOML basic string: quotes, backslashes and control characters escaped.
fn toml_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                let _ = write!(out, "\\u{:04X}", c as u32);
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

const SHIM_HEADER: &str = "\
//! Host shim generated by `baml_compiler2_rust`. Do not edit.
#![allow(unused_mut, unused_variables, dead_code, clippy::all)]
";

/// The std-only `main.rs`: `--<param> <value>` flags in any order, `--help`,
/// `error: ...` on stderr with exit 1 for bad input, the entry function's
/// result on stdout, and `error: uncaught throw: ...` plus the panic's exit
/// code when it throws.
fn host_shim(module: &NativeModule<'_>, options: &ProjectOptions<'_>) -> std::io::Result<String> {
    let entry = module
        .functions
        .get(module.entry)
        .ok_or_else(|| std::io::Error::other("module entry index is out of range"))?;
    let crate_ident = format_ident!("{}", options.crate_name.replace('-', "_"));
    let function = format_ident!("{}", entry.rust_name);

    let usage = {
        let mut text = format!("usage: {}", options.crate_name);
        for (name, scalar) in &entry.params {
            let kind = match scalar {
                Scalar::Int => "int",
                Scalar::Bool => "bool",
            };
            let _ = write!(text, " --{name} <{kind}>");
        }
        text
    };

    let slots: Vec<TokenStream> = entry
        .params
        .iter()
        .enumerate()
        .map(|(index, (_, scalar))| {
            let slot = format_ident!("arg_{index}");
            let ty = scalar_type(*scalar);
            quote! { let mut #slot: Option<#ty> = None; }
        })
        .collect();
    let arms: Vec<TokenStream> = entry
        .params
        .iter()
        .enumerate()
        .map(|(index, (name, scalar))| {
            let slot = format_ident!("arg_{index}");
            let flag = format!("--{name}");
            let parser = match scalar {
                Scalar::Int => quote! { parse_int },
                Scalar::Bool => quote! { parse_bool },
            };
            quote! { #flag => #slot = Some(#parser(#name, value)), }
        })
        .collect();
    let required: Vec<TokenStream> = entry
        .params
        .iter()
        .enumerate()
        .map(|(index, (name, _))| {
            let slot = format_ident!("arg_{index}");
            let value = format_ident!("value_{index}");
            let message = format!("missing required argument `--{name}`");
            quote! { let Some(#value) = #slot else { fail(#message) }; }
        })
        .collect();
    let values = (0..entry.params.len()).map(|index| format_ident!("value_{index}"));
    let print = match entry.ret {
        Some(_) => quote! { Ok(value) => println!("{value}"), },
        None => quote! { Ok(()) => {} },
    };

    let tokens = quote! {
        const USAGE: &str = #usage;

        fn fail(message: &str) -> ! {
            eprintln!("error: {message}");
            std::process::exit(1)
        }

        fn parse_int(name: &str, value: &str) -> bex_lang::Int63 {
            let parsed: i64 = match value.parse() {
                Ok(parsed) => parsed,
                Err(_) => fail(&format!("argument `--{name}` expects an int, got `{value}`")),
            };
            match bex_lang::int::check(parsed) {
                Ok(checked) => checked,
                Err(panic) => fail(&format!("argument `--{name}`: {}", panic.render_readable())),
            }
        }

        fn parse_bool(name: &str, value: &str) -> bool {
            match value {
                "true" => true,
                "false" => false,
                _ => fail(&format!(
                    "argument `--{name}` expects `true` or `false`, got `{value}`"
                )),
            }
        }

        fn main() {
            let args: Vec<String> = std::env::args().skip(1).collect();
            #(#slots)*
            let mut index = 0;
            while index < args.len() {
                let flag = args[index].as_str();
                if flag == "--help" || flag == "-h" {
                    println!("{USAGE}");
                    return;
                }
                index += 1;
                let Some(value) = args.get(index) else {
                    fail(&format!("missing value for `{flag}`"))
                };
                match flag {
                    #(#arms)*
                    _ => fail(&format!("unknown argument `{flag}`")),
                }
                index += 1;
            }
            #(#required)*
            match #crate_ident::#function(#(#values),*) {
                #print
                Err(panic) => {
                    eprintln!("error: uncaught throw: {}", panic.render_readable());
                    std::process::exit(panic.exit_code());
                }
            }
        }
    };
    render_rust_file(SHIM_HEADER, tokens).map_err(|error| std::io::Error::other(error.to_string()))
}

fn scalar_type(scalar: Scalar) -> TokenStream {
    match scalar {
        Scalar::Int => quote! { bex_lang::Int63 },
        Scalar::Bool => quote! { bool },
    }
}
