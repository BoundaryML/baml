use std::{path::PathBuf, str::FromStr};

use baml_surface::{Resolved, SymbolId};
use serde::{Deserialize, Serialize};
use sha2::Digest as _;

use crate::{ProjectSession, ToolingError};

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Target {
    Node,
    Web,
}

impl Target {
    pub(crate) fn as_str(self) -> &'static str {
        match self {
            Self::Node => "node",
            Self::Web => "web",
        }
    }

    fn runtime_package(self) -> &'static str {
        match self {
            Self::Node => "@boundaryml/baml-bridge",
            Self::Web => "@boundaryml/baml-bridge-web",
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(tag = "kind", content = "path", rename_all = "lowercase")]
pub enum EntrySpec {
    File(PathBuf),
    Client,
}

impl EntrySpec {
    pub(crate) fn cache_key(&self) -> String {
        match self {
            Self::File(path) => path.to_string_lossy().into_owned(),
            Self::Client => "baml:client".to_string(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum SegmentRole {
    Declaration,
    Reference,
    Type,
    Documentation,
    Synthetic,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct Segment {
    pub gen_start_utf16: u32,
    pub gen_length_utf16: u32,
    pub source_file: u32,
    pub source_start_utf8: u32,
    pub source_length_utf8: u32,
    pub symbol_id: String,
    pub signature_id: Option<String>,
    pub role: SegmentRole,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SegmentMap {
    pub version: u32,
    pub generated_file: String,
    pub sources: Vec<PathBuf>,
    pub source_hashes: Vec<String>,
    pub segments: Vec<Segment>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct VirtualModule {
    pub id: String,
    pub runtime_id: String,
    pub code: String,
    pub declaration: String,
    pub map: SegmentMap,
    pub watch_files: Vec<PathBuf>,
    pub fingerprint: String,
    pub revision: u64,
    pub stale: bool,
}

impl VirtualModule {
    pub(crate) fn poison(id: String, revision: u64, fingerprint: String) -> Self {
        Self {
            runtime_id: String::new(),
            code: "const unavailable = new Proxy({}, { get() { throw new Error('BAML project has compiler errors'); } });\nexport const b = unavailable;\n".to_string(),
            declaration: "declare const unavailable: { readonly [name: string]: never };\nexport { unavailable as b };\n".to_string(),
            map: SegmentMap {
                version: 1,
                generated_file: id.clone(),
                sources: Vec::new(),
                source_hashes: Vec::new(),
                segments: Vec::new(),
            },
            id,
            watch_files: Vec::new(),
            fingerprint,
            revision,
            stale: true,
        }
    }

    pub fn into_generated(self) -> GeneratedFile {
        GeneratedFile {
            path: PathBuf::from(self.id),
            contents: self.declaration,
            map: self.map,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct GeneratedFile {
    pub path: PathBuf,
    pub contents: String,
    pub map: SegmentMap,
}

pub(crate) fn emit_virtual_module(session: &ProjectSession, entry: &EntrySpec) -> VirtualModule {
    let id = entry.cache_key();
    let runtime_id = format!("\0baml:{}:runtime", session.project_id());
    let exports = session.filtered_exports(entry);
    let banner = format!(
        "// Generated by BAML tooling.v1. Do not edit.\n\
         // baml-fingerprint: {}\n\n",
        session.fingerprint()
    );
    let pool = baml_project::build_symbol_pool(&session.db);
    let emitted = sdkgen_typescript_shared::emit_tooling_module(
        &pool,
        &exports,
        &runtime_id,
        session.target.runtime_package(),
        &banner,
    );
    let mut sources = Vec::new();
    let mut source_hashes = Vec::new();
    for file in session.db.get_source_files() {
        sources.push(file.path(&session.db));
        let digest = sha2::Sha256::digest(file.text(&session.db).as_bytes());
        source_hashes.push(hex::encode(digest));
    }
    let segments = emitted
        .spans
        .into_iter()
        .filter_map(|span| segment_for_span(session, &sources, span))
        .collect();

    VirtualModule {
        id: id.clone(),
        runtime_id,
        code: emitted.code,
        declaration: emitted.declaration,
        map: SegmentMap {
            version: 1,
            generated_file: id,
            sources,
            source_hashes,
            segments,
        },
        watch_files: session.watch_files(),
        fingerprint: session.fingerprint(),
        revision: session.revision(),
        stale: false,
    }
}

fn segment_for_span(
    session: &ProjectSession,
    sources: &[PathBuf],
    span: sdkgen_typescript_shared::ToolingMappedSpan,
) -> Option<Segment> {
    let id = SymbolId::from_str(&span.symbol_id).ok()?;
    let resolved = id.resolve(&session.db)?;
    let (file, range) = match resolved {
        Resolved::Symbol(symbol) => (symbol.file(&session.db), symbol.name_span(&session.db)?),
        Resolved::Member(owner, member) => (owner.file(&session.db), member.name_span(&session.db)),
        Resolved::Package(_) | Resolved::Namespace(_) => return None,
    };
    let path = file.path(&session.db);
    let source_file = sources.iter().position(|source| source == &path)?;
    Some(Segment {
        gen_start_utf16: span.start_utf16,
        gen_length_utf16: span.length_utf16,
        source_file: u32::try_from(source_file)
            .expect("BAML tooling source table exceeds u32 entries"),
        source_start_utf8: range.start().into(),
        source_length_utf8: u32::from(range.len()),
        symbol_id: span.symbol_id,
        signature_id: None,
        role: match span.role {
            sdkgen_typescript_shared::ToolingDeclarationRole::Declaration => {
                SegmentRole::Declaration
            }
            sdkgen_typescript_shared::ToolingDeclarationRole::Type => SegmentRole::Type,
            sdkgen_typescript_shared::ToolingDeclarationRole::Documentation => {
                SegmentRole::Documentation
            }
            sdkgen_typescript_shared::ToolingDeclarationRole::Synthetic => SegmentRole::Synthetic,
        },
    })
}

pub(crate) fn emit_runtime_module(session: &ProjectSession) -> Result<String, ToolingError> {
    let program = session
        .db
        .get_bytecode()
        .map_err(|error| ToolingError::Bytecode(error.to_string()))?;
    let bytes =
        borsh::to_vec(&program).map_err(|error| ToolingError::Bytecode(error.to_string()))?;
    let package = session.target.runtime_package();
    // Embed the host's `baml.toml` snapshot so the direct-import runtime is
    // configured exactly like the canonical generated SDK, which initializes
    // from bytecode plus the inlined manifest. Class payloads stay
    // structural (plain objects) by design: the runtime falls back to
    // structural decode when no typemap is installed, and the declaration
    // projection models classes as interfaces, so the two agree.
    let initialize = if session.config_text().is_empty() {
        "initializeRuntimeFromBytecode(bytecode);".to_string()
    } else {
        format!(
            "initializeRuntimeFromBytecode(bytecode, {});",
            sdkgen_typescript_shared::ts_string(session.config_text())
        )
    };
    Ok(format!(
        "import {{ defineFunction, initializeRuntimeFromBytecode }} from {};\nconst bytecode = new Uint8Array({bytes:?});\n{initialize}\nexport {{ defineFunction }};\n",
        sdkgen_typescript_shared::ts_string(package)
    ))
}
