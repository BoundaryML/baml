#[test]
fn bridge_surfaces_bytecode_skew_without_generated_metadata() {
    bridge_cffi::register_bridge(bridge_cffi::BridgeInfo {
        language: bridge_cffi::BridgeLanguage::Python,
        bridge_runtime_name: "baml-bridge-test".to_owned(),
        bridge_runtime_version: baml_version::CANONICAL_VERSION.to_owned(),
        toolchain_version: baml_version::CANONICAL_VERSION.to_owned(),
    })
    .unwrap();

    let bytecode = baml_artifact::encode_with_format_for_test(
        baml_artifact::FORMAT_VERSION + 1,
        baml_artifact::ArtifactKind::Program,
        &7_u32,
    )
    .unwrap();

    let Err(error) = bridge_cffi::initialize_runtime_from_bytecode(&bytecode, None) else {
        panic!("format-skewed bytecode must fail");
    };
    assert_eq!(
        error.to_string(),
        format!(
            "BAML startup failed: generated SDK bytecode could not be loaded.\n\n`baml_sdk` could not be loaded by baml-bridge-test {}: Failed to deserialize BAML bytecode: generated bytecode: toolchain {} / format {}; this runtime: {} / format {} — regenerate baml_sdk and rebuild the bridge from the same commit",
            baml_version::CANONICAL_VERSION,
            baml_artifact::BUILD_FINGERPRINT,
            baml_artifact::FORMAT_VERSION + 1,
            baml_artifact::BUILD_FINGERPRINT,
            baml_artifact::FORMAT_VERSION,
        )
    );
}
