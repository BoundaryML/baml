//! The hash of everything codegen reads.
//!
//! Bridge staleness is decided by comparing *inputs*, never by regenerating
//! and diffing output. Two consequences follow, and both are the point:
//!
//! - **Codegen determinism stops mattering.** A `gofmt` upgrade that reflows
//!   generated code leaves the inputs untouched, so the check stays quiet. A
//!   `git diff` guard false-positives there; this does not. (Go codegen genuinely
//!   is not byte-deterministic — it shells out to the host `gofmt`.)
//! - **No compile is needed to check.** Hashing source text is milliseconds,
//!   which keeps `--check` viable in a pre-commit hook and keeps the passive
//!   check off the `baml check` latency budget.
//!
//! What is deliberately *excluded* is as load-bearing as what is included:
//!
//! - **Generator config** (`output_type`, `naming_convention`, …) is already
//!   inside `baml.toml`, which is hashed verbatim. Because
//!   `build_embedded_baml_toml` embeds `baml.toml` byte-for-byte into every
//!   bridge, even a comment-only edit really does change the generated bytes,
//!   so whole-file hashing is exact rather than over-broad.
//! - **`output_dir` / `-o`** does not affect content, so an override must not
//!   invalidate a bridge.
//! - **The toolchain version** is stored as its own manifest field and compared
//!   directly, so version skew reports "generated by 0.14.2, this toolchain is
//!   0.15.0" instead of an opaque hash mismatch.

use std::path::Path;

use anyhow::{Context, Result};
use sha2::{Digest, Sha256};

/// Bumped if the framing below ever changes, so an old fingerprint can never
/// be mistaken for a new one computed a different way.
const FINGERPRINT_DOMAIN: &[u8] = b"baml-bridge-input-fingerprint-v1";

/// The codegen inputs, read but not yet hashed.
pub(crate) struct Inputs {
    /// `baml.toml`'s verbatim bytes, or `None` for a manifest-less project.
    manifest: Option<Vec<u8>>,
    /// `.baml` sources as (project-relative, `/`-separated path, contents),
    /// sorted by path.
    sources: Vec<(String, Vec<u8>)>,
}

impl Inputs {
    /// Read every codegen input under `source_root`, naming each file
    /// relative to `root`.
    ///
    /// `root` and `source_root` must come from the same project layout the
    /// compiler uses (`baml_src/` when present, else the project root), or
    /// the fingerprint would cover a different file set than codegen reads.
    pub(crate) fn read(root: &Path, source_root: &Path) -> Result<Self> {
        let manifest_path = root.join("baml.toml");
        let manifest = match std::fs::read(&manifest_path) {
            Ok(bytes) => Some(bytes),
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => None,
            Err(error) => {
                return Err(error)
                    .with_context(|| format!("failed to read {}", manifest_path.display()));
            }
        };

        let mut sources = Vec::new();
        for path in baml_workspace::discover_baml_files(source_root) {
            let contents = std::fs::read(&path)
                .with_context(|| format!("failed to read {}", path.display()))?;
            sources.push((relative_name(&path, root, source_root), contents));
        }
        // `discover_baml_files` sorts by absolute path; re-sort by the
        // relative name actually being hashed so the order cannot depend on
        // where the project happens to live.
        sources.sort_by(|(left, _), (right, _)| left.cmp(right));

        Ok(Self { manifest, sources })
    }

    /// The fingerprint as lowercase hex.
    ///
    /// Every field is length-framed, so `("ab", "c")` cannot hash the same as
    /// `("a", "bc")` — without framing, renaming a file could be cancelled out
    /// by an edit to its contents.
    pub(crate) fn fingerprint(&self) -> String {
        let mut hasher = Sha256::new();
        feed(&mut hasher, FINGERPRINT_DOMAIN);
        match &self.manifest {
            Some(bytes) => {
                feed(&mut hasher, b"manifest");
                feed(&mut hasher, bytes);
            }
            // Distinguished from an empty `baml.toml`, which frames as a
            // present field of length zero.
            None => feed(&mut hasher, b"no-manifest"),
        }
        feed(&mut hasher, &(self.sources.len() as u64).to_le_bytes());
        for (path, contents) in &self.sources {
            feed(&mut hasher, path.as_bytes());
            feed(&mut hasher, contents);
        }
        format!("{:x}", hasher.finalize())
    }

    /// Take the inputs from a project the caller has already loaded.
    ///
    /// `generate` compiles from a [`ResolvedProject`], so fingerprinting that
    /// same value is what makes the recorded hash describe the files codegen
    /// actually read. Re-deriving the layout from the settings root instead
    /// would disagree whenever `--project` names a source tree that is not
    /// `root/baml_src` — the bridge would then be reported out of date
    /// immediately after being generated, forever.
    ///
    /// Framing is shared with [`Inputs::read`], so a project fingerprinted
    /// from memory here and from disk by a later `--check` agrees.
    pub(crate) fn from_resolved(resolved: &crate::project_load::ResolvedProject) -> Self {
        let mut sources: Vec<(String, Vec<u8>)> = resolved
            .files
            .iter()
            .map(|(path, contents)| {
                (
                    relative_name(path, &resolved.root, &resolved.source_root),
                    contents.as_bytes().to_vec(),
                )
            })
            .collect();
        sources.sort_by(|(left, _), (right, _)| left.cmp(right));
        Self {
            manifest: resolved
                .manifest
                .as_ref()
                .map(|manifest| manifest.as_bytes().to_vec()),
            sources,
        }
    }
}

/// Compute the fingerprint for a project layout in one step, reading from disk.
pub(crate) fn compute(root: &Path, source_root: &Path) -> Result<String> {
    Ok(Inputs::read(root, source_root)?.fingerprint())
}

fn feed(hasher: &mut Sha256, field: &[u8]) {
    hasher.update((field.len() as u64).to_le_bytes());
    hasher.update(field);
}

/// Name a source file portably: relative to the project root when it lives
/// under it, else relative to the source root. `/`-separated so a fingerprint
/// computed on Windows matches one from Unix.
fn relative_name(path: &Path, root: &Path, source_root: &Path) -> String {
    let relative = path
        .strip_prefix(root)
        .or_else(|_| path.strip_prefix(source_root))
        .unwrap_or(path);
    relative
        .components()
        .map(|component| component.as_os_str().to_string_lossy())
        .collect::<Vec<_>>()
        .join("/")
}

#[cfg(test)]
mod tests {
    use std::fs;

    use super::*;

    /// A project with `baml.toml` and the given `baml_src` files.
    fn project(manifest: Option<&str>, files: &[(&str, &str)]) -> tempfile::TempDir {
        let dir = tempfile::tempdir().unwrap();
        if let Some(manifest) = manifest {
            fs::write(dir.path().join("baml.toml"), manifest).unwrap();
        }
        let source_root = dir.path().join("baml_src");
        fs::create_dir_all(&source_root).unwrap();
        for (name, contents) in files {
            let path = source_root.join(name);
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent).unwrap();
            }
            fs::write(path, contents).unwrap();
        }
        dir
    }

    fn fingerprint_of(dir: &tempfile::TempDir) -> String {
        compute(dir.path(), &dir.path().join("baml_src")).unwrap()
    }

    #[test]
    fn identical_inputs_hash_identically() {
        let manifest = "[package]\nname = \"test\"\n";
        let files = [("a.baml", "class A {}"), ("b.baml", "class B {}")];

        assert_eq!(
            fingerprint_of(&project(Some(manifest), &files)),
            fingerprint_of(&project(Some(manifest), &files))
        );
    }

    #[test]
    fn editing_a_source_changes_the_fingerprint() {
        let manifest = "[package]\nname = \"test\"\n";

        assert_ne!(
            fingerprint_of(&project(Some(manifest), &[("a.baml", "class A {}")])),
            fingerprint_of(&project(Some(manifest), &[("a.baml", "class A { x int }")]))
        );
    }

    /// `baml.toml` is embedded verbatim into every bridge, so even a
    /// comment-only edit changes the generated bytes.
    #[test]
    fn editing_the_manifest_changes_the_fingerprint() {
        let files = [("a.baml", "class A {}")];

        assert_ne!(
            fingerprint_of(&project(Some("[package]\nname = \"test\"\n"), &files)),
            fingerprint_of(&project(
                Some("# a comment\n[package]\nname = \"test\"\n"),
                &files
            ))
        );
    }

    #[test]
    fn renaming_a_source_changes_the_fingerprint() {
        let manifest = "[package]\nname = \"test\"\n";

        assert_ne!(
            fingerprint_of(&project(Some(manifest), &[("a.baml", "class A {}")])),
            fingerprint_of(&project(Some(manifest), &[("b.baml", "class A {}")]))
        );
    }

    #[test]
    fn adding_and_deleting_sources_changes_the_fingerprint() {
        let manifest = "[package]\nname = \"test\"\n";
        let one = fingerprint_of(&project(Some(manifest), &[("a.baml", "class A {}")]));
        let two = fingerprint_of(&project(
            Some(manifest),
            &[("a.baml", "class A {}"), ("b.baml", "class B {}")],
        ));

        assert_ne!(one, two);
    }

    /// Without length framing, moving a byte across the path/contents
    /// boundary would leave the hash unchanged.
    #[test]
    fn framing_separates_path_from_contents() {
        let manifest = "[package]\nname = \"test\"\n";

        assert_ne!(
            fingerprint_of(&project(Some(manifest), &[("ab.baml", "c")])),
            fingerprint_of(&project(Some(manifest), &[("a.baml", "bc")]))
        );
    }

    /// A truncated file must not hash as its full version.
    #[test]
    fn truncation_changes_the_fingerprint() {
        let manifest = "[package]\nname = \"test\"\n";

        assert_ne!(
            fingerprint_of(&project(Some(manifest), &[("a.baml", "class A {}")])),
            fingerprint_of(&project(Some(manifest), &[("a.baml", "")]))
        );
    }

    /// A missing `baml.toml` must not collide with an empty one.
    #[test]
    fn absent_manifest_differs_from_empty_manifest() {
        let files = [("a.baml", "class A {}")];

        assert_ne!(
            fingerprint_of(&project(None, &files)),
            fingerprint_of(&project(Some(""), &files))
        );
    }

    /// The fingerprint must not depend on where the project is checked out.
    #[test]
    fn fingerprint_is_independent_of_the_project_location() {
        let manifest = "[package]\nname = \"test\"\n";
        let files = [("nested/deep.baml", "class A {}"), ("a.baml", "class B {}")];
        let first = project(Some(manifest), &files);
        let second = project(Some(manifest), &files);

        assert_ne!(first.path(), second.path());
        assert_eq!(fingerprint_of(&first), fingerprint_of(&second));
    }

    #[test]
    fn relative_names_are_slash_separated_and_root_anchored() {
        let root = Path::new("/tmp/project");
        let source_root = root.join("baml_src");

        assert_eq!(
            relative_name(
                &source_root.join("nested").join("a.baml"),
                root,
                &source_root
            ),
            "baml_src/nested/a.baml"
        );
    }

    /// A source tree outside the project root still gets a portable name.
    #[test]
    fn sources_outside_the_root_are_named_relative_to_the_source_root() {
        let root = Path::new("/tmp/project");
        let source_root = Path::new("/tmp/elsewhere");

        assert_eq!(
            relative_name(&source_root.join("a.baml"), root, source_root),
            "a.baml"
        );
    }
}
