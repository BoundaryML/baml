/// Type simplification for SAP attributes.
/// Type simplification converts `baml_type::RuntimeTy` to another `baml_type::RuntimeTy`, for the purpose of cleaning the type to make it easier for SAP to process. It
///
/// - Inlines type aliases where possible
/// - Moves the `null` type in a Union to the last-variant position
/// - Factors out attributes from unions, or distributes attributes into the unions, as appropriate for the attribute.
/// - Removes duplicate elements from variants (for some definition of "duplicate" that involves subtype subsumption and resolving aliases)
///
/// The rules vary by the Type (whether it's a simple type, a class, a type alias, etc), the context in which the Type is used (in a class field or at the top level), and the attributes present at the top level and at levels nested underneath the type. We'll try to cover all the important combinations below.
///
/// In each example, the input is shown on the left of `==S()==>` and the simplified result on the right. The input may be either directly user-generated syntax, or syntax generated by the compiler when producing streaming variants of types.
///
/// ### TopLevel Attributes
///
/// The metadata on each type are shown without their `@sap.` prefixes for brevity. `(def)` is occasionally used for brevity to stand for the default metadata `(Unset, Unset, Unset)`
///
/// Basic types, No Attributes
///
/// ```baml
/// int
///   parse_without_null: Unset,
///   pending_never: Unset,
///   in_progress_never: Unset,
/// ==S()==>
/// int
///   parse_without_null: Unset,
///   pending_never: Unset,
///   in_progress_never: Unset,
/// ```
///
/// ```baml
/// string (def)
/// ==S()==>
/// string (def)
/// ```
///
///  Classes, No Attributes
///
/// ```baml
/// MyClass (def)
/// ==S()==>
/// MyClass (def)
/// ```
///
/// Unions, No Attributes
///
/// ```baml
/// MyA (def) | int (def)
/// ==S()==>
/// MyA (def) | int (def)
/// ```
///
/// ---
///
/// ```baml
/// int |
///   (def)
/// ==S()==>
/// int
///   (def)
/// ```
///
/// Singleton unions get unwrapped if they somehow get created.
///
/// ---
///
/// Unions with comparable variants
///
/// ```baml
/// int
///     (def)
/// | int
///     (def)
/// ==S()==>
/// int
///     (def)
/// ```
///
/// The first interesting case. A union of two identical types with identical metadata is flattened to a smaller union with one variant, then the single variant is unwrapped.
///
/// ---
///
/// ```baml
/// int
///     (def)
/// | 5
///     (def)
/// ==S()==>
/// int
///     (def)
/// ```
///
/// The variant with type `5` is removed because when removing duplicates, we check subsumption rather than strict equality.
///
/// ---
///
/// Unions with `@sap.parse_without_null` attributes
///
/// ```baml
/// int
///     parse_without_null: Set,
///     pending_never: Unset,
///     in_progress_never: Unset
/// | int
///     (def)
/// ==S()==>
/// int
///     parse_without_null: Unset,
///     pending_never: Unset,
///     in_progress_never: Unset,
/// ```
///
/// Two types that are different on in metadata may be considered different from the perspective of deduplication. Here the `parse_without_null:Unset` is a supertype of the `parse_without_null:Set` variant, so the latter is removed during variant deduplication, and the result is unwrapped (because only one variant remains)
///
/// ---
///
/// Unions of unions
///
/// ```baml
/// (int (def)|bool (def))|float (def)
/// ==S()==>
/// int(def) | bool(def) | float (def)
/// ```
///
/// Nested unions are flattened into a single union.
///
/// I omitted the metadata. `(def)` means: the default metadata, to save space in this example.
///
/// Note that flattening generally happens before deduplication. In this simple example there is no deduplication to do.
///
/// ---
///
/// `null` normalization
///
/// ```baml
/// null(def) | int(def)
/// ==S()==>
/// int(def) | null(def)
/// ```
///
/// `null` variant in a union gets pushed to the end
///
/// ---
///
/// ```baml
/// int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// ==S()==>
/// int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// ```
///
/// `parse_as` on basic types is passed through directly to the output type.
///
/// ---
///
/// ```baml
/// int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset
/// ==S()==>
/// int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// ```
///
/// `@sap.pending_never` and `@sap.in_progress_never` on simple (non-union) types are carried over directly during type simplification.
///
/// ---
///
/// ```baml
/// int
///     parse_without_null: Unset,
///     pending_never: Set,
///     in_progress_never: Unset,
/// | int
///     parse_without_null: Unset,
///     pending_never: Set,
///     in_progress_never: Unset
/// ==S()==>
/// int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset
/// ```
///
/// Equal `@sap.pending_never` on equal base types still allows subsumption for variant deduping. This would also be true if the second base type was `5` (or any other subtype of `int`)
///
/// ---
///
/// Type Aliases
///
/// ```baml
/// type X = int
///
/// int (def) | 5 (def) | X (def)
/// ==S()==>
/// int (def)
/// ```
///
/// Type aliases get simplified and then inlined prior to flattening and deduplication in a union.
///
/// ---
///
/// ```baml
/// type X = int @sap.parse_without_null
///
/// X |
///   5 (def) |
///   int (parse_without_null: Set)
/// ==S()==>
/// int
///     parse_without_null: Set,
///     pending_never: Unset,
///     in_progress_never: Unset,
/// | 5 (def)
/// ```
///
///  The `X` type alias in the user's code would be expanded to an `int` with `@sap.parse_without_null`. From there, it is treated with the deduplication rules we have already seen.
///
/// ---
///
/// Attributes on unions
///
/// ```baml
/// (int (def) | string (def))
///   parse_without_null: Set,
///   pending_never: Unset,
///   in_progress_never: Unset
/// ==S()==>
/// (int
///   parse_without_null: Set,
///   ..def
/// | string
///   parse_without_null: Set,
///   ..def)
///   parse_without_null: Set,
///   pending_never: Unset,
///   in_progress_never: Unset,
/// ```
///
/// Union-level `parse_without_null` distributes into the variants and is preserved at the union level.
///
/// ---
///
/// ```baml
/// (int (def) | string (def))
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// ==S()==>
/// (int
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// | string
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// )
///   parse_without_null: Unset,
///   pending_never: Set,
///   in_progress_never: Unset,
/// ```
///
/// `pending_never` and `in_progress_never` distribute too and are preserved at the union level.
///
/// ---
///
/// How attributes compose:
///
/// The SAP attributes each form a monoid (a definition for how they combine `<>` and what the empty value is `0`).
///
/// Under deduplication of union variants, the monoid is `(Bool, min, Unset)`. IOW for all variants in the union of the same base type, for any given attribute A, the value of that attribute for the one result variant is the `min` (`Unset`) of those variants. The unit (defaultish) value is `Unset`.
///
/// `int @sap.foo | int | int | int => int`
///
/// `int @sap.foo | int @sap.foo | int @sap.foo => int @sap.foo`
///
/// Under nesting, the monoid is `(Bool, max, Unset)` :
///
/// `((((int) ) @sap.foo) ) => int @sap.foo`
///
/// `((((int @sap.foo) ) @sap.foo) ) => int @sap.foo`
///
/// `(((((int))))) => int`
///
/// `@sap.foo` and `@sap.bar` have no interaction.
///
/// **Note on structural subtyping for dedup**: only identical base types and
/// literal→base-type relationships (e.g. `5 ≤ int`) trigger dedup.  Cross-type
/// widening like `int → float` is excluded — SAP treats them as distinct parse
/// candidates with different scoring behavior.
use std::collections::{HashMap, HashSet};

use crate::{Literal, RuntimeTy};

/// Simplify a type for SAP processing.
///
/// - `aliases`: map from alias name to its definition.
/// - `recursive_aliases`: aliases that are recursive (left as `RuntimeTy::TypeAlias`).
pub fn simplify<N: crate::Head>(
    ty: RuntimeTy<N>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive_aliases: &HashSet<N>,
) -> RuntimeTy<N> {
    simplify_impl(ty, aliases, recursive_aliases, false)
}

/// Simplify a runtime-materialized SAP parse target.
///
/// In addition to [`simplify`], this expands a recursive union alias when it
/// appears directly as another union's member. This turns `json | null` into a
/// flat union while retaining recursive `json` references below lists/maps.
pub fn simplify_parse_target<N: crate::Head>(
    ty: RuntimeTy<N>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive_aliases: &HashSet<N>,
) -> RuntimeTy<N> {
    simplify_impl(ty, aliases, recursive_aliases, true)
}

fn simplify_impl<N: crate::Head>(
    ty: RuntimeTy<N>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive: &HashSet<N>,
    expand_recursive_alias_unions: bool,
) -> RuntimeTy<N> {
    match ty {
        RuntimeTy::TypeAlias(ref name) => {
            if recursive.contains(name) {
                // Recursive alias: keep as TypeAlias, don't inline.
                ty
            } else if let Some(target) = aliases.get(name) {
                // Non-recursive: expand and simplify the result.
                simplify_impl(
                    target.clone(),
                    aliases,
                    recursive,
                    expand_recursive_alias_unions,
                )
            } else {
                // Unknown alias — leave as-is.
                ty
            }
        }

        RuntimeTy::Union(variants) => {
            simplify_union(variants, aliases, recursive, expand_recursive_alias_unions)
        }

        // Recurse into compound types.
        RuntimeTy::List(inner) => RuntimeTy::List(Box::new(simplify_impl(
            *inner,
            aliases,
            recursive,
            expand_recursive_alias_unions,
        ))),
        RuntimeTy::Map { key, value } => RuntimeTy::Map {
            key: Box::new(simplify_impl(
                *key,
                aliases,
                recursive,
                expand_recursive_alias_unions,
            )),
            value: Box::new(simplify_impl(
                *value,
                aliases,
                recursive,
                expand_recursive_alias_unions,
            )),
        },

        // Leaf types pass through unchanged.
        _ => ty,
    }
}

// ---------------------------------------------------------------------------
// Union simplification
// ---------------------------------------------------------------------------

fn simplify_union<N: crate::Head>(
    variants: Box<[RuntimeTy<N>]>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive: &HashSet<N>,
    expand_recursive_alias_unions: bool,
) -> RuntimeTy<N> {
    // 1. Simplify each variant recursively.
    let variants: Vec<RuntimeTy<N>> = variants
        .into_iter()
        .map(|v| simplify_impl(v, aliases, recursive, expand_recursive_alias_unions))
        .collect();

    // 2. A recursive alias may itself be a union. It must stay named under an
    // indirection such as `json[]`, but when used directly as another union's
    // member (`json | null`) its immediate variants must be spliced into this
    // union so SAP never receives an alias-hidden nested union.
    let variants = if expand_recursive_alias_unions {
        expand_recursive_union_aliases(variants, aliases, recursive)
    } else {
        variants
    };

    // 3. Flatten nested unions.
    let variants = flatten_union(variants);

    // 4. Deduplicate.
    let variants = dedup_variants(variants);

    // 5. Push null to end.
    let variants = null_to_end(variants);

    // 6. Unwrap singleton.
    if variants.len() == 1 {
        variants
            .into_iter()
            .next()
            .unwrap_or_else(|| unreachable!("a length-1 vec has an element"))
    } else {
        RuntimeTy::Union(variants.into())
    }
}

fn expand_recursive_union_aliases<N: crate::Head>(
    variants: Vec<RuntimeTy<N>>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive: &HashSet<N>,
) -> Vec<RuntimeTy<N>> {
    let mut out = Vec::new();
    let mut expanding = HashSet::new();
    for variant in variants {
        expand_recursive_union_alias_variant(variant, aliases, recursive, &mut expanding, &mut out);
    }
    out
}

fn expand_recursive_union_alias_variant<N: crate::Head>(
    variant: RuntimeTy<N>,
    aliases: &HashMap<N, RuntimeTy<N>>,
    recursive: &HashSet<N>,
    expanding: &mut HashSet<N>,
    out: &mut Vec<RuntimeTy<N>>,
) {
    let RuntimeTy::TypeAlias(name) = variant else {
        out.push(variant);
        return;
    };

    let Some(RuntimeTy::Union(alias_variants)) = aliases.get(&name) else {
        out.push(RuntimeTy::TypeAlias(name));
        return;
    };
    if !recursive.contains(&name) || !expanding.insert(name.clone()) {
        out.push(RuntimeTy::TypeAlias(name));
        return;
    }

    for member in alias_variants {
        let member = simplify_impl(member.clone(), aliases, recursive, true);
        expand_recursive_union_alias_variant(member, aliases, recursive, expanding, out);
    }
    expanding.remove(&name);
}

/// Flatten nested unions into a single level.
fn flatten_union<N: crate::Head>(variants: Vec<RuntimeTy<N>>) -> Vec<RuntimeTy<N>> {
    let mut out = Vec::new();
    for v in variants {
        match v {
            RuntimeTy::Union(inner_variants) => out.extend(inner_variants),
            other => out.push(other),
        }
    }
    out
}

/// Remove variants that are subtypes of other variants.
///
/// If variant A is a subtype of variant B, A is dropped and B is kept.
fn dedup_variants<N: crate::Head>(variants: Vec<RuntimeTy<N>>) -> Vec<RuntimeTy<N>> {
    let mut result: Vec<RuntimeTy<N>> = Vec::new();
    for candidate in variants {
        if result
            .iter()
            .any(|existing| is_sap_structural_subtype(&candidate, existing))
        {
            // candidate is already covered by something in result — skip it.
            continue;
        }
        // Remove any existing variants that the candidate now covers.
        result.retain(|existing| !is_sap_structural_subtype(existing, &candidate));
        result.push(candidate);
    }
    result
}

/// Push `null` variants to the end.
fn null_to_end<N: crate::Head>(variants: Vec<RuntimeTy<N>>) -> Vec<RuntimeTy<N>> {
    let mut non_null = Vec::new();
    let mut nulls = Vec::new();
    for v in variants {
        if matches!(v, RuntimeTy::Null) {
            nulls.push(v);
        } else {
            non_null.push(v);
        }
    }
    non_null.extend(nulls);
    non_null
}

// ---------------------------------------------------------------------------
// Subtyping (for deduplication)
// ---------------------------------------------------------------------------

/// Restricted structural subtyping for SAP dedup.
///
/// Returns `true` when `sub` and `sup` are the same type, or when `sub` is a
/// literal whose base primitive matches `sup`.
fn is_sap_structural_subtype<N: crate::Head>(sub: &RuntimeTy<N>, sup: &RuntimeTy<N>) -> bool {
    if sub == sup {
        return true;
    }

    matches!(
        (sub, sup),
        (RuntimeTy::Literal(Literal::Int(_), _), RuntimeTy::Int)
            | (RuntimeTy::Literal(Literal::Int(_), _), RuntimeTy::Bigint)
            | (RuntimeTy::Literal(Literal::Bigint(_), _), RuntimeTy::Bigint)
            | (RuntimeTy::Literal(Literal::Float(_), _), RuntimeTy::Float)
            | (RuntimeTy::Literal(Literal::String(_), _), RuntimeTy::String)
            | (RuntimeTy::Literal(Literal::Bool(_), _), RuntimeTy::Bool)
            // The one cross-type widening allowed by SAP: `int → bigint`
            // is lossless, unlike `int → float` which loses precision past
            // 2^53.
            | (RuntimeTy::Int, RuntimeTy::Bigint)
    )
}
