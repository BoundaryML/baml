//! Semantic impls for [`TyTemplate`], the `Ty`-shaped template member of the
//! type family.
//!
//! A template is *complete*: every leaf is either realized or a positional
//! frame reference ([`TyTemplate::TypeArgRef`]), so `substitute` always has a
//! single concrete answer per position. This is the type of every emitted
//! template (a `LoadType`, a generic-function value, an instance's class type
//! args, a baked impl rule, a `match`/`is` test). A pattern position the MIR
//! lowering cannot resolve to a template is reported at the builder
//! (`Option::None`), never smuggled as an erased or match-any leaf.
//!
//! The enum itself, its satellites ([`TyTemplateInterface`],
//! [`crate::TyTemplateFunctionParamTy`]), and the `RealizedTy ⊂ TyTemplate`
//! conversions are generated by the
//! [`ty_family!`](baml_type_macros::ty_family) macro. It swaps the name-based
//! `TypeVar` for the positional frame leaf and keeps
//! `AssociatedTypeProjection` for symbolic projections — so a template can
//! express an unresolved generic *structurally*, never as an opaque name.
//!
//! A template that contains no template-only leaf is "fully realized" and
//! narrows to a [`RealizedTy`] (the generated `TryFrom`); that narrowing is
//! the `is_fully_concrete` check.
//!
//! # De Bruijn indexing
//!
//! `TypeArgRef(n)` refers to the n-th entry in the enclosing call-frame's
//! `type_args` vector (0-based). The compiler assigns indices using
//! `function_generic_params` ordering so the mapping is stable across
//! compilation.

use std::fmt;

use crate::{
    Interface, Name, RealizedFunctionParamTy, RealizedTy, RuntimeFunctionParamTy, RuntimeInterface,
    RuntimeTy, Ty, TyAttr, TyTemplate, TyTemplateInterface, TypeName,
    normalize::{ProjectionStep, TypeContext},
};

/// Symbolic realizations of the current type relative to each generic class on
/// a render traversal's ancestry stack.
///
/// Renderers use this to distinguish a finite sequence of specializations from
/// a recursive type transform whose arguments grow forever.
#[derive(Clone, Debug)]
pub struct TyTemplateOrigins<N: Clone = TypeName>(Vec<Option<TyTemplate<N>>>);

impl<N: Clone> Default for TyTemplateOrigins<N> {
    fn default() -> Self {
        Self(Vec::new())
    }
}

impl<N: Clone + PartialEq> TyTemplateOrigins<N> {
    /// No enclosing generic classes contribute symbolic origins at the root.
    pub fn root() -> Self {
        Self::default()
    }

    /// An origin-free value at the given ancestry depth.
    pub fn opaque(depth: usize) -> Self {
        Self(vec![None; depth])
    }

    /// Compose a class field template through every enclosing class transform,
    /// then add the field's template relative to its immediate class.
    pub fn through_field(&self, class_name: &N, class_arity: usize, field: &TyTemplate<N>) -> Self {
        let mut origins = self
            .0
            .iter()
            .map(|origin| {
                class_origin_args(origin.as_ref(), class_name, class_arity)
                    .map(|type_args| compose_template(field, type_args))
            })
            .collect::<Vec<_>>();
        origins.push(Some(field.clone()));
        Self(origins)
    }

    /// Whether the class realization at `ancestry_index` contains a growing
    /// dependency cycle among that class's generic parameter slots.
    pub fn class_transform_expands(
        &self,
        ancestry_index: usize,
        class_name: &N,
        class_arity: usize,
    ) -> bool {
        self.0
            .get(ancestry_index)
            .and_then(Option::as_ref)
            .and_then(|origin| class_origin_args(Some(origin), class_name, class_arity))
            .is_some_and(|type_args| transform_has_expanding_cycle(type_args, class_arity))
    }

    /// Project these origins through a list element.
    pub fn list_element(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::List(element, _) => Some(element.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through a map key.
    pub fn map_key(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Map { key, .. } => Some(key.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through a map value.
    pub fn map_value(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Map { value, .. } => Some(value.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through one union member.
    pub fn union_member(&self, index: usize) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Union(members, _) => members.get(index).cloned(),
            _ => None,
        })
    }

    /// Project these origins through a future's value type.
    pub fn future_value(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Future(value, _, _) => Some(value.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through a future's error type.
    pub fn future_error(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Future(_, error, _) => Some(error.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through a function parameter.
    pub fn function_param(&self, index: usize) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Function { params, .. } => params.get(index).map(|param| param.ty.clone()),
            _ => None,
        })
    }

    /// Project these origins through a function return type.
    pub fn function_return(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Function { ret, .. } => Some(ret.as_ref().clone()),
            _ => None,
        })
    }

    /// Project these origins through a function throws type.
    pub fn function_throws(&self) -> Self {
        self.project(|origin| match origin {
            TyTemplate::Function { throws, .. } => Some(throws.as_ref().clone()),
            _ => None,
        })
    }

    fn project(&self, mut project: impl FnMut(&TyTemplate<N>) -> Option<TyTemplate<N>>) -> Self {
        Self(
            self.0
                .iter()
                .map(|origin| origin.as_ref().and_then(&mut project))
                .collect(),
        )
    }
}

fn compose_template<N: Clone>(
    template: &TyTemplate<N>,
    type_args: &[TyTemplate<N>],
) -> TyTemplate<N> {
    let mut composed = template.clone();
    walk_template(&mut composed, false, &mut |template, _| {
        if let TyTemplate::TypeArgRef(index) = template {
            if let Some(type_arg) = type_args.get(*index as usize) {
                *template = type_arg.clone();
            }
            false
        } else {
            true
        }
    });
    composed
}

fn walk_template<N: Clone>(
    template: &mut TyTemplate<N>,
    nested: bool,
    visitor: &mut impl FnMut(&mut TyTemplate<N>, bool) -> bool,
) {
    if !visitor(template, nested) {
        return;
    }
    let mut child = |template: &mut TyTemplate<N>| walk_template(template, true, visitor);
    match template {
        TyTemplate::List(inner, _) => child(inner),
        TyTemplate::Map { key, value, .. } => {
            child(key);
            child(value);
        }
        TyTemplate::Union(members, _) | TyTemplate::Class(_, members, _) => {
            members.iter_mut().for_each(&mut child);
        }
        TyTemplate::Interface(_, args, associated_bindings, _) => {
            args.iter_mut().for_each(&mut child);
            associated_bindings
                .iter_mut()
                .for_each(|(_, binding)| child(binding));
        }
        TyTemplate::Function {
            params,
            ret,
            throws,
            ..
        } => {
            params.iter_mut().for_each(|param| child(&mut param.ty));
            child(ret);
            child(throws);
        }
        TyTemplate::Future(value, error, _) => {
            child(value);
            child(error);
        }
        TyTemplate::AssociatedTypeProjection {
            base, interface, ..
        } => {
            child(base);
            interface.generics.iter_mut().for_each(&mut child);
            interface
                .associated_types
                .iter_mut()
                .for_each(|(_, binding)| child(binding));
        }
        TyTemplate::TypeArgRef(_)
        | TyTemplate::Int { .. }
        | TyTemplate::Bigint { .. }
        | TyTemplate::Float { .. }
        | TyTemplate::String { .. }
        | TyTemplate::Bool { .. }
        | TyTemplate::Null { .. }
        | TyTemplate::Uint8Array { .. }
        | TyTemplate::Media(..)
        | TyTemplate::Literal(..)
        | TyTemplate::Enum(..)
        | TyTemplate::EnumVariant(..)
        | TyTemplate::RustType { .. }
        | TyTemplate::Type { .. }
        | TyTemplate::Resource { .. }
        | TyTemplate::PromptAst { .. }
        | TyTemplate::Void { .. }
        | TyTemplate::TypeAlias(..)
        | TyTemplate::BuiltinUnknown { .. }
        | TyTemplate::Never { .. } => {}
    }
}

fn class_origin_args<'a, N: Clone + PartialEq>(
    origin: Option<&'a TyTemplate<N>>,
    class_name: &N,
    class_arity: usize,
) -> Option<&'a [TyTemplate<N>]> {
    let Some(TyTemplate::Class(origin_name, type_args, _)) = origin else {
        return None;
    };
    (origin_name == class_name && type_args.len() == class_arity).then_some(type_args)
}

fn transform_has_expanding_cycle<N: Clone>(type_args: &[TyTemplate<N>], arity: usize) -> bool {
    fn reaches(
        edges: &[Vec<(usize, bool)>],
        current: usize,
        target: usize,
        visited: &mut [bool],
    ) -> bool {
        if current == target {
            return true;
        }
        if visited[current] {
            return false;
        }
        visited[current] = true;
        edges[current]
            .iter()
            .any(|(next, _)| reaches(edges, *next, target, visited))
    }

    let mut edges = vec![Vec::<(usize, bool)>::new(); arity];
    for (output, type_arg) in type_args.iter().enumerate().take(arity) {
        let mut dependencies = Vec::new();
        walk_template(&mut type_arg.clone(), false, &mut |template, nested| {
            if let TyTemplate::TypeArgRef(index) = template {
                dependencies.push((*index as usize, nested));
                false
            } else {
                true
            }
        });
        for (input, expanding) in dependencies {
            if input < arity {
                edges[input].push((output, expanding));
            }
        }
    }

    edges.iter().enumerate().any(|(input, outgoing)| {
        outgoing.iter().any(|(output, expanding)| {
            *expanding && reaches(&edges, *output, input, &mut vec![false; arity])
        })
    })
}

/// Why a [`TyTemplate::substitute`] failed to fully realize a template against a
/// frame's realized type arguments.
///
/// Substitution at runtime must produce a fully realized [`RealizedTy`] — every
/// frame reference filled, every projection reduced — or fail loudly. It never
/// erases an unresolved position to `unknown` (which would silently break the
/// value's compile-time type contract). Each variant is a broken invariant the VM
/// surfaces as an internal error, not a user-facing type.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SubstituteError {
    /// An associated-type projection `(base as I).member` over a *realized* base
    /// could not be reduced to a concrete type — no impl binding was found. The
    /// compiler proves the impl exists for any realized base, so this is a broken
    /// invariant at runtime rather than a legitimate outcome.
    UnreducibleProjection {
        /// The associated-type member that failed to reduce.
        member: Name,
    },
    /// A projection reduced, but to a type that still contained a non-realized
    /// position (named by `variant`). A realized base should reduce to a realized
    /// witness, so this too is a broken invariant.
    ProjectionNotRealized {
        /// The associated-type member whose reduction was not realized.
        member: Name,
        /// The offending non-realized variant encountered in the reduced type.
        variant: &'static str,
    },
    /// A projection-reduction chain exceeded the fuel budget — a cyclic or
    /// pathologically deep associated-type binding whose reduction re-enters
    /// itself (`type X = (_ as I).Y` reducing back through `X`). The compiler is
    /// expected to reject such cycles at declaration, so hitting this runtime
    /// backstop is a broken invariant rather than a legitimate outcome; it stops
    /// the recursion instead of overflowing the stack.
    ProjectionFuelExhausted {
        /// The associated-type member whose reduction chain did not terminate.
        member: Name,
    },
    /// A `TypeArgRef(index)` referenced a slot the frame does not supply. It is
    /// a system invariant that a template's indices only reference its
    /// surrounding frame — the compiler seeds every generic frame at full
    /// declared width (an unconstrained parameter is seeded as an explicit
    /// `unknown`, never omitted) — so an out-of-range reference means the
    /// emitted De Bruijn indices and the seeded frame no longer agree: a
    /// frame-layout bug, checked in every build profile. (A later revision may
    /// drop the check in release and perform the access unchecked.)
    TypeArgRefOutOfRange {
        /// The out-of-range De Bruijn index.
        index: u32,
        /// The width of the frame the template was substituted against.
        frame_len: usize,
    },
}

impl fmt::Display for SubstituteError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::UnreducibleProjection { member } => {
                write!(
                    f,
                    "associated-type projection `.{member}` could not be reduced"
                )
            }
            Self::ProjectionNotRealized { member, variant } => write!(
                f,
                "associated-type projection `.{member}` reduced to a non-realized `{variant}`"
            ),
            Self::ProjectionFuelExhausted { member } => write!(
                f,
                "associated-type projection `.{member}` did not terminate within the reduction budget"
            ),
            Self::TypeArgRefOutOfRange { index, frame_len } => write!(
                f,
                "template references frame type-arg slot {index} but the frame has {frame_len} type args"
            ),
        }
    }
}

impl std::error::Error for SubstituteError {}

impl<N: Clone> TyTemplate<N> {
    // --- Ergonomic constructors (default TyAttr) ---
    //
    // Head-generic: a constructor only *places* a head, it never reads one, so
    // pinning these to the compiler's head would leave the runtime hand-rolling
    // the same variants.

    /// `T[]` (list) with default attributes.
    pub fn list(inner: Self) -> Self {
        TyTemplate::List(Box::new(inner), TyAttr::default())
    }

    /// `map<K, V>` with default attributes.
    pub fn map(key: Self, value: Self) -> Self {
        TyTemplate::Map {
            key: Box::new(key),
            value: Box::new(value),
            attr: TyAttr::default(),
        }
    }

    /// `A | B | ...` (union) with default attributes.
    pub fn union(members: impl IntoIterator<Item = Self>) -> Self {
        TyTemplate::Union(members.into_iter().collect(), TyAttr::default())
    }

    /// `Class<A1, A2, ...>` (generic class instantiation) with default attributes.
    pub fn class(head: N, args: Vec<Self>) -> Self {
        TyTemplate::Class(head, args, TyAttr::default())
    }

    /// `Interface<A1, Assoc = A2, ...>` with default attributes.
    pub fn interface(head: N, args: Vec<Self>, associated_bindings: Vec<(Name, Self)>) -> Self {
        TyTemplate::Interface(head, args, associated_bindings, TyAttr::default())
    }
}

impl std::fmt::Display for TyTemplateInterface {
    /// Renders as the existential template it denotes, so an interface constraint
    /// and the type it lifts to print identically in diagnostics and MIR dumps.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.to_template())
    }
}

/// Substitution is head-agnostic: it replaces frame references with realized
/// arguments and reduces projections through `ctx`, neither of which inspects a
/// nominal head. The runtime therefore realizes its `TyTemplate<TypeHead>`s with
/// the very same code the compiler uses on name-headed ones.
impl<N: crate::Head> TyTemplate<N> {
    /// Runtime type arguments are always realized (a generic call binds each
    /// parameter to a concrete type), so a template that occurs at a
    /// materialization site — a `LoadType`, a generic-function value, an instance's
    /// class type args — realizes fully or fails. It never erases an unresolved
    /// projection to `unknown`; an unreducible projection is a broken invariant
    /// returned as a [`SubstituteError`] for the VM to surface as an internal
    /// error.
    ///
    /// A projection reduces because its qualifier is always known (the interface is
    /// non-optional) and its base realizes here, so `ctx.project` — the same impl
    /// consultation the canonical algebra uses — determines the concrete witness.
    pub fn substitute<C: TypeContext<N>>(
        &self,
        type_args: &[RealizedTy<N>],
        ctx: &C,
    ) -> Result<RealizedTy<N>, SubstituteError> {
        self.substitute_with_fuel(type_args, ctx, crate::normalize::PROJECTION_REDUCTION_FUEL)
    }

    /// [`Self::substitute`] with an explicit projection-reduction budget.
    ///
    /// `fuel` bounds the associated-type reduction chain: each projection reduced
    /// through `ctx.project` (which realizes the impl binding by re-entering this
    /// method) spends one unit, so a cyclic binding — `type X = (_ as I).Y`
    /// reducing back through `X` — terminates with
    /// [`SubstituteError::ProjectionFuelExhausted`] instead of overflowing the
    /// stack. This is the runtime twin of the canonical algebra's fuel guard in
    /// `normalize`'s `from_ty` walk. The public [`Self::substitute`] seeds the full
    /// `PROJECTION_REDUCTION_FUEL` budget; `ctx.project` threads the remainder back
    /// in for the binding it realizes.
    pub fn substitute_with_fuel<C: TypeContext<N>>(
        &self,
        type_args: &[RealizedTy<N>],
        ctx: &C,
        fuel: u32,
    ) -> Result<RealizedTy<N>, SubstituteError> {
        match self {
            // ── Template-only leaf ────────────────────────────────────────────
            // A frame reference materializes to its bound type argument. The
            // frame always supplies every slot the template can reference: the
            // compiler seeds generic frames at full declared width, with an
            // unconstrained parameter seeded as an explicit `unknown` (so
            // `type.of<T>()` under an unknown-typed call still reflects
            // the honest top type through a real slot). An out-of-range index is
            // therefore a frame-layout bug — reported, never silently realized.
            Self::TypeArgRef(n) => match type_args.get(*n as usize) {
                Some(arg) => Ok(arg.clone()),
                None => Err(SubstituteError::TypeArgRefOutOfRange {
                    index: *n,
                    frame_len: type_args.len(),
                }),
            },

            // ── Composites: recurse, propagating failures ─────────────────────
            Self::List(inner, attr) => Ok(RealizedTy::List(
                Box::new(inner.substitute_with_fuel(type_args, ctx, fuel)?),
                attr.clone(),
            )),
            Self::Map { key, value, attr } => Ok(RealizedTy::Map {
                key: Box::new(key.substitute_with_fuel(type_args, ctx, fuel)?),
                value: Box::new(value.substitute_with_fuel(type_args, ctx, fuel)?),
                attr: attr.clone(),
            }),
            Self::Union(parts, attr) => Ok(RealizedTy::Union(
                parts
                    .iter()
                    .map(|p| p.substitute_with_fuel(type_args, ctx, fuel))
                    .collect::<Result<_, _>>()?,
                attr.clone(),
            )),
            Self::Class(name, args, attr) => Ok(RealizedTy::Class(
                name.clone(),
                args.iter()
                    .map(|a| a.substitute_with_fuel(type_args, ctx, fuel))
                    .collect::<Result<_, _>>()?,
                attr.clone(),
            )),
            Self::Interface(name, args, associated_bindings, attr) => Ok(RealizedTy::Interface(
                name.clone(),
                args.iter()
                    .map(|a| a.substitute_with_fuel(type_args, ctx, fuel))
                    .collect::<Result<_, _>>()?,
                associated_bindings
                    .iter()
                    .map(|(name, ty)| {
                        Ok((name.clone(), ty.substitute_with_fuel(type_args, ctx, fuel)?))
                    })
                    .collect::<Result<_, _>>()?,
                attr.clone(),
            )),
            Self::Function {
                params,
                ret,
                throws,
                attr,
            } => Ok(RealizedTy::Function {
                params: params
                    .iter()
                    .map(|p| {
                        Ok(RealizedFunctionParamTy {
                            name: p.name.clone(),
                            ty: p.ty.substitute_with_fuel(type_args, ctx, fuel)?,
                            mode: p.mode,
                        })
                    })
                    .collect::<Result<_, _>>()?,
                ret: Box::new(ret.substitute_with_fuel(type_args, ctx, fuel)?),
                throws: Box::new(throws.substitute_with_fuel(type_args, ctx, fuel)?),
                attr: attr.clone(),
            }),
            Self::Future(value, error, attr) => Ok(RealizedTy::Future(
                Box::new(value.substitute_with_fuel(type_args, ctx, fuel)?),
                Box::new(error.substitute_with_fuel(type_args, ctx, fuel)?),
                attr.clone(),
            )),
            // Realize the base, then reduce the projection to the impl's binding.
            // The qualifier is always known and the base is realized here, so a
            // realized-base projection reduces to exactly one concrete witness;
            // anything else is a broken invariant, never a symbolic leaf.
            Self::AssociatedTypeProjection {
                base,
                interface,
                member,
                ..
            } => {
                let base = base.substitute_with_fuel(type_args, ctx, fuel)?;
                let interface = interface.substitute(type_args, ctx, fuel)?;
                // Spend one unit on *this* reduction before consulting `ctx.project`,
                // which realizes the impl binding by re-entering `substitute` and can
                // reach another projection. A cyclic binding would otherwise recurse
                // forever; the backstop mirrors the canonical algebra's `from_ty`.
                let Some(fuel) = fuel.checked_sub(1) else {
                    return Err(SubstituteError::ProjectionFuelExhausted {
                        member: member.clone(),
                    });
                };
                match ctx.project(base.as_ty(), &interface, member, fuel) {
                    ProjectionStep::Reduced(reduced) => {
                        RealizedTy::try_from(&reduced).map_err(|e| {
                            SubstituteError::ProjectionNotRealized {
                                member: member.clone(),
                                variant: e.variant,
                            }
                        })
                    }
                    ProjectionStep::Opaque => Err(SubstituteError::UnreducibleProjection {
                        member: member.clone(),
                    }),
                }
            }

            // ── Realized leaf ─────────────────────────────────────────────────
            // No template refs and no nested type positions: it narrows to a
            // `RealizedTy` directly. A composite variant is handled above, so a
            // narrowing failure here would be a missing arm — surfaced loudly.
            other => Ok(RealizedTy::try_from(other.clone())
                .unwrap_or_else(|e| unreachable!("realized-leaf template narrowing failed: {e}"))),
        }
    }
}

impl TyTemplateInterface {
    /// The interface *existential* template ([`TyTemplate::Interface`]) denoted by
    /// this constraint, with default attributes — the template-level counterpart of
    /// [`Interface::to_ty`].
    ///
    /// Needed only at boundaries that carry a *type* rather than a constraint (the
    /// bytecode constant pool a `LoadType` reads from). Prefer holding the
    /// constraint itself wherever an interface is meant: a `TyTemplate` slot admits
    /// non-interface types, which an interface position can never legitimately hold.
    pub fn to_template(&self) -> TyTemplate {
        TyTemplate::interface(
            self.name.clone(),
            self.generics.clone(),
            self.associated_types.clone(),
        )
    }
}

/// Symbolic substitution needs no more of a head than cloning it, so it sits at
/// the same bound as [`TyTemplate::substitute_symbolic`] rather than the
/// stronger one reduction requires.
impl<N: Clone> TyTemplateInterface<N> {
    /// Compile-time counterpart to [`Self::substitute`] (see
    /// [`TyTemplate::substitute_symbolic`]): resolve frame refs but leave
    /// unresolved positions symbolic, producing a `RuntimeInterface`.
    ///
    /// Head-generic for the same reason: heads are cloned through, never read.
    pub(crate) fn substitute_symbolic(&self, type_args: &[RuntimeTy<N>]) -> RuntimeInterface<N> {
        RuntimeInterface::new(
            self.name.clone(),
            self.generics
                .iter()
                .map(|g| g.substitute_symbolic(type_args))
                .collect(),
            self.associated_types
                .iter()
                .map(|(name, ty)| (name.clone(), ty.substitute_symbolic(type_args)))
                .collect(),
        )
    }
}

/// Head-agnostic for the same reason as [`TyTemplate::substitute`].
impl<N: crate::Head> TyTemplateInterface<N> {
    /// Substitute frame type args through the interface's generic and
    /// associated-binding positions, producing the realized [`Interface`]
    /// constraint used to reduce the enclosing projection (see
    /// [`TyTemplate::substitute`]). Each realized position widens into `Ty` for the
    /// [`Interface`] the projection query consumes.
    fn substitute<C: TypeContext<N>>(
        &self,
        type_args: &[RealizedTy<N>],
        ctx: &C,
        fuel: u32,
    ) -> Result<Interface<N>, SubstituteError> {
        Ok(Interface::new(
            self.name.clone(),
            self.generics
                .iter()
                .map(|g| g.substitute_with_fuel(type_args, ctx, fuel).map(Ty::from))
                .collect::<Result<_, _>>()?,
            self.associated_types
                .iter()
                .map(|(name, ty)| {
                    Ok((
                        name.clone(),
                        Ty::from(ty.substitute_with_fuel(type_args, ctx, fuel)?),
                    ))
                })
                .collect::<Result<_, _>>()?,
        ))
    }
}

impl<N: Clone + crate::HeadDisplay> fmt::Display for TyTemplate<N> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        // Render through `Ty`'s `Display` so every shared construct (list-postfix
        // parenthesization, `future<…>` casing, function `throws` handling, …)
        // stays byte-identical to the canonical type renderer — no per-variant
        // drift. Only the template-only leaf needs a placeholder: a frame ref
        // shows as `#n` (a `TypeVar` named `#n`).
        fmt::Display::fmt(&self.to_display_ty(), f)
    }
}

impl<N: Clone> TyTemplate<N> {
    /// Compile-time counterpart to [`Self::substitute`]: resolve each
    /// `TypeArgRef(n)` against `type_args` but leave every unresolved position
    /// *symbolic*. An associated projection stays a projection; an out-of-range
    /// reference falls back to `unknown`. Used by compile-time type
    /// computation (e.g. a class field's type given the receiver's class args),
    /// where the args may themselves be symbolic — an unspecialized generic — so
    /// the result is a `RuntimeTy` that can still carry type variables, unlike the
    /// runtime [`Self::substitute`], which realizes fully or fails.
    ///
    /// Head-generic: every head position is cloned through, never inspected.
    pub fn substitute_symbolic(&self, type_args: &[RuntimeTy<N>]) -> RuntimeTy<N> {
        match self {
            Self::TypeArgRef(n) => type_args
                .get(*n as usize)
                .cloned()
                .unwrap_or_else(RuntimeTy::unknown),
            Self::List(inner, attr) => {
                RuntimeTy::List(Box::new(inner.substitute_symbolic(type_args)), attr.clone())
            }
            Self::Map { key, value, attr } => RuntimeTy::Map {
                key: Box::new(key.substitute_symbolic(type_args)),
                value: Box::new(value.substitute_symbolic(type_args)),
                attr: attr.clone(),
            },
            Self::Union(parts, attr) => RuntimeTy::Union(
                parts
                    .iter()
                    .map(|p| p.substitute_symbolic(type_args))
                    .collect(),
                attr.clone(),
            ),
            Self::Class(name, args, attr) => RuntimeTy::Class(
                name.clone(),
                args.iter()
                    .map(|a| a.substitute_symbolic(type_args))
                    .collect(),
                attr.clone(),
            ),
            Self::Interface(name, args, associated_bindings, attr) => RuntimeTy::Interface(
                name.clone(),
                args.iter()
                    .map(|a| a.substitute_symbolic(type_args))
                    .collect(),
                associated_bindings
                    .iter()
                    .map(|(name, ty)| (name.clone(), ty.substitute_symbolic(type_args)))
                    .collect(),
                attr.clone(),
            ),
            Self::Function {
                params,
                ret,
                throws,
                attr,
            } => RuntimeTy::Function {
                params: params
                    .iter()
                    .map(|p| RuntimeFunctionParamTy {
                        name: p.name.clone(),
                        ty: p.ty.substitute_symbolic(type_args),
                        mode: p.mode,
                    })
                    .collect(),
                ret: Box::new(ret.substitute_symbolic(type_args)),
                throws: Box::new(throws.substitute_symbolic(type_args)),
                attr: attr.clone(),
            },
            Self::Future(value, error, attr) => RuntimeTy::Future(
                Box::new(value.substitute_symbolic(type_args)),
                Box::new(error.substitute_symbolic(type_args)),
                attr.clone(),
            ),
            Self::AssociatedTypeProjection {
                base,
                interface,
                member,
                attr,
            } => RuntimeTy::AssociatedTypeProjection {
                base: Box::new(base.substitute_symbolic(type_args)),
                interface: Box::new(interface.substitute_symbolic(type_args)),
                member: member.clone(),
                attr: attr.clone(),
            },
            // A realized leaf narrows to `RealizedTy` then widens to `RuntimeTy`.
            other => RealizedTy::<N>::try_from(other.clone())
                .unwrap_or_else(|e| unreachable!("realized-leaf template narrowing failed: {e}"))
                .into(),
        }
    }

    /// Returns `true` when the template contains no template-only leaf
    /// (`TypeArgRef` or an unresolved projection) at any depth — i.e. it is a
    /// fully realized type that narrows to a [`RealizedTy`].
    ///
    /// Narrowing is a family conversion and never inspects a head, so this
    /// answers the same at either head.
    pub fn is_fully_concrete(&self) -> bool {
        <&RealizedTy<N>>::try_from(self).is_ok()
    }

    /// A lossy [`Ty`] view for rendering only: frame refs become
    /// `TypeVar("#n")`. Every other node maps structurally, so
    /// [`fmt::Display`] can delegate to `Ty`'s renderer.
    fn to_display_ty(&self) -> crate::Ty<N> {
        use crate::Ty;
        match self {
            Self::TypeArgRef(n) => Ty::TypeVar(
                crate::ParamTy::new(*n, Name::new(format!("#{n}"))),
                TyAttr::default(),
            ),
            Self::List(inner, attr) => Ty::List(Box::new(inner.to_display_ty()), attr.clone()),
            Self::Map { key, value, attr } => Ty::Map {
                key: Box::new(key.to_display_ty()),
                value: Box::new(value.to_display_ty()),
                attr: attr.clone(),
            },
            Self::Union(parts, attr) => Ty::Union(
                parts.iter().map(Self::to_display_ty).collect(),
                attr.clone(),
            ),
            Self::Class(name, args, attr) => Ty::Class(
                name.clone(),
                args.iter().map(Self::to_display_ty).collect(),
                attr.clone(),
            ),
            Self::Interface(name, args, associated_bindings, attr) => Ty::Interface(
                name.clone(),
                args.iter().map(Self::to_display_ty).collect(),
                associated_bindings
                    .iter()
                    .map(|(n, t)| (n.clone(), t.to_display_ty()))
                    .collect(),
                attr.clone(),
            ),
            Self::Function {
                params,
                ret,
                throws,
                attr,
            } => Ty::Function {
                params: params
                    .iter()
                    .map(|p| crate::FunctionParamTy {
                        name: p.name.clone(),
                        ty: p.ty.to_display_ty(),
                        mode: p.mode,
                    })
                    .collect(),
                ret: Box::new(ret.to_display_ty()),
                throws: Box::new(throws.to_display_ty()),
                attr: attr.clone(),
            },
            Self::Future(value, error, attr) => Ty::Future(
                Box::new(value.to_display_ty()),
                Box::new(error.to_display_ty()),
                attr.clone(),
            ),
            Self::AssociatedTypeProjection {
                base,
                interface,
                member,
                attr,
            } => Ty::AssociatedTypeProjection {
                base: Box::new(base.to_display_ty()),
                interface: Box::new(crate::Interface {
                    name: interface.name.clone(),
                    generics: interface.generics.iter().map(Self::to_display_ty).collect(),
                    associated_types: interface
                        .associated_types
                        .iter()
                        .map(|(n, t)| (n.clone(), t.to_display_ty()))
                        .collect(),
                }),
                member: member.clone(),
                attr: attr.clone(),
            },
            // A realized leaf widens into `Ty` by the generated conversion.
            other => Ty::from(RealizedTy::try_from(other.clone()).unwrap_or_else(|e| {
                unreachable!("realized-leaf template widening for display failed: {e}")
            })),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{Interface, QualifiedTypeName, RuntimeTy};

    /// A context-free [`TypeContext`]: these substitution tests exercise frame-ref
    /// resolution and realization, not projection reduction, so every query fails
    /// safe (no aliases, memberships, bounds, or reducible projections).
    struct NoCtx;
    impl TypeContext for NoCtx {
        /// A name-based context represents a declaration by its own name, so this
        /// is the identity — no resolution step, and never `None`.
        fn head_lookup(&self, qtn: &crate::QualifiedTypeName) -> Option<crate::QualifiedTypeName> {
            Some(qtn.clone())
        }

        fn alias_def(&self, _: &QualifiedTypeName) -> Option<Ty> {
            None
        }
        fn implements_interface(&self, _: &Ty, _: &Interface) -> bool {
            false
        }
        fn type_var_bound(&self, _: &crate::ParamTy) -> Vec<Interface> {
            Vec::new()
        }
        fn interface_requires(&self, _: &Interface, _: &Interface) -> bool {
            false
        }
        fn enum_variants(&self, _: &QualifiedTypeName) -> Option<Vec<Name>> {
            None
        }
        fn associated_type_bound(&self, _: &Interface, _: Name) -> Vec<Interface> {
            Vec::new()
        }
        fn project(&self, _: &Ty, _: &Interface, _: &Name, _fuel: u32) -> ProjectionStep {
            ProjectionStep::Opaque
        }
    }

    /// Build a `RealizedTy` frame argument from a `RuntimeTy` constructor.
    fn r(ty: RuntimeTy) -> RealizedTy {
        RealizedTy::try_from(ty).expect("test arg is realized")
    }

    /// Materialize against a frame, upcasting the realized result to `RuntimeTy`
    /// so it can be compared with `RuntimeTy`'s ergonomic constructors.
    fn sub(tmpl: &TyTemplate, args: &[RealizedTy]) -> RuntimeTy {
        RuntimeTy::from(
            tmpl.substitute(args, &NoCtx)
                .expect("substitution realizes"),
        )
    }

    #[test]
    fn generic_render_origins_reject_only_growing_dependency_cycles() {
        let step = TypeName::local(crate::Name::new("Step"));
        let step_field = TyTemplate::class(
            step.clone(),
            vec![
                TyTemplate::list(TyTemplate::TypeArgRef(1)),
                TyTemplate::from(RealizedTy::int()),
            ],
        );
        let step_origins = TyTemplateOrigins::root().through_field(&step, 2, &step_field);
        assert!(!step_origins.class_transform_expands(0, &step, 2));

        let chain = TypeName::local(crate::Name::new("Chain"));
        let chain_field = TyTemplate::class(
            chain.clone(),
            vec![TyTemplate::class(
                chain.clone(),
                vec![TyTemplate::TypeArgRef(0)],
            )],
        );
        let chain_origins = TyTemplateOrigins::root().through_field(&chain, 1, &chain_field);
        assert!(chain_origins.class_transform_expands(0, &chain, 1));

        let interface = TypeName::local(crate::Name::new("Wrapped"));
        let interface_field = TyTemplate::class(
            chain.clone(),
            vec![TyTemplate::interface(
                interface,
                vec![TyTemplate::TypeArgRef(0)],
                Vec::new(),
            )],
        );
        let interface_origins =
            TyTemplateOrigins::root().through_field(&chain, 1, &interface_field);
        assert!(interface_origins.class_transform_expands(0, &chain, 1));
    }

    #[test]
    fn concrete_template_substitutes_to_itself() {
        let tmpl = TyTemplate::from(RealizedTy::int());
        assert_eq!(sub(&tmpl, &[]), RuntimeTy::int());
        assert!(tmpl.is_fully_concrete());
    }

    #[test]
    fn type_arg_ref_substitutes_correctly() {
        let tmpl = TyTemplate::TypeArgRef(0);
        assert_eq!(sub(&tmpl, &[r(RuntimeTy::string())]), RuntimeTy::string());
        assert!(!tmpl.is_fully_concrete());
    }

    #[test]
    fn array_of_type_arg_ref() {
        // list<#0> with type_args=[int] → int[]
        let tmpl = TyTemplate::list(TyTemplate::TypeArgRef(0));
        assert_eq!(
            sub(&tmpl, &[r(RuntimeTy::int())]),
            RuntimeTy::list(RuntimeTy::int())
        );
        assert!(!tmpl.is_fully_concrete());
    }

    #[test]
    fn optional_of_type_arg_ref() {
        // (#0 | null) with type_args=[string] → string?
        let tmpl = TyTemplate::union([
            TyTemplate::TypeArgRef(0),
            TyTemplate::from(RealizedTy::null()),
        ]);
        assert_eq!(
            sub(&tmpl, &[r(RuntimeTy::string())]),
            RuntimeTy::optional(RuntimeTy::string())
        );
        assert!(!tmpl.is_fully_concrete());
    }

    #[test]
    fn out_of_range_type_arg_ref_is_an_error() {
        // A template's indices only reference the surrounding frame — the
        // compiler seeds generic frames at full declared width (an
        // unconstrained param is an explicit `unknown` slot, never omitted) —
        // so an out-of-range ref is a frame-layout bug, reported in every
        // build profile rather than silently realized as `unknown`.
        let tmpl = TyTemplate::TypeArgRef(0);
        assert_eq!(
            tmpl.substitute(&[], &NoCtx),
            Err(SubstituteError::TypeArgRefOutOfRange {
                index: 0,
                frame_len: 0
            })
        );
    }

    /// `(#0 as Cyclic).member` — a projection whose base is a realized frame ref.
    fn cyclic_projection(member: crate::Name) -> TyTemplate {
        TyTemplate::AssociatedTypeProjection {
            base: Box::new(TyTemplate::TypeArgRef(0)),
            interface: Box::new(TyTemplateInterface {
                name: crate::TypeName::local(crate::Name::new("Cyclic")),
                generics: vec![],
                associated_types: vec![],
            }),
            member,
            attr: TyAttr::default(),
        }
    }

    /// A context whose every projection reduces by realizing *the same* projection
    /// again — a cyclic associated-type binding. Without the fuel backstop this
    /// recurses forever; with it, the chain exhausts its budget and fails.
    struct CyclicCtx;
    impl TypeContext for CyclicCtx {
        /// A name-based context represents a declaration by its own name, so this
        /// is the identity — no resolution step, and never `None`.
        fn head_lookup(&self, qtn: &crate::QualifiedTypeName) -> Option<crate::QualifiedTypeName> {
            Some(qtn.clone())
        }

        fn alias_def(&self, _: &QualifiedTypeName) -> Option<Ty> {
            None
        }
        fn implements_interface(&self, _: &Ty, _: &Interface) -> bool {
            false
        }
        fn type_var_bound(&self, _: &crate::ParamTy) -> Vec<Interface> {
            Vec::new()
        }
        fn interface_requires(&self, _: &Interface, _: &Interface) -> bool {
            false
        }
        fn enum_variants(&self, _: &QualifiedTypeName) -> Option<Vec<Name>> {
            None
        }
        fn associated_type_bound(&self, _: &Interface, _: Name) -> Vec<Interface> {
            Vec::new()
        }
        fn project(&self, _: &Ty, _: &Interface, member: &Name, fuel: u32) -> ProjectionStep {
            // The binding for `member` is the same projection, so realizing it
            // re-enters `project`. The threaded `fuel` bounds the cycle; an
            // exhausted budget surfaces as a substitution error (→ `Opaque`).
            match cyclic_projection(member.clone()).substitute_with_fuel(
                &[RealizedTy::unknown()],
                self,
                fuel,
            ) {
                Ok(reduced) => ProjectionStep::Reduced(reduced.into()),
                Err(_) => ProjectionStep::Opaque,
            }
        }
    }

    #[test]
    fn projection_fuel_guard_fires_at_zero() {
        // With no remaining budget a projection cannot even attempt its reduction.
        let proj = cyclic_projection(crate::Name::new("Item"));
        assert_eq!(
            proj.substitute_with_fuel(&[RealizedTy::unknown()], &CyclicCtx, 0),
            Err(SubstituteError::ProjectionFuelExhausted {
                member: crate::Name::new("Item"),
            })
        );
    }

    #[test]
    fn cyclic_projection_terminates_instead_of_overflowing() {
        // A cyclic associated-type binding would realize to itself forever without
        // the backstop; with it, the chain exhausts its fuel and fails rather than
        // overflowing the stack.
        let proj = cyclic_projection(crate::Name::new("Item"));
        assert!(
            proj.substitute_with_fuel(&[RealizedTy::unknown()], &CyclicCtx, 16)
                .is_err()
        );
    }

    #[test]
    fn concrete_array_is_fully_concrete() {
        let tmpl: TyTemplate = TyTemplate::list(TyTemplate::from(RealizedTy::int()));
        assert!(tmpl.is_fully_concrete());
    }

    #[test]
    fn union_of_concrete_is_fully_concrete() {
        let tmpl: TyTemplate = TyTemplate::union([
            TyTemplate::from(RealizedTy::int()),
            TyTemplate::from(RealizedTy::string()),
        ]);
        assert!(tmpl.is_fully_concrete());
        assert_eq!(
            sub(&tmpl, &[]),
            RuntimeTy::union([RuntimeTy::int(), RuntimeTy::string()])
        );
    }

    #[test]
    fn union_containing_type_arg_ref_not_concrete() {
        let tmpl: TyTemplate = TyTemplate::union([
            TyTemplate::from(RealizedTy::int()),
            TyTemplate::TypeArgRef(0),
        ]);
        assert!(!tmpl.is_fully_concrete());
    }

    #[test]
    fn class_with_type_arg_ref_substitution() {
        let tmpl = TyTemplate::class(
            crate::TypeName::local(crate::Name::new("Container")),
            vec![TyTemplate::TypeArgRef(0)],
        );
        let user = RuntimeTy::user_class("User");
        assert_eq!(
            sub(&tmpl, &[r(user.clone())]),
            RuntimeTy::class_with_args(
                crate::TypeName::local(crate::Name::new("Container")),
                vec![user]
            )
        );
        assert!(!tmpl.is_fully_concrete());
    }

    #[test]
    fn class_no_args_is_fully_concrete() {
        let tmpl = TyTemplate::class(crate::TypeName::local(crate::Name::new("User")), vec![]);
        assert!(tmpl.is_fully_concrete());
        assert_eq!(
            sub(&tmpl, &[]),
            RuntimeTy::Class(
                crate::TypeName::local(crate::Name::new("User")),
                vec![],
                crate::TyAttr::default()
            )
        );
    }
}
