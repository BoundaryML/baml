    #[test]
    fn test_premature_close_with_template_string() {
        // CRITICAL: This demonstrates the "# limitation
        // User needs to use more hashes if template contains "#
        let source = r##"#"{{ "\"#" }}"#"##;
        let file_id = FileId::new(0);
        let tokens = lex_lossless(source, file_id);

        // Raw string closes prematurely at first "#
        assert_eq!(tokens[0].kind, TokenKind::RawString);
        // Closes at the "# inside the template
        assert!(tokens[0].text.contains("{{"));

        // This is expected behavior - user should use ##"..."##
    }

