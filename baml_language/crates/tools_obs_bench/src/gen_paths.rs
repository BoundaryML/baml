//! `obs-bench gen-paths` — the deterministic distinct-context workload
//! generator (design §10.2 `paths/gen_paths`).
//!
//! Emits `gen-paths-P<contexts>.baml`: a complete binary tree of `P`
//! distinct functions (each called from exactly one parent → exactly `P`
//! distinct `(parent, function)` CCT contexts, +1 for main), driven by a
//! loop that holds total profiled calls at `total_calls` regardless of `P`.
//! C4's bytes/path gate sweeps `P ∈ {4..4096}` over these files.
//!
//! Byte-deterministic: same inputs → same file, no randomness, no
//! timestamps. Committed READMEs explain why the files themselves are not
//! checked in.

use std::fmt::Write as _;

/// Generate the BAML source for `contexts` distinct functions.
///
/// The tree is heap-shaped: node `k` (1-based) calls `2k` and `2k+1` while
/// they are ≤ `contexts`. One traversal makes exactly `contexts` profiled
/// calls (every node once), so `reps = total_calls / contexts` traversals
/// hold total calls constant across the sweep (the CLI reports the exact
/// product).
pub fn generate(contexts: u32, total_calls: u64) -> (String, u64) {
    assert!(contexts >= 1, "need at least one context");
    let reps = (total_calls / u64::from(contexts)).max(1);
    let exact_calls = reps * u64::from(contexts);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// GENERATED by `obs-bench gen-paths --contexts {contexts} --total-calls {total_calls}`."
    );
    let _ = writeln!(
        out,
        "// {contexts} distinct calling contexts; {reps} reps = {exact_calls} profiled calls."
    );
    let _ = writeln!(out, "// Deterministic output — regenerate, never edit.");
    let _ = writeln!(out);
    // Emit deepest-first so every callee is defined before its caller reads
    // naturally; BAML resolves forward references, this is for humans.
    for k in (1..=contexts).rev() {
        let left = 2 * k;
        let right = 2 * k + 1;
        let _ = writeln!(out, "function n{k:04}(x: int) -> int {{");
        match (left <= contexts, right <= contexts) {
            (true, true) => {
                let _ = writeln!(out, "    n{left:04}(x) + n{right:04}(x) + 1");
            }
            (true, false) => {
                let _ = writeln!(out, "    n{left:04}(x) + 1");
            }
            _ => {
                let _ = writeln!(out, "    x + 1");
            }
        }
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
    }
    let _ = writeln!(out, "function main(reps: int) -> int {{");
    let _ = writeln!(out, "    let total = 0;");
    let _ = writeln!(out, "    let r = 0;");
    let _ = writeln!(out, "    while (r < reps) {{");
    let _ = writeln!(out, "        total += n0001(r);");
    let _ = writeln!(out, "        r += 1;");
    let _ = writeln!(out, "    }}");
    let _ = writeln!(out, "    total");
    let _ = writeln!(out, "}}");
    (out, reps)
}

pub fn file_name(contexts: u32) -> String {
    format!("gen-paths-P{contexts}.baml")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generation_is_deterministic_and_complete() {
        let (a, reps_a) = generate(64, 1_000_000);
        let (b, reps_b) = generate(64, 1_000_000);
        assert_eq!(a, b);
        assert_eq!(reps_a, reps_b);
        // 64 functions + main.
        assert_eq!(a.matches("function ").count(), 65);
        // Every node k >= 2 is called exactly once (one parent); n0001 from main.
        for k in 2..=64u32 {
            let needle = format!("n{k:04}(");
            assert_eq!(
                a.matches(&needle).count(),
                2,
                "def + one call site for {needle}"
            );
        }
    }

    #[test]
    fn reps_hold_total_calls_constant() {
        let (_, reps4) = generate(4, 1_000_000);
        let (_, reps4096) = generate(4096, 1_000_000);
        assert_eq!(reps4 * 4, 1_000_000);
        assert_eq!(reps4096 * 4096, 999_424); // floor division; reported exactly
    }
}
