//! The object-format ABI that builtin adapters are written against.
//!
//! The shared-runtime design (`documents/runtime-v2-shared-design.md`,
//! sections 1, 2 and 5) stores every field and element in one of three slot
//! kinds: a raw 8-byte word (`int`, `float`, `bool`), an 8-byte object
//! pointer, or a 16-byte tagged slot (unions, optionals, `unknown`,
//! interpreter generics). This module names those kinds with the design's
//! enums ([`Kind`], [`ElemKind`], [`SlotKind`]) and gives builtins a view of
//! the heap through traits ([`Descriptors`], [`Lists`], [`Maps`],
//! [`Strings`]) instead of through `Value` and `Object`.
//!
//! Adapters generated by `baml_builtins2_codegen` and their bodies use only
//! this module. Today `bex_vm` implements the traits over `Value`/`Object`;
//! the new heap implements them over descriptors and slots. Neither side
//! needs the other.
//!
//! Containers may be shared across threads. Whole-container reads return a
//! snapshot of one backing store, and each key or index operation is a
//! single call, so a racing writer can lose an update but never expose torn
//! or freed memory.

use std::{num::NonZeroU64, ops::Range};

/// What a heap object is, as its descriptor says.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Kind {
    Instance,
    List,
    Backing,
    Map,
    Str,
    Closure,
    Future,
    /// `uint8array` payload.
    Bytes,
    /// Anything a builtin adapter does not look inside.
    Opaque,
}

/// The storage of one list element or map entry half.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum ElemKind {
    /// Raw `i64`, `f64` bits or `bool` in 8 bytes.
    Raw8,
    /// Object pointer in 8 bytes.
    Ptr,
    /// `SafeValue`: a tag byte, padding and an 8-byte payload.
    Tagged16,
}

/// Bytes per raw or pointer slot.
const WORD_BYTES: usize = 8;
/// Bytes per tagged slot.
const TAGGED_BYTES: usize = 16;

impl ElemKind {
    /// Bytes one slot of this kind occupies.
    pub const fn stride(self) -> usize {
        match self {
            ElemKind::Raw8 | ElemKind::Ptr => WORD_BYTES,
            ElemKind::Tagged16 => TAGGED_BYTES,
        }
    }
}

/// The scalar a raw slot holds.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum RawKind {
    Int,
    Float,
    Bool,
}

/// A field or element slot as the interpreter sees it: the storage kind and,
/// for raw slots, which scalar the word holds.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum SlotKind {
    Raw(RawKind),
    Ptr,
    Tagged16,
}

impl SlotKind {
    pub const fn elem_kind(self) -> ElemKind {
        match self {
            SlotKind::Raw(_) => ElemKind::Raw8,
            SlotKind::Ptr => ElemKind::Ptr,
            SlotKind::Tagged16 => ElemKind::Tagged16,
        }
    }

    /// Whether a union is an optional reference type (`Class?`, `string?`,
    /// `T[]?`, ...): null and exactly one other member, whose slot is a
    /// pointer. Other unions, optional scalars included, stay tagged.
    fn is_nullable_pointer<N: Clone>(members: &[baml_type::RealizedTy<N>]) -> bool {
        use baml_type::RealizedTy;
        let has_null = members
            .iter()
            .any(|member| matches!(member, RealizedTy::Null));
        let mut others = members
            .iter()
            .filter(|member| !matches!(member, RealizedTy::Null));
        match (others.next(), others.next()) {
            (Some(only), None) => has_null && Self::of_type(only) == SlotKind::Ptr,
            _ => false,
        }
    }

    /// The slot a value of `ty` is stored in (design section 1, slot table).
    ///
    /// Known scalars are raw; types whose every value is one heap object are
    /// pointers; anything that may hold more than one representation is
    /// tagged. An optional reference type is a pointer slot whose null is
    /// the zero word; optional scalars and other unions are tagged.
    ///
    /// Generic over the type's head so the Rust emitter lays out the same
    /// slots from MIR types (`baml_compiler2_rust`) as the runtime does from
    /// its own.
    pub fn of_type<N: Clone>(ty: &baml_type::RealizedTy<N>) -> SlotKind {
        use baml_base::Literal;
        use baml_type::RealizedTy;

        match ty {
            RealizedTy::Int | RealizedTy::Literal(Literal::Int(_), ..) => {
                SlotKind::Raw(RawKind::Int)
            }
            RealizedTy::Float | RealizedTy::Literal(Literal::Float(_), ..) => {
                SlotKind::Raw(RawKind::Float)
            }
            RealizedTy::Bool | RealizedTy::Literal(Literal::Bool(_), ..) => {
                SlotKind::Raw(RawKind::Bool)
            }
            RealizedTy::String
            | RealizedTy::Literal(Literal::String(_) | Literal::Bigint(_), ..)
            | RealizedTy::Bigint
            | RealizedTy::Uint8Array
            | RealizedTy::Media(_)
            | RealizedTy::Class(..)
            | RealizedTy::Enum(_)
            | RealizedTy::EnumVariant(..)
            | RealizedTy::List(_)
            | RealizedTy::Map { .. }
            | RealizedTy::Function { .. }
            | RealizedTy::Future(..)
            | RealizedTy::RustType
            | RealizedTy::Type
            | RealizedTy::Resource
            | RealizedTy::PromptAst => SlotKind::Ptr,
            // A nullable object type (`Packet?`): null is the zero word a
            // pointer slot already holds, so it needs no tag.
            RealizedTy::Union(members) if Self::is_nullable_pointer(members) => SlotKind::Ptr,
            RealizedTy::Null
            | RealizedTy::Interface(..)
            | RealizedTy::Union(_)
            | RealizedTy::TypeAlias(_)
            | RealizedTy::Unknown
            | RealizedTy::Never => SlotKind::Tagged16,
        }
    }
}

/// A receiver's descriptor, as much of it as generic adapters branch on.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Shape {
    List { elem: SlotKind },
    Map { key: SlotKind, value: SlotKind },
    Str,
    Other(Kind),
}

impl Shape {
    pub const fn kind(self) -> Kind {
        match self {
            Shape::List { .. } => Kind::List,
            Shape::Map { .. } => Kind::Map,
            Shape::Str => Kind::Str,
            Shape::Other(kind) => kind,
        }
    }

    fn not_a(self, expected: Kind) -> Fault {
        Fault::WrongReceiver {
            expected,
            found: self.kind(),
        }
    }

    /// A list receiver's element slot.
    pub fn list_elem(self) -> Result<SlotKind, Fault> {
        match self {
            Shape::List { elem } => Ok(elem),
            other => Err(other.not_a(Kind::List)),
        }
    }

    /// A map receiver's value slot.
    pub fn map_value(self) -> Result<SlotKind, Fault> {
        match self {
            Shape::Map { value, .. } => Ok(value),
            other => Err(other.not_a(Kind::Map)),
        }
    }

    /// Check a string receiver.
    pub fn string(self) -> Result<(), Fault> {
        match self {
            Shape::Str => Ok(()),
            other => Err(other.not_a(Kind::Str)),
        }
    }
}

/// A generic map key as a string object. Any other key needs the
/// interpreter's hashing, which may run user code.
pub fn string_key<R: Descriptors + ?Sized>(rt: &R, key: Tagged) -> Result<ObjPtr, Fault> {
    match key {
        Tagged::Ptr(ptr) if rt.shape(ptr) == Shape::Str => Ok(ptr),
        _ => Err(Fault::NeedsVm(NeedsVm::KeyHash)),
    }
}

/// Index into the program's descriptor table (the header's `descriptor`).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct DescriptorId(pub u32);

/// A pointer slot's contents: the address of an object's header.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct ObjPtr(NonZeroU64);

impl ObjPtr {
    pub const fn from_bits(bits: NonZeroU64) -> Self {
        Self(bits)
    }

    pub const fn bits(self) -> NonZeroU64 {
        self.0
    }
}

/// A raw slot's contents. Which scalar it holds comes from the descriptor.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
#[repr(transparent)]
pub struct RawWord(u64);

impl RawWord {
    #[expect(clippy::cast_sign_loss, reason = "a raw slot stores the i64's bits")]
    pub const fn from_int(value: i64) -> Self {
        Self(value as u64)
    }

    pub const fn from_float(value: f64) -> Self {
        Self(value.to_bits())
    }

    pub const fn from_bool(value: bool) -> Self {
        Self(value as u64)
    }

    #[expect(
        clippy::cast_possible_wrap,
        reason = "a raw slot stores the i64's bits"
    )]
    pub const fn as_int(self) -> i64 {
        self.0 as i64
    }

    pub const fn as_float(self) -> f64 {
        f64::from_bits(self.0)
    }

    pub const fn as_bool(self) -> bool {
        self.0 != 0
    }

    pub const fn bits(self) -> u64 {
        self.0
    }

    pub fn to_tagged(self, raw: RawKind) -> Tagged {
        match raw {
            RawKind::Int => Tagged::Int(self.as_int()),
            RawKind::Float => Tagged::Float(self.as_float()),
            RawKind::Bool => Tagged::Bool(self.as_bool()),
        }
    }

    /// The word for `value` in a raw slot holding `raw`, or `None` when the
    /// value is a different scalar or not a scalar.
    pub fn from_tagged(value: Tagged, raw: RawKind) -> Option<Self> {
        match (raw, value) {
            (RawKind::Int, Tagged::Int(int)) => Some(Self::from_int(int)),
            (RawKind::Float, Tagged::Float(float)) => Some(Self::from_float(float)),
            (RawKind::Bool, Tagged::Bool(boolean)) => Some(Self::from_bool(boolean)),
            _ => None,
        }
    }
}

/// A tagged slot's contents, read out of its lock (design `SafeValue`).
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Tagged {
    Null,
    Bool(bool),
    Int(i64),
    Float(f64),
    Ptr(ObjPtr),
}

/// A slot representation bodies are generic over: [`RawWord`], [`ObjPtr`],
/// [`Tagged`], or the interpreter's [`Value`](crate::Value), a tagged word
/// whose floats are boxed.
pub trait Elem: Copy + std::fmt::Debug {
    const KIND: ElemKind;
}

impl Elem for RawWord {
    const KIND: ElemKind = ElemKind::Raw8;
}

impl Elem for ObjPtr {
    const KIND: ElemKind = ElemKind::Ptr;
}

impl Elem for Tagged {
    const KIND: ElemKind = ElemKind::Tagged16;
}

impl Elem for crate::Value {
    const KIND: ElemKind = ElemKind::Tagged16;
}

/// Conversions between a slot representation and the universal [`Tagged`]
/// form. A runtime implements them where they need the heap (the
/// interpreter's boxed floats); the pure representations have them for every
/// runtime.
pub trait Slots<E: Elem> {
    /// The universal form of an element read from a slot of kind `slot`.
    fn to_tagged(&self, elem: E, slot: SlotKind) -> Tagged;

    /// This representation of `value` for a slot of kind `slot`.
    fn untag(&mut self, value: Tagged, slot: SlotKind) -> Result<E, Fault>;
}

impl<R: ?Sized> Slots<RawWord> for R {
    fn to_tagged(&self, elem: RawWord, slot: SlotKind) -> Tagged {
        let SlotKind::Raw(raw) = slot else {
            unreachable!("a raw word read from a {slot:?} slot");
        };
        elem.to_tagged(raw)
    }

    fn untag(&mut self, value: Tagged, slot: SlotKind) -> Result<RawWord, Fault> {
        let mismatch = Fault::SlotMismatch { slot, value };
        let SlotKind::Raw(raw) = slot else {
            return Err(mismatch);
        };
        RawWord::from_tagged(value, raw).ok_or(mismatch)
    }
}

impl<R: ?Sized> Slots<ObjPtr> for R {
    fn to_tagged(&self, elem: ObjPtr, _slot: SlotKind) -> Tagged {
        Tagged::Ptr(elem)
    }

    fn untag(&mut self, value: Tagged, slot: SlotKind) -> Result<ObjPtr, Fault> {
        match value {
            Tagged::Ptr(ptr) => Ok(ptr),
            _ => Err(Fault::SlotMismatch { slot, value }),
        }
    }
}

impl<R: ?Sized> Slots<Tagged> for R {
    fn to_tagged(&self, elem: Tagged, _slot: SlotKind) -> Tagged {
        elem
    }

    fn untag(&mut self, value: Tagged, _slot: SlotKind) -> Result<Tagged, Fault> {
        Ok(value)
    }
}

/// Why an adapter did not produce a result.
#[derive(Clone, Debug, PartialEq)]
pub enum Fault {
    /// The receiver's descriptor is not the declared kind.
    WrongReceiver { expected: Kind, found: Kind },
    /// A generic argument does not fit the receiver's slot.
    SlotMismatch { slot: SlotKind, value: Tagged },
    /// The builtin's declared `InvalidArgument` error.
    InvalidArgument { message: String },
    /// `Map.index` of a missing key.
    MapKeyNotFound,
    /// Needs interpreter machinery; the caller takes the `Value` glue path.
    NeedsVm(NeedsVm),
}

/// What an adapter defers to the interpreter.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum NeedsVm {
    /// A map key that is not a string; hashing it may run user code.
    KeyHash,
    /// An element that is not a scalar or string; rendering it may run a
    /// `to_string` override.
    Render,
}

/// The descriptor of a list an adapter allocates.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ListOf {
    /// The receiver list's own descriptor.
    SameAs(ObjPtr),
    /// A list of the map's value type.
    ValuesOf(ObjPtr),
    /// `string[]`.
    Strings,
    /// `int[]`.
    Ints,
}

/// A string map key, hashed with [`crate::map_string_hash`].
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct StrKey {
    pub ptr: ObjPtr,
    pub hash: u64,
}

/// Descriptor reads.
pub trait Descriptors {
    fn shape(&self, obj: ObjPtr) -> Shape;

    /// The element slot of lists allocated as `of`.
    fn list_of_slot(&self, of: ListOf) -> SlotKind;
}

/// Lists whose elements are stored as `E`.
///
/// Callers pass `E` matching the list's element slot ([`Shape::List`]).
pub trait Lists<E: Elem>: Descriptors {
    fn list_len(&self, list: ObjPtr) -> usize;

    /// The element at `index`, or `None` past the end.
    fn list_get(&self, list: ObjPtr, index: usize) -> Option<E>;

    /// A snapshot of every element.
    fn list_to_vec(&self, list: ObjPtr) -> Vec<E>;

    /// Replace the elements in `range` (clamped to the current length) with
    /// `with` and return the removed ones.
    fn list_splice(&mut self, list: ObjPtr, range: Range<usize>, with: &[E]) -> Vec<E>;

    /// Append `elem`; returns the new length.
    fn list_push(&mut self, list: ObjPtr, elem: E) -> usize;

    /// Remove and return the last element.
    fn list_pop(&mut self, list: ObjPtr) -> Option<E>;

    fn list_alloc(&mut self, of: ListOf, elems: &[E]) -> ObjPtr;
}

/// Maps with string keys whose values are stored as `V`. Entries keep
/// insertion order; replacing a value keeps its position.
pub trait Maps<V: Elem>: Descriptors {
    fn map_len(&self, map: ObjPtr) -> usize;

    fn map_get(&self, map: ObjPtr, key: StrKey) -> Option<V>;

    /// Insert or replace; returns the previous value.
    fn map_set(&mut self, map: ObjPtr, key: StrKey, value: V) -> Option<V>;

    fn map_remove(&mut self, map: ObjPtr, key: StrKey) -> Option<V>;

    fn map_clear(&mut self, map: ObjPtr);

    /// A new list of the keys, typed as the map's keys.
    fn map_key_list(&mut self, map: ObjPtr) -> ObjPtr;

    /// A snapshot of the values.
    fn map_values(&self, map: ObjPtr) -> Vec<V>;
}

/// Immutable strings and byte payloads.
pub trait Strings: Descriptors {
    fn str_text(&self, string: ObjPtr) -> &str;

    /// The string's map hash ([`crate::map_string_hash`] of its text). A
    /// model whose cells cache it computes it once per cell.
    fn str_hash(&self, string: ObjPtr) -> u64 {
        crate::map_string_hash(self.str_text(string))
    }

    /// Length in Unicode scalar values.
    fn str_char_len(&self, string: ObjPtr) -> usize;

    /// The byte range of the chars `chars`; an index past the end maps to
    /// the byte length. The default scans the text; a model that knows
    /// where its ASCII prefix ends answers in O(1) inside it.
    fn str_char_bytes(&self, string: ObjPtr, chars: Range<usize>) -> Range<usize> {
        let text = self.str_text(string);
        let byte_at = |char_index: usize| {
            text.char_indices()
                .nth(char_index)
                .map_or(text.len(), |(byte, _)| byte)
        };
        byte_at(chars.start)..byte_at(chars.end)
    }

    fn str_alloc(&mut self, text: &str) -> ObjPtr;

    /// The substring at `bytes` (char boundaries), sharing storage where the
    /// representation allows.
    fn str_substring(&mut self, string: ObjPtr, bytes: Range<usize>) -> ObjPtr;

    fn bytes_alloc(&mut self, bytes: &[u8]) -> ObjPtr;
}

/// Every trait an adapter may need, for each slot representation.
pub trait ObjectModel:
    Descriptors
    + Strings
    + Lists<RawWord>
    + Lists<ObjPtr>
    + Lists<Tagged>
    + Maps<RawWord>
    + Maps<ObjPtr>
    + Maps<Tagged>
{
}

impl<T> ObjectModel for T where
    T: Descriptors
        + Strings
        + Lists<RawWord>
        + Lists<ObjPtr>
        + Lists<Tagged>
        + Maps<RawWord>
        + Maps<ObjPtr>
        + Maps<Tagged>
{
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::RealizedTy;

    #[test]
    fn strides_follow_the_slot_table() {
        assert_eq!(ElemKind::Raw8.stride(), 8);
        assert_eq!(ElemKind::Ptr.stride(), 8);
        assert_eq!(ElemKind::Tagged16.stride(), 16);
    }

    #[test]
    fn slot_kinds_follow_the_slot_table() {
        let cases = [
            (RealizedTy::Int, SlotKind::Raw(RawKind::Int)),
            (RealizedTy::Float, SlotKind::Raw(RawKind::Float)),
            (RealizedTy::Bool, SlotKind::Raw(RawKind::Bool)),
            (RealizedTy::String, SlotKind::Ptr),
            (RealizedTy::list(RealizedTy::Int), SlotKind::Ptr),
            (RealizedTy::optional(RealizedTy::Int), SlotKind::Tagged16),
            // An optional reference type is a pointer slot, null the zero word.
            (RealizedTy::optional(RealizedTy::String), SlotKind::Ptr),
            (
                RealizedTy::optional(RealizedTy::list(RealizedTy::Int)),
                SlotKind::Ptr,
            ),
            // Other unions stay tagged, optional or not.
            (
                RealizedTy::Union(vec![RealizedTy::String, RealizedTy::Int].into()),
                SlotKind::Tagged16,
            ),
            (
                RealizedTy::optional(RealizedTy::Union(
                    vec![RealizedTy::String, RealizedTy::list(RealizedTy::Int)].into(),
                )),
                SlotKind::Tagged16,
            ),
            (RealizedTy::Unknown, SlotKind::Tagged16),
        ];
        for (ty, slot) in cases {
            assert_eq!(SlotKind::of_type(&ty), slot, "{ty:?}");
        }
    }

    #[test]
    fn raw_words_round_trip_through_tagged() {
        let cases = [
            (Tagged::Int(-7), RawKind::Int),
            (Tagged::Float(2.5), RawKind::Float),
            (Tagged::Bool(true), RawKind::Bool),
        ];
        for (value, raw) in cases {
            let word = RawWord::from_tagged(value, raw).unwrap();
            assert_eq!(word.to_tagged(raw), value);
        }
    }

    #[test]
    fn a_value_of_another_kind_does_not_fit_a_raw_slot() {
        let slot = SlotKind::Raw(RawKind::Int);
        let value = Tagged::Float(1.0);
        assert_eq!(
            Slots::<RawWord>::untag(&mut (), value, slot),
            Err(Fault::SlotMismatch { slot, value })
        );
    }
}
