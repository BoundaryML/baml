"""End-to-end check of the 09a-style baml_src → baml_sdk pipeline.

Unlike the `python_<fixture>` rig crates that drive `to_source_code`
from an in-memory `SymbolPool`, this crate goes through the full
`baml_project::build_symbol_pool` path. So these assertions exercise
parser → HIR → TIR → SymbolPool → emitter together.

Scope (subset of 09a-codegen-example-scenario.md):
- user.lorem.Resume + ExtractResume (with auto-generated companions)
- user.ipsum.Sentiment (enum) + ClassifySentiment
"""


def test_root_imports_cleanly():
    import baml_sdk  # noqa: F401


def test_namespaces_reachable_via_attribute_access():
    import baml_sdk
    assert baml_sdk.lorem is not None
    assert baml_sdk.ipsum is not None


def test_lorem_resume_class_shape():
    import pydantic
    from baml_sdk.lorem import Resume

    assert issubclass(Resume, pydantic.BaseModel)
    fields = Resume.model_fields
    assert set(fields) == {"name", "email"}


def test_ipsum_sentiment_enum_shape():
    import enum
    from baml_sdk.ipsum import Sentiment

    assert issubclass(Sentiment, enum.Enum)
    assert {v.name for v in Sentiment} == {"POSITIVE", "NEGATIVE", "NEUTRAL"}
    # 09b: enum values are the variant name verbatim, mixed with `str`
    # so they round-trip through JSON.
    assert Sentiment.POSITIVE.value == "POSITIVE"
    assert isinstance(Sentiment.POSITIVE, str)


def test_extract_resume_factory_bindings():
    # Sync + async siblings at the namespace leaf, per 09b §4.
    from baml_sdk import lorem

    assert callable(lorem.ExtractResume)
    assert callable(lorem.ExtractResume_async)
    assert lorem.ExtractResume.param_names == ["text"]


def test_extract_resume_companion_bindings():
    # Companions auto-generated by the compiler from the prompt block:
    # `$build_request`, `$render_prompt`, `$parse`, `$parse_stream`.
    # Each gets a flat `__<companion>` binding per 09b §3.
    from baml_sdk import lorem

    for name in (
        "ExtractResume__build_request",
        "ExtractResume__render_prompt",
        "ExtractResume__parse",
        "ExtractResume__parse_stream",
    ):
        binding = getattr(lorem, name)
        assert callable(binding), f"missing companion binding {name}"
        # Async sibling too.
        binding_async = getattr(lorem, f"{name}_async")
        assert callable(binding_async), f"missing async companion {name}_async"


def test_classify_sentiment_factory_bindings():
    from baml_sdk import ipsum

    assert callable(ipsum.ClassifySentiment)
    assert callable(ipsum.ClassifySentiment_async)
    assert ipsum.ClassifySentiment.param_names == ["text"]


def test_inlinedbaml_files_present():
    # baml/_inlinedbaml.py captures the user .baml source; the runtime
    # uses it to bootstrap without re-reading from disk.
    from baml_sdk.baml import _inlinedbaml

    assert "FILES" in dir(_inlinedbaml)
    paths = set(_inlinedbaml.FILES.keys())
    # Paths are relative to baml_src/.
    assert "ns_lorem/types.baml" in paths
    assert "ns_lorem/functions.baml" in paths
    assert "ns_ipsum/types.baml" in paths
    assert "ns_ipsum/functions.baml" in paths


def test_runtime_init_called_at_import():
    # The root __init__.py invokes BamlRuntime.initialize_runtime(...) at
    # import time; the conftest stub no-ops it. Just verifying the call
    # didn't blow up during module load by checking we can still reach
    # the SDK surface.
    import baml_sdk
    assert hasattr(baml_sdk, "lorem")
    assert hasattr(baml_sdk, "ipsum")
